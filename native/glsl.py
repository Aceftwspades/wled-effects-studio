"""Shaders in: a Shadertoy-style GLSL fragment shader translated into a code
effect (the feature review's sixth, STUDIO.md: xLights, TouchDesigner,
Resolume and Madrix take GLSL or ISF).

    cpp = translate(source, "Plasma Tunnel")   # the whole .cpp, or ShaderError(line, why)

What it takes: the shader as Shadertoy has it - `void mainImage(out vec4
fragColor, in vec2 fragCoord)` and whatever functions, constants and
#defines it calls - with iTime, iResolution, iFrame, iTimeDelta, iMouse and
iDate. Every pixel of the segment runs mainImage once a frame, at its
own fragCoord (the matrix, or the cube's net, as one picture; y up as
Shadertoy has it), and the colour it leaves is the pixel's. Speed scales
iTime, Intensity is the brightness.

What it does: the GLSL is tokenised and rewritten as C++, and the effect
carries its own small vector library - vec2, vec3, vec4, mat2, mat3 and
the built-in functions under gl_ names - in an anonymous namespace, so
it compiles on any firmware with the studio's effect API, and two shader
effects in one firmware never meet. Only the swizzles the shader uses are
made (as methods returning a proxy, so `p.xy *= rot` writes through).

What it refuses, saying so: textures and buffers (iChannel, texture()),
types it has no C++ for (ivec, bvec, mat4, samplers), and
multi-pass shaders. A device has none of a GPU's speed: every pixel runs
the whole shader in floats, so a heavy one is slow there (Node > What
each node costs tells for graphs; the code pane's build says the frame
time).
"""
