_SETS = ("xyzw", "rgba", "stpq")


def _tokens(src):
    out, pos, line = [], 0, 1
    while pos < len(src):
        m = _TOKEN.match(src, pos)
        if not m:
            raise ShaderError(line, f"a character it cannot read: {src[pos]!r}")
        kind = m.lastgroup
        out.append([kind, m.group(), line])
        if kind == "nl":
            line += 1
        pos = m.end()
    return out


def _strip_comments(src):
    """Comments away, a newline kept for each one they spanned (the lines still count)."""
    def blank(m):
        return "\n" * m.group().count("\n") or " "
    return re.sub(r"//[^\n]*|/\*.*?\*/", blank, src, flags=re.S)


def _is_swizzle(name):
    return 1 <= len(name) <= 4 and any(all(ch in s for ch in name) for s in _SETS)


def _swz_xyzw(name):
    return "".join("xyzw"[_SWZ[ch]] for ch in name)


def translate(src, title="Shader", ident=None):
    """A Shadertoy shader as a whole effect file (C++), or ShaderError saying where and why. `ident`: the
    effect's C name (its file's stem); the title's by default."""
    from native.project import _ident
    ident = _ident(ident or title) or "shader"
    if "mainImage" not in src:
        raise ShaderError(0, "no mainImage(out vec4 fragColor, in vec2 fragCoord) - a Shadertoy image shader is what it reads")
    toks = _tokens(_strip_comments(src.replace("\r\n", "\n")))
    swizzles = set()
    out = []
    i = 0
    n = len(toks)

    def prev_sig(k):
        j = k - 1
        while j >= 0 and toks[j][0] in ("ws", "nl"):
            j -= 1
        return toks[j] if j >= 0 else None

    def next_sig(k):
        j = k + 1
        while j < n and toks[j][0] in ("ws", "nl"):
            j += 1
        return j

    line_start = True
    skip_to_eol = False
    while i < n:
        kind, text, line = toks[i]
        if kind == "nl":
            out.append(text); line_start = True; skip_to_eol = False; i += 1; continue
        if skip_to_eol:
            i += 1; continue
        if kind == "ws":
            out.append(text); i += 1; continue
        if line_start and text == "#":
            # a preprocessor line: #define and #if kept (their numbers and names translated as the rest),
            # #version, #extension and #pragma dropped
            j = next_sig(i)
            word = toks[j][1] if j < n else ""
            if word in ("version", "extension", "pragma", "line"):
                skip_to_eol = True; i += 1; continue
        line_start = False
        # a statement GLSL needs and C++ has no use for: precision, and the uniforms the effect provides
        if kind == "id" and text == "precision":
            while i < n and toks[i][1] != ";":
                i += 1
            i += 1; continue
        if kind == "id" and text == "uniform":
            j = i
            names = []
            while j < n and toks[j][1] != ";":
                if toks[j][0] == "id":
                    names.append(toks[j][1])
                j += 1
            unknown = [x for x in names[2:] if x not in UNIFORMS] if len(names) > 2 else []
            if unknown:
                raise ShaderError(line, f"a uniform it cannot give: {', '.join(unknown)} (it gives {', '.join(sorted(UNIFORMS))})")
            i = j + 1; continue
        if kind == "id":
            if text in REFUSED_NAMES:
                raise ShaderError(line, f"{REFUSED_NAMES[text]}: an LED has no textures or buffers - only image shaders "
                                        "that compute their colour are read")
            if text in REFUSED_TYPES:
                raise ShaderError(line, f"{REFUSED_TYPES[text]} has no C++ here yet - vec2, vec3, vec4, mat2 and mat3 do")
            p = prev_sig(i)
            if p is not None and p[1] == ".":
                # a member after a dot: a swizzle, or a struct's field (left as it is)
                if _is_swizzle(text):
                    if len(text) == 1:
                        out.append(_swz_xyzw(text))
                    else:
                        sw = _swz_xyzw(text)
                        swizzles.add(sw)
                        out.append(sw + "()")
                    i += 1; continue
                out.append(text); i += 1; continue
            if text in ("out", "inout", "in"):
                # a parameter's qualifier: out and inout by reference, in by value
                j = next_sig(i)
                if j < n and toks[j][0] == "id":
                    k = next_sig(j)
                    if k < n and toks[k][0] == "id":
                        out.append(toks[j][1] + (" &" if text != "in" else " "))
                        i = k; continue
                i += 1; continue
            if text == "highp" or text == "mediump" or text == "lowp":
                i += 1; continue
            if text in BUILTINS:
                out.append("gl_" + text); i += 1; continue
            if text == "iGlobalTime":
                out.append("iTime"); i += 1; continue
            if text in TAKEN:
                out.append(text + "_"); i += 1; continue
            out.append(text); i += 1; continue
        if kind == "num":
            t = text.rstrip("uU")
            if t[:2].lower() == "0x":
                out.append(t)
            elif "." in t or "e" in t.lower():
                out.append(t.rstrip("fF") + "f")
            else:
                out.append(t)
            i += 1; continue
        if text == "^^":
            out.append("!=")                       # GLSL's logical xor on bools
            i += 1; continue
        out.append(text)
        i += 1
    body = "".join(out)
    upper = re.sub(r"[^A-Z0-9_]", "_", ident.upper())
    return _FILE.format(title=title.replace('"', "'").replace("\\", "/").replace("@", " ").replace(";", " "),
                        ident=ident, upper=upper, prelude=_prelude(swizzles), body=body)


# --- the vector library the effect carries ------------------------------------------------
def _swizzle_methods(size, used):
    """(the declarations inside vec<size>, their definitions after every type is whole) of the swizzles used: a
    vector by value when read from a const one, a proxy that writes through otherwise (not for a repeated
    component - p.xx cannot be written)."""
    decls, defs = [], []
    for sw in sorted(used):
        if len(sw) < 2 or any("xyzw".index(ch) >= size for ch in sw):
            continue
        idx = ",".join(str("xyzw".index(ch)) for ch in sw)
        k = len(sw)
        parts = ", ".join(f"v[{'xyzw'.index(ch)}]" for ch in sw)
        decls.append(f"  vec{k} {sw}() const;")
        defs.append(f"inline vec{k} vec{size}::{sw}() const {{ return vec{k}({parts}); }}")
        if len(set(sw)) == k:
            decls.append(f"  sw{k}<{idx}> {sw}();")
            defs.append(f"inline sw{k}<{idx}> vec{size}::{sw}() {{ return sw{k}<{idx}>(v); }}")
    return "\n".join(decls), "\n".join(defs)


def _prelude(used):
    """The vector types and functions, with the swizzles `used` (as xyzw)."""
    vecs, defs = [], []
    for size in (2, 3, 4):
        names = "xyzw"[:size]
        fields = ", ".join(names)
        args = ", ".join(f"float {c}_" for c in names)
        init = "; ".join(f"v[{k}] = {c}_" for k, c in enumerate(names))
        decl, d = _swizzle_methods(size, used)
        vecs.append(_VEC.format(n=size, fields=fields, args=args, init=init, swz=decl))
        defs.append(d)
    head, tail = _PRELUDE_TAIL.split("// @SWIZZLES@\n", 1)
    return (_PRELUDE_HEAD + "\n".join(vecs) + head + "// the swizzles this shader reads and writes\n"
            + "\n".join(x for x in defs if x) + "\n" + tail)


