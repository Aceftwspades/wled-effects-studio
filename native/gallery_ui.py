def share_dialog(app):
    """Share this graph...: its name, a line about it, tags and your name - then the folder to send."""
    c = _c()
    g = app.gp.graph
    if not g or not app.gp.file:
        app.gp.status("open the graph to share first (it is the graph pane's open one that is shared)"); return
    if not dpg.does_item_exist(SHARE):
        with dpg.window(tag=SHARE, label="Share to the gallery", no_title_bar=True, show=False, width=px(520),
                        height=px(300), no_collapse=True):
            c.dialog_header(SHARE, "Share to the gallery")
            dpg.add_text("", tag="gal_share_note", color=c.DIM, wrap=px(490))
            for tag, words, hint in (("gal_s_name", "NAME", "what it is called"),
                                     ("gal_s_desc", "ABOUT", "one sentence about it"),
                                     ("gal_s_tags", "TAGS", "a few, with commas: 2-D, audio, calm"),
                                     ("gal_s_author", "BY", "your name or handle")):
                with dpg.group(horizontal=True):
                    typeface.label(dpg.add_text(words, color=c.ACCENT))
                    dpg.add_input_text(tag=tag, width=px(400), hint=hint)
            with dpg.group(horizontal=True):
                from native import weight
                b = dpg.add_button(label="Make the folder", tag="gal_s_go", callback=lambda: share(app))
                weight.primary(b)
                c.tip("its bundle and a preview turning on the cube, with the entry, in captures/gallery-share - "
                      "then the folder and the gallery's page open, for the pull request")
                dpg.add_text("", tag="gal_s_msg", color=c.DIM, wrap=px(360))
    dpg.set_value("gal_share_note", "The graph open now, as the folder you send: its bundle, a preview (the effect on "
                  "screen now, turning - show it in the sim first) and its entry. The gallery's page says how to send "
                  "it: a pull request, which a check looks over.")
    dpg.set_value("gal_s_name", g.name or "")
    dpg.set_value("gal_s_author", app.prefs.get("gallery_author", ""))
    dpg.set_value("gal_s_msg", "")
    c._centre(SHARE, 520, 300)
    dpg.show_item(SHARE)


def share(app, name=None, desc=None, tags=None, author=None, open_after=True):
    """The open graph made into a gallery entry's folder: its bundle exported, a preview of the effect on screen
    (the graph's, built and shown), the entry. The folder's path, or None with the reason."""
    from native.shape_preview import turntable, save
    from native.synth import Synth
    g = app.gp.graph
    say = (lambda m: dpg.set_value("gal_s_msg", m)) if dpg.does_item_exist("gal_s_msg") else app.gp.status
    if not g or not app.gp.file:
        say("no graph open"); return None
    name = (name if name is not None else dpg.get_value("gal_s_name") or g.name or "").strip()
    desc = (desc if desc is not None else dpg.get_value("gal_s_desc") or "").strip()
    tags = tags if tags is not None else [t.strip() for t in (dpg.get_value("gal_s_tags") or "").split(",") if t.strip()]
    author = (author if author is not None else dpg.get_value("gal_s_author") or "").strip()
    if not name or not desc:
        say("a name and a sentence about it are needed"); return None
    if app.eng.names[app.eng.idx].strip().lower() != (g.name or "").strip().lower():
        say(f"show {g.name} in the sim first (build it and pick it): the preview is the effect on screen"); return None
    bundle = app.gp.export_bundle(False)
    if not bundle:
        say("the bundle could not be made"); return None
    try:
        frames = turntable(app, "effect", 4.0, 15, 200, 0.25, syn=Synth())
        gpath, _ = save(app, frames, 15, name=os.path.join("gallery", gallery.make_id(name)))
    except Exception as e:
        say(f"the preview could not be made: {e}"); return None
    if author:
        app.prefs["gallery_author"] = author
        from native.project import save_prefs
        save_prefs(app.prefs)
    folder = gallery.prepare_share(bundle, gpath, name, author, desc, tags)
    say(f"made: {folder}")
    app.gp.status(f"gallery entry ready to send: {folder}")
    if open_after:
        app.reveal(folder)
        _open_page()
    return folder
