import os
import queue
import threading

import dearpygui.dearpygui as dpg

from native import gallery
from native.typeface import px
from native import typeface

SHARE = "gallery_share"


def _c():
    from native import chrome
    return chrome


def _st(app):
    st = app.__dict__.get("_web_gallery")
    if st is None:
        st = app._web_gallery = {"entries": None, "error": "", "loading": False, "frames": {}, "q": queue.Queue(),
                         "worker": None}
    return st


def load(app, again=False):
    """The index, read on a worker; the previews then, one after another."""
    from native import tasks
    st = _st(app)
    if st["loading"] or (st["entries"] is not None and not again):
        return
    st["loading"], st["error"] = True, ""

    def done(r):
        ok, got = r
        st["loading"] = False
        if ok:
            st["entries"] = got
            _previews(app)
        else:
            st["error"], st["entries"] = got, st["entries"] or []
        _refresh_lib(app)

    def work():                                            # the outcome either way, for the main loop to show
        try:
            return True, gallery.fetch_index()
        except gallery.GalleryError as e:
            return False, str(e)
    if not tasks.run(app, "gallery:index", "reading the gallery", work, done):
        st["loading"] = False


def _previews(app):
    st = _st(app)
    if st["worker"] is not None and st["worker"].is_alive():
        return
    todo = [e for e in st["entries"] or () if e.id not in st["frames"]]
    if not todo:
        return
    q = st["q"]

    def work():
        for e in todo:
            q.put((e.id, gallery.fetch_preview(e)))
    st["worker"] = threading.Thread(target=work, daemon=True)
    st["worker"].start()


def poll(app):
    st = app.__dict__.get("_web_gallery")
    if st is None:
        return
    got = 0
    while got < 6:
        try:
            eid, frames = st["q"].get_nowait()
        except queue.Empty:
            break
        st["frames"][eid] = frames or []
        got += 1
    if got and app.__dict__.get("_lib_bank") == "gallery":
        app._lib_dirty = True                              # the tiles made again (not while a button is held)


def _refresh_lib(app):
    from native import library_ui
    library_ui.refresh(app)


def refresh(app, parent, query):
    """The Gallery bank's tiles under `parent`; returns how many are shown."""
    from native import library_ui
    c = _c()
    st = _st(app)
    if st["entries"] is None and not st["loading"]:
        load(app)
    with dpg.group(horizontal=True, parent=parent):
        dpg.add_button(label="Share this graph...", small=True, tag="gal_share", callback=lambda: share_dialog(app))
        c.tip("the graph open now as a gallery entry: its bundle, a preview and the entry, in a folder to send "
              "(the gallery's page says how)")
        dpg.add_button(label="Read it again", small=True, tag="gal_reload", callback=lambda: load(app, again=True))
        c.tip("the gallery's list read again - for what was added since")
        dpg.add_button(label="The gallery's page", small=True, tag="gal_page", callback=lambda: _open_page())
        c.tip(f"{gallery.page_url()} in the browser: what is there, and how to share yours")
    if st["loading"]:
        dpg.add_text("reading the gallery...", parent=parent, color=c.DIM)
        return 0
    if st["error"]:
        dpg.add_text(f"{st['error']} - Read it again when the network is back", parent=parent, color=c.DIM, wrap=0)
    entries = [e for e in st["entries"] or [] if not query or query in e.name.lower()
               or query in e.description.lower() or any(query in t.lower() for t in e.tags)]
    width = max(library_ui.TILE + 20, int(dpg.get_item_rect_size(parent)[0] or 600))
    per_row = max(1, (width - 12) // (library_ui.TILE + 14))
    for i in range(0, len(entries), per_row):
        with dpg.group(horizontal=True, parent=parent):
            for e in entries[i:i + per_row]:
                with dpg.group():
                    frames = st["frames"].get(e.id)
                    tex = library_ui._texture(app, "gallery:" + e.id, frames) if frames else None
                    if tex:
                        dpg.add_image_button(tex, width=library_ui.TILE, height=library_ui.TILE, user_data=e,
                                             callback=lambda s, a, u: get(app, u))
                    else:
                        words = "preview\ncoming" if frames is None else "no preview"     # a tile's stand-in
                        dpg.add_button(label=words, width=library_ui.TILE + 2 * px(7), height=library_ui.TILE + 2 * px(4),
                                       user_data=e, callback=lambda s, a, u: get(app, u))
                    dpg.add_text(e.name[:14], color=c.TEXT)
                    if e.author:
                        typeface.small(dpg.add_text(e.author[:16], color=c.DIM))
                    with dpg.tooltip(dpg.last_item()):
                        dpg.add_text(f"{e.name}" + (f" - by {e.author}" if e.author else "")
                                     + (f"\n{e.description}" if e.description else "")
                                     + (f"\ntags: {', '.join(e.tags)}" if e.tags else "")
                                     + (f"\nneeds: {', '.join(e.requires)}" if e.requires else "")
                                     + "\na click fetches it into this project (asked first: an effect is code)",
                                     wrap=px(300))
    if not entries and not st["error"]:
        dpg.add_text("nothing matches" if query else "the gallery is empty", parent=parent, color=c.DIM)
    return len(entries)


def get(app, entry):
    """A gallery effect into the project: fetched (its sha256 checked) on a worker, then the graph pane's import -
    which asks first."""
    from native import tasks

    def done(path):
        app.gp.import_bundle(path)                         # the question: an effect from elsewhere is code
    tasks.run(app, "gallery:get", f"fetching {entry.name} from the gallery", lambda: gallery.fetch_bundle(entry), done)


def _open_page():
    import webbrowser
    webbrowser.open(gallery.page_url())


