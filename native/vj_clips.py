"""Video clips played from the pads: a part of a video file - its In to its Out - put on a VJ deck over what the
deck shows, its level shaped by an envelope (attack, decay, sustain, release), the way a sampler plays a sound.

A clip is a pad's target, kept with the pad:

    {"kind": "pad_clip", "deck": 2, "file": "assets/vj/drop.mp4", "in": 1.5, "out": 4.0, "mode": "oneshot",
     "attack": 0.05, "decay": 0.0, "sustain": 1.0, "release": 0.3, "level": 1.0}

A live camera is the same, with a camera in place of a file and no In or Out - it plays until it is let go:

    {"kind": "pad_cam", "deck": 2, "name": "Integrated Camera", "attack": 0.1, "decay": 0.0, "sustain": 1.0,
     "release": 0.3, "level": 1.0}

"name" is an entry of the camera list (cameras(): a webcam's name, or video.PHONE); the cameras pads bring up are
kept open while the VJ runs (vj._warm_cams - a camera takes a second or so to start), so a press shows one at once.

"out" 0 is the file's end. A "oneshot" plays from In to Out once (its release timed to end at Out); a "loop" plays
In to Out round again until it is stopped. What starts and stops it is the pad's type (pads.press / release):
a trigger starts a one-shot again from In each press, and starts or stops a loop; a toggle starts and stops it;
a hold plays it while held (a one-shot ends at Out even if held longer).

One clip a deck: another on the same deck takes its place, its attack from the level the last had (no jump). While
one plays the deck shows it through the deck's own look when that is a video look (else "Clean"), at the clip's
level times its envelope - deck C, over the mix, is where clips usually go. Run state only (app._vj_clips), never
saved: a project switched or the VJ closed lets every clip go.

    play(app, t, owner)            # a pad (owner: its id) starts t
    stop(app, owner)               # its release begins
    playing(app, owner)            # lit
    held(app, owner)               # started and not let go (a press in its release starts it again)
    tick(app)                      # each frame (vj.update): the envelopes moved on, the one-shots ended
    deck(app, i, d)                # deck i's settings as it draws: the clip's source and look over its own
    level(app, i)                  # deck i's level while a clip plays, or None
"""
# AI: below section was generated by an AI
import math
import os

from native import clock

MODES = (("oneshot", "one shot"), ("loop", "loop"))
DEFAULT = {"kind": "pad_clip", "deck": 2, "file": "", "in": 0.0, "out": 0.0, "mode": "oneshot", "attack": 0.02,
           "decay": 0.0, "sustain": 1.0, "release": 0.2, "level": 1.0}
CAM_DEFAULT = {"kind": "pad_cam", "deck": 2, "name": "", "attack": 0.1, "decay": 0.0, "sustain": 1.0,
               "release": 0.3, "level": 1.0}
KINDS = ("pad_clip", "pad_cam")
ENV = (("attack", 0.0, 10.0), ("decay", 0.0, 10.0), ("sustain", 0.0, 1.0), ("release", 0.0, 10.0))   # (key, lo, hi)
START_WAIT_S = 2.0                 # a clip's first frame waited for this long at most before its time starts anyway
VIDEO_EXT = (".mp4", ".mov", ".mkv", ".webm", ".avi", ".gif", ".m4v")


def _rt(app):
    return app.__dict__.setdefault("_vj_clips", {})


def fill(t):
    """A clip or camera target with every field there and of its kind (a hand-edited or older pad's put right)."""
    cam = t.get("kind") == "pad_cam"
    for k, v in (CAM_DEFAULT if cam else DEFAULT).items():
        cur = t.get(k)
        if isinstance(v, str):
            ok = isinstance(cur, str)
        else:
            ok = isinstance(cur, (int, float)) and not isinstance(cur, bool) and math.isfinite(cur)   # (an Infinity Out)
        if not ok:
            t[k] = v
    t["deck"] = max(0, min(3, int(t["deck"])))                    # (3: the selected deck - resolved as it plays)
    for k, lo, hi in ENV:
        t[k] = max(lo, min(hi, float(t[k])))
    t["level"] = max(0.0, min(1.0, float(t["level"])))
    if cam:
        for k in ("file", "in", "out", "mode"):
            t.pop(k, None)
        return t
    if t["mode"] not in dict(MODES):
        t["mode"] = "oneshot"
    t["in"] = max(0.0, float(t["in"]))
    t["out"] = max(0.0, float(t["out"]))
    return t


def length(app, t):
    """The clip's seconds, In to Out (Out 0: to the file's end), or None when the file's length is not known."""
    a, b = float(t.get("in", 0.0)), float(t.get("out", 0.0))
    if b > a:
        return b - a
    from native import video, vj
    d = video.duration_of(vj.media(app, t.get("file", "")), wait=False)
    return max(0.0, d - a) if d else None


def play(app, t, owner):
    """Clip t started on its deck from its In - in place of the one there, from the level it had."""
    t = fill(dict(t))
    if t["deck"] == 3:                                          # on the selected deck: the one selected now
        from native import vj
        t["deck"] = vj.selected(app)
    if not t.get("name" if t["kind"] == "pad_cam" else "file"):
        return
    rt = _rt(app)
    old = rt.get(t["deck"])
    app._vj_clip_take = getattr(app, "_vj_clip_take", 0) + 1
    shown = old["lv"] * float(old["t"]["level"]) if old else 0.0
    lv = min(1.0, shown / float(t["level"])) if float(t["level"]) > 0 else 0.0
    rt[t["deck"]] = {"owner": owner, "t": t, "take": app._vj_clip_take, "pressed": clock.now(), "t0": None,
                     "at": clock.now(), "gate": True, "stage": "a", "lv": lv, "rate": 0.0,
                     "rise": (1.0 - lv) * float(t["attack"])}     # its attack's seconds, from the level it took over


def stop(app, owner):
    """The clips `owner` started let go: each into its release."""
    for p in _rt(app).values():
        if p["owner"] == owner and p["gate"]:
            _gate_off(p)


def stop_deck(app, i):
    p = _rt(app).get(i)
    if p is not None and p["gate"]:
        _gate_off(p)


def _gate_off(p, left=None):
    """Into its release: over the release's seconds - or `left`, a one shot's time to its Out."""
    p["gate"] = False
    p["stage"] = "r"
    rel = float(p["t"]["release"]) if left is None else left
    p["rate"] = p["lv"] / rel if rel > 0 else float("inf")


def playing(app, owner):
    """Whether a clip `owner` started is playing (its release counts)."""
    return any(p["owner"] == owner for p in _rt(app).values())


def held(app, owner):
    """Whether a clip `owner` started is on and not let go yet (in its release it is not: pressed, it starts again)."""
    return any(p["owner"] == owner and p["gate"] for p in _rt(app).values())


def stop_tries(app, keep=None):
    """The clips the editor's Play started let go - all but the one for the pad `keep` (its id)."""
    for p in _rt(app).values():
        o = p["owner"]
        if isinstance(o, tuple) and o[0] == "try" and o[1] != keep and p["gate"]:
            _gate_off(p)


def shift(app, d):
    """Every clip's times moved by d seconds (the clock jumped at a render's end: vj._follow_clock)."""
    for p in _rt(app).values():
        for k in ("pressed", "t0", "at"):
            if p[k] is not None:
                p[k] += d


def started(app, i, take):
    """Deck i showed its clip's first frame (vj._take_video): its time starts now - a file's opening (a fraction
    of a second) not counted against its length."""
    p = _rt(app).get(i)
    if p is not None and p["take"] == take and p["t0"] is None:
        p["t0"] = clock.now()


def tick(app):
    """Each frame: every clip's envelope moved on; a one-shot let go in time for its release to end at its Out (not
    before its attack is up: a release longer than the part is shortened to what is left), or at the file's end when
    its length is not known; a clip whose release is done taken off its deck."""
    from native import vj
    now = clock.now()
    rt = _rt(app)
    for i in list(rt):
        p = rt[i]
        back = now - p["at"]
        if back < 0:                                        # the clock went back (a render that ran ahead let go):
            for k in ("pressed", "t0"):                     # its times moved with it, not frozen that long
                if p[k] is not None:
                    p[k] += back
        dt = max(0.0, back)
        p["at"] = now
        t = p["t"]
        if p["t0"] is None and vj.clip_ended(app, i, p["take"]):
            del rt[i]                                       # it would not open: nothing of it to show
            continue
        if p["t0"] is None and now - p["pressed"] >= START_WAIT_S:
            p["t0"] = now                                   # no picture yet (a file gone): its time runs anyway
        if p["t0"] is None:
            continue                                        # the last picture held, at the level it had
        if p["gate"] and t.get("mode") == "oneshot":
            n = length(app, t)
            if n is None:
                if vj.clip_ended(app, i, p["take"]):        # no length known (no ffprobe): let go at its end
                    _gate_off(p)
            elif vj.clip_ended(app, i, p["take"]):          # its file ended before its Out (a shorter file, an Out
                _gate_off(p)                                # typed past the end): let go there, not held frozen
            else:
                off_at = min(n, max(n - float(t["release"]), p["rise"]))
                past = now - p["t0"] - off_at
                if past >= 0:                               # let go part-way through this frame: the frame's
                    pre = max(0.0, dt - past)               # time before it held, the rest released
                    _env(p, pre)
                    _gate_off(p, n - off_at)
                    dt -= pre
        _env(p, dt)
        if p["stage"] == "off":
            del rt[i]


def _env(p, dt):
    """The envelope a frame on: up over its attack, down to its sustain over its decay, held, then down to 0 over its
    release (from wherever it was let go)."""
    t = p["t"]
    a, d, s = float(t["attack"]), float(t["decay"]), float(t["sustain"])
    if p["stage"] == "a":                                   # (what is left of the frame goes on to the next stage)
        need = (1.0 - p["lv"]) * a
        if dt >= need:
            p["lv"], p["stage"], dt = 1.0, "d", dt - need
        else:
            p["lv"], dt = p["lv"] + dt / a, 0.0
    if p["stage"] == "d":
        need = (p["lv"] - s) * d / (1.0 - s) if s < 1.0 else 0.0
        if dt >= need:
            p["lv"], p["stage"] = s, "s"
        else:
            p["lv"] -= dt * (1.0 - s) / d
    if p["stage"] == "r":
        p["lv"] = max(0.0, p["lv"] - dt * p["rate"])
        if p["lv"] <= 1e-9:
            p["lv"], p["stage"] = 0.0, "off"


def level(app, i):
    """Deck i's level while a clip plays on it (the clip's level through its envelope), else None."""
    p = _rt(app).get(i)
    return None if p is None else p["lv"] * float(p["t"]["level"])


def deck(app, i, d):
    """Deck i's settings as it draws: deck C's, while a clip plays on it, the clip's (clip_deck) - C shows the clip
    over the mix in place of its own picture. Decks A and B draw their own: a clip on one is laid over its picture
    by the clip's envelope (vj._draw_clip, vj.deck_led), not put in its place."""
    return d if i < 2 else clip_deck(app, i, d)


def clip_deck(app, i, d):
    """The settings a clip on deck i draws with: its file from In to Out as the source (a new take each start, so
    it starts from In again) and a video look - the deck's own when it is one, else Clean; d itself when none
    plays."""
    p = _rt(app).get(i)
    if p is None:
        return d
    from native import vj_looks
    t = p["t"]
    lk = vj_looks.LOOKS.get(d.get("look"))
    look = d.get("look") if lk is not None and lk.family == "video" else "Clean"
    if t["kind"] == "pad_cam":
        return dict(d, source=cam_source(t["name"]), look=look, _clip_take=p["take"])
    src = {"kind": "file", "path": t["file"], "files": [], "clip": 0, "speed": 1.0, "in": float(t["in"]),
           "out": float(t["out"]), "advance": "off", "take": p["take"], "once": t["mode"] == "oneshot", "name": "",
           "url": ""}                                       # once: a one shot's file not run round again
    return dict(d, source=src, look=look, _clip_take=p["take"])


def cam_source(name):
    """A deck's source for a camera list entry: the phone's camera, or a webcam by its name."""
    from native import video
    if name == video.PHONE:
        return {"kind": "phone", "path": "", "name": "", "url": ""}
    return {"kind": "webcam", "path": "", "name": name, "url": ""}


def cam_names(app):
    """The cameras the project's pads bring up (their camera list entries), each once."""
    from native import pads
    out = []
    for b in pads.state(app.project).get("banks", []):
        for c in b.get("controls", []):
            t = c.get("target") or {}
            if t.get("kind") == "pad_cam" and t.get("name") and t["name"] not in out:
                out.append(t["name"])
    return out


def cameras():
    """The camera list a camera pad picks from: the webcams ffmpeg sees here, then the phone's camera (asks ffmpeg -
    a second or so: called on a worker)."""
    from native import video
    return [n for n, _ in video.webcams()] + [video.PHONE]


def let_go(app):
    """Every clip off its deck at once (another project, the VJ closed)."""
    _rt(app).clear()


def files(app):
    """The video files kept with the project (its assets/vj), as kept paths - the clip editor's list."""
    from native import vj
    root = os.path.join(app.project.path, *vj.MEDIA_DIR.split("/"))
    try:
        names = sorted(f for f in os.listdir(root) if f.lower().endswith(VIDEO_EXT))
    except OSError:
        names = []
    return [f"{vj.MEDIA_DIR}/{n}" for n in names]


def words(t):
    """A clip in a few words: its file's name and its part ("drop.mp4 1.5-4.0 s", "drop.mp4" whole); a camera: its
    name."""
    if t.get("kind") == "pad_cam":
        return t.get("name") or "(no camera picked)"
    name = os.path.basename(t.get("file") or "") or "(no file picked)"
    a, b = float(t.get("in", 0.0)), float(t.get("out", 0.0))
    if b > a:
        return f"{name} {a:.1f}-{b:.1f} s"
    return f"{name} from {a:.1f} s" if a > 0 else name
