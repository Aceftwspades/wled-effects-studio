DEFAULTS = {"pic_key": "alpha", "pic_key_col": [0.0, 1.0, 0.0], "pic_tol": 0.25, "pic_soft": 0.1, "pic_fit": "fill",
            "pic_scale": 1.0, "pic_x": 0.0, "pic_y": 0.0, "pic_rot": 0.0, "pic_flip": "none", "pic_drift": 1.0}
