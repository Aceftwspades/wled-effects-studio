def _get(deck, key):
    v = (deck or {}).get(key)
    return DEFAULTS[key] if v is None else v


def plain(deck, video=True):
    """Whether the deck leaves a picture as it comes (its own alpha, filling, unmoved; a video undrifted): then a
    video frame without alpha need not go through prepare() at all."""
    d = deck or {}
    return (_get(d, "pic_key") == "alpha" and _get(d, "pic_fit") in ("fill", "stretch")
            and abs(float(_get(d, "pic_scale")) - 1.0) < 1e-6 and not float(_get(d, "pic_x")) and not float(_get(d, "pic_y"))
            and not float(_get(d, "pic_rot")) and _get(d, "pic_flip") == "none")


def _smooth(e0, e1, x):
    t = np.clip((x - e0) / max(1e-6, e1 - e0), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def key(img, deck):
    """(rgb, alpha) of a picture (H, W, 3 or 4) by the deck's transparency: its own alpha, none (its colour as on
    black, all of it shown), a colour keyed out, or the dark keyed out (each on top of its own alpha)."""
    rgb = img[..., :3]
    a0 = img[..., 3] if img.shape[-1] > 3 else np.ones(img.shape[:2], np.float32)
    mode = _get(deck, "pic_key")
    tol, soft = float(_get(deck, "pic_tol")), max(1e-3, float(_get(deck, "pic_soft")))
    if mode == "none":
        return rgb * a0[..., None], np.ones_like(a0)
    if mode == "colour":
        kc = np.asarray(_get(deck, "pic_key_col"), np.float32)[:3]
        dist = np.sqrt(((rgb - kc) ** 2).sum(-1) / 3.0)             # 0 the key colour, 1 its opposite
        return rgb, a0 * _smooth(tol, tol + soft, dist)
    if mode == "dark":
        lum = rgb @ np.array([0.3, 0.59, 0.11], np.float32)
        return rgb, a0 * _smooth(tol, tol + soft, lum)
    return rgb, a0


def place(rgb, alpha, w, h, deck, t=0.0, amount=0.5, beat=0.0, drift=None):
    """The keyed picture laid on a w x h canvas by the deck's fit, scale, place, turn and flip (and drift): (rgb,
    alpha) at the canvas's size, clear where the picture is not (tiled: everywhere)."""
    from native import vj_looks
    H, W = rgb.shape[:2]
    ca, sa = w / max(1, h), W / max(1, H)                           # the canvas's and the picture's width / height
    fit = _get(deck, "pic_fit")
    if fit == "stretch":
        bw, bh = ca, 1.0
    elif (fit == "fill") == (sa > ca):                              # fill a wider picture / fit a taller one: by height
        bw, bh = sa, 1.0
    else:
        bw, bh = ca, ca / sa
    dr = float(_get(deck, "pic_drift")) if drift is None else drift
    z = float(_get(deck, "pic_scale")) * (1.0 + dr * (amount * 0.6 + beat * 0.05))
    a = t * 0.05
    ox = float(_get(deck, "pic_x")) * 0.5 * ca + dr * math.sin(a) * 0.05 * ca
    oy = float(_get(deck, "pic_y")) * 0.5 + dr * math.cos(a * 0.7) * 0.05
    rot = math.radians(float(_get(deck, "pic_rot")))
    u, v = np.meshgrid((np.arange(w, dtype=np.float32) + 0.5) / w, (np.arange(h, dtype=np.float32) + 0.5) / h)
    px, py = (u - 0.5) * ca - ox, (v - 0.5) + oy                     # canvas units: its height 1, y down, the middle 0
    c, s = math.cos(-rot), math.sin(-rot)
    px, py = (px * c - py * s) / z, (px * s + py * c) / z
    su, sv = px / bw + 0.5, py / bh + 0.5
    flip = _get(deck, "pic_flip")
    if flip in ("h", "both"):
        su = 1.0 - su
    if flip in ("v", "both"):
        sv = 1.0 - sv
    tile = fit == "tile"
    pic = vj_looks.sample(np.dstack([rgb, alpha]).astype(np.float32), su, sv, wrap=tile)
    out_rgb, out_a = pic[..., :3], pic[..., 3]
    if not tile:
        inside = (su >= 0) & (su <= 1) & (sv >= 0) & (sv <= 1)
        out_a = out_a * inside
    return out_rgb, np.clip(out_a, 0, 1)


def prepare(img, w, h, deck, t=0.0, amount=0.5, beat=0.0, drift=None):
    """A picture or a video frame (H, W, 3 or 4, 0..1) as the deck shows it: (rgb premultiplied - black where it is
    clear, as the looks take it - and alpha), w x h."""
    rgb, a = key(np.asarray(img, np.float32), deck)
    still = (drift if drift is not None else float(_get(deck, "pic_drift"))) == 0.0
    if not (still and plain(deck) and rgb.shape[:2] == (h, w)):  # moved, or another size: laid on the canvas
        rgb, a = place(rgb, a, w, h, deck, t, amount, beat, drift)  # (else as it is: a resample at its own size blurs)
    return np.clip(rgb * a[..., None], 0, 1).astype(np.float32), a.astype(np.float32)
