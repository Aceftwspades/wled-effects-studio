"""Timecode in (the second feature review's fifth, after Resolume, MadMapper
and Chromatik): the show's playhead chasing a clock from outside - a DAW's,
a DJ's, a lighting desk's timeline running the show.

    mtc = Mtc(); mtc.feed(msg, now)      # MIDI Time Code, from the MIDI frame's input port
    ltc = Ltc(); ltc.feed(samples, rate, now)   # Linear Timecode, read out of an audio input
    t, running, fps = src.position(now)  # the timecode's seconds (None before any), and whether it runs
    x = ltc_encode(t, fps, rate)         # LTC as audio: the tests', and to stripe a track

MTC is the MIDI standard's (MMA RP-004): eight quarter-frame messages (F1
0n) carry one time over two frames, and a full-frame SysEx (F0 7F cc 01 01
hh mm ss ff F7) locates without running. LTC is SMPTE 12M's: 80 bits a
frame in biphase mark code (a transition at every bit's edge, and one more in
the middle of a 1), the frame's end marked by its sync word. Both carry hours,
minutes, seconds and frames at 24, 25, 29.97 (drop-frame) or 30 a second.

Between two readings the time runs on from the last by the real clock, so the
playhead moves smoothly; `chase` keeps the show within a few frames of it,
seeking only when it has drifted further (a seek every frame would stutter).
"""
