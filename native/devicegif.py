import io
import json
import os
import urllib.request

import numpy as np

TAG = "devgif_win"
LENGTHS = (2, 4, 8, 15)
RATES = (10, 20, 25)             # a GIF's delays are in hundredths: these come out exact
SPARE_KB = 24                    # room left on the device's files after the GIF (its presets and config grow)


def options(app):
    o = app.project.options.setdefault("device_gif", {})
    o.setdefault("seconds", 4)
    o.setdefault("fps", 20)
    o.setdefault("name", "studio.gif")
    return o


def clean_name(name):
    """A file name the Image effect will take: letters, digits, - and _, ending .gif, short enough for a
    segment's name (32 characters with its /)."""
    base = os.path.splitext(os.path.basename(str(name or "")))[0]
    base = "".join(ch for ch in base if ch.isalnum() or ch in "-_")[:26] or "studio"
    return base + ".gif"


def encode(frames, fps):
    """GIF bytes of the frames ((rows, cols, 3) uint8), looping, each shown 1/fps."""
    from PIL import Image
    ims = [Image.fromarray(np.ascontiguousarray(f, dtype=np.uint8), "RGB") for f in frames]
    if not ims:
        raise ValueError("no frames")
    buf = io.BytesIO()
    delay = int(round(100.0 / fps)) * 10
    ims[0].save(buf, format="GIF", save_all=True, append_images=ims[1:], duration=delay, loop=0, disposal=1)
    return buf.getvalue()


def from_file(path, cols, rows, max_frames=600):
    """(frames, fps) of a GIF (or a still picture), each frame fitted to cols x rows (cropped to fill it)."""
    from PIL import Image, ImageOps, ImageSequence
    im = Image.open(path)
    frames, delays = [], []
    for fr in ImageSequence.Iterator(im):
        f = ImageOps.fit(fr.convert("RGB"), (int(cols), int(rows)), Image.NEAREST if max(fr.size) <= 64 else Image.BILINEAR)
        frames.append(np.asarray(f, np.uint8).copy())
        delays.append(fr.info.get("duration", im.info.get("duration", 50)) or 50)
        if len(frames) >= max_frames:
            break
    fps = 1000.0 / max(10.0, float(np.median(delays))) if delays else 20.0
    return frames, fps


def _req(host, path, body=None, timeout=6.0):
    url = f"http://{host}{path}"
    req = urllib.request.Request(url, data=body, headers={"Content-Type": "application/json"} if body else {})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read().decode("utf-8", "replace") or "null")


def send(host, data, name, log=lambda m: None):
    """The GIF to the device's files as /name, and its main segment set to the Image effect showing it.
    (ok, words)."""
    from native import devices, flash
    host = devices.clean_host(host)
    if not host:
        return False, "no device chosen - Window > Devices..."
    try:
        info = _req(host, "/json/info")
    except Exception as e:
        return False, f"the device did not answer: {e}"
    if "8266" in str(info.get("arch", "")):
        return False, "an ESP8266 build has no GIF player (WLED_ENABLE_GIF): an ESP32 plays them"
    fs = info.get("fs") or {}
    if fs.get("t"):
        free = (int(fs.get("t", 0)) - int(fs.get("u", 0))) * 1024
        if len(data) > free - SPARE_KB * 1024:
            return False, (f"{len(data) // 1024} KB is more than the device has room for ({max(0, free) // 1024} KB "
                           "free): fewer seconds or frames a second")
    try:
        names = [str(n).split("@", 1)[0] for n in _req(host, "/json/effects")]
    except Exception as e:
        return False, f"could not read the device's effects: {e}"
    if "Image" not in names:
        return False, "the device has no Image effect (a WLED from before 0.15)"
    ok, words = flash.send_file(host, "/" + name, data, log)
    if not ok:
        return False, words
    try:
        st = _req(host, "/json/state")
        seg = int(st.get("mainseg", 0))
        _req(host, "/json/state", json.dumps({"on": True, "seg": [{"id": seg, "fx": names.index("Image"), "n": name,
                                                                    "sx": 128, "ix": 0}]}).encode())
    except Exception as e:
        return False, f"sent, but the effect could not be set: {e}"
    return True, f"{name} ({len(data) // 1024 or 1} KB) playing on {host} - Image effect, its segment named {name}"


