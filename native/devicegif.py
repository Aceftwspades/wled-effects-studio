"""A GIF played by the device itself (the second feature review's sixth,
after WLED 16's GIF playback): what the sim shows - any effect, a graph, a
video look, a show playing - caught for a few seconds at the device's own
matrix size, or a GIF file fitted to it, sent to the device's files and
played there by WLED's Image effect. No stream: the device plays it alone,
the studio closed.

    frames = capture over `seconds` (poll(app) each loop, from the sim's engine)
    data = encode(frames, fps)                 # GIF bytes, looping
    frames, fps = from_file(path, cols, rows)  # a GIF (or a still) fitted to the matrix
    send(host, data, name)                     # uploaded, then the main segment set to Image with it

WLED's Image effect (FX_MODE_IMAGE, wled00/image_loader.cpp) takes its file
from the segment's name and draws it at the segment's size, frame by frame at
the GIF's own delays (speed 128); it needs a build with WLED_ENABLE_GIF -
every ESP32 build has it, an ESP8266 one does not.
"""
