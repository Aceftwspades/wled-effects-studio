def build(app):
    import dearpygui.dearpygui as dpg
    from native import chrome, form, weight
    from native.typeface import px
    o = options(app)
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(470), height=px(300)):
        chrome.dialog_header(TAG, "Play a GIF on the device")
        dpg.add_text("What the sim shows, caught for a few seconds at the device's matrix size - or a GIF file fitted "
                     "to it - sent to the device's files and played there by WLED's Image effect: no stream, the "
                     "studio can close. An ESP32 build plays them.", color=chrome.DIM, wrap=px(440))
        with form.row("length", tip="how long a loop of the sim is caught - make the effect's loop fit it"):
            dpg.add_combo([f"{s} s" for s in LENGTHS], tag="dg_secs", width=-1, default_value=f"{o['seconds']} s",
                          callback=lambda s, v: _set(app, "seconds", int(v.split()[0])))
        with form.row("frames a second", tip="more is smoother and a bigger file"):
            dpg.add_combo([f"{r}" for r in RATES], tag="dg_fps", width=-1, default_value=str(o["fps"]),
                          callback=lambda s, v: _set(app, "fps", int(v)))
        with form.row("its name", tip="the file on the device - the segment's name points the Image effect at it"):
            dpg.add_input_text(tag="dg_name", width=-1, default_value=o["name"], on_enter=True,
                               callback=lambda s, v: _set(app, "name", clean_name(v)))
        dpg.add_text("", tag="dg_words", color=chrome.DIM, wrap=px(440))
        with dpg.group(horizontal=True):
            dpg.add_button(label="Catch the sim and send", tag="dg_go", callback=lambda: start(app))
            weight.primary("dg_go")
            weight.need("dg_go", "device")
            chrome.tip("the sim's frames from now for the length chosen, then the GIF to the device, playing")
            dpg.add_button(label="Send a GIF file...", tag="dg_file", callback=lambda: dpg.show_item("dg_dialog"))
            weight.need("dg_file", "device")
            chrome.tip("a GIF (or a picture) fitted to the matrix, then to the device, playing")
    with dpg.file_dialog(directory_selector=False, show=False, tag="dg_dialog", width=px(620), height=px(420),
                         callback=lambda s, a: send_file(app, a.get("file_path_name", ""))):
        dpg.add_file_extension("{.gif,.png,.jpg,.jpeg,.webp}", color=(120, 170, 255))
        dpg.add_file_extension(".*")


def _set(app, key, v):
    import dearpygui.dearpygui as dpg
    options(app)[key] = v
    if key == "name":
        dpg.set_value("dg_name", v)
    app.project.save()
    refresh(app)


def refresh(app):
    import dearpygui.dearpygui as dpg
    if not dpg.does_item_exist("dg_words"):
        return
    o = options(app)
    n = int(o["seconds"]) * int(o["fps"])
    host = app.active_host()
    dpg.set_value("dg_words", f"{n} frames of {app.eng.cols} x {app.eng.rows}, to " + (host or "no device yet"))


def show(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    refresh(app)
    chrome._centre(TAG, 470, 300)
    dpg.show_item(TAG)


def start(app):
    """The sim's frames caught from now (poll), then sent."""
    from native import clock
    if getattr(app, "_dg_cap", None) is not None:
        app.gp.status("a GIF is being caught already"); return False
    if not app.active_host():
        app.gp.status("no device chosen - Window > Devices..."); return False
    o = options(app)
    now = clock.now()
    app._dg_cap = {"frames": [], "next": now, "end": now + float(o["seconds"]), "fps": float(o["fps"])}
    app.gp.status(f"catching {o['seconds']} s of the sim for the device")
    return True


def poll(app):
    """A frame of the sim's every 1/fps while a GIF is being caught; caught, it is sent."""
    from native import clock
    cap = getattr(app, "_dg_cap", None)
    if cap is None:
        return
    now = clock.now()
    if now < cap["end"]:
        if now >= cap["next"]:
            cap["frames"].append(app.frame_rgb().copy())      # as the views show it: a blend, the mixer, the brightness
            cap["next"] += 1.0 / cap["fps"]
        return
    app._dg_cap = None
    _send(app, cap["frames"], cap["fps"])


def send_file(app, path):
    if not path or not os.path.isfile(path):
        return False
    try:
        frames, fps = from_file(path, app.eng.cols, app.eng.rows)
    except Exception as e:
        app.gp.status(f"could not read {os.path.basename(path)}: {e}"); return False
    return _send(app, frames, fps)


def _send(app, frames, fps):
    from native import tasks
    host, name = app.active_host(), clean_name(options(app)["name"])

    def work():
        data = encode(frames, fps)
        return send(host, data, name)

    def done(r):
        ok, words = r
        app.gp.status(words)
        import dearpygui.dearpygui as dpg
        if dpg.does_item_exist("dg_words"):
            dpg.set_value("dg_words", words)
    return tasks.run(app, "devicegif", f"sending {len(frames)} frames to the device as {name}", work, done)
