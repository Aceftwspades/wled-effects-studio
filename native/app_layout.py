            if dpg.does_item_exist("cube_src_tex"):
                dpg.delete_item("cube_src_tex")
            dpg.add_raw_texture(n, n, np.zeros(n * n * 4, np.float32), format=dpg.mvFormat_Float_rgba, tag="cube_src_tex", parent=tex_registry())
