"""Modulators on any slider (the second feature review's seventh, after
Chromatik's LFOs, envelopes and step sequencers): sliders of the effect moved
by something that runs on its own - a wave, the beat, a pattern of steps -
around where each slider is set, in the sim and so in the stream.

    mods = modulators(app)       # [{"id", "keys", "kind", "shape", "sync", "period", "hz", "depth", "decay", "steps", "on"}]
    apply(app)                   # each frame, before the engine's step: the sliders moved
    offset(m, pos, since, cs)    # one modulator's push, `pos` cycles into its wave, `since` the last beat
    targets(app)                 # [(label, target)]: each modulator's rate, depth, shape, on/off and restart
    set_target(app, t, f)        # one of those set from a control (0..1), as MIDI, a pad or the phone does

A modulator moves one slider or several (`keys`) by the same wave, each by
`depth` of 255 of its own range. It does not take a slider over: whatever
sets the slider - a drag, a step of the show, a ramp, MIDI, a pad - sets the
place it moves around (the value it finds there that is not the one it
wrote last). Taken away or off, the slider is left where it was set.

The kinds:
  lfo     a wave (sine, triangle, saw up or down, square, random), swinging
          `depth` either way of the slider's place
  beat    on each beat a push of `depth` upward, eased in over 140 ms (a
          beat moves a pattern, it does not jump it) and let go over `decay`
  steps   a pattern of up to 16 levels, eased from one to the next over 50 ms

Its rate: synced (`sync`, the default) a wave or a step every `period` beats
of the tempo; free, `hz` of them a second. Each keeps where it is in its wave
(its phase) and moves on from there, so a rate turned while it runs never
jumps it; a synced one then eases back onto the beat grid, its speed held to
within a quarter of its own, nothing jumping. A restart puts it back to its
start and the grid's start to now.
"""
