def _draw_scopes(app):
    """Each row's scope drawn again: its last two seconds of levels, a gap where it was not running."""
    if not getattr(app, "_mod_dialog_built", False):
        return
    import dearpygui.dearpygui as dpg
    from native import chrome
    from native.typeface import px
    if not dpg.does_item_exist(TAG) or not dpg.is_item_shown(TAG):
        return
    w, h = px(SCOPE_W), px(SCOPE_H)
    for i, m in enumerate(modulators(app)):
        tag = f"mod_scope_{i}"
        if not dpg.does_item_exist(tag):
            continue
        dpg.delete_item(tag, children_only=True)
        dpg.draw_rectangle((0, 0), (w, h), color=chrome.DIM[:3] + (60,), parent=tag)
        vals = history(app, m["id"])
        run = []
        for k, v in enumerate(vals):
            if v is None:
                if len(run) > 1:
                    dpg.draw_polyline(run, color=chrome.ACCENT, thickness=px(1.5), parent=tag)
                run = []
                continue
            run.append((w * k / max(1, SCOPE_N - 1), h - 2 - (h - 4) * float(v)))
        if len(run) > 1:
            dpg.draw_polyline(run, color=chrome.ACCENT, thickness=px(1.5), parent=tag)


def sync_dialog(app):
    """The dialog's widgets as the modulators are now (a pad, MIDI or the phone turned one)."""
    if not getattr(app, "_mod_dialog_built", False):
        return
    import dearpygui.dearpygui as dpg
    from native import num
    if not dpg.does_item_exist(TAG) or not dpg.is_item_shown(TAG) or num.busy():
        return
    for i, m in enumerate(modulators(app)):
        for tag, v in ((f"mod_on_{i}", bool(m.get("on", True))), (f"mod_shape_{i}", m.get("shape", "sine")),
                       (f"mod_period_{i}", _beats(m.get("period", 4)))):
            if dpg.does_item_exist(tag) and dpg.get_value(tag) != v:
                dpg.set_value(tag, v)
        nums = [(f"mod_hz_{i}", float(m.get("hz", 0.5))), (f"mod_depth_{i}", int(m.get("depth", 96)))]
        nums += [(f"mod_amt_{i}_{j}", amount(m, k)) for j, k in enumerate(m.get("keys") or ())]
        for tag, v in nums:
            if dpg.does_item_exist(tag):
                num.set(tag, v)


def _beats(p):
    p = float(p)
    return f"{int(p)} beat{'s' if p != 1 else ''}" if p >= 1 else f"1/{int(round(1 / p))} beat"


def _unbeats(words):
    w = words.split()[0]
    return 1.0 / float(w.split("/")[1]) if "/" in w else float(w)


