def apply(app):
    """Each frame: every modulator's sliders set to their places plus its push. A slider's place is what it finds
    there when that is not what it wrote last (something else set it since)."""
    from native import clock
    now = clock.now()
    _flush(app, now)
    mods = modulators(app)
    st = app.__dict__.setdefault("_mod_state", {})
    if st.get("project", app.project) is not app.project:     # another project opened: nothing of the last one's
        reset(app)                                          # (its places, phases, held notes) carried into this one
        st = app._mod_state
    if getattr(app, "_mod_moved", False):
        app._mod_moved = False
        sync_dialog(app)
    if not mods and not st:
        return
    st["project"] = app.project
    eng = app.eng
    bpm = tempo(app)
    if "beats" not in st:
        st["beats"], st["at"] = 0.0, now
    dt = max(0.0, now - st["at"])
    edt = min(GAP_MAX_S, dt)
    st["beats"] += dt * bpm / 60.0
    st["at"] = now
    last_hit = getattr(app, "last_hit_at", None)
    since = None if last_hit is None else now - last_hit
    grid = getattr(app, "_vj_grid_beat_at", None)                # the VJ running on its bar grid: its beat
    if grid is not None and now - getattr(app, "_vj_at", -1e9) < 0.25:
        since = now - grid
    beat_at = None if since is None else now - since         # a beat since the last frame: one later than the last
    prev = st.get("beat_at")                                 # seen (the VJ's grid beat is set earlier in the frame,
    if beat_at is None:                                      # so not one within this frame's dt); at the start, only
        hit = False                                          # one that is fresh, not an old one
    elif prev is None:
        hit = since <= dt + 1e-3
    else:
        hit = beat_at > prev + 1e-4
    st["beat_at"] = beat_at
    sound = None
    ph = st.setdefault("phase", {})
    push = {}
    levels = st["level"] = {}
    for m0 in mods:
        m = _eff(app, m0)
        kind = m.get("kind", "lfo")
        pos = _advance(m, ph, st["beats"], dt, bpm) if kind in ("lfo", "steps") else 0.0
        held = gated(app, m["id"])
        lv = None
        if kind == "env":
            e = st.setdefault("env", {}).setdefault(m["id"], [0.0, "off"])
            if m.get("fire") == "beat" and hit and m.get("on", True):
                e[1] = "a"                                  # each beat: up over its attack, down over its release
                st.setdefault("vel", {})[m["id"]] = 1.0
            lv = _env(m, e, edt, held)
            if e[1] == "off":
                continue                                    # silent: its sliders at their places
            if m.get("vel", True):
                lv *= st.get("vel", {}).get(m["id"], 1.0)
        elif kind == "audio":
            if sound is None:
                sound = _sound(app)
            lv = _follow(m, st.setdefault("aud", {}).setdefault(m["id"], [0.0, 0.0]), sound, edt)
        if not m.get("on", True) or (kind in ("lfo", "steps") and m.get("start") == "held" and not held):
            continue
        d = float(m.get("depth", 0))
        cs = cycle_s(m, bpm)
        keys = [k for k in dict.fromkeys(m.get("keys") or ()) if not str(k).startswith(f"m{m['id']}.")]
        unit = len(_steps(m)) if kind == "steps" else 1.0       # a share of a wave, in its cycles
        spread = float(m.get("spread", 0.0)) / max(1, len(keys))

        def off_at(j):
            if lv is not None:
                return d * lv
            return offset(m, pos + (float(m.get("phase", 0.0)) + j * spread) * unit, since, cs)
        o0 = off_at(0)
        levels[m["id"]] = (lv if lv is not None else max(0.0, min(1.0, o0 / d + (0.0 if kind == "beat" else 0.5)))
                           if d > 0 else 0.5)                  # where its wave is, 0..1 (a pad's light pulses with it)
        for j, k in enumerate(keys):
            if _get(app, k) is None:
                continue
            off = o0 if j == 0 else off_at(j)
            push[k] = push.get(k, 0.0) + off * amount(m0, k) * hi(k) / 255.0   # depth of 255 of its own range
    for dd in (ph, st.get("env", {}), st.get("gate", {}), st.get("aud", {}), st.get("vel", {}), st.get("hist", {})):
        for i in [i for i in dd if find(app, i) is None]:      # a modulator gone: its phase, level and holders too
            del dd[i]
    changed = False
    places = st.setdefault("places", {})
    live = st.setdefault("live", {})                        # what each modulated one is moved to now (a pad shows it)
    for k in list(dict.fromkeys([*push, *places])):
        cur = _get(app, k)
        if cur is None:                                     # nothing there to move any more (its modulator gone)
            places.pop(k, None)
            live.pop(k, None)
            _unset(app, k)
            continue
        written = places.get(k)
        if k in push:
            if written is None or cur != written[1]:
                base = cur                                  # set since by something else: its new place
            else:
                base = written[0]
            v = int(round(min(hi(k), max(0, base + push[k]))))
            if k not in FX_KEYS and v == cur:
                _unset(app, k)                              # a push of nothing: the knob its own (a kept-apart
            elif v != cur:                                  # one held what it was moved to last)
                changed |= _set(app, k, v)
            places[k] = (base, _get(app, k))                # as it reads back (a knob of whole steps rounds it)
            live[k] = v
        elif written is not None:                           # no longer modulated: left at its place
            live.pop(k, None)
            if k in FX_KEYS:
                if cur == written[1] and cur != written[0]:
                    changed |= _set(app, k, written[0])
            else:
                _unset(app, k)
            del places[k]
    if now - st.get("hist_at", -1e9) >= 1.0 / SCOPE_HZ:
        st["hist_at"] = now
        hist = st.setdefault("hist", {})
        for m in mods:
            hist.setdefault(m["id"], deque(maxlen=SCOPE_N)).append(levels.get(m["id"]))
        _draw_scopes(app)
    if not mods:
        app._mod_state = {}
        app._vj_mod, app._mod_over = {}, {}
    if changed:
        eng.push()


def _vj_key(k):
    i, knob = k[2:].split(".", 1)
    return int(i), knob


def _get(app, k):
    """A target's value now, 0..hi(k), or None when there is none to move. A VJ knob's, a crossfader's or a
    modulator setting's is its own - its place: what a modulator moves it to is kept apart (_set), never in the
    project's options."""
    if k in FX_KEYS:
        return app.eng.fx.get(k) if k in app.eng.fx else None
    if k in VJ_KEYS:
        from native import vj
        i, knob = _vj_key(k)
        return int(round(vj.knob_get(app, i, knob) * 255))
    if k in MIX_KEYS:
        try:
            from native import mixer, vj
            o = vj.options(app) if k == "vj.fader" else mixer.options(app)
            return int(round(float(o.get("fader", 0.0)) * 255))
        except Exception:
            return None
    mk = _mkey(k)
    if mk is not None:
        m = find(app, mk[0])
        if m is None:
            return None
        return int(round(float(_scened(app, m).get("depth", 0)) if mk[1] == "depth" else _rate_f(m) * 255))
    return None


def _set(app, k, v):
    """A target set; True when the engine has to be told."""
    if k in FX_KEYS:
        app.eng.fx[k] = int(v)
        return True
    if k in VJ_KEYS:
        from native import vj
        i, knob = _vj_key(k)
        lo, hi_ = next((a, b) for kk, a, b in vj.KNOBS if kk == knob)
        app.__dict__.setdefault("_vj_mod", {})[(i, knob)] = lo + (hi_ - lo) * max(0.0, min(1.0, v / 255.0))
        return False
    app.__dict__.setdefault("_mod_over", {})[k] = max(0.0, min(1.0, v / 255.0))   # a fader's, a modulator's
    return False


def _unset(app, k):
    """What a modulator moved a kept-apart target to let go: it is its own again."""
    if k in VJ_KEYS:
        getattr(app, "_vj_mod", {}).pop(_vj_key(k), None)
    else:
        getattr(app, "_mod_over", {}).pop(k, None)


def over(app, key):
    """What the modulators move a crossfader ("vj.fader", "mix.fader") to now, 0..1, or None when none does."""
    return (getattr(app, "_mod_over", None) or {}).get(key)


def unmodulated(app, key, v):
    """An effect slider's value `v` (what it holds now) without the modulators' push: its place while it still holds
    what they wrote last, else v itself (set since - by the hand, by playback). A show's take records this, not the
    wave (played back with the modulator on top, the wave was there twice)."""
    w = (getattr(app, "_mod_state", {}) or {}).get("places", {}).get(key)
    return w[0] if w is not None and v == w[1] else v


def place(app, key):
    """The value a modulated slider moves around (what the slider was set to), or None when it is not."""
    w = (getattr(app, "_mod_state", {}) or {}).get("places", {}).get(key)
    return None if w is None else w[0]


def key_of(t):
    """The modulators' name for a control's target (an effect slider, a VJ deck's knob, a crossfader, a
    modulator's depth or rate), or None for one they cannot move."""
    k = (t or {}).get("kind")
    if k == "fx" and t.get("key") in FX_KEYS:
        return t["key"]
    if k == "vj_knob":
        key = f"vj{int(t.get('deck', 0))}.{t.get('key')}"
        return key if key in VJ_KEYS else None
    if k == "vj_fader":
        return "vj.fader"
    if k == "mixer":
        return "mix.fader"
    if k == "mod" and t.get("key") in MOD_PARAMS:
        return f"m{int(t.get('id', 0))}.{t['key']}"
    return None


def on_key(app, key):
    """The modulators moving `key`, in their order."""
    return [m for m in modulators(app) if key in (m.get("keys") or ())]


def swing(app, key):
    """How far the modulators on `key` move it now: (lowest, highest, where it is) in its own steps (0..hi(key)),
    or None when none that is on moves it. A wave swings depth around the place, a step pattern from its lowest
    level to its highest, the beat, an envelope and the sound up by depth from it - each through its amount (a
    negative one the other way)."""
    lo = up = 0.0
    any_ = False
    for m in on_key(app, key):
        m = _scened(app, m)
        if not m.get("on", True):
            continue
        any_ = True
        d = float(m.get("depth", 0)) * hi(key) / 255.0
        kind = m.get("kind", "lfo")
        if kind in ("beat", "env", "audio"):
            a, b = 0.0, d
        elif kind == "steps":
            lv = _steps(m)
            a, b = d * (min(lv) - 0.5), d * (max(lv) - 0.5)
        else:
            a, b = -d / 2.0, d / 2.0
        f = amount(m, key)
        lo += min(a * f, b * f)
        up += max(a * f, b * f)
    w = (getattr(app, "_mod_state", {}) or {}).get("places", {}).get(key)
    if not any_ or w is None:
        return None
    clamp = lambda v: max(0.0, min(float(hi(key)), v))          # noqa: E731
    now = (app._mod_state.get("live") or {}).get(key, w[0])
    return clamp(w[0] + lo), clamp(w[0] + up), float(now)


def attach(app, key):
    """A new wave on `key` (the pad editor's + LFO): synced, its depth the default."""
    return add(app, key=key)


def detach(app, m, key):
    """`key` no longer moved by modulator m; m taken away when it moved nothing else."""
    keys = m.get("keys") or []
    if key in keys:
        keys.remove(key)
    (m.get("amt") or {}).pop(key, None)
    if not keys:
        _drop(app, m)
    app.project.save()
    refresh(app)


def set_amount(app, mid, key, a):
    """How much of modulator mid's depth moves `key`, -1..1 (the pad editor's, the dialog's): saved once left alone."""
    from native import clock
    m = find(app, mid)
    if m is None:
        return
    amt = m.get("amt")
    if not isinstance(amt, dict):
        amt = m["amt"] = {}
    amt[key] = round(max(-1.0, min(1.0, float(a))), 3)
    app._mod_moved = True
    app._mod_save_at = (clock.now(), app.project)


def brief(m):
    """A modulator in a few words: "sine, 4 beats", "steps, 2 Hz", "on the beat", "the bass"."""
    kind = m.get("kind", "lfo")
    if kind == "beat":
        return "on the beat"
    if kind == "env":
        return "envelope" + (", on each beat" if m.get("fire") == "beat" else "")
    if kind == "audio":
        return dict(BANDS).get(m.get("band", "bass"), "the sound")
    what = m.get("shape", "sine") if kind == "lfo" else "steps"
    feel = m.get("feel", "straight")
    rate = (_beats(m.get("period", 4)) + (f" {dict((k, w) for k, _, w in FEELS)[feel]}" if feel != "straight" else "")
            if m.get("sync", True) else f"{float(m.get('hz', 0.5)):g} Hz")
    start = m.get("start", "free")
    return f"{what}, {rate}" + (f", {dict(STARTS)[start]}" if start in ("held", "press") else "")


def plays(m):
    """Whether a play target does anything for m: an envelope, or a wave or steps set to run while held or to
    restart on a press."""
    kind = m.get("kind", "lfo")
    return kind == "env" or (kind in ("lfo", "steps") and m.get("start", "free") in ("held", "press"))


# --- kept with a VJ preset (the modulators on its deck's knobs) and with a show step (which run, how deep) ----------
def deck_mods(app, i):
    """Copies of the modulators that move only deck i's knobs, as a preset keeps them: their keys "vj*.<knob>", no
    id (made again on whichever deck the preset is loaded onto)."""
    pre, out = f"vj{int(i)}.", []
    for m in modulators(app):
        keys = m.get("keys") or []
        if keys and all(str(k).startswith(pre) for k in keys):
            c = json.loads(json.dumps(m))
            for k in ("id", "preset_deck"):
                c.pop(k, None)
            c["keys"] = ["vj*." + k[len(pre):] for k in keys]
            c["amt"] = {"vj*." + k[len(pre):]: v for k, v in (m.get("amt") or {}).items() if str(k).startswith(pre)}
            out.append(c)
    return out


def _same_mod(a, b):
    """Two modulators alike but for their ids, seeds and where they came from."""
    skip = ("id", "seed", "preset_deck")
    return {k: v for k, v in a.items() if k not in skip} == {k: v for k, v in b.items() if k not in skip}


def put_deck_mods(app, i, mods):
    """A preset's modulators onto deck i, in place of the ones the last preset loaded there brought (preset_deck);
    the ones made by hand are left - and one made by hand that the preset kept (saved from this deck) is not made a
    second time beside itself. A preset without any takes the last one's off too: they went with its look. Another
    modulator moving the depth or rate of one taken off moves the one that takes its place (in their order), or
    nothing when there is none. One save, one undo step."""
    pre = f"vj{int(i)}."
    all_ = modulators(app)
    old = [m for m in all_ if m.get("preset_deck") == int(i)]
    for m in old:
        all_.remove(m)
        _forget(app, m["id"])
    made = []
    for c in mods or ():
        if not isinstance(c, dict):
            continue                                        # a damaged preset's
        c = _fixed(json.loads(json.dumps(c)))
        c.pop("seed", None)                                 # a random wave of its own on each deck it is loaded onto
        keys = [pre + str(k)[4:] for k in c.get("keys") or () if str(k).startswith("vj*.") and pre + str(k)[4:] in VJ_KEYS]
        if not keys:
            continue
        c["amt"] = {pre + str(k)[4:]: v for k, v in (c.get("amt") or {}).items() if str(k).startswith("vj*.")}
        c.update(keys=keys, preset_deck=int(i))
        if any(_same_mod(c, m) for m in modulators(app) if m.get("preset_deck") is None):
            continue                                        # the hand-made one it was saved from: already here
        made.append(add(app, _quiet=True, **c))
    moved = {f"m{a['id']}.{p}": (f"m{b['id']}.{p}" if b is not None else None)
             for k, a in enumerate(old) for b in [made[k] if k < len(made) else None] for p in MOD_PARAMS}
    for x in modulators(app):
        if moved.keys() & set(x.get("keys") or ()):
            amt = x.get("amt") or {}
            x["keys"] = [moved.get(k, k) for k in x["keys"] if moved.get(k, k) is not None]
            x["amt"] = {moved.get(k, k): v for k, v in amt.items() if moved.get(k, k) is not None}
    if old or made:
        app.project.save()
        refresh(app)
    return len(made)


def scene(app):
    """What a VJ show step keeps of the modulators: each one's on or off and depth, by id - as the step playing has
    them while a show plays one (what shows is what is kept, as with its decks)."""
    out = {}
    for m in modulators(app):
        m = _scened(app, m)
        out[str(m["id"])] = {"on": bool(m.get("on", True)), "depth": int(round(float(m.get("depth", 0))))}
    return out


def play_scene(app, sc):
    """A show step's modulators while the show plays it: each one on or off and as deep as the step kept it - over
    the modulators, never saved into them (None: let go, each as it is set)."""
    app._mod_scene = {int(k): dict(v) for k, v in sc.items()} if sc else None
    app._mod_moved = True


def load_scene(app, sc):
    """A step's modulators loaded into the sim (not playing): into the modulators themselves, saved."""
    changed = False
    for k, v in (sc or {}).items():
        m = find(app, int(k))
        if m is not None:
            m.update(on=bool(v.get("on", True)), depth=int(v.get("depth", m.get("depth", 0))))
            changed = True
    if changed:
        app.project.save()
        refresh(app)


