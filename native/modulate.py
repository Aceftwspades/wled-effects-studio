def undo(app):
    """The modulators' last change taken back (the dialog's Undo; the pads' takes it back too when it was last)."""
    if not app.project.undo("modulators"):
        gp = getattr(app, "gp", None)
        if gp is not None:
            gp.status("nothing to undo in the modulators")
        return False
    app._mod_moved = True
    refresh(app)
    return True


def add(app, **kw):
    """One more modulator: on the first slider without one (or `keys`, or `key` for one), a wave unless said
    otherwise; an id of its own."""
    mods = modulators(app)
    used = {k for m in mods for k in (m.get("keys") or ())}
    m = dict(DEFAULT, steps=list(DEFAULT["steps"]), amt={}, seed=random.randrange(1 << 20))   # a random wave of its own
    m["keys"] = [next((k for k in FX_KEYS + VJ_KEYS if k not in used), "sx")]
    if "key" in kw:
        kw["keys"] = [kw.pop("key")]
    m.update(kw)
    m["keys"] = list(m["keys"])
    m["id"] = 1 + max((int(x.get("id", 0)) for x in mods), default=0)
    mods.append(m)
    app.project.save()
    refresh(app)
    return m


def edit(app, i, **kw):
    mods = modulators(app)
    if 0 <= i < len(mods):
        mods[i].update(kw)
        app.project.save()
        if {"kind", "sync", "shape", "start", "fire"} & set(kw):
            refresh(app)


def set_key(app, i, j, key):
    """Modulator i's j-th slider set to `key` (one already in its list: the row left as it was); its amount goes
    with it."""
    mods = modulators(app)
    if 0 <= i < len(mods):
        keys = mods[i].setdefault("keys", ["sx"])
        if not keys and j == 0:
            keys.append(key)
            app.project.save()
        elif 0 <= j < len(keys) and key not in keys:
            amt = mods[i].get("amt")
            if isinstance(amt, dict) and keys[j] in amt:
                amt[key] = amt.pop(keys[j])
            keys[j] = key
            app.project.save()
        refresh(app)


def add_key(app, i):
    """One more slider for modulator i: the first it does not move yet."""
    mods = modulators(app)
    if 0 <= i < len(mods):
        keys = mods[i].setdefault("keys", ["sx"])
        k = next((k for k in FX_KEYS + VJ_KEYS if k not in keys), None)
        if k is not None:
            keys.append(k)
            app.project.save()
        refresh(app)


def remove_key(app, i, j):
    mods = modulators(app)
    if 0 <= i < len(mods):
        keys = mods[i].setdefault("keys", ["sx"])
        if 1 <= j < len(keys):
            (mods[i].get("amt") or {}).pop(keys[j], None)
            del keys[j]
            app.project.save()
        refresh(app)


def _drop(app, m):
    """Modulator m taken away, and with it what the others moved of it (its depth, its rate)."""
    mods = modulators(app)
    if m in mods:
        mods.remove(m)
    mine = {f"m{m['id']}.{p}" for p in MOD_PARAMS}
    for x in mods:
        if mine & set(x.get("keys") or ()):
            x["keys"] = [k for k in x["keys"] if k not in mine]
            for k in mine:
                (x.get("amt") or {}).pop(k, None)


def remove(app, i):
    mods = modulators(app)
    if 0 <= i < len(mods):
        _drop(app, mods[i])
        app.project.save()
        refresh(app)


def _set_step(app, i, j, v):
    mods = modulators(app)
    if 0 <= i < len(mods):
        mods[i].setdefault("steps", list(DEFAULT["steps"]))[j] = round(float(v), 3)
        app.project.save()


def _steps_len(app, i, d):
    mods = modulators(app)
    if 0 <= i < len(mods):
        st = mods[i].setdefault("steps", list(DEFAULT["steps"]))
        if d > 0 and len(st) < 16:
            st.append(0.0)
        elif d < 0 and len(st) > 1:
            st.pop()
        app.project.save()
        refresh(app)
