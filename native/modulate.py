def _gate(app, m, src, down, vel=1.0):
    """Modulator m's play target pressed (down, at `vel` 0..1: a note's velocity) or let go from `src`. Opened: an
    envelope starts its attack, a wave or steps that run while held or restart on a press start from the top. Its
    last holder gone: an envelope releases (in apply)."""
    st = app.__dict__.setdefault("_mod_state", {})
    holders = st.setdefault("gate", {}).setdefault(m["id"], set())
    was = bool(holders)
    (holders.add if down else holders.discard)(src)
    if holders and not was:
        st.setdefault("vel", {})[m["id"]] = max(0.0, min(1.0, float(vel)))
        if m.get("kind") == "env" or m.get("start", "free") in ("held", "press"):
            restart(app, m)


def _scened(app, m):
    """Modulator m with the show step playing's on/off and depth for it (play_scene), m itself without one."""
    sc = (getattr(app, "_mod_scene", None) or {}).get(m.get("id"))
    if not sc:
        return m
    return dict(m, on=bool(sc.get("on", m.get("on", True))), depth=float(sc.get("depth", m.get("depth", 0))))


def _eff(app, m):
    """Modulator m as it runs now: on and its depth as a show step playing has them, its depth and rate as other
    modulators move them (m itself when nothing does)."""
    over = getattr(app, "_mod_over", None) or {}
    d, r = over.get(f"m{m['id']}.depth"), over.get(f"m{m['id']}.rate")
    s = _scened(app, m)
    if d is None and r is None:
        return s
    e = dict(s)
    if d is not None:
        e["depth"] = d * 255.0
    if r is not None:
        if e.get("sync", True):                             # off the grid anyway: swept smoothly along the beat
            hi_p, lo_p = math.log2(PERIODS[-1]), math.log2(PERIODS[0])   # lengths, not stepped from one to the next
            e["period"] = 2.0 ** (hi_p - (hi_p - lo_p) * max(0.0, min(1.0, r)))
        else:
            _rate_set(e, r)
        e["_unlocked"] = True
    return e


