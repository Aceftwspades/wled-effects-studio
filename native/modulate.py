def _labels(app):
    """{key: its name}: the current effect's sliders, the VJ knobs and faders, each modulator's depth and rate."""
    m = app.eng.meta[app.eng.idx]
    generic = {"sx": "Speed", "ix": "Intensity", "c1": "Custom 1", "c2": "Custom 2", "c3": "Custom 3"}
    out = {}
    for i, k in enumerate(FX_KEYS):
        lab = (m["labels"][i] if i < len(m["labels"]) else "").strip()
        lab = lab if lab and lab != "!" else generic[k]
        out[k] = f"{lab} ({generic[k]})" if lab in out.values() else lab   # two of one name: the picker told apart
    from native import vj
    for k in VJ_KEYS:
        i, knob = _vj_key(k)
        out[k] = f"VJ {vj.LETTERS[i]} {vj.KNOB_WORDS[knob]}"
    out.update({"vj.fader": "VJ crossfader", "mix.fader": "Mixer fader"})
