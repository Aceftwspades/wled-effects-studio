def hi(key):
    return 31 if key == "c3" else 255


def _mkey(k):
    """(id, setting) of another modulator's setting "m<id>.depth" / "m<id>.rate", else None."""
    if not isinstance(k, str) or not k.startswith("m") or "." not in k:
        return None
    i, p = k[1:].split(".", 1)
    return (int(i), p) if i.isdigit() and p in MOD_PARAMS else None


def _rand(seed, k):
    return random.Random(seed * 1000003 + k).random()


def wave(shape, phase, cycle=0, seed=1, width=0.5):
    """0..1 of a wave at `phase` (0..1) of its `cycle`th period; `width` a square's high share and where a
    triangle peaks."""
    p = phase % 1.0
    w = max(0.02, min(0.98, float(width)))
    if shape == "triangle":
        return p / w if p < w else (1.0 - p) / (1.0 - w)
    if shape == "saw up":
        return p
    if shape == "saw down":
        return 1.0 - p
    if shape == "square":
        return 1.0 if p < w else 0.0
    if shape == "random":                          # a new level each period, eased into from the last
        a, b = _rand(seed, cycle - 1), _rand(seed, cycle)
        u = min(1.0, p * 4.0)
        return a + (b - a) * (0.5 - 0.5 * math.cos(math.pi * u))
    if shape == "s&h":                             # a new level each period, held to the next
        return _rand(seed, cycle)
    return 0.5 - 0.5 * math.cos(2.0 * math.pi * p)   # sine, from its low point


def _per(m):
    """A synced wave's (or step's) length in beats: its period through its feel (triplets two thirds, dotted half
    as long again)."""
    mult = next((f for k, f, _ in FEELS if k == m.get("feel", "straight")), 1.0)
    return max(1e-3, float(m.get("period", 4)) * mult)


def cycle_s(m, bpm):
    """A wave's (or a step's) length in seconds: `period` beats of the tempo synced, else 1 / `hz`."""
    if m.get("sync", True):
        return _per(m) * 60.0 / bpm
    return 1.0 / max(1e-3, float(m.get("hz", 0.5)))


def offset(m, pos, since, cs=0.5):
    """The push one modulator gives: `pos` the cycles of its wave gone by (continuous; a step pattern's steps),
    `since` the seconds since the last beat (None: none yet), `cs` a cycle's seconds. Slider steps of 255, either
    way."""
    depth = float(m.get("depth", 0))
    kind = m.get("kind", "lfo")
    if kind == "beat":
        if since is None or since < 0:
            return 0.0
        decay = max(0.02, float(m.get("decay", 0.4)))
        if since < ATTACK_S:
            e = 0.5 - 0.5 * math.cos(math.pi * since / ATTACK_S)
        else:
            e = math.exp(-(since - ATTACK_S) / decay * 3.0)
        return depth * e
    k = int(math.floor(pos))
    if kind == "steps":
        lv = _steps(m)
        cur, prev = lv[k % len(lv)], lv[(k - 1) % len(lv)]
        u = min(1.0, (pos - k) * cs / STEP_SLEW_S)       # seconds into this step against the ease
        return depth * ((prev + (cur - prev) * u) - 0.5)
    return depth * (wave(m.get("shape", "sine"), pos, k, seed=int(m.get("seed", 7)),
                         width=float(m.get("width", 0.5))) - 0.5)


def _steps(m):
    return [float(v) for v in (m.get("steps") or [0.5])][:16] or [0.5]


def amount(m, key):
    """How much of its depth modulator m moves `key` by, -1..1 (a negative one the other way)."""
    try:
        return max(-1.0, min(1.0, float((m.get("amt") or {}).get(key, 1.0))))
    except (TypeError, ValueError):
        return 1.0


def modulators(app):
    """The project's modulators, each with an id of its own and a list of targets (one made before either: its
    "key" a list of one, the next id)."""
    mods = app.project.options.setdefault("modulators", [])
    for m in mods:
        if "keys" not in m:
            m["keys"] = [m.pop("key", "sx")]
        if "id" not in m:
            m["id"] = 1 + max((int(x.get("id", 0)) for x in mods), default=0)
    return mods


def find(app, mid):
    return next((m for m in modulators(app) if m.get("id") == mid), None)


def tempo(app):
    """The beats a minute the waves run at: the show's tempo when it has one, else the synth's."""
    try:
        from native import sequence_ui
        bpm = float(sequence_ui._steps(app).get("bpm") or 0)
    except Exception:
        bpm = 0.0
    if bpm <= 0:
        bpm = float(getattr(getattr(app, "syn", None), "bpm", 120) or 120)
    return max(20.0, min(300.0, bpm))


def _advance(m, ph, beats, dt, bpm):
    """One modulator's phase moved on by dt seconds at its rate; a synced one eased back onto the beat grid (counted
    from its last restart), never faster or slower than LOCK_SPEED of its own speed - unless another modulator is
    moving its rate (then it runs free of the grid). ph: {id: [cycles, grid's 0]}."""
    sync = m.get("sync", True)
    per = _per(m)
    p = ph.get(m["id"])
    if p is None:
        p = ph[m["id"]] = [beats / per if sync else 0.0, 0.0]
    step = dt / cycle_s(m, bpm)
    p[0] += step
    if sync and not m.get("_unlocked"):
        d = ((beats - p[1]) / per - p[0] + 0.5) % 1.0 - 0.5     # how far off the grid, -0.5..0.5 of a cycle
        lim = LOCK_SPEED * step
        p[0] += max(-lim, min(lim, d))
    return p[0]


def restart(app, m):
    """A modulator back to the start of its wave, and a synced one's grid counted from now."""
    st = app.__dict__.setdefault("_mod_state", {})
    st.setdefault("phase", {})[m["id"]] = [0.0, float(st.get("beats", 0.0))]
    if m.get("kind") == "env":
        st.setdefault("env", {})[m["id"]] = [st.get("env", {}).get(m["id"], [0.0])[0], "a"]


def _env_param(m, k):
    """An envelope's attack, decay (kept as env_decay: "decay" is the beat's), sustain or release, in its range."""
    _, d, lo, hi_ = next(e for e in ENV if e[0] == k)
    return max(lo, min(hi_, float(m.get("env_decay" if k == "decay" else k, d))))


def _env(m, e, dt, gated):
    """An envelope moved on by dt: e is [level 0..1, stage] - "a"ttack up to 1 over its attack, "d"ecay down to the
    sustain level while held, "s"ustain there, "r"elease down to 0 over its release once let go, then "off". One
    let go (or only restarted, or fired by the beat) during its attack goes from its peak straight to release."""
    lv, sg = e
    sus = _env_param(m, "sustain")
    if sg == "a":
        need = (1.0 - lv) * _env_param(m, "attack")        # seconds left to the peak
        if dt < need:
            lv, dt = lv + dt / _env_param(m, "attack"), 0.0
        else:                                           # past it this frame: only what is left goes on down
            lv, dt, sg = 1.0, dt - need, ("d" if gated else "r")
    if sg in ("d", "s") and not gated:
        sg = "r"
    elif sg == "d":
        lv -= dt * (1.0 - sus) / _env_param(m, "decay")
        if lv <= sus:
            lv, sg = sus, "s"
    elif sg == "s":
        lv = sus
    if sg == "r":
        lv -= dt / _env_param(m, "release")
        if lv <= 0.0:
            lv, sg = 0.0, "off"
    e[0], e[1] = lv, sg
    return lv


def _sound(app):
    """{"level", "bass", "mid", "treb"} 0..1 of what the effects hear now (vj.sound's), or {} without any."""
    try:
        from native import vj
        b, m, t, lv, _ = vj.sound(app)
        return {"level": float(lv), "bass": float(b), "mid": float(m), "treb": float(t)}
    except Exception:
        return {}


def _follow(m, a, sound, dt):
    """An audio modulator's level 0..1: its band followed up over its attack and down over its release (a is
    [followed, loudest lately]); on auto level, against the loudest of the last few seconds."""
    raw = max(0.0, min(1.0, float(sound.get(m.get("band", "bass"), 0.0))))
    if dt > 0:
        tau = _env_param(m, "attack" if raw > a[0] else "release")
        a[0] += (raw - a[0]) * (1.0 - math.exp(-dt / tau))
        a[1] = max(a[0], a[1] * math.exp(-dt / AUTO_S))
    if m.get("auto", True):
        return min(1.0, a[0] / max(AUTO_FLOOR, a[1]))
    return min(1.0, a[0])


def level(app, mid):
    """Where a running modulator's wave (or envelope, or push) is now, 0..1; None when it is not running (off, an
    envelope silent, a wave that runs while held not held)."""
    return (getattr(app, "_mod_state", {}) or {}).get("level", {}).get(mid)


def history(app, mid):
    """Its last two seconds of levels (None where it was not running), oldest first, for a scope."""
    return list((getattr(app, "_mod_state", {}) or {}).get("hist", {}).get(mid, ()))


def gated(app, mid):
    """Whether something holds a modulator's play target (a pad, a MIDI note, the phone)."""
    return bool((getattr(app, "_mod_state", {}) or {}).get("gate", {}).get(mid))


def _gate(app, m, src, down, vel=1.0):
    """Modulator m's play target pressed (down, at `vel` 0..1: a note's velocity) or let go from `src`. Opened: an
    envelope starts its attack, a wave or steps that run while held or restart on a press start from the top. Its
    last holder gone: an envelope releases (in apply)."""
    st = app.__dict__.setdefault("_mod_state", {})
    holders = st.setdefault("gate", {}).setdefault(m["id"], set())
    was = bool(holders)
    (holders.add if down else holders.discard)(src)
    if holders and not was:
        st.setdefault("vel", {})[m["id"]] = max(0.0, min(1.0, float(vel)))
        if m.get("kind") == "env" or m.get("start", "free") in ("held", "press"):
            restart(app, m)


def _eff(app, m):
    """Modulator m as it runs now: its depth and rate as other modulators move them (m itself when none does)."""
    over = getattr(app, "_mod_over", None) or {}
    d, r = over.get(f"m{m['id']}.depth"), over.get(f"m{m['id']}.rate")
    if d is None and r is None:
        return m
    e = dict(m)
    if d is not None:
        e["depth"] = d * 255.0
    if r is not None:
        _rate_set(e, r)
        e["_unlocked"] = True
    return e


def apply(app):
    """Each frame: every modulator's sliders set to their places plus its push. A slider's place is what it finds
    there when that is not what it wrote last (something else set it since)."""
    from native import clock
    now = clock.now()
    _flush(app, now)
    mods = modulators(app)
    st = app.__dict__.setdefault("_mod_state", {})
    if st.get("project", app.project) is not app.project:     # another project opened: nothing of the last one's
        st.clear()                                          # (its places, phases, held notes) carried into this one
        app._vj_mod, app._mod_over = {}, {}
    if getattr(app, "_mod_moved", False):
        app._mod_moved = False
        sync_dialog(app)
    if not mods and not st:
        return
    st["project"] = app.project
    eng = app.eng
    bpm = tempo(app)
    if "beats" not in st:
        st["beats"], st["at"] = 0.0, now
    dt = max(0.0, now - st["at"])
    st["beats"] += dt * bpm / 60.0
    st["at"] = now
    last_hit = getattr(app, "last_hit_at", None)
    since = None if last_hit is None else now - last_hit
    grid = getattr(app, "_vj_grid_beat_at", None)                # the VJ running on its bar grid: its beat
    if grid is not None and now - getattr(app, "_vj_at", -1e9) < 0.25:
        since = now - grid
    hit = since is not None and (st.get("since") is None or since < st["since"])   # a beat since the last frame
    st["since"] = since
    sound = None
    ph = st.setdefault("phase", {})
    push = {}
    levels = st["level"] = {}
    for n, m0 in enumerate(mods):
        if "seed" not in m0:                                # one made before seeds: its own, kept
            m0["seed"] = 7 + n * 7919
        m = _eff(app, m0)
        kind = m.get("kind", "lfo")
        pos = _advance(m, ph, st["beats"], dt, bpm) if kind in ("lfo", "steps") else 0.0
        held = gated(app, m["id"])
        lv = None
        if kind == "env":
            e = st.setdefault("env", {}).setdefault(m["id"], [0.0, "off"])
            if m.get("fire") == "beat" and hit and m.get("on", True):
                e[1] = "a"                                  # each beat: up over its attack, down over its release
                st.setdefault("vel", {})[m["id"]] = 1.0
            lv = _env(m, e, dt, held)
            if e[1] == "off":
                continue                                    # silent: its sliders at their places
            if m.get("vel", True):
                lv *= st.get("vel", {}).get(m["id"], 1.0)
        elif kind == "audio":
            if sound is None:
                sound = _sound(app)
            lv = _follow(m, st.setdefault("aud", {}).setdefault(m["id"], [0.0, 0.0]), sound, dt)
        if not m.get("on", True) or (kind in ("lfo", "steps") and m.get("start") == "held" and not held):
            continue
        d = float(m.get("depth", 0))
        cs = cycle_s(m, bpm)
        keys = [k for k in dict.fromkeys(m.get("keys") or ()) if not str(k).startswith(f"m{m['id']}.")]
        unit = len(_steps(m)) if kind == "steps" else 1.0       # a share of a wave, in its cycles
        spread = float(m.get("spread", 0.0)) / max(1, len(keys))

        def off_at(j):
            if lv is not None:
                return d * lv
            return offset(m, pos + (float(m.get("phase", 0.0)) + j * spread) * unit, since, cs)
        o0 = off_at(0)
        levels[m["id"]] = (lv if lv is not None else max(0.0, min(1.0, o0 / d + (0.0 if kind == "beat" else 0.5)))
                           if d > 0 else 0.5)                  # where its wave is, 0..1 (a pad's light pulses with it)
        for j, k in enumerate(keys):
            if _get(app, k) is None:
                continue
            off = o0 if j == 0 else off_at(j)
            push[k] = push.get(k, 0.0) + off * amount(m0, k) * hi(k) / 255.0   # depth of 255 of its own range
    for dd in (ph, st.get("env", {}), st.get("gate", {}), st.get("aud", {}), st.get("vel", {}), st.get("hist", {})):
        for i in [i for i in dd if find(app, i) is None]:      # a modulator gone: its phase, level and holders too
            del dd[i]
    changed = False
    places = st.setdefault("places", {})
    live = st.setdefault("live", {})                        # what each modulated one is moved to now (a pad shows it)
    for k in list(dict.fromkeys([*push, *places])):
        cur = _get(app, k)
        if cur is None:                                     # nothing there to move any more (its modulator gone)
            places.pop(k, None)
            live.pop(k, None)
            _unset(app, k)
            continue
        written = places.get(k)
        if k in push:
            if written is None or cur != written[1]:
                base = cur                                  # set since by something else: its new place
            else:
                base = written[0]
            v = int(round(min(hi(k), max(0, base + push[k]))))
            if v != cur:
                changed |= _set(app, k, v)
            places[k] = (base, _get(app, k))                # as it reads back (a knob of whole steps rounds it)
            live[k] = v
        elif written is not None:                           # no longer modulated: left at its place
            live.pop(k, None)
            if k in FX_KEYS:
                if cur == written[1] and cur != written[0]:
                    changed |= _set(app, k, written[0])
            else:
                _unset(app, k)
            del places[k]
    if now - st.get("hist_at", -1e9) >= 1.0 / SCOPE_HZ:
        st["hist_at"] = now
        hist = st.setdefault("hist", {})
        for m in mods:
            hist.setdefault(m["id"], deque(maxlen=SCOPE_N)).append(levels.get(m["id"]))
        _draw_scopes(app)
    if not mods:
        app._mod_state = {}
        app._vj_mod, app._mod_over = {}, {}
    if changed:
        eng.push()


def _vj_key(k):
    i, knob = k[2:].split(".", 1)
    return int(i), knob


def _get(app, k):
    """A target's value now, 0..hi(k), or None when there is none to move. A VJ knob's, a crossfader's or a
    modulator setting's is its own - its place: what a modulator moves it to is kept apart (_set), never in the
    project's options."""
    if k in FX_KEYS:
        return app.eng.fx.get(k) if k in app.eng.fx else None
    if k in VJ_KEYS:
        from native import vj
        i, knob = _vj_key(k)
        return int(round(vj.knob_get(app, i, knob) * 255))
    if k in MIX_KEYS:
        try:
            from native import mixer, vj
            o = vj.options(app) if k == "vj.fader" else mixer.options(app)
            return int(round(float(o.get("fader", 0.0)) * 255))
        except Exception:
            return None
    mk = _mkey(k)
    if mk is not None:
        m = find(app, mk[0])
        if m is None:
            return None
        return int(round(float(m.get("depth", 0)) if mk[1] == "depth" else _rate_f(m) * 255))
    return None


def _set(app, k, v):
    """A target set; True when the engine has to be told."""
    if k in FX_KEYS:
        app.eng.fx[k] = int(v)
        return True
    if k in VJ_KEYS:
        from native import vj
        i, knob = _vj_key(k)
        lo, hi_ = next((a, b) for kk, a, b in vj.KNOBS if kk == knob)
        app.__dict__.setdefault("_vj_mod", {})[(i, knob)] = lo + (hi_ - lo) * max(0.0, min(1.0, v / 255.0))
        return False
    app.__dict__.setdefault("_mod_over", {})[k] = max(0.0, min(1.0, v / 255.0))   # a fader's, a modulator's
    return False


def _unset(app, k):
    """What a modulator moved a kept-apart target to let go: it is its own again."""
    if k in VJ_KEYS:
        getattr(app, "_vj_mod", {}).pop(_vj_key(k), None)
    else:
        getattr(app, "_mod_over", {}).pop(k, None)


def over(app, key):
    """What the modulators move a crossfader ("vj.fader", "mix.fader") to now, 0..1, or None when none does."""
    return (getattr(app, "_mod_over", None) or {}).get(key)


def place(app, key):
    """The value a modulated slider moves around (what the slider was set to), or None when it is not."""
    w = (getattr(app, "_mod_state", {}) or {}).get("places", {}).get(key)
    return None if w is None else w[0]


def key_of(t):
    """The modulators' name for a control's target (an effect slider, a VJ deck's knob, a crossfader, a
    modulator's depth or rate), or None for one they cannot move."""
    k = (t or {}).get("kind")
    if k == "fx" and t.get("key") in FX_KEYS:
        return t["key"]
    if k == "vj_knob":
        key = f"vj{int(t.get('deck', 0))}.{t.get('key')}"
        return key if key in VJ_KEYS else None
    if k == "vj_fader":
        return "vj.fader"
    if k == "mixer":
        return "mix.fader"
    if k == "mod" and t.get("key") in MOD_PARAMS:
        return f"m{int(t.get('id', 0))}.{t['key']}"
    return None


def on_key(app, key):
    """The modulators moving `key`, in their order."""
    return [m for m in modulators(app) if key in (m.get("keys") or ())]


def swing(app, key):
    """How far the modulators on `key` move it now: (lowest, highest, where it is) in its own steps (0..hi(key)),
    or None when none that is on moves it. A wave swings depth around the place, a step pattern from its lowest
    level to its highest, the beat, an envelope and the sound up by depth from it - each through its amount (a
    negative one the other way)."""
    lo = up = 0.0
    any_ = False
    for m in on_key(app, key):
        if not m.get("on", True):
            continue
        any_ = True
        d = float(m.get("depth", 0)) * hi(key) / 255.0
        kind = m.get("kind", "lfo")
        if kind in ("beat", "env", "audio"):
            a, b = 0.0, d
        elif kind == "steps":
            lv = _steps(m)
            a, b = d * (min(lv) - 0.5), d * (max(lv) - 0.5)
        else:
            a, b = -d / 2.0, d / 2.0
        f = amount(m, key)
        lo += min(a * f, b * f)
        up += max(a * f, b * f)
    w = (getattr(app, "_mod_state", {}) or {}).get("places", {}).get(key)
    if not any_ or w is None:
        return None
    clamp = lambda v: max(0.0, min(float(hi(key)), v))          # noqa: E731
    now = (app._mod_state.get("live") or {}).get(key, w[0])
    return clamp(w[0] + lo), clamp(w[0] + up), float(now)


def attach(app, key):
    """A new wave on `key` (the pad editor's + LFO): synced, its depth the default."""
    return add(app, key=key)


def detach(app, m, key):
    """`key` no longer moved by modulator m; m taken away when it moved nothing else."""
    keys = m.get("keys") or []
    if key in keys:
        keys.remove(key)
    (m.get("amt") or {}).pop(key, None)
    if not keys:
        _drop(app, m)
    app.project.save()
    refresh(app)


def set_amount(app, mid, key, a):
    """How much of modulator mid's depth moves `key`, -1..1 (the pad editor's, the dialog's): saved once left alone."""
    from native import clock
    m = find(app, mid)
    if m is None:
        return
    amt = m.get("amt")
    if not isinstance(amt, dict):
        amt = m["amt"] = {}
    amt[key] = round(max(-1.0, min(1.0, float(a))), 3)
    app._mod_moved = True
    app._mod_save_at = (clock.now(), app.project)


def brief(m):
    """A modulator in a few words: "sine, 4 beats", "steps, 2 Hz", "on the beat", "the bass"."""
    kind = m.get("kind", "lfo")
    if kind == "beat":
        return "on the beat"
    if kind == "env":
        return "envelope" + (", on each beat" if m.get("fire") == "beat" else "")
    if kind == "audio":
        return dict(BANDS).get(m.get("band", "bass"), "the sound")
    what = m.get("shape", "sine") if kind == "lfo" else "steps"
    feel = m.get("feel", "straight")
    rate = (_beats(m.get("period", 4)) + (f" {dict((k, w) for k, _, w in FEELS)[feel]}" if feel != "straight" else "")
            if m.get("sync", True) else f"{float(m.get('hz', 0.5)):g} Hz")
    start = m.get("start", "free")
    return f"{what}, {rate}" + (f", {dict(STARTS)[start]}" if start in ("held", "press") else "")


def plays(m):
    """Whether a play target does anything for m: an envelope, or a wave or steps set to run while held or to
    restart on a press."""
    kind = m.get("kind", "lfo")
    return kind == "env" or (kind in ("lfo", "steps") and m.get("start", "free") in ("held", "press"))


# --- a modulator's settings as targets: MIDI's, the pads', the phone's -----------------------------------------------
def title(app, m, labs=None):
    """A modulator's name in lists: its number and what it moves ("Mod 2 (Speed + 1)")."""
    labs = _labels(app) if labs is None else labs
    keys = m.get("keys") or []
    what = labs.get(keys[0], keys[0]) if keys else "nothing"
    return f"Mod {m.get('id')} ({what}{f' + {len(keys) - 1}' if len(keys) > 1 else ''})"


def targets(app):
    """[(label, target)] for every modulator - only what does something for its kind: a rate (a wave, steps), its
    depth, a shape (a wave), on or off, a restart (a wave, steps, an envelope) and play (see plays)."""
    out = []
    try:
        labs = _labels(app)
    except Exception:
        labs = {}
    for m in modulators(app):
        name = title(app, m, labs)
        kind = m.get("kind", "lfo")
        params = [p for p in PARAMS if (p[0] != "rate" or kind in ("lfo", "steps")) and (p[0] != "shape" or kind == "lfo")]
        out += [(f"{name}: {w}", {"kind": "mod", "id": m["id"], "key": k}) for k, w in params]
        out.append((f"{name}: on or off", {"kind": "mod_on", "id": m["id"]}))
        if kind in ("lfo", "steps", "env"):
            out.append((f"{name}: {'fire its envelope' if kind == 'env' else 'restart its wave'}",
                        {"kind": "mod_restart", "id": m["id"]}))
        if plays(m):
            out.append((f"{name}: play (while held)", {"kind": "mod_gate", "id": m["id"]}))
    return out


def signature(app):
    """What the modulators' targets' labels depend on: their ids, what each moves, and what it is."""
    try:
        return tuple((m.get("id"), tuple(m.get("keys") or ()), m.get("kind"), m.get("start")) for m in modulators(app))
    except Exception:
        return ()


def _rate_f(m):
    """A modulator's rate as 0..1 of a control's travel: synced, along PERIODS (up the faster); free, along the log
    scale of HZ_LO..HZ_HI."""
    if m.get("sync", True):
        per = float(m.get("period", 4))
        i = min(range(len(PERIODS)), key=lambda j: abs(PERIODS[j] - per))
        return (len(PERIODS) - 1 - i) / (len(PERIODS) - 1)
    hz = max(HZ_LO, min(HZ_HI, float(m.get("hz", 0.5))))
    return math.log(hz / HZ_LO) / math.log(HZ_HI / HZ_LO)


def _rate_set(m, f):
    """A modulator's rate from 0..1 of a control's travel (the inverse of _rate_f)."""
    f = max(0.0, min(1.0, float(f)))
    if m.get("sync", True):
        m["period"] = PERIODS[len(PERIODS) - 1 - int(round(f * (len(PERIODS) - 1)))]
    else:
        m["hz"] = round(HZ_LO * (HZ_HI / HZ_LO) ** f, 4)


def value(app, t):
    """A setting's position as 0..1 (a pad's fader shows it), or None for one without a position."""
    m = find(app, t.get("id"))
    if m is None or t.get("kind") != "mod":
        return None
    k = t.get("key")
    if k == "rate":
        return _rate_f(m)
    if k == "depth":
        return float(m.get("depth", 0)) / 255.0
    if k == "shape":
        s = m.get("shape", "sine")
        return SHAPES.index(s) / (len(SHAPES) - 1) if s in SHAPES else 0.0
    return None


def is_on(app, t):
    m = find(app, t.get("id"))
    if m is None:
        return None
    return gated(app, m["id"]) if t.get("kind") == "mod_gate" else bool(m.get("on", True))


def set_target(app, t, f):
    """A setting set from a control's 0..1: a rate along its scale, a depth of 255, a shape along the list; on/off
    flipped; a restart fired; play pressed at any value above 0 (a note's velocity, which an envelope plays at) and
    let go at 0. Saved once the control is left alone (a turned knob is many)."""
    from native import clock
    m = find(app, t.get("id"))
    if m is None:
        return
    f = max(0.0, min(1.0, float(f)))
    kind = t.get("kind")
    if kind == "mod_gate":                                  # pressed or let go, from t's "src"
        _gate(app, m, t.get("src"), f > 0.0, f)
        return
    if kind == "mod_on":
        m["on"] = not m.get("on", True)
    elif kind == "mod_restart":
        restart(app, m)
        return
    else:
        k = t.get("key")
        if k == "rate":
            _rate_set(m, f)
        elif k == "depth":
            m["depth"] = int(round(f * 255))
        elif k == "shape":
            m["shape"] = SHAPES[int(round(f * (len(SHAPES) - 1)))]
        else:
            return
    app._mod_moved = True
    app._mod_save_at = (clock.now(), app.project)


def _flush(app, now, force=False):
    """A setting turned from a control saved once it has been left SAVE_AFTER_S (into the project it was turned in)."""
    s = getattr(app, "_mod_save_at", None)
    if s is not None and (force or now - s[0] >= SAVE_AFTER_S):
        app._mod_save_at = None
        s[1].save()


