W, H = 860, 360
RATES = (("sync", "synced"), ("free", "free (Hz)"))


def _labels(app):
    """{key: the slider's name for the current effect}."""
    m = app.eng.meta[app.eng.idx]
    generic = {"sx": "Speed", "ix": "Intensity", "c1": "Custom 1", "c2": "Custom 2", "c3": "Custom 3"}
    out = {}
    for i, k in enumerate(FX_KEYS):
        lab = (m["labels"][i] if i < len(m["labels"]) else "").strip()
        out[k] = lab if lab and lab != "!" else generic[k]
    from native import vj
    for k in VJ_KEYS:
        i, knob = _vj_key(k)
        out[k] = f"VJ {vj.LETTERS[i]} {vj.KNOB_WORDS[knob]}"
    return out


def build(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    from native.typeface import px
    app._mod_dialog_built = True
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(W), height=px(H)):
        chrome.dialog_header(TAG, "Modulators")
        dpg.add_text("Sliders moved by a wave, the beat or a pattern of steps, around where each is set - in the sim "
                     "and the stream. Whatever sets a slider sets the place it moves around. A pad, MIDI or the phone "
                     "can turn a modulator's rate, depth and shape, switch or restart it, and play it (an envelope, or a "
                     "wave that runs while held).", color=chrome.DIM,
                     wrap=px(W - 30))
        dpg.add_group(tag="mod_rows")
        with dpg.group(horizontal=True):
            dpg.add_button(label="+ Modulator", tag="mod_add", callback=lambda: add(app))
            chrome.tip("one more: a wave on the first slider not moved yet")
            dpg.add_text("", tag="mod_words", color=chrome.DIM)


def refresh(app):
    import dearpygui.dearpygui as dpg
    from native import chrome, num
    from native.typeface import px
    if not getattr(app, "_mod_dialog_built", False) or not dpg.does_item_exist("mod_rows"):
        return                                              # never opened (or no window at all: a test)
    dpg.delete_item("mod_rows", children_only=True)
    labs = _labels(app)
    by_lab = {v: k for k, v in labs.items()}
    for i, m in enumerate(modulators(app)):
        keys = m.get("keys") or ["sx"]
        with dpg.group(horizontal=True, parent="mod_rows"):
            dpg.add_checkbox(tag=f"mod_on_{i}", default_value=bool(m.get("on", True)),
                             callback=lambda s, v, i=i: edit(app, i, on=bool(v)))
            chrome.tip(f"Mod {m['id']} on or off: off, its sliders stay where they are set")
            dpg.add_combo([labs[k] for k in KEYS], width=px(130), default_value=labs.get(keys[0], "Speed"),
                          callback=lambda s, v, i=i: set_key(app, i, 0, by_lab.get(v, "sx")))
            dpg.add_button(label="+", small=True, callback=lambda s, a, i=i: add_key(app, i))
            chrome.tip("one more slider moved by this same wave (each by the depth, of its own range)")
            dpg.add_combo([w for _, w in KINDS], width=px(150), default_value=dict(KINDS).get(m.get("kind"), "a wave (LFO)"),
                          callback=lambda s, v, i=i: edit(app, i, kind=next(k for k, w in KINDS if w == v)))
            kind = m.get("kind", "lfo")
            if kind == "lfo":
                dpg.add_combo(list(SHAPES), tag=f"mod_shape_{i}", width=px(80), default_value=m.get("shape", "sine"),
                              callback=lambda s, v, i=i: edit(app, i, shape=v))
            if kind in ("lfo", "steps"):
                sync = m.get("sync", True)
                dpg.add_combo([w for _, w in RATES], width=px(80), default_value=RATES[0 if sync else 1][1],
                              callback=lambda s, v, i=i: edit(app, i, sync=v == RATES[0][1]))
                chrome.tip("synced: a length in beats of the show's tempo (the synth's without one); free: so many a second")
                if sync:
                    dpg.add_combo([_beats(p) for p in PERIODS], tag=f"mod_period_{i}", width=px(80),
                                  default_value=_beats(m.get("period", 4)),
                                  callback=lambda s, v, i=i: edit(app, i, period=_unbeats(v)))
                    chrome.tip("a wave's length, or a step's, in beats")
                else:
                    num.add(f"mod_hz_{i}", float(m.get("hz", 0.5)), HZ_LO, HZ_HI, width=px(80), digits=2, unit="Hz",
                            callback=lambda s, v, i=i: edit(app, i, hz=float(v)))
                    chrome.tip("waves (or steps) a second")
            if kind in ("lfo", "steps"):
                dpg.add_combo([w for _, w in STARTS], width=px(110), default_value=dict(STARTS).get(m.get("start", "free")),
                              callback=lambda s, v, i=i: edit(app, i, start=next(k for k, w in STARTS if w == v)))
                chrome.tip("always: it runs all the time; while held: only while its play target is held (a pad, a "
                           "note), from the top of its wave; restart on press: all the time, from the top at each press")
            if kind == "beat":
                num.add(f"mod_decay_{i}", float(m.get("decay", 0.4)), 0.05, 4.0, width=px(80), digits=2, unit="s",
                        callback=lambda s, v, i=i: edit(app, i, decay=float(v)))
                chrome.tip("how long the push takes to let go")
            num.add(f"mod_depth_{i}", int(m.get("depth", 96)), 0, 255, integer=True, width=px(70),
                    callback=lambda s, v, i=i: edit(app, i, depth=int(v)))
            chrome.tip("how far it moves each slider, of 255 of its range: a wave and steps this much in all, the beat this much up")
            dpg.add_button(label="x", small=True, callback=lambda s, a, i=i: remove(app, i))
            chrome.tip("this modulator taken away: its sliders left where they are set")
        if len(keys) > 1:
            with dpg.group(horizontal=True, parent="mod_rows"):
                dpg.add_text("   also moves", color=chrome.DIM)
                for j, k in enumerate(keys[1:], 1):
                    dpg.add_combo([labs[x] for x in KEYS], width=px(120), default_value=labs.get(k, "Speed"),
                                  callback=lambda s, v, i=i, j=j: set_key(app, i, j, by_lab.get(v, "sx")))
                    dpg.add_button(label="x", small=True, callback=lambda s, a, i=i, j=j: remove_key(app, i, j))
                    chrome.tip("this slider no longer moved by it: left where it is set")
        if m.get("kind") == "env":
            with dpg.group(horizontal=True, parent="mod_rows"):
                dpg.add_text("   envelope", color=chrome.DIM)
                for k, d, lo, hi_ in ENV:
                    dpg.add_text(k[0].upper(), color=chrome.DIM)
                    num.add(f"mod_env_{k}_{i}", _env_param(m, k), lo, hi_, digits=2, width=px(60),
                            unit="" if k == "sustain" else "s",
                            callback=lambda s, v, i=i, k=k: edit(app, i, **{"env_decay" if k == "decay" else k: round(float(v), 3)}))
                    chrome.tip({"attack": "seconds up to full when its play target is pressed",
                                "decay": "seconds from full down to the sustain level, held",
                                "sustain": "the level it stays at while held (of the depth)",
                                "release": "seconds from full down to nothing once let go"}[k])
        if m.get("kind") == "steps":
            with dpg.group(horizontal=True, parent="mod_rows"):
                dpg.add_text("   steps", color=chrome.DIM)
                for j, v in enumerate((m.get("steps") or [])[:16]):
                    num.add(f"mod_step_{i}_{j}", float(v), 0.0, 1.0, digits=2, width=px(40),
                            callback=lambda s, val, i=i, j=j: _set_step(app, i, j, val))
                dpg.add_button(label="+", small=True, callback=lambda s, a, i=i: _steps_len(app, i, 1))
                dpg.add_button(label="-", small=True, callback=lambda s, a, i=i: _steps_len(app, i, -1))
    n = len(modulators(app))
    dpg.set_value("mod_words", f"{n} modulator{'s' if n != 1 else ''}, at {tempo(app):g} bpm" if n else "none yet")


def sync_dialog(app):
    """The dialog's widgets as the modulators are now (a pad, MIDI or the phone turned one)."""
    if not getattr(app, "_mod_dialog_built", False):
        return
    import dearpygui.dearpygui as dpg
    from native import num
    if not dpg.does_item_exist(TAG) or not dpg.is_item_shown(TAG) or num.busy():
        return
    for i, m in enumerate(modulators(app)):
        for tag, v in ((f"mod_on_{i}", bool(m.get("on", True))), (f"mod_shape_{i}", m.get("shape", "sine")),
                       (f"mod_period_{i}", _beats(m.get("period", 4)))):
            if dpg.does_item_exist(tag) and dpg.get_value(tag) != v:
                dpg.set_value(tag, v)
        for tag, v in ((f"mod_hz_{i}", float(m.get("hz", 0.5))), (f"mod_depth_{i}", int(m.get("depth", 96)))):
            if dpg.does_item_exist(tag):
                num.set(tag, v)


def _beats(p):
    p = float(p)
    return f"{int(p)} beat{'s' if p != 1 else ''}" if p >= 1 else f"1/{int(round(1 / p))} beat"


def _unbeats(words):
    w = words.split()[0]
    return 1.0 / float(w.split("/")[1]) if "/" in w else float(w)


def show(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    refresh(app)
    chrome._centre(TAG, W, H)
    dpg.show_item(TAG)


def add(app, **kw):
    """One more modulator: on the first slider without one (or `keys`, or `key` for one), a wave unless said
    otherwise; an id of its own."""
    mods = modulators(app)
    used = {k for m in mods for k in (m.get("keys") or ())}
    m = dict(DEFAULT, steps=list(DEFAULT["steps"]), seed=random.randrange(1 << 20))   # a random wave of its own
    m["keys"] = [next((k for k in KEYS if k not in used), "sx")]
    if "key" in kw:
        kw["keys"] = [kw.pop("key")]
    m.update(kw)
    m["keys"] = list(m["keys"])
    m["id"] = 1 + max((int(x.get("id", 0)) for x in mods), default=0)
    mods.append(m)
    app.project.save()
    refresh(app)
    return m


def edit(app, i, **kw):
    mods = modulators(app)
    if 0 <= i < len(mods):
        mods[i].update(kw)
        app.project.save()
        if {"kind", "sync"} & set(kw):
            refresh(app)


def set_key(app, i, j, key):
    """Modulator i's j-th slider set to `key` (one already in its list: the row left as it was)."""
    mods = modulators(app)
    if 0 <= i < len(mods):
        keys = mods[i].setdefault("keys", ["sx"])
        if 0 <= j < len(keys) and key not in keys:
            keys[j] = key
            app.project.save()
        refresh(app)


def add_key(app, i):
    """One more slider for modulator i: the first it does not move yet."""
    mods = modulators(app)
    if 0 <= i < len(mods):
        keys = mods[i].setdefault("keys", ["sx"])
        k = next((k for k in KEYS if k not in keys), None)
        if k is not None:
            keys.append(k)
            app.project.save()
        refresh(app)


def remove_key(app, i, j):
    mods = modulators(app)
    if 0 <= i < len(mods):
        keys = mods[i].setdefault("keys", ["sx"])
        if 1 <= j < len(keys):
            del keys[j]
            app.project.save()
        refresh(app)


def remove(app, i):
    mods = modulators(app)
    if 0 <= i < len(mods):
        del mods[i]
        app.project.save()
        refresh(app)


def _set_step(app, i, j, v):
    mods = modulators(app)
    if 0 <= i < len(mods):
        mods[i].setdefault("steps", list(DEFAULT["steps"]))[j] = round(float(v), 3)
        app.project.save()


def _steps_len(app, i, d):
    mods = modulators(app)
    if 0 <= i < len(mods):
        st = mods[i].setdefault("steps", list(DEFAULT["steps"]))
        if d > 0 and len(st) < 16:
            st.append(0.0)
        elif d < 0 and len(st) > 1:
            st.pop()
        app.project.save()
        refresh(app)
