def _beats(p):
    p = float(p)
    return f"{int(p)} beat{'s' if p != 1 else ''}" if p >= 1 else f"1/{int(round(1 / p))} beat"


def _unbeats(words):
    w = words.split()[0]
    return 1.0 / float(w.split("/")[1]) if "/" in w else float(w)


