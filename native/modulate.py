"""Modulators on any slider (the second feature review's seventh, after
Chromatik's LFOs, envelopes and step sequencers): sliders of the effect, a VJ
deck's knobs, the crossfaders and other modulators' depth and rate, moved by
something that runs on its own - a wave, the beat, a pattern of steps, an
envelope, the sound - around where each is set, in the sim and so in the
stream.

    mods = modulators(app)       # [{"id", "keys", "kind", "shape", "sync", "period", "hz", "depth", ...}]
    apply(app)                   # each frame, before the engine's step: the sliders moved
    offset(m, pos, since, cs)    # one wave's push, `pos` cycles into it, `since` the last beat
    targets(app)                 # [(label, target)]: each modulator's settings a control can turn, switch or play
    set_target(app, t, f)        # one of those set from a control (0..1), as MIDI, a pad or the phone does
    level(app, mid)              # where a running one is, 0..1 (a pad's light pulses with it)
    swing(app, key)              # the band the modulators move a slider over, and where it is now

A modulator moves one slider or several (`keys`) by the same wave, each by
`depth` of 255 of its own range times its own amount (`amt`, -1..1: a
negative one moves it the other way). It does not take a slider over:
whatever sets the slider - a drag, a step of the show, a ramp, MIDI, a pad -
sets the place it moves around (the value it finds there that is not the one
it wrote last). Taken away or off, the slider is left where it was set. What
it moves a VJ knob, a crossfader or another modulator's setting to is kept
apart from the setting itself (never saved), so the project only ever holds
the places.

The kinds:
  lfo     a wave (sine, triangle, saw up or down, square, random eased, or
          sample and hold), swinging `depth` either way of the place;
          `width` sets a square's duty and a triangle's peak
  beat    on each beat a push of `depth` upward, eased in over 140 ms (a
          beat moves a pattern, it does not jump it) and let go over `decay`
  steps   a pattern of up to 16 levels, eased from one to the next over 50 ms
  env     an envelope (attack, decay, sustain, release) played from its play
          target - a pad, a note (its velocity scales it) - or fired on each
          beat
  audio   the sound's level, bass, mid or treble, followed over its attack
          and release; on auto level, the loudest of the last few seconds
          counts as full

Its rate: synced (`sync`, the default) a wave or a step every `period` beats
of the tempo (`feel`: straight, triplets or dotted); free, `hz` of them a
second. Each keeps where it is in its wave (its phase) and moves on from
there, so a rate turned while it runs never jumps it; a synced one then eases
back onto the beat grid, its speed held to within a quarter of its own. A
restart puts it back to its start and the grid's start to now. `phase` moves
the whole wave on, `spread` each further slider's a share of a wave from the
one before (so several move apart). `start`: always, only while its play
target is held, or from the top at each press.
"""
