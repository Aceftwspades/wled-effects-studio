"""Modulators on any slider (the second feature review's seventh, after
Chromatik's LFOs, envelopes and step sequencers): a slider of the effect
moved by something that runs on its own - a wave, the beat, a pattern of
steps - around where the slider is set, in the sim and so in the stream.

    mods = modulators(app)       # [{"key", "kind", "shape", "period", "depth", "decay", "steps", "on"}]
    apply(app)                   # each frame, before the engine's step: the sliders moved
    offset(m, beats, since, spb) # one modulator's push, `beats` into the tempo, `since` the last beat

A modulator does not take the slider over: whatever sets the slider - a
drag, a step of the show, a ramp, MIDI - sets the place it moves around (the
value it finds there that is not the one it wrote last). Taken away or off,
the slider is left where it was set.

The kinds:
  lfo     a wave (sine, triangle, saw up or down, square, random) over
          `period` beats, swinging `depth` either way of the slider's place
  beat    on each beat a push of `depth` upward, eased in over 140 ms (a
          beat moves a pattern, it does not jump it) and let go over `decay`
  steps   a pattern of up to 16 levels, a step every `period` beats, eased
          from one to the next over 50 ms
"""
# AI: below section was generated by an AI
import math
import random

FX_KEYS = ("sx", "ix", "c1", "c2", "c3")
# the VJ frame's deck knobs too (vj.py): "vj0.amount" is deck A's amount - 0..255 of the knob's range
VJ_KEYS = tuple(f"vj{i}.{k}" for i in (0, 1, 2) for k in ("level", "amount", "speed", "hue", "kaleido", "trails", "blur"))
KEYS = FX_KEYS + VJ_KEYS
KINDS = (("lfo", "a wave (LFO)"), ("beat", "on the beat"), ("steps", "a step pattern"))
SHAPES = ("sine", "triangle", "saw up", "saw down", "square", "random")
PERIODS = (0.25, 0.5, 1, 2, 4, 8, 16, 32)          # beats
ATTACK_S = 0.14                                    # a beat's push eased in over this
STEP_SLEW_S = 0.05
DEFAULT = {"key": "sx", "kind": "lfo", "shape": "sine", "period": 4, "depth": 96, "decay": 0.4,
           "steps": [1.0, 0.0, 0.5, 0.0, 0.75, 0.0, 0.25, 0.0], "on": True}


def hi(key):
    return 31 if key == "c3" else 255


def _rand(seed, k):
    return random.Random(seed * 1000003 + k).random()


def wave(shape, phase, cycle=0, seed=1):
    """0..1 of a wave at `phase` (0..1) of its `cycle`th period."""
    p = phase % 1.0
    if shape == "triangle":
        return 1.0 - abs(2.0 * p - 1.0)
    if shape == "saw up":
        return p
    if shape == "saw down":
        return 1.0 - p
    if shape == "square":
        return 1.0 if p < 0.5 else 0.0
    if shape == "random":                          # a new level each period, eased into from the last
        a, b = _rand(seed, cycle - 1), _rand(seed, cycle)
        u = min(1.0, p * 4.0)
        return a + (b - a) * (0.5 - 0.5 * math.cos(math.pi * u))
    return 0.5 - 0.5 * math.cos(2.0 * math.pi * p)   # sine, from its low point


def offset(m, beats, since, spb=0.5):
    """The push one modulator gives: `beats` the beats gone by (continuous), `since` the seconds since the last
    beat (None: none yet), `spb` a beat's seconds. A number of slider steps, either way."""
    depth = float(m.get("depth", 0))
    kind = m.get("kind", "lfo")
    if kind == "beat":
        if since is None or since < 0:
            return 0.0
        decay = max(0.02, float(m.get("decay", 0.4)))
        if since < ATTACK_S:
            e = 0.5 - 0.5 * math.cos(math.pi * since / ATTACK_S)
        else:
            e = math.exp(-(since - ATTACK_S) / decay * 3.0)
        return depth * e
    per = max(1e-3, float(m.get("period", 4)))
    if kind == "steps":
        lv = [float(v) for v in (m.get("steps") or [0.5])][:16] or [0.5]
        pos = beats / per
        k = int(math.floor(pos))
        into = (pos - k) * per                     # beats into this step
        cur, prev = lv[k % len(lv)], lv[(k - 1) % len(lv)]
        u = min(1.0, into * spb / STEP_SLEW_S)    # seconds into it against the ease
        return depth * ((prev + (cur - prev) * u) - 0.5)
    pos = beats / per
    return depth * (wave(m.get("shape", "sine"), pos, int(math.floor(pos)), seed=int(m.get("seed", 7))) - 0.5)


def modulators(app):
    return app.project.options.setdefault("modulators", [])


def tempo(app):
    """The beats a minute the waves run at: the show's tempo when it has one, else the synth's."""
    try:
        from native import sequence_ui
        bpm = float(sequence_ui._steps(app).get("bpm") or 0)
    except Exception:
        bpm = 0.0
    if bpm <= 0:
        bpm = float(getattr(getattr(app, "syn", None), "bpm", 120) or 120)
    return max(20.0, min(300.0, bpm))


def apply(app):
    """Each frame: every modulator's slider set to its place plus its push. Its place is what it finds there
    when that is not what it wrote last (something else set it since)."""
    from native import clock
    mods = modulators(app)
    st = app.__dict__.setdefault("_mod_state", {})
    if not mods and not st:
        return
    eng = app.eng
    now = clock.now()
    bpm = tempo(app)
    if "beats" not in st:
        st["beats"], st["at"] = 0.0, now
    st["beats"] += max(0.0, now - st["at"]) * bpm / 60.0
    st["at"] = now
    last_hit = getattr(app, "last_hit_at", None)
    since = None if last_hit is None else now - last_hit
    push = {}
    for n, m in enumerate(mods):
        if "seed" not in m:                                 # one made before seeds: its own, kept
            m["seed"] = 7 + n * 7919
        k = m.get("key")
        if not m.get("on", True) or _get(app, k) is None:
            continue
        push[k] = push.get(k, 0.0) + offset(m, st["beats"], since, 60.0 / bpm)
    changed = False
    places = st.setdefault("places", {})
    for k in KEYS:
        cur = _get(app, k)
        if cur is None:
            continue
        written = places.get(k)
        if k in push:
            if written is None or cur != written[1]:
                base = cur                                  # set since by something else: its new place
            else:
                base = written[0]
            v = int(round(min(hi(k), max(0, base + push[k]))))
            if v != cur:
                changed |= _set(app, k, v)
            places[k] = (base, _get(app, k))                # as it reads back (a knob of whole steps rounds it)
        elif written is not None:                           # no longer modulated: left at its place
            if k in VJ_KEYS:
                getattr(app, "_vj_mod", {}).pop(_vj_key(k), None)
            elif cur == written[1] and cur != written[0]:
                changed |= _set(app, k, written[0])
            del places[k]
    if not mods:
        app._mod_state = {}
        app._vj_mod = {}
    if changed:
        eng.push()


def _vj_key(k):
    i, knob = k[2:].split(".", 1)
    return int(i), knob


def _get(app, k):
    """A target's value now, 0..hi(k), or None when there is none to move. A VJ knob's is the knob's own - its
    place: what the modulator moves it to is kept apart (vj.knob_value), never in the project's options."""
    if k in FX_KEYS:
        return app.eng.fx.get(k) if k in app.eng.fx else None
    if k in VJ_KEYS:
        from native import vj
        i, knob = _vj_key(k)
        return int(round(vj.knob_get(app, i, knob) * 255))
    return None


def _set(app, k, v):
    """A target set; True when the engine has to be told."""
    if k in FX_KEYS:
        app.eng.fx[k] = int(v)
        return True
    from native import vj
    i, knob = _vj_key(k)
    lo, hi_ = next((a, b) for kk, a, b in vj.KNOBS if kk == knob)
    app.__dict__.setdefault("_vj_mod", {})[(i, knob)] = lo + (hi_ - lo) * max(0.0, min(1.0, v / 255.0))
    return False


def place(app, key):
    """The value a modulated slider moves around (what the slider was set to), or None when it is not."""
    w = (getattr(app, "_mod_state", {}) or {}).get("places", {}).get(key)
    return None if w is None else w[0]


# --- the dialog ------------------------------------------------------------------------------------
TAG = "modulators_win"


def _labels(app):
    """{key: the slider's name for the current effect}."""
    m = app.eng.meta[app.eng.idx]
    generic = {"sx": "Speed", "ix": "Intensity", "c1": "Custom 1", "c2": "Custom 2", "c3": "Custom 3"}
    out = {}
    for i, k in enumerate(FX_KEYS):
        lab = (m["labels"][i] if i < len(m["labels"]) else "").strip()
        out[k] = lab if lab and lab != "!" else generic[k]
    from native import vj
    for k in VJ_KEYS:
        i, knob = _vj_key(k)
        out[k] = f"VJ {vj.LETTERS[i]} {vj.KNOB_WORDS[knob]}"
    return out


def build(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    from native.typeface import px
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(560), height=px(330)):
        chrome.dialog_header(TAG, "Modulators")
        dpg.add_text("A slider moved by a wave, the beat or a pattern of steps, around where it is set - in the sim "
                     "and the stream. Whatever sets the slider sets the place it moves around.", color=chrome.DIM,
                     wrap=px(530))
        dpg.add_group(tag="mod_rows")
        with dpg.group(horizontal=True):
            dpg.add_button(label="+ Modulator", tag="mod_add", callback=lambda: add(app))
            chrome.tip("one more: a wave on the first slider not moved yet")
            dpg.add_text("", tag="mod_words", color=chrome.DIM)


def refresh(app):
    import dearpygui.dearpygui as dpg
    from native import chrome, num
    from native.typeface import px
    if not dpg.does_item_exist("mod_rows"):
        return
    dpg.delete_item("mod_rows", children_only=True)
    labs = _labels(app)
    by_lab = {v: k for k, v in labs.items()}
    for i, m in enumerate(modulators(app)):
        with dpg.group(horizontal=True, parent="mod_rows"):
            dpg.add_checkbox(default_value=bool(m.get("on", True)), callback=lambda s, v, i=i: edit(app, i, on=bool(v)))
            chrome.tip("on or off: off, the slider stays where it is set")
            dpg.add_combo([labs[k] for k in KEYS], width=px(140), default_value=labs.get(m.get("key"), "Speed"),
                          callback=lambda s, v, i=i: edit(app, i, key=by_lab.get(v, "sx")))
            dpg.add_combo([w for _, w in KINDS], width=px(110), default_value=dict(KINDS).get(m.get("kind"), "a wave (LFO)"),
                          callback=lambda s, v, i=i: edit(app, i, kind=next(k for k, w in KINDS if w == v)))
            kind = m.get("kind", "lfo")
            if kind == "lfo":
                dpg.add_combo(list(SHAPES), width=px(80), default_value=m.get("shape", "sine"),
                              callback=lambda s, v, i=i: edit(app, i, shape=v))
            if kind in ("lfo", "steps"):
                dpg.add_combo([_beats(p) for p in PERIODS], width=px(80), default_value=_beats(m.get("period", 4)),
                              callback=lambda s, v, i=i: edit(app, i, period=_unbeats(v)))
                chrome.tip("a wave's length, or a step's, in beats of the show's tempo (the synth's without one)")
            if kind == "beat":
                num.add(f"mod_decay_{i}", float(m.get("decay", 0.4)), 0.05, 4.0, width=px(80), digits=2, unit="s",
                        callback=lambda s, v, i=i: edit(app, i, decay=float(v)))
                chrome.tip("how long the push takes to let go")
            num.add(f"mod_depth_{i}", int(m.get("depth", 96)), 0, 255, integer=True, width=px(70),
                    callback=lambda s, v, i=i: edit(app, i, depth=int(v)))
            chrome.tip("how far it moves the slider: a wave and steps this much in all, the beat this much up")
            dpg.add_button(label="x", small=True, callback=lambda s, a, i=i: remove(app, i))
            chrome.tip("this modulator taken away: the slider left where it is set")
        if m.get("kind") == "steps":
            with dpg.group(horizontal=True, parent="mod_rows"):
                dpg.add_text("   steps", color=chrome.DIM)
                for j, v in enumerate((m.get("steps") or [])[:16]):
                    num.add(f"mod_step_{i}_{j}", float(v), 0.0, 1.0, digits=2, width=px(40),
                            callback=lambda s, val, i=i, j=j: _set_step(app, i, j, val))
                dpg.add_button(label="+", small=True, callback=lambda s, a, i=i: _steps_len(app, i, 1))
                dpg.add_button(label="-", small=True, callback=lambda s, a, i=i: _steps_len(app, i, -1))
    n = len(modulators(app))
    dpg.set_value("mod_words", f"{n} modulator{'s' if n != 1 else ''}, at {tempo(app):g} bpm" if n else "none yet")


def _beats(p):
    p = float(p)
    return f"{int(p)} beat{'s' if p != 1 else ''}" if p >= 1 else f"1/{int(round(1 / p))} beat"


def _unbeats(words):
    w = words.split()[0]
    return 1.0 / float(w.split("/")[1]) if "/" in w else float(w)


def show(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    refresh(app)
    chrome._centre(TAG, 560, 330)
    dpg.show_item(TAG)


def add(app, **kw):
    """One more modulator: the first slider without one (or `key`), a wave unless said otherwise."""
    mods = modulators(app)
    used = {m.get("key") for m in mods}
    m = dict(DEFAULT, steps=list(DEFAULT["steps"]), seed=random.randrange(1 << 20))   # a random wave of its own
    m["key"] = next((k for k in KEYS if k not in used), "sx")
    m.update(kw)
    mods.append(m)
    app.project.save()
    refresh(app)
    return m


def edit(app, i, **kw):
    mods = modulators(app)
    if 0 <= i < len(mods):
        mods[i].update(kw)
        app.project.save()
        if {"kind", "key"} & set(kw):
            refresh(app)


def remove(app, i):
    mods = modulators(app)
    if 0 <= i < len(mods):
        del mods[i]
        app.project.save()
        refresh(app)


def _set_step(app, i, j, v):
    mods = modulators(app)
    if 0 <= i < len(mods):
        mods[i].setdefault("steps", list(DEFAULT["steps"]))[j] = round(float(v), 3)
        app.project.save()


def _steps_len(app, i, d):
    mods = modulators(app)
    if 0 <= i < len(mods):
        st = mods[i].setdefault("steps", list(DEFAULT["steps"]))
        if d > 0 and len(st) < 16:
            st.append(0.0)
        elif d < 0 and len(st) > 1:
            st.pop()
        app.project.save()
        refresh(app)
