def add(app, **kw):
    """One more modulator: on the first slider without one (or `keys`, or `key` for one), a wave unless said
    otherwise; an id of its own."""
    mods = modulators(app)
    used = {k for m in mods for k in (m.get("keys") or ())}
    m = dict(DEFAULT, steps=list(DEFAULT["steps"]), seed=random.randrange(1 << 20))   # a random wave of its own
    m["keys"] = [next((k for k in KEYS if k not in used), "sx")]
    if "key" in kw:
        kw["keys"] = [kw.pop("key")]
    m.update(kw)
    m["keys"] = list(m["keys"])
    m["id"] = 1 + max((int(x.get("id", 0)) for x in mods), default=0)
    mods.append(m)
    app.project.save()
    refresh(app)
    return m


