"""The shape editor's run state: what the Shape frame keeps between frames that is not saved.

    S = shape_state.of(app)     # the app's (made the first time it is asked for)
    S.sel, S.undo, ...          # every field below, always there, with its default
    S.forget(*PROJECT)          # another project opened: its shape's steps and selection dropped

It was 18 loose `app._shape_*` attributes, each read with its own default at each place; here each has one
default and one comment (pads_state.py is the pads', made the same way). The shape itself is the project's
geometry.
"""
# AI: below section was generated by an AI
import dataclasses as _dc
from dataclasses import dataclass, field


@dataclass(eq=False)
class ShapeState:
    # --- one project's shape: dropped when another project opens (PROJECT) -------------------------------
    undo: list = field(default_factory=list)        # the steps back: each the shape as it was (json), 40 at most
    redo: list = field(default_factory=list)        # the steps undone, to redo
    undo_names: list = field(default_factory=list)  # each undo step in words ("moved strip 1")
    redo_names: list = field(default_factory=list)  # each redo step in words
    sels: object = None             # the selected parts (a set of indices); None: nothing picked yet (the first)
    sel: int = -1                   # the active part, the last picked (-1: none)
    pending: object = None          # the parts of a drag under way, applied when it ends
    pre: object = None              # the shape as the drag found it (json): its undo step
    drag: object = None             # the part being dragged in the view
    drag_to: object = None          # where the dragged part is now ([x, y, z])
    hover: object = None            # the LED under the mouse in the view: (its x on screen, its part, ...)

    # --- the frame ----------------------------------------------------------------------------------------
    tab: str = "part"               # the tab in front: "part" or "shape"
    tab_for: object = None          # the selection the tab was last chosen for (another: the part's tab)
    ref: bool = False               # the file being opened is a reference picture, not parts
    place: bool = False             # a click in the view places the selected part on the plane
    plane: tuple = ("z", 0.0)       # the plane parts are placed on: its axis and where on it
    exact: bool = False             # the exact-numbers fold is open
    warns: int = 0                  # the checks' warnings last counted (more: said on the footer)

    def forget(self, *names):
        """Fields put back to their defaults."""
        for n in names:
            setattr(self, n, _DEFAULTS[n]())


_DEFAULTS = {f.name: (f.default_factory if f.default_factory is not _dc.MISSING else (lambda v=f.default: v))
             for f in _dc.fields(ShapeState)}
PROJECT = ("undo", "redo", "undo_names", "redo_names", "sels", "sel", "pending", "pre", "drag", "drag_to", "hover")


def of(app):
    """The app's shape editor run state (any object can hold one: the tests' stand-in apps too)."""
    s = app.__dict__.get("shape_state")
    if s is None:
        s = app.__dict__.setdefault("shape_state", ShapeState())
    return s
