def state(project):
    """The project's pads, made if missing: one starter bank, every field filled and the grid made whole (a
    control off its bank's grid or on another's cells is dropped - a hand-edited file)."""
    st = project.options.setdefault("pads", {})
    st.setdefault("next_id", 1)
    if not isinstance(st.get("banks"), list) or not st["banks"]:
        st["banks"] = [starter(st)]
    for b in st["banks"]:
        b.setdefault("name", "Bank")
        b.setdefault("colour", "blue")
        b["cols"] = max(GRID_MIN, min(GRID_MAX, int(b.get("cols", 4))))
        b["rows"] = max(GRID_MIN, min(GRID_MAX, int(b.get("rows", 4))))
        kept = []
        for c in b.get("controls") or []:
            if not isinstance(c, dict) or c.get("type") not in TYPES:
                continue
            for k, v in (("w", 1), ("h", 1), ("label", ""), ("colour", "grey"), ("target", {}), ("lo", 0.0),
                         ("hi", 1.0), ("invert", False), ("orient", "v"), ("midi", None)):
                c.setdefault(k, v)
            if "id" not in c:
                c["id"] = st["next_id"]
                st["next_id"] += 1
            if fits(b, c, kept):
                kept.append(c)
        b["controls"] = kept
    st["bank"] = max(0, min(len(st["banks"]) - 1, int(st.get("bank", 0))))
    return st


def current(st):
    return st["banks"][st["bank"]]


def cells(c):
    return {(x, y) for x in range(c["x"], c["x"] + c["w"]) for y in range(c["y"], c["y"] + c["h"])}


def fits(bank, c, others=None):
    """Whether `c` lies on the bank's grid without covering another control (`others`: those to test against;
    the bank's own other than c by default)."""
    if c["w"] < 1 or c["h"] < 1 or c["x"] < 0 or c["y"] < 0:
        return False
    if c["x"] + c["w"] > bank["cols"] or c["y"] + c["h"] > bank["rows"]:
        return False
    mine = cells(c)
    for o in bank["controls"] if others is None else others:
        if o is not c and o.get("id") != c.get("id") and mine & cells(o):
            return False
    return True


def at(bank, col, row):
    for c in bank["controls"]:
        if c["x"] <= col < c["x"] + c["w"] and c["y"] <= row < c["y"] + c["h"]:
            return c
    return None


def find(st, cid):
    for b in st["banks"]:
        for c in b["controls"]:
            if c["id"] == cid:
                return c
    return None


def place(bank, c, x, y, w=None, h=None):
    """Moved and/or resized if it fits there; True when it did."""
    trial = dict(c, x=int(x), y=int(y), w=int(c["w"] if w is None else w), h=int(c["h"] if h is None else h))
    if not fits(bank, trial):
        return False
    c.update(x=trial["x"], y=trial["y"], w=trial["w"], h=trial["h"])
    return True


def resize_grid(bank, cols, rows):
    """The bank's grid made cols x rows; False (and unchanged) when a control would fall off it."""
    cols, rows = max(GRID_MIN, min(GRID_MAX, int(cols))), max(GRID_MIN, min(GRID_MAX, int(rows)))
    if any(c["x"] + c["w"] > cols or c["y"] + c["h"] > rows for c in bank["controls"]):
        return False
    bank["cols"], bank["rows"] = cols, rows
    return True


def copy_bank(st, i):
    """Bank i copied after itself, its controls given new ids; the copy's index."""
    b = copy.deepcopy(st["banks"][i])
    b["name"] = f"{b['name']} copy"
    for c in b["controls"]:
        c["id"] = st["next_id"]
        st["next_id"] += 1
    st["banks"].insert(i + 1, b)
    return i + 1


def kind_of(t):
    """'switch' (fires: a cut, a shuffle, a look stepped), 'flip' (a switch that turns something on and off),
    'look' / 'preset' (the pads' own), or 'value' (a slider, a knob, a check, the fader: set to a value)."""
    k = (t or {}).get("kind")
    if k in FLIPS:
        return "flip"
    if k in ("pad_look", "pad_preset"):
        return k[4:]
    if k in _midi().SWITCHES:
        return "switch"
    return "value"


# --- what the targets are now, read back -----------------------------------------------------------------------
def _paused(app, i):
    from native import vj
    try:
        run = vj._runs(app)[i]
        ent = vj._pool(app).get(run.src_key)
        return bool(ent and ent[0] is not None and ent[0].paused)
    except Exception:
        return False


def value(app, t):
    """A value target's position as 0..1, or None where it cannot be read (a pin, the palette by index)."""
    k = (t or {}).get("kind")
    try:
        if k == "vj_fader":
            from native import vj
            return float(vj.options(app)["fader"])
        if k == "vj_knob":
            from native import vj
            return float(vj.knob_get(app, int(t.get("deck", 0)), t.get("key", "amount")))
        if k == "mixer":
            from native import mixer
            return float(mixer.options(app)["fader"])
        if k == "fx":
            return float(app.eng.fx.get(t.get("key"), 0)) / (31.0 if t.get("key") == "c3" else 255.0)
        if k == "check":
            return 1.0 if app.eng.fx.get(t.get("key")) else 0.0
    except Exception:
        return None
    return None


def is_on(app, t):
    """A flip's state (on air, deck C in, a deck's video paused), or None for other targets."""
    k = (t or {}).get("kind")
    from native import vj
    if k == "vj_air":
        return bool(vj.on(app))
    if k in ("vj_c_toggle", "vj_c_in"):
        return bool(vj.c_is_in(app))
    if k and k.startswith("vj_pause_"):
        return _paused(app, "abc".index(k[-1]))
    return None


# --- acting ------------------------------------------------------------------------------------------------------
def _span(c, f):
    """0..1 along the control (a fader's travel) as the target's 0..1, through the control's range and invert."""
    f = max(0.0, min(1.0, float(f)))
    if c.get("invert"):
        f = 1.0 - f
    lo, hi = float(c.get("lo", 0.0)), float(c.get("hi", 1.0))
    return lo + (hi - lo) * f


def _rt(app):
    """The pads' run state, never saved: held controls, what a hold changed (to put back), toggles' own on/off for
    targets that cannot be read, triggers' flash times."""
    r = getattr(app, "_pads_rt", None)
    if r is None:
        r = app._pads_rt = {"held": set(), "before": {}, "on": {}, "flash": {}}
    return r


def _apply(app, t, f):
    """The target set to f (0..1) - or fired, for a switch - the way MIDI's control would."""
    from native import midi_ui, vj
    k = t.get("kind")
    if k == "pad_look":
        names = set(vj_looks_names())
        if t.get("look") in names:
            vj.options(app)["decks"][int(t.get("deck", 0))]["look"] = t["look"]
            app._vj_dirty = True
        return
    if k == "pad_preset":
        if t.get("name") in vj.options(app)["presets"]:
            vj.load_preset(app, int(t.get("deck", 0)), t["name"])
            app._vj_dirty = True
            app._vj_knobs_moved = True
        return
    midi_ui.apply_target(app, t, f, 1.0)


def vj_looks_names():
    from native import vj_looks
    return list(vj_looks.LOOKS)


def press(app, c, f=None):
    """A control pressed (a fader or a knob: where it was touched, as 0..1 - `f`)."""
    r = _rt(app)
    t, typ, kind = c.get("target") or {}, c["type"], kind_of(c.get("target"))
    r["held"].add(c["id"])
    if not t.get("kind"):
        return
    if typ in SLIDERS:
        if f is not None:
            drag(app, c, f)
        return
    if kind in ("switch", "look", "preset"):
        r["flash"][c["id"]] = time.monotonic()
        if typ == "hold" and t.get("kind") == "vj_c_flash":         # a flash held: deck C in at once, out on release
            from native import vj
            vj.c_go(app, True, beats=0)
            return
        _apply(app, t, 1.0)
        return
    if kind == "flip":
        if typ == "trigger":
            r["flash"][c["id"]] = time.monotonic()
        _apply(app, t, 1.0)
        return
    # a value target
    hi, lo = _span(c, 1.0), _span(c, 0.0)
    if typ == "trigger":
        r["flash"][c["id"]] = time.monotonic()
        _apply(app, t, hi)
    elif typ == "toggle":
        now = value(app, t)
        on = (abs(now - hi) < 1e-3) if now is not None else bool(r["on"].get(c["id"]))
        r["on"][c["id"]] = not on
        _apply(app, t, lo if on else hi)
    else:                                                           # hold: hi while held, what was there after
        r["before"][c["id"]] = value(app, t)
        _apply(app, t, hi)


def release(app, c):
    r = _rt(app)
    if c["id"] not in r["held"]:
        return
    r["held"].discard(c["id"])
    t, typ, kind = c.get("target") or {}, c["type"], kind_of(c.get("target"))
    if typ != "hold" or not t.get("kind"):
        return
    if t.get("kind") == "vj_c_flash":
        from native import vj
        vj.c_go(app, False, beats=0)
    elif kind == "flip":
        _apply(app, t, 1.0)                                         # flipped back
    elif kind == "value":
        was = r["before"].pop(c["id"], None)
        _apply(app, t, _span(c, 0.0) if was is None else was)


def drag(app, c, f):
    """A fader or a knob moved to f (0..1 of its travel)."""
    t = c.get("target") or {}
    if c["type"] not in SLIDERS or kind_of(t) != "value" or not t.get("kind"):
        return
    _rt(app)["on"][("pos", c["id"])] = max(0.0, min(1.0, float(f)))    # where it shows, for a target not read back
    _apply(app, t, _span(c, f))


def position(app, c):
    """Where a fader or a knob shows itself, 0..1 of its travel: its target's value back through the range."""
    v = value(app, c.get("target"))
    r = _rt(app)
    if v is None:
        return float(r["on"].get(("pos", c["id"]), 0.0))
    lo, hi = float(c.get("lo", 0.0)), float(c.get("hi", 1.0))
    f = 0.0 if abs(hi - lo) < 1e-9 else (v - lo) / (hi - lo)
    f = max(0.0, min(1.0, f))
    return 1.0 - f if c.get("invert") else f


def lit(app, c):
    """Shown lit: held, a trigger just pressed, a toggle on, a flip whose target is on."""
    r = _rt(app)
    if c["id"] in r["held"]:
        return True
    if time.monotonic() - r["flash"].get(c["id"], -1e9) < FLASH_MS:
        return True
    t = c.get("target") or {}
    on = is_on(app, t)
    if on is not None and c["type"] != "trigger":
        return on
    if c["type"] == "toggle" and kind_of(t) == "value":
        v = value(app, t)
        return (abs(v - _span(c, 1.0)) < 1e-3) if v is not None else bool(r["on"].get(c["id"]))
    return False


def let_go(app):
    """Every held control released (the window closed, the mouse gone off it, a bank switched mid-press)."""
    st = state(app.project)
    for cid in list(_rt(app)["held"]):
        c = find(st, cid)
        if c is not None:
            release(app, c)
        else:
            _rt(app)["held"].discard(cid)
