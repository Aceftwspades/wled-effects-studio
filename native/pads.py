"""The VJ's pads: a drum-machine surface of controls - buttons, faders, knobs - on a grid, in banks, each control
driving any of the targets MIDI learn reaches (midi_ui.targets, applied by midi_ui.apply_target, so a pad, a knob
on a controller, an OSC fader and the phone all do one thing the same way), and a few of its own: a given look on a
deck, a saved VJ preset on a deck. Kept in the project's options under "pads":

    {"bank": 0, "banks": [{"name": "Bank 1", "colour": "blue", "cols": 4, "rows": 4,
                           "controls": [{"id": 1, "type": "trigger", "x": 0, "y": 0, "w": 1, "h": 1,
                                         "label": "Cut", "colour": "red", "target": {"kind": "vj_cut"},
                                         "lo": 0.0, "hi": 1.0, "invert": false}, ...]}]}

A bank switched only changes what the grid shows: never the picture. A control acts when it is pressed, let go or
dragged (press / release / drag here; the window, pads_ui.py, and later the phone's page call them).

    st = state(project)            # made if missing, every field filled
    bank = current(st)
    c = at(bank, col, row)         # the control on a cell, or None
    press(app, c); release(app, c); drag(app, c, f)
    lit(app, c)                    # shown lit: a toggle on, a hold held, a target that is on
"""
