def _span(c, f):
    """0..1 along the control (a fader's travel) as the target's 0..1, through the control's range and invert."""
    f = max(0.0, min(1.0, float(f)))
    if c.get("invert"):
        f = 1.0 - f
    lo, hi = float(c.get("lo", 0.0)), float(c.get("hi", 1.0))
    return lo + (hi - lo) * f


def _rt(app):
    """The pads' run state, never saved: held controls, what a hold or a snapping XY pad changed (to put back),
    toggles' own on/off for targets that cannot be read, triggers' flash times, the staged pad and its deck, and how
    many hold each held control (the mouse, a phone, a controller: let go when the last does)."""
    r = getattr(app, "_pads_rt", None)
    if r is None:
        r = app._pads_rt = {"held": set(), "count": {}, "before": {}, "on": {}, "flash": {}, "staged": None}
    return r


def _apply(app, t, f):
    """The target set to f (0..1) - or fired, for a switch - the way MIDI's control would."""
    from native import midi_ui, vj
    k = t.get("kind")
    if k == "pad_look":
        names = set(vj_looks_names())
        if t.get("look") in names:
            vj.options(app)["decks"][int(t.get("deck", 0))]["look"] = t["look"]
            app._vj_dirty = True
        return
    if k == "pad_preset":
        if t.get("name") in vj.options(app)["presets"]:
            vj.load_preset(app, int(t.get("deck", 0)), t["name"])
            app._vj_dirty = True
            app._vj_knobs_moved = True
        return
    midi_ui.apply_target(app, t, f, 1.0)


def vj_looks_names():
    from native import vj_looks
    return list(vj_looks.LOOKS)


def _range(c, axis, f):
    """0..1 across an axis of an XY pad as its target's 0..1, through that axis's range (across turned by invert)."""
    _, _, lo, hi, _ = next(a for a in AXES if a[0] == axis)
    f = max(0.0, min(1.0, float(f)))
    if axis == "x" and c.get("invert"):
        f = 1.0 - f
    return float(c.get(lo, 0.0)) + (float(c.get(hi, 1.0)) - float(c.get(lo, 0.0))) * f


def surface_targets(c):
    """[(axis, target)] an XY or pressure pad drives (those set)."""
    out = [(a, c.get(key) or {}) for a, key, _, _, _ in AXES if a != "p" or c["type"] == "pressure"]
    return [(a, t) for a, t in out if t.get("kind") and kind_of(t) == "value"]


def move(app, c, x, y, p=None):
    """An XY pad's finger at x, y (0..1, y up) - with its pressure, 0..1, on a pressure pad."""
    if c["type"] not in SURFACES:
        return
    p = 1.0 if p is None else max(0.0, min(1.0, float(p)))
    at = {"x": x, "y": y, "p": p}
    _rt(app)["on"][("xy", c["id"])] = (max(0.0, min(1.0, x)), max(0.0, min(1.0, y)), p)
    for axis, t in surface_targets(c):
        _apply(app, t, _range(c, axis, at[axis]))


def staged(app, c):
    """The deck a staged pad loaded (still off the air), or None."""
    s = _rt(app)["staged"]
    if not s or s[0] != c["id"]:
        return None
    from native import vj
    if vj.cue_deck(app) != s[1]:                                    # its deck went on air: the GO
        _rt(app)["staged"] = None
        return None
    return s[1]


def press(app, c, f=None, xy=None, pressure=None):
    """A control pressed (a fader or a knob: where it was touched, as 0..1 - `f`; an XY pad: where, x and y 0..1
    with y up - `xy` - and how hard on a pressure pad). One already held from elsewhere is not pressed again (what
    it was before stays the first press's, to go back to): only where it is touched moves."""
    r = _rt(app)
    t, typ, kind = c.get("target") or {}, c["type"], kind_of(c.get("target"))
    if c["id"] in r["held"]:
        r["count"][c["id"]] = r["count"].get(c["id"], 1) + 1
        if typ in SURFACES and xy is not None:
            move(app, c, xy[0], xy[1], pressure)
        elif typ in SLIDERS and f is not None:
            drag(app, c, f)
        return
    r["count"][c["id"]] = 1
    r["held"].add(c["id"])
    if typ in SURFACES:
        if c.get("release", "snap") == "snap":
            for axis, tt in surface_targets(c):
                r["before"][(c["id"], axis)] = value(app, tt)
        if xy is not None:
            move(app, c, xy[0], xy[1], pressure)
        return
    if not t.get("kind"):
        return
    if typ in SLIDERS:
        if f is not None:
            drag(app, c, f)
        return
    if kind in ("look", "preset") and c.get("stage"):
        from native import vj
        deck = vj.cue_deck(app)                                     # onto the deck off the air, there till GO
        r["staged"] = (c["id"], deck)
        _apply(app, dict(t, deck=deck), 1.0)
        return
    if kind in ("switch", "look", "preset"):
        r["flash"][c["id"]] = time.monotonic()
        if typ == "hold" and t.get("kind") == "vj_c_flash":         # a flash held: deck C in at once, out on release
            from native import vj
            vj.c_go(app, True, beats=0)
            return
        _apply(app, t, 1.0)
        return
    if kind == "flip":
        if typ == "trigger":
            r["flash"][c["id"]] = time.monotonic()
        _apply(app, t, 1.0)
        return
    if kind == "gate":                                              # held while pressed; a toggle latches it
        g = dict(t, src=("pad", c["id"]))
        if typ == "toggle":
            r["on"][c["id"]] = not r["on"].get(c["id"])
            _apply(app, g, 1.0 if r["on"][c["id"]] else 0.0)
        else:
            _apply(app, g, 1.0)
        return
    # a value target
    hi, lo = _span(c, 1.0), _span(c, 0.0)
    if typ == "trigger":
        r["flash"][c["id"]] = time.monotonic()
        _apply(app, t, hi)
    elif typ == "toggle":
        now = value(app, t)
        on = (abs(now - hi) < 1e-3) if now is not None else bool(r["on"].get(c["id"]))
        r["on"][c["id"]] = not on
        _apply(app, t, lo if on else hi)
    else:                                                           # hold: hi while held, what was there after
        r["before"][c["id"]] = value(app, t)
        _apply(app, t, hi)


def release(app, c):
    r = _rt(app)
    if c["id"] not in r["held"]:
        return
    n = r["count"].get(c["id"], 1) - 1
    if n > 0:                                                       # still held from elsewhere
        r["count"][c["id"]] = n
        return
    r["count"].pop(c["id"], None)
    r["held"].discard(c["id"])
    t, typ, kind = c.get("target") or {}, c["type"], kind_of(c.get("target"))
    if kind == "gate" and typ != "toggle":
        _apply(app, dict(t, src=("pad", c["id"])), 0.0)
        return
    if typ in SURFACES:
        if c.get("release", "snap") == "snap":                      # back where they were before the touch
            for axis, tt in surface_targets(c):
                was = r["before"].pop((c["id"], axis), None)
                _apply(app, tt, _range(c, axis, 0.0) if was is None else was)
            r["on"].pop(("xy", c["id"]), None)
        return
    if typ != "hold" or not t.get("kind"):
        return
    if t.get("kind") == "vj_c_flash":
        from native import vj
        vj.c_go(app, False, beats=0)
    elif kind == "flip":
        _apply(app, t, 1.0)                                         # flipped back
    elif kind == "value":
        was = r["before"].pop(c["id"], None)
        _apply(app, t, _span(c, 0.0) if was is None else was)


def drag(app, c, f):
    """A fader or a knob moved to f (0..1 of its travel)."""
    t = c.get("target") or {}
    if c["type"] not in SLIDERS or kind_of(t) != "value" or not t.get("kind"):
        return
    _rt(app)["on"][("pos", c["id"])] = max(0.0, min(1.0, float(f)))    # where it shows, for a target not read back
    _apply(app, t, _span(c, f))


def position(app, c):
    """Where a fader or a knob shows itself, 0..1 of its travel: its target's value back through the range."""
    v = value(app, c.get("target"))
    r = _rt(app)
    if v is None:
        return float(r["on"].get(("pos", c["id"]), 0.0))
    return _travel_of(c, v)


def _travel_of(c, v):
    """A target's 0..1 as 0..1 of a control's travel: back through its range and invert, held to the ends."""
    lo, hi = float(c.get("lo", 0.0)), float(c.get("hi", 1.0))
    f = 0.0 if abs(hi - lo) < 1e-9 else (v - lo) / (hi - lo)
    f = max(0.0, min(1.0, f))
    return 1.0 - f if c.get("invert") else f


def swing(app, c):
    """How far the modulators move a fader's or a knob's target, along its travel: (from, to, where now), from
    below to; or None when none moves it."""
    from native import modulate
    key = modulate.key_of(c.get("target"))
    s = modulate.swing(app, key) if key else None
    if s is None:
        return None
    a, b, now = (_travel_of(c, v / modulate.hi(key)) for v in s)
    return min(a, b), max(a, b), now


def where(app, c):
    """Where an XY pad shows its dot: (x, y, pressure) 0..1, or None when it is not being touched and stays nowhere
    (snapped back). A pad left where it was let go ("stay") keeps showing there."""
    return _rt(app)["on"].get(("xy", c["id"]))


def lit(app, c):
    """Shown lit: held, a trigger just pressed, a toggle on, a flip whose target is on; a staged pad blinks."""
    r = _rt(app)
    if c["id"] in r["held"]:
        return True
    if staged(app, c) is not None:
        return int(time.monotonic() * BLINK_HZ * 2) % 2 == 0
    if time.monotonic() - r["flash"].get(c["id"], -1e9) < FLASH_MS:
        return True
    t = c.get("target") or {}
    on = is_on(app, t)
    if on is not None and c["type"] != "trigger":
        return on
    if c["type"] == "toggle" and kind_of(t) == "value":
        v = value(app, t)
        return (abs(v - _span(c, 1.0)) < 1e-3) if v is not None else bool(r["on"].get(c["id"]))
    return False


def let_go(app):
    """Every held control released (the window closed, the mouse gone off it, a bank switched mid-press) - however
    many held it - and the controller's pads it held forgotten (pressed again, they press again)."""
    from native import pads_hw
    pads_hw.let_go(app)
    st = state(app.project)
    for cid in list(_rt(app)["held"]):
        _rt(app)["count"].pop(cid, None)
        c = find(st, cid)
        if c is not None:
            release(app, c)
        else:
            _rt(app)["held"].discard(cid)
