"""The show's run state: what the sequence, its timeline and its sends keep between frames that is not saved.

    S = seq_state.of(app)       # the app's (made the first time it is asked for)
    S.sel, S.play, ...          # every field below, always there, with its default
    S.forget("play", ...)       # fields put back to their defaults

It was ~35 loose `app._seq_*` / `app._tl_*` / `app._show_*` attributes, each read with its own default at
each place - the selected step was read as 0 in some places and -1 in others; here each has one default and
one comment (vj_state.py and pads_state.py are made the same way). The show itself is saved in the
project's options (sequence_ui._steps).
"""
# AI: below section was generated by an AI
import dataclasses as _dc
from dataclasses import dataclass


@dataclass(eq=False)
class SeqState:
    # --- the steps and playing them -----------------------------------------------------------------------
    sel: int = 0                    # the selected step (the list's refresh keeps it within the steps)
    play: object = None             # the show playing: {"i": step, "next": clock time it ends, "paused": seconds left...}
    bri: object = None              # the playing step's brightness ramp's value now (the picture is dimmed by it)
    beats: object = None            # the show's audio's beat times, for the timeline's ticks
    save_at: object = None          # when an edit's save is due (edits close together saved once)
    rows_dirty: bool = False        # the step list is listed again on the next poll

    # --- Edit live --------------------------------------------------------------------------------------------
    edit: bool = False              # Edit live is on: a change to the sim goes into the step under the playhead
    edit_step: object = None        # the step being edited (None: taken up on the next poll)
    edit_base: object = None        # (segments, colours) of that step when taken up: a difference is an edit
    edit_at: float = 0.0            # when the last edit was taken in
    fx_sig: object = None           # the effect's sliders as last seen, to tell a change
    look: object = None             # an edit's look being gathered: {"st", "idx", "until", "next", "frames"}
    look_due: object = None         # when the look of the last edit is gathered

    # --- sending the show -------------------------------------------------------------------------------------
    send: object = None             # the send's worker thread
    sent_now: object = None         # what the send last sent (None: it failed)
    send_result: object = None      # the send's words, for the log

    # --- the show's audio and the auto show -------------------------------------------------------------------
    player: object = None           # the show's audio player (showaudio.Player), made when first played
    audio_src: object = None        # the show's audio as the effects hear it (showaudio.ShowAudio)
    autoshow_after: bool = False    # a show is made from the sections once they are in (autoshow.poll)

    # --- the timeline -----------------------------------------------------------------------------------------
    tl_dirty: bool = True           # drawn again on the next poll
    tl_view: object = None          # the zoomed span {"t0", "span"} (None: the whole show)
    tl_drag: object = None          # a drag on it: ("move"|"curve"|"scrub"|"end"|"blend"|"block", ...)
    tl_pan: object = None           # a pan's (pointer x, t0, span) at its start
    tl_hover: object = None         # what the pointer is over (a block or a time on the ruler)
    tl_hover_was: object = None     # tl_hover as last drawn
    tl_state_was: object = None     # the play state as last drawn
    tl_held: bool = False           # the pointer is over it (the show's follow paused)
    tl_scale: object = None         # (seconds to pixels, height, t0) as last drawn, for the playhead between draws
    tl_ov: object = None            # a drag on the overview: ("left"|"right"|"box", where, t0, span)
    tl_grip: object = None          # the height grip's drag: (the pointer's y, the height then)
    tl_grip_hot: bool = False       # the pointer is on the height grip
    tl_frame_w: object = None       # the frame's width as last laid out

    def forget(self, *names):
        """Fields put back to their defaults."""
        for n in names:
            setattr(self, n, _DEFAULTS[n]())


_DEFAULTS = {f.name: (f.default_factory if f.default_factory is not _dc.MISSING else (lambda v=f.default: v))
             for f in _dc.fields(SeqState)}


def of(app):
    """The app's show run state (any object can hold one: the tests' stand-in apps too)."""
    s = app.__dict__.get("seq_state")
    if s is None:
        s = app.__dict__.setdefault("seq_state", SeqState())
    return s
