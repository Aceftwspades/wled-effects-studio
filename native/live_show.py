"""A starter live show: a new project with the VJ's decks, two banks of pads, a clip pad and a camera pad set up.

    live_show.make(app, "Friday set")      # File > New live show project...

The pads' first bank is every project's (pads.starter: the decks' shuffles, Cut and Fade, deck C, the
crossfader). The second, "Show", picks the deck the rest drive - A, B, C, the next one - with knobs on the
selected deck's look, amount, speed and hue, and two pads on deck C: a clip and a camera. The clip is made
here, on a worker, by ffmpeg (a Mandelbrot zoom, eight seconds) into the project's assets/vj; the camera is
the first webcam ffmpeg finds. Without ffmpeg, or a webcam, those two pads are left for their CLIP section to
set (the status line says so). Decks A and B get two different looks, so a Cut shows a change at once.
"""
# AI: below section was generated by an AI
import os

from native import pads, procs, vj, vj_clips

DEFAULT_NAME = "Live show"
CLIP_FILE = "starter_clip.mp4"           # made in the project's assets/vj
CLIP_S = 8                               # its length, seconds
LOOKS = ("Plasma", "Kaleido Tunnel")     # decks A and B to start


def show_bank(st):
    """The "Show" bank: which deck the rest drive, knobs on that deck, a clip and a camera on deck C."""
    b = pads.new_bank("Show", 4, 4, "violet")
    add = b["controls"].append
    for i, (d, colour) in enumerate(zip(vj.LETTERS, ("blue", "orange", "violet"))):
        add(pads.new_control(st, "trigger", i, 0, target={"kind": f"vj_sel_{d.lower()}"}, label=f"Deck {d}", colour=colour))
    add(pads.new_control(st, "trigger", 3, 0, target={"kind": "vj_sel_next"}, label="Next deck", colour="grey"))
    for x, (key, label) in enumerate((("look", None), ("amount", "Amount"), ("speed", "Speed"), ("hue", "Hue"))):
        t = ({"kind": "vj_look", "deck": vj.SEL} if key == "look" else {"kind": "vj_knob", "deck": vj.SEL, "key": key})
        add(pads.new_control(st, "knob", x, 1, target=t, label=label or "Look", colour="teal"))
    add(pads.new_control(st, "trigger", 0, 2, 2, 2, target=dict(vj_clips.DEFAULT, deck=2), label="Clip", colour="pink"))
    add(pads.new_control(st, "hold", 2, 2, 2, 2, target=dict(vj_clips.CAM_DEFAULT, deck=2), label="Camera", colour="cyan"))
    return b


def _pad(app, kind):
    """The Show bank's clip or camera pad (by its target's kind), or None."""
    from native import pads_ui
    for b in pads_ui._st(app)["banks"]:
        if b.get("name") == "Show":
            for c in b["controls"]:
                if c.get("target", {}).get("kind") == kind:
                    return c
    return None


def make_clip(folder):
    """The starter clip made by ffmpeg in `folder`: its kept path (assets/vj/...), or None without ffmpeg."""
    from native import video
    ff = video.ffmpeg()
    if not ff:
        return None
    os.makedirs(folder, exist_ok=True)
    out = os.path.join(folder, CLIP_FILE)
    procs.run([ff, "-y", "-v", "error", "-f", "lavfi", "-i", "mandelbrot=size=320x180:rate=30",
               "-t", str(CLIP_S), "-pix_fmt", "yuv420p", out], check=True, timeout=120)    # (no console window)
    return f"{vj.MEDIA_DIR}/{CLIP_FILE}"


def first_camera(names):
    """The webcam a camera pad starts on: the first ffmpeg found, not the phone (it needs the remote served)."""
    from native import video
    return next((n for n in names if n != video.PHONE), None)


def make(app, name):
    """A new project named `name`, set up as a live show, opened. One of that name already: opened, left as it is."""
    from native.project import project_path
    from native import pads_ui, tasks
    name = (name or "").strip() or DEFAULT_NAME
    path = project_path(name)
    if os.path.isdir(path):
        app.switch_project(path)
        app.gp.status(f"{name} is a project already: opened as it is"); return
    app.switch_project(path, create=True)
    st = pads_ui._st(app)
    if not any(b.get("name") == "Show" for b in st["banks"]):
        st["banks"].append(show_bank(st))
    o = vj.options(app)
    for d, look in zip(o["decks"], LOOKS):
        d["look"] = look
    app.project.save()
    pads_state_forget(app)

    def clip_done(kept):
        c = _pad(app, "pad_clip")
        if kept and c is not None and app.project.path == path:
            c["target"]["file"] = kept
            app.project.save(); pads_state_forget(app)
        app.gp.status("live show: the clip pad plays the starter clip" if kept else
                      "live show: no ffmpeg - the Clip pad's file is yours to set (its CLIP section)")
    tasks.run(app, "live_show_clip", "making the starter clip",
              lambda: make_clip(os.path.join(path, *vj.MEDIA_DIR.split("/"))), clip_done)

    def cams_done(names):
        c, cam = _pad(app, "pad_cam"), first_camera(names or [])
        if cam and c is not None and app.project.path == path:
            c["target"]["name"] = cam
            app.project.save(); pads_state_forget(app)
        if not cam:
            app.gp.status("live show: no webcam found - the Camera pad's camera is yours to pick (its CLIP section)")
    tasks.run(app, "live_show_cams", "looking for a webcam", vj_clips.cameras, cams_done)
    from native import device_ui
    device_ui.show(app, "vj")                            # the VJ frame and the pads, open on the new project
    pads_ui.show(app)
    app.gp.status(f"live show {name}: the VJ's decks and two banks of pads - Live and Show")


def pads_state_forget(app):
    """The pad grid drawn again from the project (a pad changed behind it)."""
    from native import pads_state
    pads_state.of(app).forget("drawn")
