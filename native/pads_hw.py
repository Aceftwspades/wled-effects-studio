"""A pad controller for the VJ's pads (native/pads.py): its pads and knobs learned onto the controls, and its
lights showing the layout. The messages come in on the project's MIDI port (Window > MIDI, OSC and phone -
midi_ui.poll hands them to events() first); the lights go out on a port chosen here.

A control learns a note or a CC (Learn in the Pads window's Edit panel; a bank button too): a note presses it and
lets it go, its velocity is a pressure pad's first pressure and its aftertouch the rest; a CC moves a fader or a
knob, and presses a button above half and lets it go below. A controller the studio knows also gives its own grid:
the pads' grid laid on its pads from the top left, a control spanning several pads lit on each and pressed by any,
and its row or column of side buttons for the banks - nothing to learn.

    DEVICES                    # (kind, words)
    hw(st)                     # the project's controller settings, filled in
    evs = events(app, evs)     # the MIDI frame's events learned or played; those the pads did not take
    lights(app, out)           # what the controller's lights should be, sent where it changed (out: a MidiOut)
    poll(app)                  # each frame (midi_ui.poll): the lights' port opened as set, and the lights

What each kind's messages are comes from its maker's programming reference: a Launchpad (Mini MK3, X, Pro MK3) in
Programmer mode - its pads notes 11..88 by row from the bottom, its top row CC 91..98, a pad's colour the velocity
from its palette; an APC mini mk2 - pads notes 0..63 from the bottom left, the channel the brightness, the velocity
the colour; the first APC mini - the same notes, velocity 1 green, 3 red, 5 yellow (one more blinks); the scene
buttons on the right for the banks. Not tried on the devices themselves: tests/test_pads_hw.py checks the messages.
"""
# AI: below section was generated by an AI
import time

from native import pads

DEVICES = (("generic", "any (learned pads)"),       # lit by velocity 127 / 0
           ("launchpad", "Launchpad (Programmer)"),   # Novation Launchpad Mini MK3, X, Pro MK3
           ("apc_mk2", "APC mini mk2"),               # Akai
           ("apc_mk1", "APC mini (first)"))
GRIDS = ("launchpad", "apc_mk2", "apc_mk1")     # the kinds with an 8 x 8 grid the pads can lie on
LIGHTS_HZ = 60.0                # at most this often (each frame): only what changed is sent
MAX_SENDS = 96                  # a frame's messages at most (a whole Launchpad's lights fit): the rest wait a frame
PULSE_HZ = 20.0                 # a pad pulsing with a modulator: its level read this often...
PULSE_SENDS = 16                # ...and at most this many pulsing lights changed each time (the rest catch up)
STEPS = {"launchpad": 3, "apc_mk2": 4, "apc_mk1": 2, "generic": 8}   # a pulse's brightness steps on each device
APC_STEPS = (0x91, 0x92, 0x94, 0x96)           # an APC mini mk2's 25%, 50%, 75% and 100% (its note-on channels)
RETRY_S = 3.0                   # a lights port not there is looked for again this often (the controller plugged in)
# Launchpad palette indexes (and the APC mini mk2's, which follows it): the pads' colours (bright, dim)
PALETTE = {"grey": (3, 1), "red": (5, 7), "orange": (9, 11), "amber": (9, 11), "yellow": (13, 15),
           "lime": (17, 19), "green": (21, 23), "teal": (33, 35), "cyan": (37, 39), "blue": (45, 47),
           "violet": (49, 51), "pink": (53, 55)}
# the first APC mini's three colours, each pad's nearest: velocity 1 green, 3 red, 5 yellow
MK1 = {"grey": 5, "red": 3, "orange": 5, "amber": 5, "yellow": 5, "lime": 1, "green": 1, "teal": 1, "cyan": 1,
       "blue": 1, "violet": 3, "pink": 3}
APC_DIM, APC_LIT = 0x91, 0x96                  # an APC mini mk2 pad's note-on channel: 25% and 100% brightness
# Programmer mode, by device id: Launchpad X 0x0C, Mini MK3 0x0D, Pro MK3 0x0E (one not plugged in ignores it)
LP_IDS = (0x0C, 0x0D, 0x0E)


def hw(st):
    h = st.setdefault("hw", {})
    if h.get("device") not in dict(DEVICES):
        h["device"] = "generic"
    h.setdefault("out", "")
    h.setdefault("grid", True)
    return h


def _grid_on(h):
    return h["device"] in GRIDS and bool(h.get("grid", True))


# --- where a cell is on the controller --------------------------------------------------------------------------
def cell_note(device, col, row):
    """The note of the controller's pad at (col, row) from its top left, or None off its 8 x 8."""
    if not (0 <= col < 8 and 0 <= row < 8):
        return None
    if device == "launchpad":
        return 10 * (8 - row) + col + 1
    if device in ("apc_mk1", "apc_mk2"):
        return (7 - row) * 8 + col
    return None


def note_cell(device, note):
    """(col, row) of a note on the controller's grid, or None."""
    if device == "launchpad":
        r, c = divmod(int(note), 10)
        if 1 <= r <= 8 and 1 <= c <= 8:
            return c - 1, 8 - r
        return None
    if device in ("apc_mk1", "apc_mk2") and 0 <= note < 64:
        return note % 8, 7 - note // 8
    return None


def bank_ctl(device, i):
    """The controller's own button for bank i: (kind, channel, number), or None past its eight."""
    if not 0 <= i < 8:
        return None
    if device == "launchpad":
        return ("cc", 0, 91 + i)                       # the top row
    if device == "apc_mk1":
        return ("note", 0, 82 + i)                     # the scene launch column
    if device == "apc_mk2":
        return ("note", 0, 112 + i)
    return None


def program_mode(device):
    """The messages that make the controller take its lights from here (a Launchpad into Programmer mode)."""
    if device == "launchpad":
        return [[0xF0, 0x00, 0x20, 0x29, 0x02, d, 0x0E, 0x01, 0xF7] for d in LP_IDS]
    return []


# --- coming in ------------------------------------------------------------------------------------------------
def _rt(app):
    r = getattr(app, "_pads_hw_rt", None)
    if r is None:
        r = app._pads_hw_rt = {"held": {}, "lights": {}, "at": 0.0, "out": None}
    return r


def let_go(app):
    """The pads the controller holds forgotten (pads.let_go: they were let go another way)."""
    _rt(app)["held"].clear()


def _same(a, b):
    return a is not None and b is not None and list(a) == list(b)


def learning(app):
    """What a learn waits for: ("control", id) or ("bank", index), or None."""
    return getattr(app, "_pads_learn", None)


def learn(app, what):
    """Wait for the next note or CC for ("control", id) or ("bank", index); None stops waiting."""
    app._pads_learn = what


def forget(app, what):
    """A control's or a bank's learned note or CC taken off."""
    from native import pads_ui
    st = pads_ui._st(app)
    if what[0] == "control":
        c = pads.find(st, what[1])
        if c is not None:
            c["midi"] = None
    elif 0 <= what[1] < len(st["banks"]):
        st["banks"][what[1]]["midi"] = None
    app.project.save()


def _controls_for(st, h, ctl):
    """The controls of the bank shown that a control of the controller plays: the ones that learned it, and on a
    known grid the one on that pad."""
    b = pads.current(st)
    out = [c for c in b["controls"] if _same(c.get("midi"), ctl)]
    if ctl[0] == "note" and _grid_on(h):
        cell = note_cell(h["device"], ctl[2])
        if cell is not None:
            c = pads.at(b, *cell)
            if c is not None and c not in out:
                out.append(c)
    return out


def events(app, evs):
    """The MIDI frame's events [(ctl, value, full)] onto the pads; those they did not take, for the MIDI window's
    learn and maps. A learn waiting takes the first note or CC and binds it (and none go on). Otherwise each is
    played - a bank button, a control of the bank shown (none while the pads are edited), a pressure pad held -
    and one that played something goes no further: a pad's note mapped in the MIDI window too does one thing."""
    from native import pads_ui
    st = pads_ui._st(app)
    h = hw(st)
    want = learning(app)
    if want is not None:
        for ctl, v, full in evs:
            if ctl[0] not in ("note", "cc") or (ctl[0] == "note" and v == 0):
                continue
            if want[0] == "control":
                c = pads.find(st, want[1])
                if c is not None:
                    c["midi"] = list(ctl)
            elif 0 <= want[1] < len(st["banks"]):
                st["banks"][want[1]]["midi"] = list(ctl)
            app._pads_learn = None
            app.project.save()
            app.gp.status(f"pads: learned {_words(ctl)}")
            pads_ui._fill_banks(app)
            pads_ui._fill_side(app)
            return []
        return evs
    r = _rt(app)
    editing = bool(getattr(app, "_pads_edit", False))
    rest = []
    for ev in evs:
        ctl, v, full = ev
        if ctl[0] not in ("note", "cc", "pat", "cp"):
            rest.append(ev)
            continue
        f = max(0.0, min(1.0, float(v) / float(full or 127.0)))
        took = False
        # a bank button: the controller's own, or one learned (its release taken with it)
        for i, b in enumerate(st["banks"]):
            if ctl[0] in ("note", "cc") and (_same(b.get("midi"), ctl) or
                                             (_grid_on(h) and _same(bank_ctl(h["device"], i), ctl))):
                if v > 0:
                    pads_ui.switch_bank(app, i)
                took = True
                break
        if ctl[0] in ("pat", "cp"):                          # pressed harder: the pressure pads it holds
            for cid, (held, p) in list(r["held"].items()):
                c = pads.find(st, cid)
                if c is None or c["type"] != "pressure":
                    continue
                if ctl[0] == "cp" or (held[0] == "note" and held[1] == ctl[1] and held[2] == ctl[2]):
                    x, y, _ = pads.where(app, c) or (0.5, 0.5, f)
                    pads.move(app, c, x, y, f)
                    took = True
            if not took:
                rest.append(ev)
            continue
        played = [] if editing else _controls_for(st, h, ctl)
        if not (took or played):
            rest.append(ev)
        for c in played:
            if ctl[0] == "cc" and c["type"] in pads.SLIDERS:
                pads.drag(app, c, f)
            elif ctl[0] == "cc" and c["type"] in pads.SURFACES:     # a knob on an XY pad: it moves across -
                at = pads.where(app, c) or (0.5, 0.5, 1.0)          # not pressed, as a knob is never let go
                pads.move(app, c, f, at[1], at[2])
            elif v > (0 if ctl[0] == "note" else 63):
                if c["id"] in r["held"]:
                    continue
                r["held"][c["id"]] = (tuple(ctl), f)
                if c["type"] in pads.SURFACES:
                    at = pads.where(app, c) or (0.5, 0.5, f)
                    pads.press(app, c, xy=at[:2], pressure=f)    # a pad's velocity: the first pressure
                elif c["type"] in pads.SLIDERS:
                    pads.drag(app, c, f)
                else:
                    pads.press(app, c)
            elif c["id"] in r["held"]:
                del r["held"][c["id"]]
                pads.release(app, c)
    return rest


def _words(ctl):
    from native import midi
    return midi.ctl_label(tuple(ctl))


def words(ctl):
    """A learned control in words, or "" for none."""
    return _words(ctl) if ctl else ""


# --- the lights ---------------------------------------------------------------------------------------------------
def poll(app):
    """Each frame: the port the lights go out on opened (or closed) as the project has it - a port that is not
    there said once - and the lights set."""
    from native import midi, pads_ui
    if not midi.available():
        return
    out = getattr(app, "_pads_out", None)
    if out is None:
        out = app._pads_out = midi.MidiOut()
    h = hw(pads_ui._st(app))
    if h["out"] != out.port:
        if out.is_open:
            for k in _rt(app)["lights"]:                    # the old one left dark
                out.send(_dark(k))
            _rt(app)["lights"] = {}
            out.close()
        # tried as it is picked, then again every RETRY_S while it is not there (said once, not each time)
        tried, now = getattr(app, "_pads_out_tried", None), time.monotonic()
        new = tried is None or tried[0] != h["out"]
        if h["out"] and (new or (now - tried[1] >= RETRY_S and h["out"] in midi.out_ports())):
            app._pads_out_tried = (h["out"], now)
            try:
                out.open(h["out"])
            except Exception as e:
                if new:
                    app.gp.status(f"pads: the controller's lights: {e}", "warn")
    lights(app, out)



def _pad_msg(device, note, colour, lit, ch=0, step=None):
    """The message that lights one pad: [status, note, velocity] - lit, unlit, or (`step`, 0 up to STEPS[device]
    - 1) pulsing: as bright as the modulator it goes with is up."""
    if step is not None and not lit:
        top = STEPS.get(device, 8) - 1
        if device == "launchpad":
            bright, dim = PALETTE.get(colour, PALETTE["grey"])
            return (0x90, note, (dim, (bright + dim) // 2, bright)[min(step, 2)])
        if device == "apc_mk2":
            return (APC_STEPS[min(step, 3)], note, PALETTE.get(colour, PALETTE["grey"])[0])
        if device == "apc_mk1":
            return (0x90, note, MK1.get(colour, 5) if step else 0)     # it cannot dim: on and off
        return (0x90 | (ch & 0x0F), note, int(round(127 * step / top)))
    if device == "launchpad":
        bright, dim = PALETTE.get(colour, PALETTE["grey"])
        return (0x90, note, bright if lit else dim)
    if device == "apc_mk2":
        bright, dim = PALETTE.get(colour, PALETTE["grey"])
        return (APC_LIT if lit else APC_DIM, note, bright)
    if device == "apc_mk1":
        v = MK1.get(colour, 5)
        return (0x90, note, v + 1 if lit else v)              # its pads cannot dim: lit, they blink
    return (0x90 | (ch & 0x0F), note, 127 if lit else 0)


def pulses(app, st):
    """{control id: brightness step} of the bank's controls whose lights pulse with a modulator, in the device's
    steps (so a light is sent again only when it moves a whole step)."""
    n = STEPS.get(hw(st)["device"], 8)
    out = {}
    for c in pads.current(st)["controls"]:
        v = pads.pulse(app, c)
        if v is not None:
            out[c["id"]] = min(n - 1, int(v * n))
    return out


def wanted(app, st, pulse=None, pulsing=None):
    """{(kind, channel, number): message} - what every light the pads use should be now; `pulse` the steps of those
    pulsing with a modulator (pulses()), their lights' keys put in the set `pulsing`."""
    h = hw(st)
    dev = h["device"]
    b = pads.current(st)
    out = {}
    pulse = pulse or {}
    lit = {c["id"]: bool(pads.lit(app, c)) for c in b["controls"]}     # each control's once, for all its pads
    for c in b["controls"]:
        on = lit[c["id"]]
        ctl = c.get("midi")
        step = pulse.get(c["id"])
        if ctl and ctl[0] == "note":
            m = _pad_msg(dev, int(ctl[2]), c.get("colour"), on, int(ctl[1]), step)
            out[("note", int(ctl[1]), int(ctl[2]))] = m
            if step is not None and pulsing is not None:
                pulsing.add(("note", int(ctl[1]), int(ctl[2])))
        elif ctl and ctl[0] == "cc" and dev in ("generic", "launchpad"):
            v = 127 if on or (step is not None and step >= STEPS.get(dev, 8) // 2) else 0
            out[("cc", int(ctl[1]), int(ctl[2]))] = (0xB0 | (int(ctl[1]) & 0x0F), int(ctl[2]), v)
            if step is not None and pulsing is not None:
                pulsing.add(("cc", int(ctl[1]), int(ctl[2])))
    if _grid_on(h):
        under = {cell: c for c in b["controls"] for cell in pads.cells(c)}     # the control on each cell
        for x in range(8):
            for y in range(8):
                n = cell_note(dev, x, y)
                c = under.get((x, y))
                key = ("note", 0, n)
                if key in out and c is None:
                    continue
                out[key] = _pad_msg(dev, n, c.get("colour"), lit[c["id"]], 0, pulse.get(c["id"])) if c else (0x90, n, 0)
                if c is not None and c["id"] in pulse and pulsing is not None:
                    pulsing.add(key)
        for i in range(8):
            k = bank_ctl(dev, i)
            if k is None:
                continue
            here = i < len(st["banks"])
            cur = i == st["bank"]
            if dev == "launchpad":
                col = st["banks"][i].get("colour", "blue") if here else None
                out[k] = (0xB0, k[2], (PALETTE.get(col, PALETTE["grey"])[0 if cur else 1]) if here else 0)
            else:
                out[k] = (0x90, k[2], 1 if cur else 0)       # the APC's scene buttons: one colour, on or off
    for i, bk in enumerate(st["banks"]):                   # learned bank buttons
        k = bk.get("midi")
        if k and k[0] in ("note", "cc"):
            st_byte = (0x90 if k[0] == "note" else 0xB0) | (int(k[1]) & 0x0F)
            out[(k[0], int(k[1]), int(k[2]))] = (st_byte, int(k[2]), 127 if i == st["bank"] else 0)
    return out


def _dark(k):
    """The message that puts out the light of a (kind, channel, number)."""
    return [(0xB0 if k[0] == "cc" else 0x90) | (int(k[1]) & 0x0F), int(k[2]), 0]


def lights(app, out, now=None):
    """The controller's lights set to the pads, at most LIGHTS_HZ a second, sending only what changed (a device
    switched or the port opened sends its mode and everything again; a light no longer used is put out). A frame
    sends MAX_SENDS at most, pulsing lights PULSE_SENDS of them: what is held back waits for a later frame (its old
    message kept as what was sent, so it is tried again)."""
    from native import pads_ui
    r = _rt(app)
    now = time.monotonic() if now is None else now
    if out is None or not out.is_open:
        r["out"] = None
        return 0
    if now - r["at"] < 1.0 / LIGHTS_HZ:
        return 0
    r["at"] = now
    st = pads_ui._st(app)
    h = hw(st)
    who = (out.port, h["device"], bool(h.get("grid", True)))
    sent = 0
    if r["out"] != who:                                    # a new port or device: its mode, and every light again
        for k in r["lights"]:
            out.send(_dark(k))
        r["lights"] = {}
        for m in program_mode(h["device"]):
            out.send(m)
            sent += 1
        r["out"] = who
    fresh = now - r.get("pulse_at", -1e9) >= 1.0 / PULSE_HZ
    if fresh:
        r["pulse"], r["pulse_at"] = pulses(app, st), now
    pulsing = set()
    want = wanted(app, st, r.get("pulse"), pulsing)
    lights_now = dict(r["lights"])
    budget = PULSE_SENDS if fresh else 0                   # pulses changed only as their levels are read
    waiting = []
    for k, m in want.items():
        if lights_now.get(k) == m or sent >= MAX_SENDS:
            continue
        if k in pulsing and k in lights_now:               # a pulse's next step (one newly lit is not held back)
            waiting.append(k)
            continue
        out.send(list(m))
        sent += 1
        lights_now[k] = m
    when = r.setdefault("pulse_sent", {})
    waiting.sort(key=lambda k: when.get(k, -1e9))           # the longest kept waiting first: every pulse gets its turn
    for k in waiting[:max(0, min(budget, MAX_SENDS - sent))]:
        out.send(list(want[k]))
        sent += 1
        lights_now[k] = want[k]
        when[k] = now
    for k in [k for k in when if k not in pulsing]:
        del when[k]
    for k in [k for k in lights_now if k not in want]:     # a light no longer used: out
        if sent >= MAX_SENDS:
            break
        out.send(_dark(k))
        sent += 1
        del lights_now[k]
    r["lights"] = lights_now
    return sent
