"""Add-on looks for the VJ: packs of MilkDrop presets and Shadertoy shaders from the gallery (gallery.py's
repository), installed once for the whole studio - every project sees them - a pack at a time or a look at a
time, and removed the same way.

    packs = fetch_packs()                 # [Pack] the gallery offers, or gallery.GalleryError
    install(pack)                         # all of it; install(pack, ["one.milk"]) just that one
    installed()                           # {pack id: Pack} on this computer, with the files that are here
    remove("milkdrop-tunnels")            # the whole pack; remove(pid, "one.milk") one look
    dirs()                                # the installed packs' folders, for vj_looks.load_user
    preview(pack)                         # the pack's picture (a strip of its looks), or None

The gallery keeps them beside its graphs: packs.json lists the packs, each a folder looks/<pack id>/ of .milk and
.glsl files, with previews/packs/<pack id>.png:

    {"packs": 1, "list": [{"id": "milkdrop-tunnels", "name": "MilkDrop: Tunnels & radial", "kind": "milkdrop",
      "description": "...", "licence": "...", "items": [{"file": "tunnel-race.milk", "name": "Tunnel race",
      "author": "martin", "licence": "...", "sha256": "<the file's>", "tags": ["tunnel"]}]}]}

What comes from it is not trusted, as with the graphs: a pack's files are found by its id and their names alone
(letters, digits, spaces, dots, dashes - nothing that names another folder or host), only .milk and .glsl are
taken (neither can run anything but its own equations or its shader on the graphics card), each has a size it
may not pass, and one whose sha256 is not the list's is refused. Each look keeps its author and licence at its
top and in its pack's pack.json: a pack marked non-commercial (CC BY-NC-SA) is the authors' to that end.
"""
# AI: below section was generated by an AI
import hashlib
import json
import os
import re
import shutil

from native import gallery, paths

PACKS_MAX = 1 << 20              # packs.json
LOOK_MAX = 512 << 10             # a .milk or a .glsl: the biggest of the cream of the crop is ~40 KB
PREVIEW_MAX = 4 << 20
FILE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 ._()+&,'-]{0,90}\.(milk|glsl)$")
KINDS = ("milkdrop", "shadertoy")


def root():
    d = os.path.join(paths.HOME, "addons", "looks")
    os.makedirs(d, exist_ok=True)
    return d


class Item:
    __slots__ = ("file", "name", "author", "licence", "sha256", "tags", "note")

    def __init__(self, d):
        self.file = d["file"]
        self.name = gallery._text(d.get("name"), 80) or os.path.splitext(self.file)[0]
        self.author = gallery._text(d.get("author"), 80)
        self.licence = gallery._text(d.get("licence"), 80)
        self.sha256 = str(d.get("sha256") or "").lower()
        self.tags = [gallery._text(t, 20) for t in (d.get("tags") or [])[:8] if gallery._text(t, 20)]
        self.note = gallery._text(d.get("note"), 300)            # what was changed for the studio, if anything

    def as_dict(self):
        return {k: getattr(self, k) for k in self.__slots__}


class Pack:
    __slots__ = ("id", "name", "kind", "description", "licence", "items", "noncommercial")

    def __init__(self, d):
        self.id = d["id"]
        self.name = gallery._text(d.get("name"), 80) or self.id
        self.kind = d.get("kind") if d.get("kind") in KINDS else "milkdrop"
        self.description = gallery._text(d.get("description"), 400)
        self.licence = gallery._text(d.get("licence"), 120)
        self.noncommercial = bool(d.get("noncommercial")) or "NC" in self.licence.upper().split("-")
        self.items = []
        seen = set()
        for it in (d.get("items") or [])[:200]:
            if isinstance(it, dict) and isinstance(it.get("file"), str) and FILE.match(it["file"]) \
                    and re.fullmatch(r"[0-9a-fA-F]{64}", str(it.get("sha256") or "")) and it["file"] not in seen:
                seen.add(it["file"])
                self.items.append(Item(it))

    def as_dict(self):
        return {"id": self.id, "name": self.name, "kind": self.kind, "description": self.description,
                "licence": self.licence, "noncommercial": self.noncommercial,
                "items": [i.as_dict() for i in self.items]}

    def file_url(self, item):
        from urllib.parse import quote
        return f"{gallery.base_url()}looks/{self.id}/{quote(item.file)}"

    def preview_url(self):
        return f"{gallery.base_url()}previews/packs/{self.id}.png"


def parse_packs(data):
    """[Pack] from packs.json's bytes: the packs that are whole (an id of the gallery's form, files of the allowed
    names and kinds, each with its sha256); the rest left out."""
    try:
        d = json.loads(data.decode("utf-8"))
    except (ValueError, UnicodeError):
        raise gallery.GalleryError("the gallery's packs.json does not read as JSON") from None
    if not isinstance(d, dict) or not isinstance(d.get("list"), list):
        raise gallery.GalleryError("the gallery's packs.json has no list")
    out, seen = [], set()
    for p in d["list"][:200]:
        if isinstance(p, dict) and isinstance(p.get("id"), str) and gallery.ID.match(p["id"]) and p["id"] not in seen:
            pk = Pack(p)
            if pk.items:
                seen.add(pk.id)
                out.append(pk)
    return out


def fetch_packs():
    return parse_packs(gallery._get(gallery.base_url() + "packs.json", PACKS_MAX))


def _pack_dir(pid):
    if not gallery.ID.match(pid):
        raise ValueError(f"not a pack id: {pid!r}")
    return os.path.join(root(), pid)


def installed():
    """{pack id: Pack} of the packs on this computer, each with the items whose file is here."""
    out = {}
    r = root()
    for pid in sorted(os.listdir(r)):
        meta = os.path.join(r, pid, "pack.json")
        if not gallery.ID.match(pid) or not os.path.isfile(meta):
            continue
        try:
            with open(meta, encoding="utf-8") as f:
                pk = Pack(json.load(f))
        except (OSError, ValueError, KeyError):
            continue
        pk.items = [i for i in pk.items if os.path.isfile(os.path.join(r, pid, i.file))]
        if pk.items:
            out[pid] = pk
    return out


def dirs():
    """The installed packs' folders (what vj_looks.load_user reads besides the project's looks/)."""
    return [os.path.join(root(), pid) for pid in installed()]


def state(pack):
    """For each of a gallery pack's items: "installed", "update" (here, but not the gallery's file now) or "" (not
    here) - {file: state}."""
    d = os.path.join(root(), pack.id)
    out = {}
    for it in pack.items:
        p = os.path.join(d, it.file)
        if not os.path.isfile(p):
            out[it.file] = ""
            continue
        with open(p, "rb") as f:
            out[it.file] = "installed" if hashlib.sha256(f.read()).hexdigest() == it.sha256 else "update"
    return out


def install(pack, files=None):
    """The pack's looks (all, or those named in `files`) fetched, checked against the list and written into its
    folder, its pack.json made to name what is here: [the files installed]. GalleryError at the first that fails
    (the ones before it kept)."""
    d = _pack_dir(pack.id)
    os.makedirs(d, exist_ok=True)
    want = [i for i in pack.items if files is None or i.file in files]
    done = []
    try:
        for it in want:
            data = gallery._get(pack.file_url(it), LOOK_MAX)
            if hashlib.sha256(data).hexdigest() != it.sha256:
                raise gallery.GalleryError(f"{it.name}: the file is not the one the pack names (its sha256 differs) "
                                           "- not installed")
            tmp = os.path.join(d, it.file + ".part")
            with open(tmp, "wb") as f:
                f.write(data)
            os.replace(tmp, os.path.join(d, it.file))
            done.append(it.file)
    finally:
        _write_meta(pack, d)
    return done


def _write_meta(pack, d):
    here = [i for i in pack.items if os.path.isfile(os.path.join(d, i.file))]
    if not here and not os.listdir(d):
        shutil.rmtree(d, ignore_errors=True)
        return
    meta = pack.as_dict()
    meta["items"] = [i.as_dict() for i in here]
    with open(os.path.join(d, "pack.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1)


def remove(pid, file=None):
    """A pack (or one look of it) taken off this computer. True when there was something to take."""
    d = _pack_dir(pid)
    if not os.path.isdir(d):
        return False
    if file is None:
        shutil.rmtree(d, ignore_errors=True)
        return True
    if not FILE.match(file) or not os.path.isfile(os.path.join(d, file)):
        return False
    os.remove(os.path.join(d, file))
    pk = installed().get(pid)
    if pk is None:                                                # its last look: the pack goes too
        shutil.rmtree(d, ignore_errors=True)
    else:
        _write_meta(pk, d)
    return True


def preview(pack):
    """The pack's picture (a PNG strip of its looks), fetched once into HOME/gallery/packs/, as RGB, or None."""
    from PIL import Image
    import io
    cache = os.path.join(gallery.cache_dir(), "packs")
    os.makedirs(cache, exist_ok=True)
    p = os.path.join(cache, pack.id + ".png")
    if not os.path.isfile(p):
        try:
            data = gallery._get(pack.preview_url(), PREVIEW_MAX)
            Image.open(io.BytesIO(data)).verify()
        except Exception:
            return None
        with open(p, "wb") as f:
            f.write(data)
    try:
        import numpy as np
        return np.asarray(Image.open(p).convert("RGB"))
    except Exception:
        return None


def pack_of(path):
    """The installed pack a look's file belongs to (its id), or None for a project's own."""
    r = os.path.normcase(os.path.abspath(root()))
    p = os.path.normcase(os.path.abspath(path))
    if os.path.dirname(os.path.dirname(p)) == r:
        return os.path.basename(os.path.dirname(p))
    return None
