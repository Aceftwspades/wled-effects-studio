"""MilkDrop 2's shaders - a preset's warp and composite shaders (HLSL, Shader
Model 2/3) - translated to GLSL and run on the graphics card (vj_glsl's
thread), for milk.py's presets.

    sh = translate(hlsl, "warp")         # GLSL source, or ValueError
    img, err = run(sh, w, h, inputs)     # the shader's picture, (h, w, 3) float, row 0 the top

The warp shader is the feedback: each frame it reads the last frame (sampler_main)
at the place the preset's motion moves it to (uv) and writes the next. The
composite shader makes what is shown out of that frame, without feeding back.

The translation is by type (native/hlsl.py): the shader is parsed, every expression's type worked out, and what
HLSL converts by itself - a number where a vector goes, a vector cut to a smaller one, an int as a float, a
function's arguments to its types - written out, as GLSL needs. MilkDrop's helpers (GetPixel, GetBlur1..3, lum)
and its inputs (the samplers - the frame, its blurs, the noise textures and volumes - texsize, aspect, time, the
sound, q1..q32, the roam values) are declared; a texture of the preset's own (sampler_lichen: an image MilkDrop
ships) is noise here. A shader the typed translation cannot read falls back to the older rewrite below (HLSL's
names given GLSL's by #define, the common scalar-for-vector cases rewritten); one that still fails to compile is
left out - the preset then runs without it and says so.
"""
