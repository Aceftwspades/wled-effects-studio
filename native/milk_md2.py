MARK = "// the preset's own:\n"


def _decls():
    out = [f"uniform sampler2D {s};" for s in SAMPLERS_2D]
    out += [f"uniform sampler3D {s};" for s in SAMPLERS_3D]
    out += [f"uniform float {f};" for f in FLOATS]
    out += [f"uniform vec4 {v};" for v in VEC4S]
    out += ["uniform vec3 hue_shader;", "uniform sampler2D vj_uvmap;", "uniform float vj_warp;", "out vec4 vj_out;"]
    return "\n".join(out) + "\n"


_VEC_VARS = re.compile(r"\b(?:float|half)([234])\s+(\w+)\s*=\s*(-?\d*\.?\d+(?:[eE][-+]?\d+)?)\s*;")


def _fix_scalars(code, vecs):
    """HLSL's `float3 x = 0.5;` and `ret = 0;` - a number where a vector is - made GLSL's vec3(0.5)."""
    code = _VEC_VARS.sub(lambda m: f"vec{m.group(1)} {m.group(2)} = vec{m.group(1)}({m.group(3)});", code)
    for name, n in vecs.items():
        code = re.sub(rf"(?<![\w.])({re.escape(name)})\s*=\s*(-?\d*\.?\d+(?:[eE][-+]?\d+)?)\s*;",
                      lambda m, n=n: f"{m.group(1)} = vec{n}({m.group(2)});", code)
    return code


def _vector_names(code):
    """{name: size} of the vectors declared in the code (and ret, a float3), for the scalar rewrite."""
    out = {"ret": 3}
    for m in re.finditer(r"\b(?:float|half|vec)([234])\s+(\w+)", code):
        out[m.group(2)] = int(m.group(1))
    return out


def translate(hlsl, which):
    """A preset's warp or comp shader as GLSL: its declarations before `shader_body`, its body in main()."""
    text = hlsl.replace("\r", "")
    m = re.search(r"shader_body\s*\{", text)
    if not m:
        raise ValueError(f"the {which} shader has no shader_body")
    head = text[:m.start()]
    depth, k = 1, m.end()
    while k < len(text) and depth:
        depth += {"{": 1, "}": -1}.get(text[k], 0)
        k += 1
    body = text[m.end():k - 1]
    # what HLSL declares that GLSL cannot: its samplers (declared here), static
    head = re.sub(r"^\s*sampler(?:2D|3D)?\s+\w+\s*;\s*$", "", head, flags=re.M)
    head = re.sub(r"\bstatic\s+const\b", "const", head)
    head = re.sub(r"\bstatic\b", "", head)
    head = re.sub(r"^\s*(?:float|half)4\s+texsize_\w+\s*;\s*$", "", head, flags=re.M)   # declared already
    vecs = _vector_names(head + body)
    head, body = _fix_scalars(head, vecs), _fix_scalars(body, vecs)
    main = (
        "void main() {\n"
        "    vec2 uv_orig = vec2(gl_FragCoord.x / texsize.x, 1.0 - gl_FragCoord.y / texsize.y);\n"
        "    vec2 uv = vj_warp > 0.5 ? texture(vj_uvmap, uv_orig).xy : uv_orig;\n"
        "    vec2 vj_d = (uv_orig - 0.5) * aspect.xy;\n"
        "    float rad = length(vj_d) * 2.0;\n"
        "    float ang = atan(vj_d.y, vj_d.x);\n"
        "    vec3 ret = vec3(0.0);\n"
        + body + "\n"
        "    vj_out = vec4(ret, 1.0);\n"
        "}\n")
    return PRELUDE + _decls() + MARK + head + "\n" + main


