"""MilkDrop 2's shaders - a preset's warp and composite shaders (HLSL, Shader
Model 2/3) - translated to GLSL and run on the graphics card (vj_glsl's
thread), for milk.py's presets.

    sh = translate(hlsl, "warp")         # GLSL source, or ValueError
    img, err = run(sh, w, h, inputs)     # the shader's picture, (h, w, 3) float, row 0 the top

The warp shader is the feedback: each frame it reads the last frame (sampler_main)
at the place the preset's motion moves it to (uv) and writes the next. The
composite shader makes what is shown out of that frame, without feeding back.

A translation, so a careful one rather than a complete one: HLSL's types and
functions are given GLSL's (float3 -> vec3, lerp -> mix, frac -> fract,
saturate, tex2D, mul, fmod...), MilkDrop's helpers (GetPixel, GetBlur1..3, lum)
and its inputs (the samplers - the frame, its blurs, the noise textures and
volumes - texsize, aspect, time, the sound, q1..q32, the roam values) are
declared. HLSL lets a number stand for a vector (`ret = 0;`) where GLSL does
not; the common cases are rewritten, the rest fail to compile - the preset then
runs without that shader and says so.
"""
