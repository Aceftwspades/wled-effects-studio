_NOISE = {}


def noise_textures():
    """MilkDrop's noise: 2-D textures of four sizes (RGBA, repeating) and two 32^3 volumes - made once."""
    if not _NOISE:
        rng = np.random.default_rng(2007)
        for name, n in (("sampler_noise_lq", 256), ("sampler_noise_lq_lite", 32), ("sampler_noise_mq", 256),
                        ("sampler_noise_hq", 256)):
            a = rng.random((n, n, 4)).astype(np.float32)
            if name != "sampler_noise_lq":                       # the finer ones smoother, as MilkDrop's are made
                from PIL import Image
                small = (rng.random((n // 4, n // 4, 4)) * 255).astype(np.uint8)
                a = np.asarray(Image.fromarray(small, "RGBA").resize((n, n), Image.BICUBIC), np.float32) / 255.0
            _NOISE[name] = a
        for name in SAMPLERS_3D:
            _NOISE[name] = (rng.random((32, 32, 32, 4)) * 255).astype(np.uint8)
    return _NOISE


def run(src, w, h, uni, frame, blurs, uvmap=None, key="md2"):
    """The shader drawn: its picture (h, w, 3) float, row 0 the top - or (None, error)."""
    from native import vj_glsl
    tex = {"sampler_main": frame, "sampler_fw_main": frame, "sampler_fc_main": frame, "sampler_pw_main": frame,
           "sampler_pc_main": frame, "sampler_blur1": blurs[0], "sampler_blur2": blurs[1], "sampler_blur3": blurs[2]}
    tex.update(noise_textures())
    u = dict(uni)
    u["vj_warp"] = 1.0 if uvmap is not None else 0.0
    if uvmap is not None:
        tex["vj_uvmap"] = uvmap
    img, err = vj_glsl.run_frag(key, src, w, h, u, tex)
    if img is None:
        return None, err
    return np.flipud(img), ""


def uniforms(v, w, h, t, frame):
    """MilkDrop's shader inputs from a preset's variables at this frame."""
    u = {k: float(v.get(k, 0.0)) for k in FLOATS if k in v}
    u.update(time=float(t), frame=float(frame), fps=float(v.get("fps", 30.0)),
             vol=(float(v.get("bass", 1)) + float(v.get("mid", 1)) + float(v.get("treb", 1))) / 3.0,
             vol_att=(float(v.get("bass_att", 1)) + float(v.get("mid_att", 1)) + float(v.get("treb_att", 1))) / 3.0,
             blur1_min=0.0, blur1_max=1.0, blur2_min=0.0, blur2_max=1.0, blur3_min=0.0, blur3_max=1.0)
    u["texsize"] = (float(w), float(h), 1.0 / w, 1.0 / h)
    asp = (float(h) / w if w > h else 1.0, float(w) / h if h > w else 1.0)
    u["aspect"] = (asp[0], asp[1], 1.0 / asp[0], 1.0 / asp[1])
    qs = [float(v.get(f"q{k}", 0.0)) for k in range(1, 33)]
    for j, name in enumerate(("_qa", "_qb", "_qc", "_qd", "_qe", "_qf", "_qg", "_qh")):
        u[name] = tuple(qs[j * 4:j * 4 + 4])
    for k in range(1, 33):
        u[f"q{k}"] = qs[k - 1]
    rng = np.random.default_rng(int(frame))
    u["rand_frame"] = tuple(float(x) for x in rng.random(4))
    u["rand_preset"] = (0.31, 0.62, 0.17, 0.83)
    r = [t * s for s in (0.005, 0.008, 0.013, 0.022)]
    u["roam_cos"] = tuple(0.5 + 0.5 * math.cos(x * 20) for x in r)
    u["roam_sin"] = tuple(0.5 + 0.5 * math.sin(x * 20) for x in r)
    u["slow_roam_cos"] = tuple(0.5 + 0.5 * math.cos(x) for x in r)
    u["slow_roam_sin"] = tuple(0.5 + 0.5 * math.sin(x) for x in r)
    hs = 0.5 + 0.5 * np.cos(t * np.array([0.33, 0.41, 0.53]) + np.array([0.0, 2.0, 4.0]))
    u["hue_shader"] = tuple(float(x) for x in hs)
    for name in ("noise_lq", "noise_mq", "noise_hq"):
        u["texsize_" + name] = (256.0, 256.0, 1 / 256.0, 1 / 256.0)
    u["texsize_noise_lq_lite"] = (32.0, 32.0, 1 / 32.0, 1 / 32.0)
    u["texsize_noisevol_lq"] = u["texsize_noisevol_hq"] = (32.0, 32.0, 1 / 32.0, 1 / 32.0)
    return u


def blurs(fb, src=""):
    """MilkDrop's three blurs of the frame, each softer than the last - the frame shrunk to a half, a quarter and an
    eighth and grown back. Only when the shader reads one (`src` says); else the frame itself stands for them."""
    own = src.split(MARK, 1)[-1] if src else ""
    if src and "blur" not in own.lower():
        return fb, fb, fb
    from PIL import Image
    h, w = fb.shape[:2]
    out = []
    for k in (2, 4, 8):
        sw, sh = max(1, w // k), max(1, h // k)
        chans = [np.asarray(Image.fromarray(np.ascontiguousarray(fb[..., c]), "F").resize((sw, sh), Image.BOX)
                            .resize((w, h), Image.BILINEAR)) for c in range(3)]
        out.append(np.stack(chans, -1).astype(np.float32))
    return tuple(out)
