class _Tok:
    __slots__ = ("kind", "val", "line")

    def __init__(self, kind, val, line):
        self.kind, self.val, self.line = kind, val, line

    def __repr__(self):
        return f"{self.kind}:{self.val}"


_LEX = re.compile(r"""
    (?P<ws>[ \t\r\n]+) |
    (?P<cm>//[^\n]*|/\*.*?\*/) |
    (?P<num>(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?[fFhH]?|0[xX][0-9A-Fa-f]+) |
    (?P<id>[A-Za-z_]\w*) |
    (?P<op><<=|>>=|\+\+|--|<<|>>|<=|>=|==|!=|&&|\|\||[-+*/%&|^]=|[-+*/%<>=!~&|^?:;,.(){}\[\]])
""", re.X | re.S)


def tokens(src):
    out, i, line = [], 0, 1
    while i < len(src):
        m = _LEX.match(src, i)
        if not m:
            raise ValueError(f"cannot read {src[i:i + 16]!r}")
        k = m.lastgroup
        if k not in ("ws", "cm"):
            out.append(_Tok(k, m.group(k), line))
        line += m.group(0).count("\n")
        i = m.end()
    return out


def defines(src):
    """The source without its directives, and its #defines {name: (parameters or None, tokens)}."""
    lines, defs = [], {}
    for ln in src.replace("\\\n", " ").split("\n"):
        s = ln.strip()
        if s.startswith("#"):
            m = re.match(r"#\s*define\s+(\w+)(\(([^)]*)\))?\s*(.*)$", s)
            if m:
                params = [p.strip() for p in m.group(3).split(",") if p.strip()] if m.group(2) else None
                defs[m.group(1)] = (params, tokens(m.group(4)))
            lines.append("")
            continue
        lines.append(ln)
    return "\n".join(lines), defs


def preprocess(src, defs=None):
    """#define (object-like and with arguments) expanded on the tokens; the other directives dropped. `defs`: macros
    defined elsewhere (a shader's head's, for its body) as well as its own."""
    text, own = defines(src)
    defs = dict(defs or {})
    defs.update(own)
    toks = tokens(text)
    if not defs:
        return toks
    for _ in range(8):                                     # nested macros, a few levels deep
        out, i, changed = [], 0, False
        while i < len(toks):
            t = toks[i]
            d = defs.get(t.val) if t.kind == "id" else None
            if d is None:
                out.append(t); i += 1; continue
            params, body = d
            if params is None:
                out += body; i += 1; changed = True; continue
            if i + 1 >= len(toks) or toks[i + 1].val != "(":
                out.append(t); i += 1; continue
            args, cur, depth, j = [], [], 0, i + 2
            while j < len(toks):
                v = toks[j].val
                if v == "(":
                    depth += 1
                elif v == ")":
                    if depth == 0:
                        break
                    depth -= 1
                elif v == "," and depth == 0:
                    args.append(cur); cur = []; j += 1; continue
                cur.append(toks[j]); j += 1
            args.append(cur)
            sub = dict(zip(params, args))
            for bt in body:
                out += [_Tok("op", "(", bt.line)] + sub[bt.val] + [_Tok("op", ")", bt.line)] \
                    if bt.kind == "id" and bt.val in sub else [bt]
            i = j + 1
            changed = True
        toks = out
        if not changed:
            break
    return toks


# --- conversions ------------------------------------------------------------------------------------------------------
def _is_int_literal(code):
    return re.fullmatch(r"\(?-?\d+\)?", code) is not None


def _float_literal(code):
    c = code.strip("()")
    return f"({c}.0)" if c.startswith("-") else c + ".0"


def conv(code, src, dst):
    """`code` of type src made of type dst, as HLSL would do it by itself."""
    if src is None or dst is None or src == dst:
        return code
    sb, sn = src
    db, dn = dst
    if sb == "array" or db == "array":
        return code
    if db in ("sampler2D", "sampler3D", "void", "mat") or sb in ("sampler2D", "sampler3D", "void", "mat"):
        return code
    if db == "float":
        if sb in ("int", "bool"):
            if sn == 1:
                code = _float_literal(code) if (sb == "int" and _is_int_literal(code)) else f"float({code})"
            else:
                code = f"vec{sn}({code})"
            sn = sn
        if sn == dn:
            return code
        if sn == 1:
            return f"vec{dn}({code})"
        if dn == 1:
            return f"({code}).x"
        if sn > dn:
            return f"({code}).{'xyzw'[:dn]}"
        return f"vec{dn}({code}{', 0.0' * (dn - sn)})"
    if db == "int":
        if sn == 1 and dn == 1:
            return f"int({code})"
        if dn == 1:
            return f"int(({code}).x)"
        return f"ivec{dn}({conv(code, src, ('float', dn))})"
    if db == "bool":
        if dn == 1:
            if sn == 1:
                return f"({code} != {'0.0' if sb == 'float' else '0'})" if sb != "bool" else code
            return f"any(notEqual({conv(code, src, ('float', sn))}, vec{sn}(0.0)))"
        return f"bvec{dn}({code})"
    return code


def unify(types):
    """The size a set of operands is worked at: the smallest vector among them (larger ones cut), a lone scalar's
    size 1; and the base: float if any is float, else int."""
    vec = [t[1] for t in types if t and t[0] in ("float", "int", "bool") and t[1] > 1]
    n = min(vec) if vec else 1
    base = "float" if any(t and t[0] == "float" for t in types) or not types else (
        "int" if any(t and t[0] == "int" for t in types) else "bool")
    if base == "bool":
        base = "float"
    return (base, n)


