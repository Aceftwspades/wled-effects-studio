"""HLSL to GLSL for MilkDrop 2's shaders, by type: the shader parsed, the type of every expression worked out, and
what HLSL does by itself written out for GLSL, which does none of it.

    glsl_head, glsl_body = translate(head, body, symbols)

HLSL (Shader Model 2/3, as MilkDrop compiles it with D3DX) converts quietly where GLSL refuses:

- a number where a vector goes - `float3 c = 0.5;`, `ret = 0;` - is that number in every component: vec3(0.5);
- a vector where a smaller one goes is cut to it: `float x = tex2D(s, uv);` is its .x, `ret = tex2D(...)` its .xyz;
- two vectors of different sizes in one sum are cut to the smaller (`v4 * v3` is a float3);
- a function's arguments take the types it asks for (`pow(c, 2)`: the 2 a float3; a user function's parameters);
- an int is a float wherever a float is wanted, a float or a vector a condition (`if (x)`: x != 0);
- a number can be swizzled (`x.xxx`), and `%` works on floats (fmod).

And the names: HLSL's functions as GLSL's (lerp mix, frac fract, tex2D texture...), a preset's own names that GLSL
keeps for itself (texture, sample, input, filter...) or forbids (a double underscore) renamed, `mul(v, M)` with
HLSL's row-major matrices turned round, #define expanded, global initialisers that read the inputs moved into
main(). What it cannot read raises ValueError - the preset then runs without that shader and says so.

The approach - an HLSL front end that types the shader before writing GLSL - is projectM's (its hlslparser, from
Unknown Worlds' HLSLParser: github.com/projectM-visualizer/projectm, MIT/zlib); this is written from the rules of
HLSL above, nothing copied.
"""
