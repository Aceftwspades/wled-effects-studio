class Scope:
    def __init__(self, parent=None):
        self.vars, self.parent = {}, parent

    def find(self, name):
        s = self
        while s is not None:
            if name in s.vars:
                return s.vars[name]
            s = s.parent
        return None


class _Translator:
    def __init__(self, toks, symbols, funcs):
        self.t, self.k = toks, 0
        self.scope = Scope()
        for n, v in symbols.items():                      # {name: type} or {name: (glsl name, type)}
            self.scope.vars[n] = v if isinstance(v[1], tuple) else (n, v)
        self.funcs = {k: list(v) for k, v in funcs.items()}   # name -> [(glsl name, return type, [param types])]
        self.helpers = set(funcs)                         # MilkDrop's: a preset's own of the name replaces it
        self.inputs = set(symbols)                        # MilkDrop's inputs: written to, they need a copy
        self.written = set()
        self.samplers = []                                # sampler names the shader declares (textures of its own)
        self.moved = []                                   # global initialisers to run at the top of main()

    # -- tokens --
    def peek(self, a=0):
        k = self.k + a
        return self.t[k] if k < len(self.t) else _Tok("eof", "", -1)

    def take(self, want=None):
        tok = self.peek()
        if want is not None and tok.val != want:
            raise ValueError(f"line {tok.line}: expected {want!r}, found {tok.val!r}")
        self.k += 1
        return tok

    def accept(self, val):
        if self.peek().val == val:
            self.k += 1
            return True
        return False

    # -- names --
    def own_name(self, name):
        if name in _GLSL_RESERVED or name in self.helpers or "__" in name or name.startswith("gl_") \
                or name.startswith("_hlsl"):
            return "h_" + name.replace("__", "_U_")
        return name

    def is_type(self, a=0):
        tok = self.peek(a)
        return tok.kind == "id" and tok.val in _TYPES

    def read_type(self):
        while self.peek().val in ("static", "const", "uniform", "inline", "in", "out", "inout", "extern"):
            self.take()
        tok = self.take()
        if tok.val not in _TYPES:
            raise ValueError(f"line {tok.line}: not a type: {tok.val!r}")
        return _TYPES[tok.val]

    # -- the head: globals and functions --
    def head(self):
        out = []
        while self.peek().kind != "eof":
            if self.accept(";"):
                continue
            quals = []
            while self.peek().val in ("static", "const", "uniform", "inline", "extern"):
                quals.append(self.take().val)
            if not self.is_type():
                raise ValueError(f"line {self.peek().line}: expected a declaration, found {self.peek().val!r}")
            ty = self.read_type()
            name = self.take().val
            if self.peek().val == "(":
                out.append(self.function(ty, name))
            else:
                out.append(self.global_decl(ty, name, "const" in quals))
        return "\n".join(o for o in out if o)

    def function(self, ret, name):
        self.take("(")
        params, sig = [], []
        inner = Scope(self.scope)
        while not self.accept(")"):
            qual = ""
            while self.peek().val in ("in", "out", "inout", "const", "uniform"):
                v = self.take().val
                qual = v if v in ("out", "inout") else qual
            pt = self.read_type()
            pn = self.take().val
            if self.accept(":"):
                self.take()                               # a semantic (: TEXCOORD0) - not GLSL's
            g = self.own_name(pn)
            inner.vars[pn] = (g, pt)
            params.append(f"{(qual + ' ') if qual else ''}{glsl_type(pt)} {g}")
            sig.append(pt)
            self.accept(",")
        gname = self.own_name(name)
        if name in self.helpers:                          # the preset's own GetPixel, lum...: its, not MilkDrop's
            self.helpers.discard(name)
            self.funcs[name] = []
        self.funcs.setdefault(name, []).append((gname, ret, sig))
        if self.accept(";"):
            return f"{glsl_type(ret)} {gname}({', '.join(params)});"
        saved, self.scope = self.scope, inner
        self.ret_type = ret
        body = self.block()
        self.scope = saved
        return f"{glsl_type(ret)} {gname}({', '.join(params)}) {body}"

    def global_decl(self, ty, name, const):
        if ty[0] in ("sampler2D", "sampler3D"):
            if self.accept("="):                          # = sampler_state { AddressU = WRAP; ... }: D3D's, not GLSL's
                if self.peek().val == "sampler_state":
                    self.take()
                depth = 0
                while True:
                    v = self.take().val
                    depth += {"{": 1, "}": -1}.get(v, 0)
                    if depth == 0 and v == "}":
                        break
            parts = [name]
            while self.accept(","):
                parts.append(self.take().val)
            self.take(";")
            for n in parts:
                self.scope.vars[n] = (n, ty)
                if n not in self.samplers:
                    self.samplers.append((n, ty))
            return ""
        out = []
        while True:
            g = self.own_name(name)
            arr = self.array_size()
            known = self.scope.find(name)
            if self.accept("="):
                code, et = self.initializer(ty, arr)
                if known is not None and known[0] == name and not arr:
                    pass                                   # an input MilkDrop gives (texsize_x...): declared already
                elif const and not re.search(r"[A-Za-z_]", re.sub(r"\b(vec[234]|float|int)\b|\d[eE]", "", code)):
                    out.append(f"const {glsl_type(ty)} {g}{arr} = {code};")
                else:                                      # read from the inputs: set at the top of main()
                    out.append(f"{glsl_type(ty)} {g}{arr};")
                    self.moved.append(f"{g} = {code};")
            elif known is None or arr:
                out.append(f"{glsl_type(ty)} {g}{arr};")
            if known is None:
                self.scope.vars[name] = (g, ty if not arr else ("array", ty))
            if self.accept(","):
                name = self.take().val
                continue
            if self.accept(":"):
                self.take()
            self.take(";")
            return "\n".join(out)

    def array_size(self):
        if self.accept("["):
            n = self.take().val
            self.take("]")
            return f"[{n}]"
        return ""

    def initializer(self, ty, arr):
        if self.peek().val == "{":                         # {1, 2, 3}: the type's constructor
            self.take()
            items = []
            while not self.accept("}"):
                c, t = self.assign()
                items.append((c, t))
                self.accept(",")
            if arr:
                n = int(arr[1:-1]) if arr[1:-1].isdigit() else 0
                if ty[0] == "float" and ty[1] > 1 and n and len(items) == n * ty[1] and all(t and t[1] == 1 for _, t in items):
                    # an array of vectors given number by number: {0, 0, 0, 1, 0, 1, ...}
                    k = ty[1]
                    items = [(f"{glsl_type(ty)}({', '.join(conv(c, t, F1) for c, t in items[j:j + k])})", ty)
                             for j in range(0, len(items), k)]
                return f"{glsl_type(ty)}{arr}({', '.join(conv(c, t, ty) for c, t in items)})", ty
            if ty[0] == "mat":
                return f"{glsl_type(ty)}({', '.join(conv(c, t, F1) if t and t[1] == 1 else c for c, t in items)})", ty
            return f"{glsl_type(ty)}({', '.join(conv(c, t, (ty[0], 1)) for c, t in items)})", ty
        c, t = self.assign()
        return (c if arr else conv(c, t, ty)), ty

    # -- statements --
    def block(self):
        self.take("{")
        saved, self.scope = self.scope, Scope(self.scope)
        parts = []
        while not self.accept("}"):
            if self.peek().kind == "eof":
                raise ValueError("a block is not closed")
            parts.append(self.statement())
        self.scope = saved
        return "{\n" + "\n".join(p for p in parts if p) + "\n}"

    def body(self):
        """The shader_body's statements (main's scope already holds uv, ret...)."""
        parts = []
        while self.peek().kind != "eof":
            parts.append(self.statement())
        return "\n".join(p for p in parts if p)

    def statement(self):
        tok = self.peek()
        v = tok.val
        if v == "{":
            return self.block()
        if v == ";":
            self.take(); return ""
        if v == "if":
            self.take(); self.take("(")
            c, t = self.expr()
            self.take(")")
            s = f"if ({conv(c, t, B1)}) {self.sub_statement()}"
            if self.accept("else"):
                s += f" else {self.sub_statement()}"
            return s
        if v == "while":
            self.take(); self.take("(")
            c, t = self.expr()
            self.take(")")
            return f"while ({conv(c, t, B1)}) {self.sub_statement()}"
        if v == "do":
            self.take()
            s = self.sub_statement()
            self.take("while"); self.take("(")
            c, t = self.expr()
            self.take(")"); self.take(";")
            return f"do {s} while ({conv(c, t, B1)});"
        if v == "for":
            self.take(); self.take("(")
            saved, self.scope = self.scope, Scope(self.scope)
            init = self.decl_or_expr(";")
            self.take(";")
            cond = ""
            if self.peek().val != ";":
                c, t = self.expr()
                cond = conv(c, t, B1)
            self.take(";")
            step = ""
            if self.peek().val != ")":
                step = self.expr()[0]
            self.take(")")
            s = self.sub_statement()
            self.scope = saved
            return f"for ({init}; {cond}; {step}) {s}"
        if v == "return":
            self.take()
            if self.accept(";"):
                return "return;"
            c, t = self.expr()
            self.take(";")
            rt = getattr(self, "ret_type", None)
            return f"return {conv(c, t, rt) if rt else c};"
        if v in ("break", "continue", "discard"):
            self.take(); self.take(";")
            return f"{v};"
        s = self.decl_or_expr(";")
        self.take(";")
        return s + ";"

    def sub_statement(self):
        if self.peek().val == "{":
            return self.block()
        saved, self.scope = self.scope, Scope(self.scope)
        s = self.statement()
        self.scope = saved
        return "{ " + s + " }"

    def decl_or_expr(self, end):
        if self.peek().val == end:
            return ""
        j = 0
        while self.peek(j).val in ("static", "const", "uniform", "in"):
            j += 1
        if self.is_type(j) and self.peek(j + 1).kind == "id":
            const = any(self.peek(i).val == "const" for i in range(j))
            ty = self.read_type()
            out = []
            while True:
                name = self.take().val
                g = self.own_name(name)
                arr = self.array_size()
                if self.accept("="):
                    code, _ = self.initializer(ty, arr)
                    out.append(f"{g}{arr} = {code}")
                else:
                    out.append(f"{g}{arr}")
                self.scope.vars[name] = (g, ty if not arr else ("array", ty))
                if not self.accept(","):
                    break
            return f"{glsl_type(ty)} " + ", ".join(out)
        return self.expr()[0]

    # -- expressions: (GLSL code, type) --
    def expr(self):
        c, t = self.assign()
        while self.accept(","):
            c2, t = self.assign()
            c = f"{c}, {c2}"
        return c, t

    _ASSIGN = ("=", "+=", "-=", "*=", "/=", "%=")

    def assign(self):
        start = self.k
        lc, lt = self.ternary()
        op = self.peek().val
        if op in self._ASSIGN:
            root = self.t[start].val if self.t[start].kind == "id" else None
            if root in self.inputs and self.scope.find(root) and self.scope.find(root)[0] == root:
                self.written.add(root)
            self.take()
            rc, rt = self.assign()
            if lt is None:
                return f"{lc} {op} {rc}", lt
            if op == "=":
                return f"{lc} = {conv(rc, rt, lt)}", lt
            if op == "%=":
                return f"{lc} = _hlsl_fmod({lc}, {conv(rc, rt, lt)})", lt
            if lt[0] == "mat":
                return f"{lc} {op} {rc}", lt
            if rt and rt[1] == 1 and lt[0] == "float":     # a vector times a number: as it is (the number a float)
                return f"{lc} {op} {conv(rc, rt, F1)}", lt
            return f"{lc} {op} {conv(rc, rt, lt)}", lt
        return lc, lt

    def ternary(self):
        c, t = self.binary(0)
        if self.accept("?"):
            ac, at = self.assign()
            self.take(":")
            bc, bt = self.assign()
            u = unify([at, bt])
            if t and t[1] > 1:                            # a vector condition: chosen component by component
                return f"mix({conv(bc, bt, u)}, {conv(ac, at, u)}, vec{t[1]}({c}))", u
            return f"(({conv(c, t, B1)}) ? {conv(ac, at, u)} : {conv(bc, bt, u)})", u
        return c, t

    _PREC = {"||": 1, "&&": 2, "|": 3, "^": 4, "&": 5, "==": 6, "!=": 6, "<": 7, ">": 7, "<=": 7, ">=": 7,
             "<<": 8, ">>": 8, "+": 9, "-": 9, "*": 10, "/": 10, "%": 10}
    _VCMP = {"<": "lessThan", ">": "greaterThan", "<=": "lessThanEqual", ">=": "greaterThanEqual", "==": "equal",
             "!=": "notEqual"}

    def binary(self, prec):
        lc, lt = self.unary()
        while True:
            op = self.peek().val
            if self.peek().kind != "op" or op not in self._PREC or self._PREC[op] < prec:
                return lc, lt
            self.take()
            rc, rt = self.binary(self._PREC[op] + 1)
            lc, lt = self.combine(op, lc, lt, rc, rt)

    def combine(self, op, lc, lt, rc, rt):
        if lt is None or rt is None:
            return f"({lc} {op} {rc})", lt or rt
        if op in ("&&", "||"):
            return f"({conv(lc, lt, B1)} {op} {conv(rc, rt, B1)})", B1
        if lt[0] == "mat" or rt[0] == "mat":
            if lt[0] == "mat" and rt[0] == "mat":
                return f"({lc} {op} {rc})", lt
            m = lt if lt[0] == "mat" else rt
            return f"({lc} {op} {conv(rc, rt, F1) if rt[1] == 1 else rc})" if lt[0] == "mat" else \
                f"({conv(lc, lt, F1) if lt[1] == 1 else lc} {op} {rc})", m
        if op in self._VCMP:
            u = unify([lt, rt])
            if u[1] > 1:
                return f"{self._VCMP[op]}({conv(lc, lt, u)}, {conv(rc, rt, u)})", ("bool", u[1])
            if lt[0] == "int" and rt[0] == "int":
                return f"({lc} {op} {rc})", B1
            return f"({conv(lc, lt, F1)} {op} {conv(rc, rt, F1)})", B1
        if op in ("&", "|", "^", "<<", ">>"):
            return f"({conv(lc, lt, I1)} {op} {conv(rc, rt, I1)})", I1
        if lt[0] == "bool" or rt[0] == "bool":                 # true * 2: the bool as a float
            lc, lt = conv(lc, lt, ("float", lt[1])), ("float", lt[1])
            rc, rt = conv(rc, rt, ("float", rt[1])), ("float", rt[1])
        u = unify([lt, rt])
        if u[0] == "int" and op != "%":
            return f"({lc} {op} {rc})", u
        if op == "%":
            return f"_hlsl_fmod({conv(lc, lt, ('float', u[1]))}, {conv(rc, rt, ('float', u[1]))})", ("float", u[1])
        # a number with a vector: as it is in GLSL (made a float); vectors of two sizes: both cut to the smaller
        a = conv(lc, lt, F1) if lt[1] == 1 else conv(lc, lt, u)
        b = conv(rc, rt, F1) if rt[1] == 1 else conv(rc, rt, u)
        return f"({a} {op} {b})", u

    def unary(self):
        v = self.peek().val
        if v in ("-", "+", "!", "~") and self.peek().kind == "op":
            self.take()
            c, t = self.unary()
            if v == "!":
                if t and t[1] > 1:
                    return f"not({conv(c, t, ('bool', t[1]))})", ("bool", t[1])
                return f"(!{conv(c, t, B1)})", B1
            if v == "~":
                return f"(~{conv(c, t, I1)})", I1
            return (f"({v}{c})", t)
        if v in ("++", "--"):
            self.take()
            c, t = self.unary()
            return f"{v}{c}", t
        if v == "(" and self.is_type(1) and self.peek(2).val == ")":     # a cast: (float3)x
            self.take()
            ty = self.read_type()
            self.take(")")
            c, t = self.unary()
            if ty[0] == "float" and t and t[0] == "float" and t[1] == 1 and ty[1] > 1:
                return f"{glsl_type(ty)}({c})", ty
            return conv(c, t, ty), ty
        return self.postfix()

    def postfix(self):
        c, t = self.primary()
        while True:
            v = self.peek().val
            if v == ".":
                self.take()
                sw = self.take().val
                if not re.fullmatch(r"[xyzw]{1,4}|[rgba]{1,4}", sw):
                    raise ValueError(f"line {self.peek().line}: not a swizzle: .{sw}")
                n = len(sw)
                if t and t[1] == 1 and t[0] in ("float", "int", "bool"):      # a number swizzled: x.xxx
                    c, t = (c if n == 1 else f"vec{n}({conv(c, t, F1)})"), (("float", n) if n > 1 else t)
                else:
                    c, t = f"{c}.{sw}", ((t[0] if t else "float"), n)
            elif v == "[":
                self.take()
                ic, it = self.expr()
                self.take("]")
                if t and t[0] == "array":
                    c, t = f"{c}[{conv(ic, it, I1)}]", t[1]
                elif t and t[0] == "mat":
                    c, t = f"{c}[{conv(ic, it, I1)}]", ("float", t[1])
                else:
                    c, t = f"{c}[{conv(ic, it, I1)}]", ((t[0] if t else "float"), 1)
            elif v in ("++", "--"):
                self.take()
                c = f"{c}{v}"
            else:
                return c, t

    def primary(self):
        tok = self.take()
        if tok.kind == "num":
            s = tok.val
            if s.lower().startswith("0x"):
                return str(int(s, 16)), I1
            s = s.rstrip("fFhH")
            if re.fullmatch(r"\d+", s):
                return s, I1
            if s.endswith("."):
                s += "0"
            if s.startswith("."):
                s = "0" + s
            return s, F1
        if tok.val == "(":
            c, t = self.expr()
            self.take(")")
            return f"({c})", t
        if tok.kind != "id":
            raise ValueError(f"line {tok.line}: unexpected {tok.val!r}")
        name = tok.val
        if name in ("true", "false"):
            return name, B1
        if self.peek().val == "(":
            return self.call(name)
        found = self.scope.find(name)
        if found is None and name.startswith("sampler_"):    # a texture of the preset's own, used undeclared
            found = (name, ("sampler2D", 0))
            self.root_scope().vars[name] = found
            self.samplers.append((name, found[1]))
        if found is None:
            raise ValueError(f"line {tok.line}: {name!r} is not declared")
        return found

    def root_scope(self):
        s = self.scope
        while s.parent is not None:
            s = s.parent
        return s

    def args(self):
        self.take("(")
        out = []
        while not self.accept(")"):
            out.append(self.assign())
            if not self.accept(","):
                self.take(")")
                break
        return out

    def call(self, name):
        if name in _TYPES:                                  # a constructor: float3(...), float2x2(...)
            ty = _TYPES[name]
            a = self.args()
            if ty[0] == "float" and len(a) == 1 and a[0][1] and a[0][1][0] == "float" and a[0][1][1] < ty[1] \
                    and a[0][1][1] > 1:
                return conv(a[0][0], a[0][1], ty), ty
            parts = [conv(c, t, ("float", t[1])) if (t and t[0] == "int" and ty[0] == "float") else c for c, t in a]
            return f"{glsl_type(ty)}({', '.join(parts)})", ty
        a = self.args()
        types = [t for _, t in a]
        if name in self.funcs:                              # the preset's own (or MilkDrop's helpers)
            cands = self.funcs[name]
            best = next((f for f in cands if len(f[2]) == len(a)), cands[0])
            g, ret, sig = best
            parts = [conv(c, t, pt) for (c, t), pt in zip(a, sig)]
            return f"{g}({', '.join(parts)})", ret
        return self.builtin(name, a, types)

    def builtin(self, name, a, types):
        g = _RENAME.get(name, name)
        n = len(a)

        def to(i, ty):
            return conv(a[i][0], types[i], ty)
        if n == 1 and (name in _GEN1 or name in ("frac", "rsqrt", "ddx", "ddy", "saturate", "log10")):
            t = types[0] if types[0] and types[0][0] == "float" else ("float", types[0][1] if types[0] else 1)
            if name == "normalize" and t[1] == 1:
                return f"sign({to(0, t)})", t
            return f"{g}({to(0, t)})", t
        if name in ("pow", "min", "max", "fmod", "atan2", "step", "reflect") and n == 2:
            u = unify(types)
            u = ("float", u[1])
            return f"{g}({to(0, u)}, {to(1, u)})", u
        if name in ("dot", "distance") and n == 2:
            u = ("float", unify(types)[1])
            if name == "dot" and u[1] == 1:
                return f"({to(0, u)} * {to(1, u)})", F1
            return f"{g}({to(0, u)}, {to(1, u)})", F1
        if name == "length" and n == 1:
            t = ("float", types[0][1] if types[0] else 1)
            return f"length({to(0, t)})", F1
        if name == "cross" and n == 2:
            return f"cross({to(0, ('float', 3))}, {to(1, ('float', 3))})", ("float", 3)
        if name in ("lerp", "mix") and n == 3:
            u = ("float", unify(types[:2] + ([types[2]] if types[2] and types[2][1] > 1 else []))[1])
            tt = F1 if types[2] and types[2][1] == 1 else u
            return f"mix({to(0, u)}, {to(1, u)}, {to(2, tt)})", u
        if name == "clamp" and n == 3:
            u = ("float", types[0][1] if types[0] else 1)
            lim = [F1 if (t and t[1] == 1) else u for t in types[1:]]
            return f"clamp({to(0, u)}, {to(1, lim[0])}, {to(2, lim[1])})", u
        if name == "smoothstep" and n == 3:
            u = ("float", types[2][1] if types[2] else 1)
            lim = [F1 if (t and t[1] == 1) else u for t in types[:2]]
            return f"smoothstep({to(0, lim[0])}, {to(1, lim[1])}, {to(2, u)})", u
        if name in ("tex2D", "tex2d") and n == 2:
            return f"texture({a[0][0]}, {to(1, ('float', 2))})", ("float", 4)
        if name in ("tex3D", "tex3d") and n == 2:
            return f"texture({a[0][0]}, {to(1, ('float', 3))})", ("float", 4)
        if name == "tex2Dlod" and n == 2:
            c = to(1, ("float", 4))
            return f"textureLod({a[0][0]}, ({c}).xy, ({c}).w)", ("float", 4)
        if name == "tex2Dbias" and n == 2:
            c = to(1, ("float", 4))
            return f"texture({a[0][0]}, ({c}).xy, ({c}).w)", ("float", 4)
        if name == "mul" and n == 2:
            # HLSL's matrices are written row by row, GLSL's column by column: mul(v, M) is M * v here
            (ac, at), (bc, bt) = a
            if at and at[0] == "mat" and bt and bt[0] == "mat":
                return f"({bc} * {ac})", at
            if bt and bt[0] == "mat":
                return f"({bc} * {conv(ac, at, ('float', bt[1]))})", ("float", bt[1])
            if at and at[0] == "mat":
                return f"({conv(bc, bt, ('float', at[1]))} * {ac})", ("float", at[1])
            return f"({ac} * {bc})", unify(types)
        if name in ("all", "any") and n == 1:
            t = types[0]
            if t and t[1] > 1:
                return f"{name}(bvec{t[1]}({a[0][0]}))", B1
            return conv(a[0][0], t, B1), B1
        if name == "isnan" and n == 1:
            return f"isnan({a[0][0]})", ("bool", types[0][1] if types[0] else 1)
        if name == "sincos" and n == 3:
            c = to(0, F1)
            return f"({a[1][0]} = sin({c}), {a[2][0]} = cos({c}))", F1
        raise ValueError(f"no such function: {name}()")


def translate(head, body, symbols, funcs):
    """The shader's head and body as GLSL: (head, the samplers it declares [(name, type)], lines for the top of
    main(), body). `symbols` MilkDrop's inputs {name: type}, `funcs` its helpers {name: [(glsl name, return type,
    [parameter types])]}. An input the shader writes to (HLSL lets it: a uniform is a copy there) is read and written
    as a global copy of it, made at the top of main()."""
    _, defs = defines(head)
    _, body_defs = defines(body)
    defs.update(body_defs)
    renamed = {}
    symbols = {n: (v if isinstance(v[1], tuple) else (n, v)) for n, v in symbols.items()}
    for _ in range(2):
        syms = {n: (renamed.get(n, g), t) for n, (g, t) in symbols.items()}
        tr = _Translator(preprocess(head, defs), syms, funcs)
        h = tr.head()
        tr2 = _Translator(preprocess(body, defs), {}, {})
        tr2.funcs, tr2.helpers, tr2.inputs, tr2.samplers = tr.funcs, tr.helpers, tr.inputs, tr.samplers
        tr2.scope = Scope(tr.scope)
        for n, ty in (("uv", ("float", 2)), ("uv_orig", ("float", 2)), ("rad", F1), ("ang", F1), ("ret", ("float", 3))):
            tr2.scope.vars.setdefault(n, (n, ty))
        b = tr2.body()
        written = (tr.written | tr2.written) - set(renamed)
        if not written:
            break
        renamed.update({n: "h_w_" + n for n in written})
    copies = [f"{glsl_type(symbols[n][1])} {g};" for n, g in renamed.items()]
    first = [f"{g} = {symbols[n][0]};" for n, g in renamed.items()]
    return "\n".join(copies + [h]), tr.samplers, first + tr.moved, b


