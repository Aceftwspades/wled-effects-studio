def glsl_type(t):
    b, n = t
    if b == "float":
        return "float" if n == 1 else f"vec{n}"
    if b == "int":
        return "int" if n == 1 else f"ivec{n}"
    if b == "bool":
        return "bool" if n == 1 else f"bvec{n}"
    if b == "mat":
        return f"mat{n}"
    return b


