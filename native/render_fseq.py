"""The Sequence exported for Falcon Player (the second feature review's
fourth): the show rendered frame by frame on the held clock, as the video
render does it (native/render_video.py), each frame's LEDs into an FSEQ v2
file - the format xLights writes and FPP plays to any controllers, WLED
among them over DDP or E1.31 - and the show's audio beside it, named in the
file as its media.

    render_fseq.show(app)        # the dialog: the rate, the length, the audio
    render_fseq.start(app)
    render_fseq.advance(app)     # each frame, before the show's poll: the clock a frame on
    render_fseq.capture(app)     # each frame, after the engine's step: the LEDs into the file

    write_header(f, channels, frames, step_ms, media="")   # the FSEQ v2 header, uncompressed
    read(path)                   # (header dict, frames as (n, channels) uint8) - the tests'

The channels are the LEDs in wiring order, three a LED (RGB): LED 0's red is
channel 1, as a pixel controller numbers them. The file is uncompressed (FSEQ
v2.0, compression type 0), which every FPP plays; into captures/.

The format, as FPP and xLights document it: a 32-byte header ("PSEQ", the
offset of the channel data, version 2.0, the header's length, the channels a
frame, the frames, a frame's milliseconds, the compression, the sparse ranges
and a unique id), then variable headers (each its length, a two-letter code
and its data - "mf" the media file, "sp" what made it), then the frames.
"""
