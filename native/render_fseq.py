import os
import shutil
import struct
import time
import wave

import numpy as np

from native import clock, procs

TAG = "render_fseq_win"
RATES = (20, 25, 40)             # FPP's usual: 50, 40 and 25 ms a frame
LENGTHS = (("show", "the whole show"), ("step", "the selected step"))
DEFAULTS = {"fps": 40, "length": "show", "audio": True}
PRODUCER = "WLED Effects Studio"


def _var(code, data):
    """One variable header: its length (these four bytes counted), its code, its data."""
    return struct.pack("<H", 4 + len(data)) + code.encode("ascii") + data


def write_header(f, channels, frames, step_ms, media="", uid=None):
    """The FSEQ v2.0 header of an uncompressed file, with its media file and producer; returns its length (the
    channel data's offset)."""
    var = b""
    if media:
        var += _var("mf", media.encode("utf-8") + b"\0")
    var += _var("sp", PRODUCER.encode("utf-8") + b"\0")
    std = 32                                         # no compression blocks, no sparse ranges
    offset = std + len(var)
    offset += (-offset) % 4                          # the channel data on a 4-byte boundary, as xLights puts it
    uid = int(time.time() * 1e6) if uid is None else int(uid)
    head = (b"PSEQ" + struct.pack("<HBBHIIBBBBBBQ", offset, 0, 2, std, int(channels), int(frames), int(step_ms) & 255,
                                  0, 0, 0, 0, 0, uid))
    assert len(head) == 32
    f.write(head + var + b"\0" * (offset - std - len(var)))
    return offset


def read(path):
    """(header, frames (n, channels) uint8) of an uncompressed FSEQ v2 file."""
    with open(path, "rb") as f:
        b = f.read()
    if b[:4] != b"PSEQ":
        raise ValueError("not an FSEQ file")
    offset, minor, major, std, ch, n, step, flags, comp, blocks, sparse, _, uid = struct.unpack("<HBBHIIBBBBBBQ", b[4:32])
    var, k = {}, std + blocks * 8 + sparse * 6
    while k + 4 <= offset:
        ln = struct.unpack("<H", b[k:k + 2])[0]
        if ln < 4:
            break
        var[b[k + 2:k + 4].decode("ascii", "replace")] = b[k + 4:k + ln].rstrip(b"\0").decode("utf-8", "replace")
        k += ln
    head = {"offset": offset, "version": (major, minor), "channels": ch, "frames": n, "step_ms": step,
            "compression": comp & 15, "sparse": sparse, "uid": uid, "vars": var}
    data = np.frombuffer(b[offset:offset + ch * n], np.uint8).reshape(n, ch) if ch and n else np.zeros((0, ch), np.uint8)
    return head, data


def options(app):
    from native import sequence_ui
    o = sequence_ui._steps(app).setdefault("fseq", {})
    for k, v in DEFAULTS.items():
        o.setdefault(k, v)
    return o


def span(app):
    from native import sequence_ui
    starts, total = sequence_ui._starts(app)
    if options(app)["length"] == "step":
        i = getattr(app, "_seq_sel", 0)
        steps = sequence_ui._steps(app)["steps"]
        if 0 <= i < len(steps):
            return starts[i], starts[i] + float(steps[i].get("dur", 10))
    return 0.0, total


def leds(app):
    """The frame's LEDs in wiring order, (n, 3) bytes as the file carries them."""
    from native import live_out
    return live_out.stream_bytes(app.frame_rgb(), app.project.geometry, "wiring")   # as the stream sends it


# --- the dialog ----------------------------------------------------------------------------------
def build(app):
    import dearpygui.dearpygui as dpg
    from native import chrome, form, weight
    from native.typeface import px
    o = options(app)
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(470), height=px(270)):
        chrome.dialog_header(TAG, "Export for Falcon Player (FSEQ)")
        dpg.add_text("The show frame by frame into an FSEQ file - the LEDs in wiring order, three channels a LED - for "
                     "Falcon Player to play to the controllers (WLED over DDP or E1.31), with its audio beside it. "
                     "Into captures/.", color=chrome.DIM, wrap=px(440))
        with form.row("frames a second", tip="FPP's usual are 40 (25 ms a frame) and 20 (50 ms)"):
            dpg.add_combo([str(r) for r in RATES], tag="fs_fps", width=-1, default_value=str(o["fps"]),
                          callback=lambda s, v: _set(app, "fps", int(v)))
        with form.row("length"):
            dpg.add_combo([w for _, w in LENGTHS], tag="fs_len", width=-1, default_value=dict(LENGTHS)[o["length"]],
                          callback=lambda s, v: _set(app, "length", next(k for k, w in LENGTHS if w == v)))
        with form.row("audio", tip="the show's audio tracks mixed into a file beside it, named in it as its media"):
            dpg.add_checkbox(tag="fs_audio", default_value=bool(o["audio"]), callback=lambda s, v: _set(app, "audio", bool(v)))
        dpg.add_text("", tag="fs_words", color=chrome.DIM, wrap=px(440))
        with dpg.group(horizontal=True):
            dpg.add_button(label="Export", tag="fs_go", callback=lambda: start(app))
            weight.primary("fs_go")
            dpg.add_button(label="Cancel", tag="fs_cancel", callback=lambda: cancel(app))


def _set(app, key, v):
    options(app)[key] = v
    app.project.save()
    refresh(app)


def refresh(app):
    import dearpygui.dearpygui as dpg
    if not dpg.does_item_exist("fs_words"):
        return
    job = getattr(app, "_fseq_job", None)
    if job is not None:
        dpg.set_value("fs_words", f"exporting: frame {job['frame']} of {job['frames']}")
        return
    o = options(app)
    t0, t1 = span(app)
    n = len(leds(app)) // 3
    frames = int(round((t1 - t0) * o["fps"]))
    mb = frames * n * 3 / 1e6
    words = f"{t1 - t0:.1f} s, {frames} frames of {n} LEDs ({n * 3} channels), {mb:.1f} MB"
    if getattr(app, "_fseq_last", None):
        words += "\nlast: " + app._fseq_last
    dpg.set_value("fs_words", words)


def show(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    refresh(app)
    chrome._centre(TAG, 470, 270)
    dpg.show_item(TAG)


# --- the export ----------------------------------------------------------------------------------
def start(app):
    """The export begun: the show from the length's start on the held clock."""
    from native import render_video, sequence_ui
    if getattr(app, "_fseq_job", None) is not None or render_video.rendering(app):
        return False
    if not sequence_ui._has_steps(app):
        app.gp.status("no steps to export"); return False
    o = options(app)
    t0, t1 = span(app)
    fps = int(o["fps"])
    frames = max(1, int(round((t1 - t0) * fps)))
    ch = len(leds(app))
    from native.recorder import GIF_DIR
    os.makedirs(GIF_DIR, exist_ok=True)
    name = "".join(ch_ if ch_.isalnum() else "_" for ch_ in str(sequence_ui._steps(app).get("name") or "show"))
    stem = os.path.join(GIF_DIR, f"{name}_{int(time.time())}")
    audio = bool(o["audio"]) and render_video.has_audio(app)
    media = os.path.basename(stem) + (".mp3" if shutil.which("ffmpeg") else ".wav") if audio else ""
    try:
        f = open(stem + ".fseq", "wb")
        write_header(f, ch, frames, int(round(1000.0 / fps)), media)
    except OSError as e:
        app.gp.status(f"the export could not be begun: {e}", "warn"); return False
    sequence_ui.stop(app)
    clock.hold()
    sequence_ui.seek(app, t0)
    p = getattr(app, "_seq_play", None)
    if p is not None and p.get("paused") is not None:
        sequence_ui.play_pause(app)
    if getattr(app, "_seq_play", None) is not None:
        app._seq_play["once"] = True
    app.playing = True
    app._fseq_job = {"f": f, "path": stem + ".fseq", "stem": stem, "media": media, "t0": t0, "t1": t1, "fps": fps,
                     "frames": frames, "frame": 0, "ch": ch, "t_real": time.perf_counter()}
    refresh(app)
    app.gp.status(f"exporting {t1 - t0:.1f} s of the show for FPP ({frames} frames)...")
    return True


def advance(app):
    job = getattr(app, "_fseq_job", None)
    if job is not None and job["frame"] > 0:
        clock.step(1.0 / job["fps"])


def capture(app):
    """After the engine's step, each frame of an export: its LEDs into the file; at the end the audio beside it."""
    job = getattr(app, "_fseq_job", None)
    if job is None:
        return
    try:
        b = leds(app)
        if len(b) != job["ch"]:                      # the shape changed under it: the frame kept its size
            b = (b + bytes(job["ch"]))[:job["ch"]]
        job["f"].write(b)
    except Exception as e:
        _end(app, f"the export failed: {e}")
        return
    job["frame"] += 1
    if job["frame"] % 20 == 0:
        refresh(app)
    if job["frame"] >= job["frames"]:
        try:
            job["f"].close()
            if job["media"]:
                _audio(app, job)
            took = time.perf_counter() - job["t_real"]
            _end(app, f"{os.path.basename(job['path'])}: {job['t1'] - job['t0']:.1f} s, {job['frames']} frames of "
                      f"{job['ch'] // 3} LEDs" + (f", with {job['media']}" if job["media"] else "") +
                      f", made in {took:.0f} s", ok=True)
        except Exception as e:
            _end(app, f"the export failed: {e}")


def _audio(app, job):
    """The show's audio for the export's stretch, mixed into a WAV beside it (an MP3 when ffmpeg is there)."""
    from native import sequence_ui, showaudio
    resolved = showaudio.resolve(sequence_ui._steps(app), app.project.path)
    n = int(round((job["t1"] - job["t0"]) * showaudio.RATE))
    mix = np.zeros((n, 2), np.float32)
    step = showaudio.RATE * 10
    for k in range(0, n, step):
        mix[k:k + step] = showaudio.render(resolved, job["t0"] + k / showaudio.RATE, min(step, n - k))
    wav = job["stem"] + ".wav"
    with wave.open(wav, "wb") as f:
        f.setnchannels(2); f.setsampwidth(2); f.setframerate(showaudio.RATE)
        f.writeframes((np.clip(mix, -1, 1) * 32767).astype(np.int16).tobytes())
    if job["media"].endswith(".mp3"):
        r = procs.run([shutil.which("ffmpeg"), "-y", "-loglevel", "error", "-i", wav, "-b:a", "192k",
                       job["stem"] + ".mp3"], capture_output=True, timeout=600)
        if r.returncode == 0:
            os.remove(wav)
        else:
            raise RuntimeError("the audio could not be made an MP3: " + (r.stderr or b"").decode("utf-8", "replace")[-160:])


def _end(app, words, ok=False):
    from native import sequence_ui
    job = getattr(app, "_fseq_job", None)
    app._fseq_job = None
    if job is not None and not ok:
        try:
            job["f"].close()
        except Exception:
            pass
        for p in (job["path"], job["stem"] + ".wav", job["stem"] + ".mp3"):
            try:
                if os.path.exists(p):
                    os.remove(p)
            except OSError:
                pass
    clock.release()
    app.last = time.perf_counter()
    sequence_ui.stop(app)
    if ok:
        app.gp.status(words)
    else:
        app.gp.status(words, "warn")
    app.rec_msg = words
    app._fseq_last = words
    refresh(app)


def cancel(app):
    if getattr(app, "_fseq_job", None) is not None:
        _end(app, "the export was cancelled")


def exporting(app):
    return getattr(app, "_fseq_job", None) is not None
