"""A show made from a track (the second feature review's second, after
SoundSwitch's autoscript): steps laid on the show's sections and its bars -
calm effects for an intro, a verse or a breakdown, the brightest for a drop,
the intensity and the speed rising over a build, a cut on the drop, slow
fades into the quiet parts, the outro faded out - from the effects chosen,
then the user's to edit like any other show.

    scores = score(eng, names)               # each effect's energy, 0..1: how bright it is and how much it moves
    plan = plan(sections, bar, scores, seed) # [{"effect", "dur", "trans", "bri", "ramps"}]
    show(app)                                # the dialog; make(app) builds the steps from its choices

An effect's energy is measured, not guessed: each run a second and a half on
a spare engine (the sim's own is left alone), with the synth's beat, and its
frames' brightness and how much they change from one to the next ranked
against the others'.
"""
# AI: below section was generated by an AI
import json
import random

import numpy as np

TAG = "autoshow_win"
TARGET = {"intro": 0.25, "verse": 0.5, "build": 0.6, "drop": 0.95, "breakdown": 0.3, "outro": 0.2}
INTO = {"drop": 0.0, "build": 1.5, "breakdown": 3.0, "outro": 3.0, "intro": 2.0, "verse": 1.5}   # the blend into a section
WITHIN = 1.0                     # the blend between two steps of one section
POOLS = (("studio", "the studio's and the project's effects"), ("setlist", "the setlist (MIDI and OSC)"),
         ("all", "every effect"))
BARS = (2, 4, 8)
SCORE_FRAMES = 36                # a second and a half at 40 ms a frame, every frame kept


def score(eng, names, syn=None):
    """{name: energy 0..1} for the effects named: their mean brightness and their frame-to-frame change, each
    ranked against the others' and averaged."""
    from native.library_ui import clean_frames
    from native.synth import Synth
    syn = syn or Synth()
    raw = {}
    for n in names:
        if n not in eng.names:
            continue
        fr = clean_frames(eng, eng.names.index(n), SCORE_FRAMES, every=1, syn=syn, warm=6)
        a = np.asarray(fr, np.float32) / 255.0
        bright = float(a.mean())
        motion = float(np.abs(np.diff(a, axis=0)).mean()) if len(a) > 1 else 0.0
        raw[n] = (bright, motion)
    if not raw:
        return {}
    ks = list(raw)
    rank = lambda v: np.argsort(np.argsort(v)) / max(1, len(v) - 1)              # noqa: E731 - 0..1 by rank
    b = rank(np.array([raw[k][0] for k in ks]))
    m = rank(np.array([raw[k][1] for k in ks]))
    return {k: round(float(0.5 * b[i] + 0.5 * m[i]), 3) for i, k in enumerate(ks)}


def plan(sections, bar, scores, seed=0, bars_a_step=4):
    """The steps for the sections: each section cut into steps of `bars_a_step` bars (whole ones; a section shorter
    than that one step), each step the effect whose energy is nearest its section's (one of the three nearest, by
    `seed`, none the same as either of the two before); the blend into a section by its kind, a step's brightness
    and ramps by its section's."""
    rng = random.Random(seed)
    pool = sorted(scores.items(), key=lambda kv: kv[1])
    if not pool or not sections:
        return []
    out, recent = [], []
    for si, s in enumerate(sections):
        kind = s.get("kind", "verse")
        length = float(s["len"])
        unit = (bar or 2.0) * bars_a_step
        n = max(1, int(round(length / unit)))
        durs = [length / n] * n
        target = TARGET.get(kind, 0.5)
        for j, d in enumerate(durs):
            cands = sorted(pool, key=lambda kv: abs(kv[1] - target))
            fresh = [kv for kv in cands if kv[0] not in recent[-2:]] or cands
            name = rng.choice(fresh[:3])[0]
            recent.append(name)
            step = {"effect": name, "dur": round(d, 3), "section": si,
                    "trans": (INTO.get(kind, 1.5) if j == 0 and si > 0 else (0.0 if j == 0 else WITHIN)),
                    "bri": 255 if kind in ("drop", "build", "verse") else 200, "ramps": {}}
            if kind == "build":                                    # rising: the intensity and the speed, eased in
                step["ramps"] = {"ix": {"end": 255, "shape": "ease in"}, "sx": {"end": 230, "shape": "ease in"}}
                if j == 0:
                    step["bri"] = 170
                    step["ramps"]["bri"] = {"end": 255, "shape": "ease in"}
            if kind == "outro" and j == n - 1:                     # the last of it: faded out
                step["ramps"] = {"bri": {"end": 0, "shape": "ease out"}}
            out.append(step)
    return out


# --- the dialog and the building -------------------------------------------------------------------
def options(app):
    from native import sequence_ui
    o = sequence_ui._steps(app).setdefault("autoshow", {})
    o.setdefault("pool", "studio")
    o.setdefault("bars", 4)
    o.setdefault("seed", 1)
    return o


def pool_names(app, key):
    """The effects a show is made from: the studio's and the project's (graphs and usermods), the MIDI setlist, or
    every effect the sim has (the plain colour ones and the tilt-driven ones left out)."""
    from native import library_ui, midi_ui
    if key == "setlist":
        names = [n for n in midi_ui._st(app).get("setlist") or [] if n in app.eng.names]
        if names:
            return names
    b = library_ui.banks(app)
    if key == "all":
        names = [n for _, n, _ in b["usermod"] + b["stock"]] + [k for k, _, _ in b["graphs"] if k]
    else:
        names = [k for k, _, _ in b["graphs"] if k] + [n for _, n, _ in b["usermod"]]
    plain = {"solid", "blink", "breathe", "wipe", "wipe random", "random colors", "sweep", "dynamic", "studio script"}
    # left out too: a built-in leaning on the IMU (it follows a hand tilting the cube, not the music - and a file
    # may list a tilt mode beside a still one, so "gyro" in a name counts) or on audio this project's firmware
    # leaves out (flash.builtin_catalog's needs, as the Flash frame warns of them)
    try:
        from native import flash
        plain |= {e["name"].strip().lower() for e in flash.builtin_catalog()
                  if "imu" in e["needs"] or flash.missing_features(app.project, e["needs"] & {"audio", "pcm"})}
    except Exception:
        pass
    return [n for n in names if n.strip().lower() not in plain and "gyro" not in n.lower()]


def build(app):
    import dearpygui.dearpygui as dpg
    from native import chrome, form, weight
    from native.typeface import px
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(470), height=px(300)):
        chrome.dialog_header(TAG, "Make a show from the audio")
        dpg.add_text("Steps laid on the show's sections and its bars - calm effects for the quiet parts, the brightest "
                     "for the drops, the intensity rising over a build - in place of the steps there are (undo brings "
                     "them back). The sections are found first when there are none.", color=chrome.DIM, wrap=px(440))
        o = options(app)
        with form.row("effects from", tip="the effects the show is made of; each is measured for its energy first"):
            dpg.add_combo([p[1] for p in POOLS], tag="as_pool", width=-1,
                          default_value=next(p[1] for p in POOLS if p[0] == o["pool"]),
                          callback=lambda s, v: _set(app, "pool", next(p[0] for p in POOLS if p[1] == v)))
        with form.row("a step", tip="how many bars a step lasts: a section is cut into steps this long"):
            dpg.add_combo([f"{b} bars" for b in BARS], tag="as_bars", width=-1, default_value=f"{o['bars']} bars",
                          callback=lambda s, v: _set(app, "bars", int(v.split()[0])))
        dpg.add_text("", tag="as_words", color=chrome.DIM, wrap=px(440))
        with dpg.group(horizontal=True):
            dpg.add_button(label="Make the show", tag="as_go", callback=lambda: make(app))
            weight.primary("as_go")
            chrome.tip("measures the effects, then lays the steps on the sections")
            dpg.add_button(label="Another take", tag="as_again", callback=lambda: make(app, again=True))
            chrome.tip("the same sections and effects, other choices among them")


def _set(app, key, v):
    options(app)[key] = v
    app.project.save()
    refresh(app)


def refresh(app):
    import dearpygui.dearpygui as dpg
    from native import sequence_ui
    if not dpg.does_item_exist("as_words"):
        return
    o = options(app)
    secs = sequence_ui._sections(app)
    n = len(pool_names(app, o["pool"]))
    dpg.set_value("as_words", f"{n} effects to choose from; " + (f"{len(secs)} sections" if secs else
                  "the sections found first") + ("" if sequence_ui._barlen(app) else ", the tempo found first"))


def show(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    refresh(app)
    chrome._centre(TAG, 470, 300)
    dpg.show_item(TAG)


def make(app, again=False):
    """The show made: the sections found first when there are none (and the tempo), the pool's effects measured on
    a spare engine on a worker, then the steps built there and put in place of the show's."""
    from native import sequence, sequence_ui, tasks
    o = options(app)
    if again:
        o["seed"] = int(o.get("seed", 1)) + 1
    if not sequence_ui._sections(app):
        if not sequence_ui.find_sections(app):
            return False
        app._autoshow_after = True                                    # made once the sections are in (poll)
        return True
    names = pool_names(app, o["pool"])
    if not names:
        app.gp.status("no effects to make a show from"); return False
    eng = app.second_engine("autoshow")
    if eng.cols != app.eng.cols or eng.rows != app.eng.rows:
        eng.set_geometry(app.project.geometry)
    secs = json.loads(json.dumps(sequence_ui._sections(app)))
    bar = sequence_ui._barlen(app) or 2.0
    colours = [int(c) for c in app.seg_cols]
    cache = app.__dict__.setdefault("_autoshow_scores", {})
    seed, bars = int(o.get("seed", 1)), int(o.get("bars", 4))

    def work():
        todo = [n for n in names if n not in cache]
        cache.update(score(eng, todo))
        pl = plan(secs, bar, {n: cache[n] for n in names if n in cache}, seed=seed, bars_a_step=bars)
        steps = []
        from native.library_ui import clean_frames
        for p in pl:
            fr = clean_frames(eng, eng.names.index(p["effect"]), 8, every=3, warm=10)
            st = sequence.capture(eng, colours, p["bri"], p["effect"], p["dur"], p["trans"], rgb=np.stack(fr))
            if p["ramps"]:
                st["ramps"] = p["ramps"]
            steps.append(st)
        return steps

    def done(steps):
        S = sequence_ui._steps(app)
        sequence_ui.stop(app)
        S["steps"] = steps
        app._seq_sel = 0
        sequence_ui._save(app)
        app._tl_dirty = True
        app._seq_rows_dirty = True
        app.gp.status(f"a show of {len(steps)} steps over {len(secs)} sections - Another take for other choices; undo "
                      "for the steps before")
    return tasks.run(app, "autoshow", f"making a show from {len(names)} effects", work, done)


def poll(app):
    """A show asked for before its sections were found: made once they are."""
    from native import sequence_ui
    if getattr(app, "_autoshow_after", False) and sequence_ui._sections(app):
        app._autoshow_after = False
        make(app)
