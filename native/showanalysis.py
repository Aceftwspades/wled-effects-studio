"""The show's audio listened to: where its sections are and what each is
(intro, verse, build, drop, breakdown, outro), its tempo and its beats - the
ground the Sequence's sections and the show made from a track stand on
(sequence_ui: Find sections, Make a show).

    x, rate = mix(S, root)                       # the show's tracks mixed, mono, at RATE
    secs = sections(x, rate, bar=2.0)            # [{"name", "kind", "at", "len", "energy"}]
    bpm, first, beats = audio.beats_of(x, rate)  # the tempo, as before

Sections are found the way music structure analysis usually finds them
(Foote 2000, "Automatic audio segmentation using a measure of audio
novelty"): every half second's sound - its loudness in a dozen bands - set
beside every other's, and a boundary wherever the sound before and the sound
after are most unlike (a checkerboard kernel along the diagonal of that
self-similarity). Then the boundaries put on the bars, none closer than
MIN_S, and each section named by its loudness against the others'. Rough,
the way any machine's ear is: the sections are a start, edited by hand.
"""
# AI: below section was generated by an AI
import numpy as np

RATE = 11025                     # what the analysis listens at
HOP_S = 0.5                      # a frame of the features
KERNEL_S = 8.0                   # the checkerboard's half-width: the sound this long before against after
MIN_S = 8.0                      # no section shorter than this
BANDS = 12
KINDS = ("intro", "verse", "build", "drop", "breakdown", "outro")
WORDS = {"intro": "Intro", "verse": "Verse", "build": "Build", "drop": "Drop", "breakdown": "Breakdown",
         "outro": "Outro"}
COLOURS = {"intro": (90, 150, 220), "verse": (110, 170, 130), "build": (230, 170, 60), "drop": (230, 80, 80),
           "breakdown": (150, 120, 220), "outro": (120, 130, 150)}


def mix(S, root, length=None):
    """(mono float32, RATE) of the show's tracks from 0 to `length` (their end when None): as the speakers hear
    them, a quarter of the rate."""
    from native import showaudio
    resolved = showaudio.resolve(S, root)
    if not resolved:
        return np.zeros(0, np.float32), RATE
    end = float(length if length is not None else showaudio.length(S))
    n = int(end * showaudio.RATE)
    k = showaudio.RATE // RATE                                    # 4: 44100 -> 11025
    out = []
    step = showaudio.RATE * 10
    for a in range(0, n, step):
        m = min(step, n - a)
        block = showaudio.mono(showaudio.render(resolved, a / showaudio.RATE, m))
        m4 = len(block) // k * k
        out.append(block[:m4].reshape(-1, k).mean(axis=1))
    return (np.concatenate(out) if out else np.zeros(0, np.float32)).astype(np.float32), RATE


def features(x, rate):
    """(frames, BANDS) log band energies a HOP_S, and each frame's loudness (rms)."""
    hop = int(rate * HOP_S)
    n = len(x) // hop
    if n < 4:
        return np.zeros((0, BANDS), np.float32), np.zeros(0, np.float32)
    fr = x[:n * hop].reshape(n, hop)
    rms = np.sqrt((fr * fr).mean(axis=1) + 1e-12).astype(np.float32)
    spec = np.abs(np.fft.rfft(fr * np.hanning(hop)[None, :], axis=1))
    freqs = np.fft.rfftfreq(hop, 1.0 / rate)
    edges = np.geomspace(40.0, rate / 2.0, BANDS + 1)
    bands = np.stack([spec[:, (freqs >= a) & (freqs < b)].mean(axis=1) if ((freqs >= a) & (freqs < b)).any()
                      else np.zeros(n) for a, b in zip(edges[:-1], edges[1:])], axis=1)
    return np.log1p(bands * 100.0).astype(np.float32), rms


def novelty(feat):
    """How unlike the sound before each frame is to the sound after it: a checkerboard kernel (Gaussian-tapered)
    along the diagonal of the frames' cosine self-similarity."""
    n = len(feat)
    if n < 4:
        return np.zeros(n, np.float32)
    f = feat - feat.mean(axis=0)
    f = f / (np.linalg.norm(f, axis=1, keepdims=True) + 1e-9)
    sim = f @ f.T
    L = max(2, int(KERNEL_S / HOP_S))
    u = np.arange(-L, L) + 0.5
    g = np.exp(-(u / (L * 0.5)) ** 2)
    kern = np.outer(g, g) * np.sign(u)[:, None] * np.sign(u)[None, :]          # + before/before, after/after; - across
    pad = np.pad(sim, L, mode="constant")
    out = np.empty(n, np.float32)
    for i in range(n):
        out[i] = float((pad[i:i + 2 * L, i:i + 2 * L] * kern).sum())
    out[out < 0] = 0
    return out


def boundaries(nov, bar=None, beats=None):
    """The section edges, in seconds: the novelty's peaks - the strongest first, none within MIN_S of another or
    of either end - put on the nearest bar (or beat)."""
    n = len(nov)
    if n < 4 or nov.max() <= 0:
        return []
    total = n * HOP_S
    sm = np.convolve(nov, np.ones(3) / 3, mode="same")
    peaks = [i for i in range(1, n - 1) if sm[i] >= sm[i - 1] and sm[i] > sm[i + 1] and sm[i] > sm.mean() + 0.3 * sm.std()]
    peaks.sort(key=lambda i: -sm[i])
    kept = []
    for i in peaks:
        t = (i + 0.5) * HOP_S
        if t < MIN_S or total - t < MIN_S or any(abs(t - k) < MIN_S for k in kept):
            continue
        kept.append(t)
    out = []
    for t in sorted(kept):
        if bar:
            t = round(t / bar) * bar
        elif beats:
            t = min(beats, key=lambda b: abs(b - t))
        if out and t - out[-1] < MIN_S * 0.5:
            continue
        out.append(round(float(t), 3))
    return out


def label(secs):
    """Each section a kind by its loudness against the others': the loudest a drop, the quietest in the middle a
    breakdown, a quiet first an intro and a quiet last an outro, the one rising into a drop a build, the rest
    verses."""
    if not secs:
        return secs
    e = np.array([s["energy"] for s in secs], np.float64)
    # the loudest - and near the loudest of all, so a song with one loud part has one drop
    hi, lo, med = max(np.percentile(e, 70), 0.75 * e.max()), np.percentile(e, 30), np.median(e)
    for k, s in enumerate(secs):
        if s["energy"] >= hi and len(secs) > 1:
            s["kind"] = "drop"
        elif k == 0 and s["energy"] <= med:
            s["kind"] = "intro"
        elif k == len(secs) - 1 and s["energy"] <= med:
            s["kind"] = "outro"
        elif s["energy"] <= lo:
            s["kind"] = "breakdown"
        else:
            s["kind"] = "verse"
    for k in range(len(secs) - 1):                               # into a drop, quieter and rising: a build
        s, nxt = secs[k], secs[k + 1]
        if nxt["kind"] == "drop" and s["kind"] in ("verse", "breakdown") and s.get("rise", 0.0) > 0:
            s["kind"] = "build"
    for s in secs:
        s["name"] = WORDS[s["kind"]]
    return secs


def sections(x, rate, bar=None, beats=None):
    """The audio's sections: [{"name", "kind", "at", "len", "energy" (its mean loudness, 0..1 of the loudest)}]."""
    feat, rms = features(np.asarray(x, np.float32), rate)
    if len(feat) < 4:
        return []
    total = len(x) / float(rate)
    edges = [0.0] + boundaries(novelty(feat), bar, beats) + [total]
    top = float(rms.max()) or 1.0
    out = []
    for a, b in zip(edges[:-1], edges[1:]):
        i0, i1 = int(a / HOP_S), max(int(a / HOP_S) + 1, int(b / HOP_S))
        seg = rms[i0:i1]
        half = max(1, len(seg) // 2)
        out.append({"at": round(a, 3), "len": round(b - a, 3), "energy": round(float(seg.mean() / top), 3),
                    "rise": float(seg[half:].mean() - seg[:half].mean()) / top if len(seg) > 1 else 0.0})
    out = label(out)
    for s in out:
        s.pop("rise", None)
    return out
