def show(app):
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    chrome._centre(TAG, 720, 620)
    dpg.show_item(TAG)
    app._pads_labels = None
    _fill_banks(app)
    _fill_side(app)


def _close(app):
    _flush(app)
    pads.let_go(app)
    dpg.hide_item(TAG)


# --- banks -------------------------------------------------------------------------------------------------------
def _fill_banks(app):
    if not dpg.does_item_exist("pads_banks"):                   # the window not made yet (a phone switched the bank)
        return
    st = _st(app)
    dpg.delete_item("pads_banks", children_only=True)
    for i, b in enumerate(st["banks"]):
        tag = f"pads_bank{i}"
        dpg.add_button(label=b["name"], tag=tag, parent="pads_banks", user_data=i,
                       callback=lambda s, a, u: switch_bank(app, u))
        dpg.bind_item_theme(tag, _bank_theme(b["colour"], i == st["bank"]))
    edit = bool(getattr(app, "_pads_edit", False))
    dpg.configure_item("pads_bankrow", show=edit)
    b = pads.current(st)
    dpg.set_value("pads_bname", b["name"])
    dpg.set_value("pads_bcolour", b["colour"])
    num.set("pads_cols", b["cols"])
    num.set("pads_rows", b["rows"])
    dpg.configure_item("pads_delbank", enabled=len(st["banks"]) > 1)
    dpg.configure_item("pads_hwrow", show=edit)
    h = pads_hw.hw(st)
    dpg.set_value("pads_hwdev", dict(pads_hw.DEVICES)[h["device"]])
    from native import midi
    outs = ["(none)"] + midi.out_ports() + ([h["out"]] if h["out"] and h["out"] not in midi.out_ports() else [])
    dpg.configure_item("pads_hwout", items=outs)
    dpg.set_value("pads_hwout", h["out"] or "(none)")
    dpg.set_value("pads_hwgrid", bool(h.get("grid", True)))
    dpg.configure_item("pads_hwgrid", show=h["device"] in pads_hw.GRIDS)
    _fill_banks_learn(app)


_THEMES = {}


def _bank_theme(colour, on):
    key = (colour, on)
    if key not in _THEMES:
        r, g, b = pads.COLOUR.get(colour, pads.COLOUR["grey"])
        k = 1.0 if on else 0.35
        with dpg.theme() as t:
            with dpg.theme_component(dpg.mvButton):
                dpg.add_theme_color(dpg.mvThemeCol_Button, (int(r * k), int(g * k), int(b * k), 255))
                dpg.add_theme_color(dpg.mvThemeCol_ButtonHovered, (int(r * min(1, k + .2)), int(g * min(1, k + .2)),
                                                                   int(b * min(1, k + .2)), 255))
                dpg.add_theme_color(dpg.mvThemeCol_Text, (10, 10, 12, 255) if on else (230, 232, 236, 255))
        _THEMES[key] = t
    return _THEMES[key]


def switch_bank(app, i):
    """The grid shows bank i - the picture on the LEDs is not touched."""
    st = _st(app)
    if not 0 <= i < len(st["banks"]) or i == st["bank"]:
        return
    pads.let_go(app)
    st["bank"] = i                                              # saved with the next change (not an undo of its own)
    app._pads_sel = None
    _fill_banks(app)
    _fill_side(app)


def _add_bank(app):
    st = _st(app)
    if len(st["banks"]) >= pads.MAX_BANKS:
        app.gp.status(f"pads: {pads.MAX_BANKS} banks at most", "warn"); return
    st["banks"].append(pads.new_bank(f"Bank {len(st['banks']) + 1}", colour=pads.COLOURS[len(st["banks"]) % 11 + 1][0]))
    switch_bank(app, len(st["banks"]) - 1)
    _save(app)


def _bank_set(app, key, v, typed=False):
    pads.current(_st(app))[key] = v
    if typed:
        _save_soon(app)
    else:
        _save(app)
    _fill_banks(app)


def _grid_size(app, cols=None, rows=None):
    b = pads.current(_st(app))
    if not pads.resize_grid(b, b["cols"] if cols is None else cols, b["rows"] if rows is None else rows):
        app.gp.status("pads: a control is in the way - move or remove it first", "warn")
    _save(app)
    _fill_banks(app)


def _move_bank(app, d):
    st = _st(app)
    i, j = st["bank"], st["bank"] + d
    if 0 <= j < len(st["banks"]):
        st["banks"][i], st["banks"][j] = st["banks"][j], st["banks"][i]
        st["bank"] = j
        _save(app)
        _fill_banks(app)


def _copy_bank(app):
    st = _st(app)
    if len(st["banks"]) >= pads.MAX_BANKS:
        app.gp.status(f"pads: {pads.MAX_BANKS} banks at most", "warn"); return
    switch_bank(app, pads.copy_bank(st, st["bank"]))
    _save(app)


def _delete_bank(app):
    st = _st(app)
    if len(st["banks"]) <= 1:
        return
    pads.let_go(app)
    st["banks"].pop(st["bank"])
    st["bank"] = max(0, st["bank"] - 1)
    app._pads_sel = None
    _save(app)
    _fill_banks(app)
    _fill_side(app)


def _hw_set(app, key, v):
    pads_hw.hw(_st(app))[key] = v
    _save(app)
    _fill_banks(app)


def _learn(app, what):
    """Wait for the controller's next note or CC for the selected control or the bank shown (again: stop)."""
    st = _st(app)
    s = _sel(app)
    want = ("control", s["id"]) if what == "control" and isinstance(s, dict) else ("bank", st["bank"]) if what == "bank" else None
    if want is None:
        return
    pads_hw.learn(app, None if pads_hw.learning(app) == want else want)
    app.gp.status("pads: press the controller's pad or button..." if pads_hw.learning(app) else "pads: learning stopped")
    _fill_banks(app)
    _fill_side(app)


def _forget(app):
    s = _sel(app)
    if isinstance(s, dict):
        pads_hw.forget(app, ("control", s["id"]))
        _fill_side(app)


def _undo(app):
    pads.let_go(app)
    if not app.project.undo("pads"):
        app.gp.status("nothing to undo in the pads"); return
    app._pads_whole = None
    app._pads_sel = None
    _fill_banks(app)
    _fill_side(app)


# --- editing a control ---------------------------------------------------------------------------------------
def _set_edit(app, on):
    pads.let_go(app)
    pads_hw.learn(app, None)
    app._pads_edit = bool(on)
    app._pads_sel = None
    dpg.configure_item(SIDE, show=bool(on))
    dpg.configure_item("pads_area", width=-px(SIDE_W + 8) if on else -1)     # the panel beside the grid, editing
    _fill_banks(app)
    _fill_side(app)


def _sel(app):
    """The selected control, or the selected empty cell as (col, row), or None."""
    s = getattr(app, "_pads_sel", None)
    if isinstance(s, int):
        return pads.find(_st(app), s)
    return s


def _labels_for(app):
    """What the action list depends on: the effect shown and its sliders' names (another effect names them its way)."""
    from native import modulate
    eng = app.eng
    idx = getattr(eng, "idx", None)
    try:
        return idx, tuple(eng.meta[idx]["labels"]), modulate.signature(app)
    except Exception:
        return idx, None, modulate.signature(app)


def labels(app):
    """[(label, target)] of every action a control can drive: MIDI learn's, then the pads' own - made again when the
    effect changes. Each target's label is in a table too (target_label: each control's, every frame)."""
    key = _labels_for(app)
    if getattr(app, "_pads_labels", None) is None or getattr(app, "_pads_labels_key", None) != key:
        from native import midi_ui, vj
        out = [(lab, t) for lab, t in midi_ui.targets(app) if t.get("kind") != "pin"]
        for i, d in enumerate(vj.LETTERS):
            out.append((f"VJ {d}: this look (pick it below)", {"kind": "pad_look", "deck": i, "look": ""}))
            out.append((f"VJ {d}: a saved preset (pick it below)", {"kind": "pad_preset", "deck": i, "name": ""}))
        app._pads_labels, app._pads_labels_key, app._pads_label_ix = out, key, None
    if getattr(app, "_pads_label_ix", None) is None:
        ix = {}
        for lab, t in app._pads_labels:
            ix.setdefault(_label_key(t), lab)                 # two the same: the first, as the list's scan found
        app._pads_label_ix = ix
    return app._pads_labels


def _label_key(t):
    return tuple(t.get(q) for q in ("kind", "deck", "key", "id"))         # id: a modulator's


def target_label(app, t):
    if not t or not t.get("kind"):
        return "nothing yet - pick an action"
    k = t.get("kind")
    if k == "pad_look":
        return f"VJ {'ABC'[int(t.get('deck', 0))]}: {t.get('look') or '(no look picked)'}"
    if k == "pad_preset":
        return f"VJ {'ABC'[int(t.get('deck', 0))]}: preset {t.get('name') or '(none picked)'}"
    labels(app)
    return app._pads_label_ix.get(_label_key(t), k)


def _axis(app):
    """The axis the panel's action and range are for: (axis, target key, low key, high key, words) - always across
    for a control that is not an XY pad."""
    s = _sel(app)
    a = getattr(app, "_pads_axis", "x") if isinstance(s, dict) and s["type"] in pads.SURFACES else "x"
    if a == "p" and isinstance(s, dict) and s["type"] != "pressure":
        a = "x"
    return next(x for x in pads.AXES if x[0] == a)


def _set_axis(app, words):
    app._pads_axis = next(a for a, _, _, _, w in pads.AXES if w == words)
    _fill_side(app)


