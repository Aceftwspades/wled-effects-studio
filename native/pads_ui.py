def show(app):
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    chrome._centre(TAG, 720, 620)
    dpg.show_item(TAG)
    pads_state.of(app).labels = None
    _fill_banks(app)
    _fill_side(app)


def _close(app):
    _flush(app)
    pads.let_go(app)
    dpg.hide_item(TAG)


