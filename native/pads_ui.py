# --- the phone's /pads page ----------------------------------------------------------------------------------
def _rgb(name):
    return list(pads.COLOUR.get(name, pads.COLOUR["grey"]))


def _label(app, c):
    return c.get("label") or (_surface_label(app, c) if c["type"] in pads.SURFACES else target_label(app, c.get("target")))


def remote_state(app):
    """The bank the page shows: its grid, the banks to switch to, and each control as it is now - lit, a fader's or
    a knob's place, an XY pad's dot."""
    st = _st(app)
    b = pads.current(st)
    out = []
    for c in b["controls"]:
        d = {"id": c["id"], "type": c["type"], "x": c["x"], "y": c["y"], "w": c["w"], "h": c["h"],
             "label": _label(app, c), "rgb": _rgb(c.get("colour")), "orient": c.get("orient", "v"),
             "lit": bool(pads.lit(app, c))}
        if c["type"] in pads.SLIDERS:
            d["f"] = round(pads.position(app, c), 4)
        if c["type"] in pads.SURFACES:
            at = pads.where(app, c)
            d["xy"] = [round(v, 4) for v in at] if at else None
        out.append(d)
    return {"bank": st["bank"], "cols": b["cols"], "rows": b["rows"], "controls": out,
            "edit": bool(getattr(app, "_pads_edit", False)),
            "banks": [{"name": x["name"], "rgb": _rgb(x.get("colour"))} for x in st["banks"]]}


def remote(app, cmd):
    """One checked command from the pads page (phone.check): a bank switched, or a control of the bank shown
    pressed, moved, let go or still held."""
    import time
    st = _st(app)
    if cmd["a"] == "padbank":
        switch_bank(app, int(cmd["v"]))
        return
    if getattr(app, "_pads_edit", False):                          # the pads do nothing while they are edited
        return
    c = next((x for x in pads.current(st)["controls"] if x["id"] == cmd["id"]), None)
    if c is None:                                                   # a bank switched since the page drew it
        return
    seen = getattr(app, "_pads_remote", None)
    if seen is None:
        seen = app._pads_remote = {}
    e = cmd["e"]
    if e == "up":
        seen.pop(c["id"], None)
        pads.release(app, c)
        return
    seen[c["id"]] = time.monotonic()
    if e == "hold":
        return
    if e == "down":
        if c["type"] in pads.SURFACES:
            pads.press(app, c, xy=(cmd.get("x", 0.5), cmd.get("y", 0.5)), pressure=cmd.get("p"))
        elif c["type"] == "knob":
            pads.press(app, c)
            if "f" in cmd:
                pads.drag(app, c, cmd["f"])
        else:
            pads.press(app, c, cmd.get("f"))
    elif e == "move":
        if c["type"] in pads.SURFACES:
            pads.move(app, c, cmd.get("x", 0.5), cmd.get("y", 0.5), cmd.get("p"))
        elif c["type"] in pads.SLIDERS and "f" in cmd:
            pads.drag(app, c, cmd["f"])


def remote_poll(app):
    """Each frame: a control a phone holds but has not mentioned for REMOTE_GONE_S let go."""
    import time
    seen = getattr(app, "_pads_remote", None)
    if not seen:
        return
    now = time.monotonic()
    for cid, t in list(seen.items()):
        if now - t > REMOTE_GONE_S:
            del seen[cid]
            c = pads.find(_st(app), cid)
            if c is not None:
                pads.release(app, c)


# --- the grid: drawn and played ---------------------------------------------------------------------------------
def _geometry(app):
    """(x0, y0, cell w, cell h, gap) of the grid on screen, sized to the area it has."""
    b = pads.current(_st(app))
    aw, ah = dpg.get_item_rect_size("pads_area")
    aw, ah = max(px(120), aw - px(4)), max(px(120), ah - px(4))
    dpg.configure_item(GRID, width=int(aw), height=int(ah))
    gap = px(6)
    cw, ch = (aw - gap) / b["cols"], (ah - gap) / b["rows"]
    x0, y0 = dpg.get_item_rect_min(GRID)
    return x0, y0, cw, ch, gap


def _rect(c, cw, ch, gap):
    return (c["x"] * cw + gap, c["y"] * ch + gap, (c["x"] + c["w"]) * cw, (c["y"] + c["h"]) * ch)


def _shade(rgb, k):
    return (int(rgb[0] * k), int(rgb[1] * k), int(rgb[2] * k), 255)


def _drawn(app, cw, ch, gap):
    """All the grid shows, in brief: drawn again only when it changes (a full bank drawn each frame took 5 ms)."""
    st = _st(app)
    b = pads.current(st)
    edit = bool(getattr(app, "_pads_edit", False))
    sel = _sel(app)
    out = [st["bank"], b["cols"], b["rows"], round(cw, 2), round(ch, 2), gap, edit,
           sel["id"] if isinstance(sel, dict) else sel]
    for c in b["controls"]:
        lab = c.get("label") or (_surface_label(app, c) if c["type"] in pads.SURFACES else target_label(app, c.get("target")))
        out.append((c["id"], c["type"], c["x"], c["y"], c["w"], c["h"], c.get("colour"), c.get("orient"), lab,
                    (not edit) and bool(pads.lit(app, c)),
                    round(pads.position(app, c), 4) if c["type"] in pads.SLIDERS else None,
                    pads.where(app, c) if c["type"] in pads.SURFACES else None))
    return out


def _redraw(app, cw, ch, gap):
    key = _drawn(app, cw, ch, gap)
    if key != getattr(app, "_pads_drawn", None) or not dpg.get_item_children(GRID, 2):
        app._pads_drawn = key
        _draw(app, cw, ch, gap)


def _draw(app, cw, ch, gap):
    from native import chrome
    st = _st(app)
    b = pads.current(st)
    edit = bool(getattr(app, "_pads_edit", False))
    dpg.delete_item(GRID, children_only=True)
    dpg.draw_rectangle((0, 0), (b["cols"] * cw + gap, b["rows"] * ch + gap), fill=chrome.BG, color=(0, 0, 0, 0),
                       parent=GRID)
    if edit:
        for x in range(b["cols"]):
            for y in range(b["rows"]):
                if pads.at(b, x, y) is None:
                    dpg.draw_rectangle((x * cw + gap, y * ch + gap), ((x + 1) * cw, (y + 1) * ch),
                                       color=(70, 74, 84, 255), rounding=px(6), parent=GRID)
    sel = _sel(app)
    for c in b["controls"]:
        rgb = pads.COLOUR.get(c.get("colour"), pads.COLOUR["grey"])
        x0, y0, x1, y1 = _rect(c, cw, ch, gap)
        on = (not edit) and pads.lit(app, c)
        lab = c.get("label") or target_label(app, c.get("target"))
        if c["type"] in pads.SURFACES:
            lab = c.get("label") or _surface_label(app, c)
            _draw_surface(app, c, rgb, x0, y0, x1, y1, on)
        elif c["type"] in pads.BUTTONS:
            dpg.draw_rectangle((x0, y0), (x1, y1), fill=_shade(rgb, 1.0 if on else 0.32), color=_shade(rgb, 0.9),
                               rounding=px(8), thickness=px(2), parent=GRID)
        else:
            dpg.draw_rectangle((x0, y0), (x1, y1), fill=(28, 31, 38, 255), color=_shade(rgb, 0.7),
                               rounding=px(8), thickness=px(2), parent=GRID)
            f = pads.position(app, c)
            if c["type"] == "fader":
                pad = px(10)
                if c.get("orient", "v") == "v":
                    yb, yt = y1 - pad, y0 + pad + px(16)
                    yf = yb - (yb - yt) * f
                    dpg.draw_rectangle((x0 + pad, yf), (x1 - pad, yb), fill=_shade(rgb, 0.8), color=(0, 0, 0, 0),
                                       rounding=px(4), parent=GRID)
                    dpg.draw_line((x0 + pad, yf), (x1 - pad, yf), color=(240, 240, 240, 255), thickness=px(3),
                                  parent=GRID)
                else:
                    xl, xr = x0 + pad, x1 - pad
                    xf = xl + (xr - xl) * f
                    dpg.draw_rectangle((xl, y0 + pad + px(16)), (xf, y1 - pad), fill=_shade(rgb, 0.8),
                                       color=(0, 0, 0, 0), rounding=px(4), parent=GRID)
                    dpg.draw_line((xf, y0 + pad + px(16)), (xf, y1 - pad), color=(240, 240, 240, 255),
                                  thickness=px(3), parent=GRID)
            else:
                import math
                cx, cy = (x0 + x1) / 2, (y0 + y1) / 2 + px(8)
                r = max(px(8), min(x1 - x0, y1 - y0 - px(16)) / 2 - px(10))
                dpg.draw_circle((cx, cy), r, color=_shade(rgb, 0.5), thickness=px(4), parent=GRID)
                a0, a1 = math.radians(135), math.radians(135 + 270 * f)
                pts = [(cx + r * math.cos(a0 + (a1 - a0) * k / 24), cy + r * math.sin(a0 + (a1 - a0) * k / 24))
                       for k in range(25)]
                dpg.draw_polyline(pts, color=_shade(rgb, 1.0), thickness=px(4), parent=GRID)
                dpg.draw_line((cx, cy), pts[-1], color=(240, 240, 240, 255), thickness=px(3), parent=GRID)
        dpg.draw_text((x0 + px(7), y0 + px(5)), _wrap(lab, x1 - x0 - px(14), 3 if c["type"] in pads.BUTTONS else 1),
                      size=px(14),
                      color=(12, 12, 14, 255) if on and c["type"] in pads.BUTTONS else (232, 234, 238, 255),
                      parent=GRID)
        if edit and isinstance(sel, dict) and sel["id"] == c["id"]:
            dpg.draw_rectangle((x0 - px(2), y0 - px(2)), (x1 + px(2), y1 + px(2)), color=(255, 255, 255, 255),
                               rounding=px(9), thickness=px(2), parent=GRID)
            dpg.draw_rectangle((x1 - px(HANDLE), y1 - px(HANDLE)), (x1, y1), fill=(255, 255, 255, 255),
                               color=(0, 0, 0, 0), parent=GRID)
    if edit and isinstance(sel, tuple):
        x, y = sel
        dpg.draw_rectangle((x * cw + gap, y * ch + gap), ((x + 1) * cw, (y + 1) * ch), color=(255, 255, 255, 255),
                           rounding=px(6), thickness=px(2), parent=GRID)


def _surface_label(app, c):
    """An XY pad's words when it has no label of its own: what each movement drives."""
    parts = [f"{ {'x': 'x', 'y': 'y', 'p': 'press'}[a]}: {target_label(app, c.get(k)).split(': ')[-1]}"
             for a, k, _, _, _ in pads.AXES if (c.get(k) or {}).get("kind") and (a != "p" or c["type"] == "pressure")]
    return "  ".join(parts) or "nothing yet - pick an action"


def _draw_surface(app, c, rgb, x0, y0, x1, y1, on):
    """An XY pad: a dark field with a grid, lit at the edge while touched, the dot where the finger is (bigger the
    harder a pressure pad is pressed)."""
    dpg.draw_rectangle((x0, y0), (x1, y1), fill=_shade(rgb, 0.16), color=_shade(rgb, 1.0 if on else 0.6),
                       rounding=px(8), thickness=px(3 if on else 2), parent=GRID)
    top = y0 + px(22)
    for k in (1, 2, 3):
        gx = x0 + (x1 - x0) * k / 4
        gy = top + (y1 - top) * k / 4
        dpg.draw_line((gx, top), (gx, y1 - px(4)), color=_shade(rgb, 0.3), parent=GRID)
        dpg.draw_line((x0 + px(4), gy), (x1 - px(4), gy), color=_shade(rgb, 0.3), parent=GRID)
    at = pads.where(app, c)
    if at is None:
        return
    x, y, p = at
    cx, cy = x0 + px(6) + (x1 - x0 - px(12)) * x, y1 - px(6) - (y1 - top - px(12)) * y
    r = px(8) + (px(14) * p if c["type"] == "pressure" else px(4))
    dpg.draw_line((cx, top), (cx, y1 - px(4)), color=_shade(rgb, 0.8), parent=GRID)
    dpg.draw_line((x0 + px(4), cy), (x1 - px(4), cy), color=_shade(rgb, 0.8), parent=GRID)
    dpg.draw_circle((cx, cy), r, fill=_shade(rgb, 1.0), color=(255, 255, 255, 255), thickness=px(2), parent=GRID)


def _surface_at(c, mx, my, x0, y0, cw, ch, gap):
    """Where on an XY pad the pointer is: (x, y) 0..1, y up."""
    rx0, ry0, rx1, ry1 = _rect(c, cw, ch, gap)
    top = y0 + ry0 + px(22)
    x = (mx - (x0 + rx0 + px(6))) / max(1.0, rx1 - rx0 - px(12))
    y = ((y0 + ry1 - px(6)) - my) / max(1.0, (y0 + ry1) - top - px(12))
    return max(0.0, min(1.0, x)), max(0.0, min(1.0, y))


def _swell(app):
    """How hard a pressure pad is pressed from the mouse or a touchscreen, which cannot say: SWELL_FROM as it is
    touched, rising to full over SWELL_S held - an aftertouch swell. (How fast the pointer came in was tried: a
    mouse is still when it clicks and a touch jumps there at once, so it read the same for a tap and a slam.)"""
    import time
    held = time.monotonic() - getattr(app, "_pads_down_at", time.monotonic())
    return SWELL_FROM + (1.0 - SWELL_FROM) * max(0.0, min(1.0, held / SWELL_S))


def _wrap(text, width, lines):
    """The label broken into lines that fit the control's width (about 6.4 px a character at 14 px), at most `lines`,
    the last cut short with dots when the rest does not fit."""
    per = max(3, int(width / px(6.4)))
    out, line = [], ""
    for w in text.split():
        while len(w) > per:                                     # a word longer than the control: broken
            if line:
                out.append(line); line = ""
            out.append(w[:per]); w = w[per:]
        if not line:
            line = w
        elif len(line) + 1 + len(w) <= per:
            line += " " + w
        else:
            out.append(line); line = w
    if line:
        out.append(line)
    if len(out) > lines:
        out = out[:lines]
        out[-1] = (out[-1][:per - 3] if len(out[-1]) > per - 3 else out[-1]) + "..."
    return "\n".join(out)


def _cell(mx, my, x0, y0, cw, ch, b):
    col, row = int((mx - x0) // cw), int((my - y0) // ch)
    if 0 <= col < b["cols"] and 0 <= row < b["rows"]:
        return col, row
    return None


def _travel(c, mx, my, x0, y0, cw, ch, gap):
    """Where on a fader the pointer is, as 0..1 of its travel."""
    rx0, ry0, rx1, ry1 = _rect(c, cw, ch, gap)
    pad = px(10)
    if c.get("orient", "v") == "v":
        yb, yt = y0 + ry1 - pad, y0 + ry0 + pad + px(16)
        return max(0.0, min(1.0, (yb - my) / max(1.0, yb - yt)))
    xl, xr = x0 + rx0 + pad, x0 + rx1 - pad
    return max(0.0, min(1.0, (mx - xl) / max(1.0, xr - xl)))


def poll(app):
    """Each frame while the window is shown: the grid drawn, and the pointer on it played (or, editing, laid out);
    and, shown or not, what was typed into it saved once the typing stops."""
    import time
    _flush(app, time.monotonic())
    if not dpg.does_item_exist(TAG) or not dpg.is_item_shown(TAG):
        if getattr(app, "_pads_drag", None) is not None:
            app._pads_drag = None
            pads.let_go(app)
        return
    if getattr(app, "_pads_project", None) is not app.project:
        app._pads_project = app.project
        app._pads_whole = None
        app._pads_sel = None
        app._pads_labels = None
        _fill_banks(app)
        _fill_side(app)
    x0, y0, cw, ch, gap = _geometry(app)
    st = _st(app)
    b = pads.current(st)
    mx, my = dpg.get_mouse_pos(local=False)
    down = dpg.is_mouse_button_down(dpg.mvMouseButton_Left)
    drag = getattr(app, "_pads_drag", None)
    edit = bool(getattr(app, "_pads_edit", False))
    w, h = dpg.get_item_rect_size(GRID)
    over = x0 <= mx <= x0 + w and y0 <= my <= y0 + h and (dpg.is_item_hovered(GRID) or dpg.is_item_hovered("pads_area"))
    if drag is not None:
        if not down:
            if drag[0] == "play":
                c = pads.find(st, drag[1])
                if c is not None:
                    pads.release(app, c)
            elif drag[0] in ("move", "size"):
                _save(app)
                _fill_side(app)
            app._pads_drag = None
        else:
            _dragging(app, drag, mx, my, x0, y0, cw, ch, gap, b)
    elif over and dpg.is_mouse_button_clicked(dpg.mvMouseButton_Left):
        cell = _cell(mx, my, x0, y0, cw, ch, b)
        if cell is not None:
            c = pads.at(b, *cell)
            if edit:
                if c is None:
                    app._pads_sel = cell
                else:
                    app._pads_sel = c["id"]
                    rx0, ry0, rx1, ry1 = _rect(c, cw, ch, gap)
                    corner = mx >= x0 + rx1 - px(HANDLE) - px(4) and my >= y0 + ry1 - px(HANDLE) - px(4)
                    app._pads_drag = ("size" if corner else "move", c["id"], cell, (c["x"], c["y"]))
                _fill_side(app)
            elif c is not None:
                f = None
                if c["type"] in pads.SURFACES:
                    import time
                    app._pads_down_at = time.monotonic()
                    pads.press(app, c, xy=_surface_at(c, mx, my, x0, y0, cw, ch, gap), pressure=_swell(app))
                    app._pads_drag = ("play", c["id"])
                    _redraw(app, cw, ch, gap)
                    return
                if c["type"] == "fader":
                    f = _travel(c, mx, my, x0, y0, cw, ch, gap)
                elif c["type"] == "knob":
                    app._pads_knob = (my, pads.position(app, c))
                pads.press(app, c, f)
                app._pads_drag = ("play", c["id"])
    _redraw(app, cw, ch, gap)


def _dragging(app, drag, mx, my, x0, y0, cw, ch, gap, b):
    st = _st(app)
    c = pads.find(st, drag[1])
    if c is None:
        app._pads_drag = None
        return
    if drag[0] == "play":
        if c["type"] in pads.SURFACES:
            x, y = _surface_at(c, mx, my, x0, y0, cw, ch, gap)
            pads.move(app, c, x, y, _swell(app))                   # each frame held: the pressure swells
        elif c["type"] == "fader":
            pads.drag(app, c, _travel(c, mx, my, x0, y0, cw, ch, gap))
        elif c["type"] == "knob":
            y_start, f0 = getattr(app, "_pads_knob", (my, 0.0))
            pads.drag(app, c, f0 + (y_start - my) / px(KNOB_PX))
        return
    col = int((mx - x0) // cw)
