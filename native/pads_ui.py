def _geometry(app):
    """(x0, y0, cell w, cell h, gap) of the grid on screen, sized to the area it has."""
    b = pads.current(_st(app))
    aw, ah = dpg.get_item_rect_size("pads_area")
    aw, ah = max(px(120), aw - px(4)), max(px(120), ah - px(4))
    dpg.configure_item(GRID, width=int(aw), height=int(ah))
    gap = px(6)
    cw, ch = (aw - gap) / b["cols"], (ah - gap) / b["rows"]
    x0, y0 = dpg.get_item_rect_min(GRID)
    return x0, y0, cw, ch, gap


def _rect(c, cw, ch, gap):
    return (c["x"] * cw + gap, c["y"] * ch + gap, (c["x"] + c["w"]) * cw, (c["y"] + c["h"]) * ch)


def _shade(rgb, k):
    return (int(rgb[0] * k), int(rgb[1] * k), int(rgb[2] * k), 255)


def _drawn(app, cw, ch, gap):
    """All the grid shows, in brief: drawn again only when it changes (a full bank drawn each frame took 5 ms)."""
    st = _st(app)
    b = pads.current(st)
    edit = bool(pads_state.of(app).edit)
    sel = _sel(app)
    out = [st["bank"], b["cols"], b["rows"], round(cw, 2), round(ch, 2), gap, edit,
           sel["id"] if isinstance(sel, dict) else sel]
    for c in b["controls"]:
        lab = c.get("label") or (_surface_label(app, c) if c["type"] in pads.SURFACES else target_label(app, c.get("target")))
        out.append((c["id"], c["type"], c["x"], c["y"], c["w"], c["h"], c.get("colour"), c.get("orient"), lab,
                    (not edit) and bool(pads.lit(app, c)),
                    round(pads.position(app, c), 4) if c["type"] in pads.SLIDERS else None,
                    pads.where(app, c) if c["type"] in pads.SURFACES else None, tuple(decks_of(app, c))))
    return out


def _draw_deck_strip(app, c, x0, y0, x1, y1):
    """Along the bottom of a control that acts on a deck, that deck's colour (vj.DECK_RGB) - a control on "the
    selected deck" in the colour of the one selected now, so a glance says where the pads go; split between the
    decks of an XY pad whose axes act on more than one."""
    from native import vj
    ds = decks_of(app, c)
    if not ds:
        return
    pad, h = px(7), px(4)
    w = (x1 - x0 - 2 * pad) / len(ds)
    for k, d in enumerate(ds):
        a = x0 + pad + k * w
        dpg.draw_rectangle((a, y1 - pad - h), (a + w, y1 - pad), fill=tuple(vj.DECK_RGB[d]) + (255,),
                           color=(0, 0, 0, 0), rounding=px(2), parent=GRID)


def _redraw(app, cw, ch, gap):
    key = _drawn(app, cw, ch, gap)
    if key != pads_state.of(app).drawn or not dpg.get_item_children(GRID, 2):
        pads_state.of(app).drawn = key
        _draw(app, cw, ch, gap)
    _draw_swings(app, cw, ch, gap)


def _draw(app, cw, ch, gap):
    from native import chrome
    st = _st(app)
    b = pads.current(st)
    edit = bool(pads_state.of(app).edit)
    dpg.delete_item(GRID, children_only=True)
