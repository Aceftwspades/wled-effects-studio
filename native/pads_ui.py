def remote(app, cmd):
    """One checked command from the pads page (phone.check): a bank switched, or a control of the bank shown
    pressed, moved, let go or still held."""
    import time
    st = _st(app)
    if cmd["a"] == "padbank":
        switch_bank(app, int(cmd["v"]))
        return
    if pads_state.of(app).edit:                          # the pads do nothing while they are edited
        return
    c = next((x for x in pads.current(st)["controls"] if x["id"] == cmd["id"]), None)
    if c is None:                                                   # a bank switched since the page drew it
        return
    seen = pads_state.of(app).remote
    if seen is None:
        seen = pads_state.of(app).remote = {}
    e = cmd["e"]
    mine = seen.get(c["id"])                                        # [how many phone presses hold it, last heard]
    if e == "up":                                                   # only what a phone pressed: not the mouse's,
        if mine is not None:                                        # not the controller's, not one let go since
            mine[0] -= 1
            if mine[0] <= 0:
                del seen[c["id"]]
            pads.release(app, c)
        return
    if e in ("hold", "move"):
        if mine is None:                                            # let go since (Edit, a bank switched): nothing
            return
        mine[1] = time.monotonic()
        if e == "hold":
            return
    else:
        seen[c["id"]] = [(mine or [0])[0] + 1, time.monotonic()]
    if e == "down":
        if c["type"] in pads.SURFACES:
            pads.press(app, c, xy=(cmd.get("x", 0.5), cmd.get("y", 0.5)), pressure=cmd.get("p"))
        elif c["type"] == "knob":
            pads.press(app, c)
            if "f" in cmd:
                pads.drag(app, c, cmd["f"])
        else:
            pads.press(app, c, cmd.get("f"))
    elif e == "move":
        if c["type"] in pads.SURFACES:
            pads.move(app, c, cmd.get("x", 0.5), cmd.get("y", 0.5), cmd.get("p"))
        elif c["type"] in pads.SLIDERS and "f" in cmd:
            pads.drag(app, c, cmd["f"])


def remote_poll(app, gone=False):
    """Each frame: a control a phone holds but has not mentioned for REMOTE_GONE_S let go - every one at once when
    `gone` (the remote turned off: no phone can lift them)."""
    import time
    seen = pads_state.of(app).remote
    if not seen:
        return
    now = time.monotonic()
    for cid, (n, t) in list(seen.items()):
        if gone or now - t > REMOTE_GONE_S:
            del seen[cid]
            c = pads.find(_st(app), cid)
            for _ in range(n if c is not None else 0):             # each phone press it was holding by
                pads.release(app, c)


