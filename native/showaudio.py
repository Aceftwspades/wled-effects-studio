import math
import os
import threading
import time

import numpy as np

RATE = 44100                     # every file decoded to this, stereo: the mixer adds them sample for sample
PEAK = 256                       # frames a point of a sound's wave picture (its loudest), 5.8 ms
BLOCK = 1024                     # frames the speakers ask for at a time (23 ms)
RESYNC_S = 0.05                  # the speakers jump to the show's clock when they drift further than this


# --- the model ---------------------------------------------------------------------------------
def tracks(S):
    return S.setdefault("tracks", [])


def clip_end(c):
    return float(c.get("at", 0.0)) + float(c.get("len", 0.0))


def fades(track):
    """Each clip's (fade in, fade out) seconds on a track: as set by hand, or - a fade not set - the overlap with
    the clip before or after it on the track (a crossfade), none where there is none. Never more than the clip."""
    clips = track.get("clips") or []
    order = sorted(range(len(clips)), key=lambda k: float(clips[k].get("at", 0.0)))
    out = [(0.0, 0.0)] * len(clips)
    for pos, k in enumerate(order):
        c = clips[k]
        at, end, ln = float(c.get("at", 0.0)), clip_end(c), max(0.0, float(c.get("len", 0.0)))
        prev_end = max((clip_end(clips[j]) for j in order[:pos]), default=-1e9)
        next_at = min((float(clips[j].get("at", 0.0)) for j in order[pos + 1:]), default=1e9)
        auto_in = max(0.0, min(ln, prev_end - at))
        auto_out = max(0.0, min(ln, end - next_at))
        fi = float(c["fade_in"]) if "fade_in" in c else auto_in
        fo = float(c["fade_out"]) if "fade_out" in c else auto_out
        fi, fo = max(0.0, min(ln, fi)), max(0.0, min(ln, fo))
        if fi + fo > ln > 0:                              # the two meet in the middle at most
            s = ln / (fi + fo)
            fi, fo = fi * s, fo * s
        out[k] = (fi, fo)
    return out


def envelope(t, ln, fi, fo):
    """A clip's gain at its own times t (seconds from its start): equal-power fades, so a crossfade keeps its
    loudness."""
    g = np.ones_like(t, dtype=np.float32)
    if fi > 0:
        x = np.clip(t / fi, 0.0, 1.0)
        g *= np.sin(x * (math.pi / 2)).astype(np.float32)
    if fo > 0:
        x = np.clip((ln - t) / fo, 0.0, 1.0)
        g *= np.sin(x * (math.pi / 2)).astype(np.float32)
    return g


def resolve(S, root):
    """What the mixer plays: (sound, at, in, len, gain, fade in, fade out) for every clip of every track that is
    not muted, its file decoded (a clip whose file is still decoding, or missing, is left out until it is)."""
    out = []
    for tr in tracks(S):
        if tr.get("mute"):
            continue
        tg = float(tr.get("gain", 1.0))
        for c, (fi, fo) in zip(tr.get("clips") or [], fades(tr)):
            snd = sound(os.path.join(root, c.get("file", "")))
            if snd is None:
                continue
            out.append((snd, float(c.get("at", 0.0)), float(c.get("in", 0.0)), float(c.get("len", 0.0)),
                        tg * float(c.get("gain", 1.0)), fi, fo))
    return out


def length(S):
    """Where the last clip ends: the show's audio's length."""
    return max((clip_end(c) for tr in tracks(S) for c in tr.get("clips") or []), default=0.0)


# --- the files ---------------------------------------------------------------------------------
class Sound:
    """A decoded file: int16 stereo at RATE (half the memory of floats: a five-minute song is 53 MB), its seconds,
    and its wave's picture - the loudest of every PEAK frames, 0..1."""

    def __init__(self, data, name=""):
        self.data = np.ascontiguousarray(data, np.int16).reshape(-1, 2)
        self.name = name
        self.seconds = len(self.data) / float(RATE)
        a = np.abs(self.data.astype(np.int32)).max(axis=1)
        n = len(a) // PEAK
        pk = a[:n * PEAK].reshape(n, PEAK).max(axis=1) if n else np.zeros(1, np.int32)
        self.peaks = (pk / 32768.0).astype(np.float32)
        self.loudest = float(self.peaks.max()) if len(self.peaks) else 0.0     # the wave drawn to this, so a quiet file reads


_CACHE = {}                      # absolute path -> (mtime, Sound)
_PENDING = {}                    # absolute path -> the thread decoding it
_ERRORS = {}                     # absolute path -> why it could not be read
_LOCK = threading.Lock()


def _decode(path):
    """(n, 2) int16 at RATE: ffmpeg when there is one, a WAV by the wave module otherwise."""
    import shutil
    ff = shutil.which("ffmpeg")
    if ff:
        from native import procs
        r = procs.run([ff, "-v", "error", "-nostdin", "-i", path, "-vn", "-ac", "2", "-ar", str(RATE), "-f", "s16le", "-"],
                      capture_output=True, timeout=600)
        if r.returncode == 0 and r.stdout:
            return np.frombuffer(r.stdout, np.int16).reshape(-1, 2)
        why = (r.stderr or b"").decode("utf-8", "replace").strip().splitlines()
        raise RuntimeError("ffmpeg could not read it" + (f" ({why[-1][:120]})" if why else ""))
    if os.path.splitext(path)[1].lower() != ".wav":
        raise RuntimeError("a WAV is read as it is; anything else needs ffmpeg on the path")
    import wave
    with wave.open(path, "rb") as w:
        rate, ch, sw, n = w.getframerate(), w.getnchannels(), w.getsampwidth(), w.getnframes()
        raw = w.readframes(n)
    if sw != 2:
        raise RuntimeError("a 16-bit WAV is read without ffmpeg; this one needs it")
    a = np.frombuffer(raw, np.int16).reshape(-1, ch).astype(np.float32)
    a = a[:, :2] if ch >= 2 else np.repeat(a, 2, axis=1)
    if rate != RATE:                                     # to the mixer's rate, straight between the samples
        m = int(round(len(a) * RATE / float(rate)))
        x = np.linspace(0.0, len(a) - 1.0, m)
        a = np.stack([np.interp(x, np.arange(len(a)), a[:, k]) for k in (0, 1)], 1)
    return np.clip(a, -32768, 32767).astype(np.int16)


def sound(path, wait=False):
    """The file decoded, or None while it is decoding (it is begun on a thread the first time it is asked for) or
    when it cannot be read (error(path) says why). `wait`: decoded here and now."""
    path = os.path.abspath(path)
    try:
        mt = os.path.getmtime(path)
    except OSError:
        _ERRORS[path] = "the file is not there"
        return None
    with _LOCK:
        got = _CACHE.get(path)
        if got is not None and got[0] == mt:
            return got[1]
        if path in _PENDING and not wait:
            return None

    def work():
        try:
            snd = Sound(_decode(path), os.path.basename(path))
            with _LOCK:
                _CACHE[path] = (mt, snd)
                _ERRORS.pop(path, None)
        except Exception as e:
            with _LOCK:
                _ERRORS[path] = str(e)
        finally:
            with _LOCK:
                _PENDING.pop(path, None)
    if wait:
        work()
        with _LOCK:
            got = _CACHE.get(path)
        return got[1] if got else None
    th = threading.Thread(target=work, daemon=True, name="decode")
    with _LOCK:
        _PENDING[path] = th
    th.start()
    return None


def error(path):
    return _ERRORS.get(os.path.abspath(path))


def decoding():
    """Whether a file is still being decoded (the timeline draws it when it is done)."""
    with _LOCK:
        return bool(_PENDING)


# --- the mix -----------------------------------------------------------------------------------
def render(resolved, t, n):
    """(n, 2) float32 of the show's audio from t seconds: every clip there, from its own time in its file, by its
    gain and its fades."""
    out = np.zeros((n, 2), np.float32)
    t1 = t + n / float(RATE)
    for snd, at, cin, ln, gain, fi, fo in resolved:
        if at >= t1 or at + ln <= t or gain <= 0:
            continue
        a = max(t, at)                                    # the stretch of the block the clip plays in
        b = min(t1, at + ln)
        i0 = int(round((a - t) * RATE))
        i1 = min(n, int(round((b - t) * RATE)))
        if i1 <= i0:
            continue
        local = (a - at) + np.arange(i1 - i0, dtype=np.float64) / RATE      # seconds into the clip
        src = np.round((cin + local) * RATE).astype(np.int64)
        ok = (src >= 0) & (src < len(snd.data))
        if not ok.any():
            continue
        g = envelope(local.astype(np.float32), ln, fi, fo) * np.float32(gain / 32768.0)
        seg = np.zeros((i1 - i0, 2), np.float32)
        seg[ok] = snd.data[src[ok]]
        out[i0:i1] += seg * g[:, None]
    return out


def mono(block):
    return block.mean(axis=1)


# --- the speakers ------------------------------------------------------------------------------
class Player:
    """The show's mix through the speakers: a clock of its own that the show's keeps it to (sync), the clips it
    plays replaced whole when they change (set). `error` says why it is silent when it is."""

    def __init__(self):
        self.error = None
        self.volume = 1.0
        self._resolved = []
        self._pos = 0.0
        self._playing = False
        self._lock = threading.Lock()
        self._stream = None
        try:
            import sounddevice as sd
            self._stream = sd.OutputStream(samplerate=RATE, channels=2, dtype="float32", blocksize=BLOCK,
                                           latency="low", callback=self._cb)
            self._stream.start()
        except Exception as e:                            # no sounddevice, no output device
            self._stream = None
            self.error = f"the show's audio is not heard: {e}"

    @property
    def audible(self):
        return self._stream is not None

    def _cb(self, out, frames, time_info, status):
        with self._lock:
            playing, pos, resolved, vol = self._playing, self._pos, self._resolved, self.volume
            if playing:
                self._pos = pos + frames / float(RATE)
        if not playing or not resolved:
            out.fill(0.0)
            return
        out[:] = np.clip(render(resolved, pos, frames) * vol, -1.0, 1.0)

    def set(self, resolved):
        with self._lock:
            self._resolved = list(resolved)

    def sync(self, position, playing):
        """To the show: playing or not, and where - followed when the speakers have drifted from it."""
        with self._lock:
            if position is None:
                self._playing = False
                return
            if not playing or not self._playing or abs(self._pos - position) > RESYNC_S:
                self._pos = float(position)
            self._playing = bool(playing)

    @property
    def position(self):
        with self._lock:
            return self._pos

    def close(self):
        s, self._stream = self._stream, None
        if s is not None:
            try:
                s.stop(); s.close()
            except Exception:
                pass


# --- what the effects hear ---------------------------------------------------------------------
class ShowAudio:
    """The show's mix as the analyser's source (as audio.FileAudio is a file's): its last chunk where the show is,
    the bands, the level and the beat from it - so the effects move to the show's own sound, heard or not."""

    def __init__(self, resolved_fn, position_fn, gain=3.0, chunk=2048):
        from native import audio
        self.LO, self.HI, self.BANDS = audio.LiveAudio.LO, audio.LiveAudio.HI, audio.LiveAudio.BANDS
        self._resolved, self._position = resolved_fn, position_fn
        self.rate = RATE
        self.name = "the show's audio"
        self.gain = gain
        self.chunk = chunk
        self._buf = np.zeros(chunk, np.float32)
        self._win = np.hanning(chunk).astype(np.float32)
        self._edges = audio._band_edges(chunk, self.rate, self.LO, self.HI, self.BANDS)
        self._prev_low = 0.0
        self._floor = 0.0
        self._primed = False
        self._agc = 1.0
        self.level = 0.0
        self.seconds = 0.0

    def _window(self, n):
        t = self._position()
        if t is None:
            return np.zeros(n, np.float32)
        return mono(render(self._resolved(), t - n / float(RATE), n))

    def push(self, eng):
        from native import audio
        self._buf = self._window(self.chunk)
        return audio._push(self, eng)

    @property
    def _hist(self):
        from native import audio
        return self._window(audio._hist_len(self.rate, self.chunk))

    def pcm(self):
        from native import audio
        return audio._pcm(self)

    def chroma(self):
        from native import audio
        return audio._chroma_every(self)

    def close(self):
        pass
