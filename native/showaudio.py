"""The Sequence's audio: tracks of clips laid on the show's time under its
steps, heard with it and heard by its effects - a show of light and sound
made together. Not an editor: a clip is a file placed at a time, trimmed at
either end, faded in and out; where two on a track overlap they crossfade
by themselves, and a fade dragged by hand is kept as it is.

    S["tracks"] = [{"name": "Track 1", "mute": False, "gain": 1.0, "clips": [
        {"file": "assets/audio/beat.mp3", "at": 12.0, "in": 0.0, "len": 30.0, "gain": 1.0,
         "fade_in": 0.5, "fade_out": 2.0}]}]          # a fade_* absent: automatic (the overlap, or none)

    snd = sound(path)                  # decoded (stereo, RATE), cached; None while it is still decoding
    mix = render(resolve(S, root), t, n)   # (n, 2) float32 of the show at t seconds
    p = Player(); p.set(resolve(...)); p.sync(position, playing)    # the speakers, kept to the show's clock
    src = ShowAudio(p)                 # the analyser's source: the effects hear the mix

Decoding goes through the ffmpeg the studio already uses for audio and video
(a WAV is read as it is when there is none); the speakers through
sounddevice, the package the live audio uses. Without it the show still
plays its pictures and its effects still hear the mix - it is only not
heard.
"""
