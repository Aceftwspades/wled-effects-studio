def _stops(*cols):
    return np.array(cols, np.float32) / 255.0


GRADIENTS = {
    "rainbow": None,
    "fire": _stops((0, 0, 0), (120, 10, 0), (230, 80, 0), (255, 190, 40), (255, 255, 220)),
    "ice": _stops((0, 0, 20), (0, 60, 140), (40, 170, 230), (200, 240, 255), (255, 255, 255)),
    "neon": _stops((20, 0, 40), (255, 0, 160), (0, 220, 255), (180, 255, 0), (255, 0, 160)),
    "sunset": _stops((10, 0, 30), (120, 0, 90), (240, 60, 40), (255, 170, 60), (255, 240, 180)),
    "ocean": _stops((0, 10, 30), (0, 60, 90), (0, 150, 150), (120, 220, 200), (240, 255, 250)),
    "mono": _stops((0, 0, 0), (255, 255, 255)),
}


def gradient(name):
    stops = GRADIENTS.get(name)
    if stops is None:
        return lambda x: hsv(x, np.full_like(x, 0.9), np.ones_like(x))
    n = len(stops)

    def g(x):
        x = np.clip(np.asarray(x, np.float32), 0, 1) * (n - 1)
        i = np.minimum(x.astype(np.int32), n - 2)
        f = (x - i)[..., None]
        return stops[i] * (1 - f) + stops[i + 1] * f
    return g
