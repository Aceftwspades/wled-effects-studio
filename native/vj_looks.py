"""The VJ frame's looks (native/vj.py): each draws a deck's picture - a
small canvas the shape is then mapped from - out of its video, the sound and
the time. Plain numpy on a canvas of a hundred-odd pixels square, so a look
costs a millisecond or two.

    look = LOOKS["Neon Edges"]
    rgb = look.draw(ctx, state)          # (h, w, 3) float 0..1

Four families:
  video     the ten looks of the Video Switchboard graph, as image work on the
            deck's video: Clean, Neon Edges, Mosaic, Thermal, Halftone, Chroma
            Split, Melt, Motion Trails, Imprint, Follow Spot
  shader    per-pixel pictures in the Shadertoy manner - a function of where
            the pixel is, the time and the sound: Plasma, Tunnel, Warp,
            Voronoi, Kaleido Tunnel, Starfield, Metaballs, Beat Rings
  milkdrop  MilkDrop's way (Ryan Geiss, 2001): last frame's picture fed back,
            zoomed, turned and warped a little, faded, and the sound drawn
            over it - a preset is its motion and its colour as expressions of
            the time and the bass, mid and treble
  flame     fractal flames (Scott Draves' 1992 algorithm, Electric Sheep's):
            a few affine maps, each bent by variations (sinusoidal,
            spherical, swirl...), points thrown through them at random, their
            landing places counted and shown on a log scale - turning slowly,
            a new one bred from it by Mutate

The ctx a look reads (vj.Ctx): w, h; u, v (0..1); x, y (centred, -1..1 on
the short side), r, a (polar); t, dt (seconds); beat (a pulse 0..1 eased in
and let go), beats (beats gone by), bass, mid, treb, level (0..1), wave (the
sound as 64 numbers -1..1); video and video_prev ((h, w, 3) 0..1 or None);
amount, speed (the deck's knobs); grad(x) (the deck's colours for 0..1).
"""
