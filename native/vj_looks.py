def kaleido(ctx, img, n):
    """img folded through n mirror pairs round the middle."""
    seg = 2 * math.pi / max(1, n)
    a = np.abs(np.mod(ctx.a + ctx.t * 0.1, seg) - seg / 2)
    u = np.cos(a) * ctx.r * 0.5 * ctx.h / ctx.w + 0.5
    v = np.sin(a) * ctx.r * 0.5 + 0.5
    return sample(img, u, v)


def mirror(img):
    w = img.shape[1]
    out = img.copy()
    out[:, w - w // 2:] = img[:, :w // 2][:, ::-1]
    return out


def hue_turn(img, turns):
    """The picture's colours turned round the colour wheel (a rotation about the grey axis)."""
    if not turns:
        return img
    a = turns * 2 * math.pi
    c, s = math.cos(a), math.sin(a)
    k = 1.0 / 3.0
    m = np.array([[c + (1 - c) * k, k * (1 - c) - math.sqrt(k) * s, k * (1 - c) + math.sqrt(k) * s],
                  [k * (1 - c) + math.sqrt(k) * s, c + k * (1 - c), k * (1 - c) - math.sqrt(k) * s],
                  [k * (1 - c) - math.sqrt(k) * s, k * (1 - c) + math.sqrt(k) * s, c + k * (1 - c)]], np.float32)
    return np.clip(img @ m.T, 0, 1)


