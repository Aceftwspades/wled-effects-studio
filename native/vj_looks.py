@look("Clean", "video", "the video as it is - amount turns up its colour", video=True)
def _clean(ctx, st):
    img = _video(ctx)
    m = luma(img)[..., None]
    return np.clip(m + (img - m) * (1.0 + ctx.amount * 1.5), 0, 1)


@look("Neon Edges", "video", "only the outlines, glowing in the video's own colour - amount the gain", video=True)
def _edges(ctx, st):
    img = _video(ctx)
    l = np.pad(luma(img), 1, mode="edge")                                 # the border's own value past it: no wrap
    gx = l[1:-1, 2:] - l[1:-1, :-2]
    gy = l[2:, 1:-1] - l[:-2, 1:-1]
    e = np.clip(np.sqrt(gx * gx + gy * gy) * (2.0 + ctx.amount * 10.0), 0, 1)
    mx = np.maximum(img.max(axis=2, keepdims=True), 0.05)
    col = np.where(mx > 0.06, img / mx, 1.0)
    return blur(col * e[..., None], 1) * 1.6


@look("Mosaic", "video", "big blocks - amount how big", video=True)
def _mosaic(ctx, st):
    img = _video(ctx)
    b = max(2, int(2 + ctx.amount * 14))
    h, w = img.shape[:2]
    hh, ww = (h // b) * b, (w // b) * b
    small = img[:hh, :ww].reshape(hh // b, b, ww // b, b, 3).mean(axis=(1, 3))
    out = np.repeat(np.repeat(small, b, 0), b, 1)
    full = np.zeros_like(img)
    full[:hh, :ww] = out
    full[hh:, :] = full[hh - 1:hh, :] if hh < h else 0
    full[:, ww:] = full[:, ww - 1:ww] if ww < w else 0
    return full


@look("Thermal", "video", "the brightness as a heat camera sees it", video=True)
def _thermal(ctx, st):
    l = np.clip(luma(_video(ctx)) * (0.8 + ctx.amount), 0, 1)
    return np.stack([np.clip(l * 3.0 - 1.0, 0, 1) * 0.9 + np.clip(1 - abs(l - 0.35) * 4, 0, 1) * 0.6,
                     np.clip(l * 3.0 - 1.6, 0, 1) + np.clip(1 - abs(l - 0.15) * 6, 0, 1) * 0.1,
                     np.clip(1.0 - abs(l - 0.25) * 4.0, 0, 1) * 0.9 + np.clip(l * 4 - 3.2, 0, 1)], axis=-1)


@look("Halftone", "video", "dots as big as the picture is bright - amount the dots' size", video=True)
def _halftone(ctx, st):
    img = _video(ctx)
    n = 6 + (1.0 - ctx.amount) * 18
    cx = (np.floor(ctx.u * n * ctx.w / ctx.h) + 0.5) / (n * ctx.w / ctx.h)
    cy = (np.floor(ctx.v * n) + 0.5) / n
    c = sample(img, cx, cy)
    l = luma(c)
    d = np.hypot((ctx.u - cx) * n * ctx.w / ctx.h, (ctx.v - cy) * n)
    dot = np.clip((np.sqrt(l) * 0.62 - d) * 8.0, 0, 1)
    return c / np.maximum(c.max(axis=2, keepdims=True), 0.1) * dot[..., None]


@look("Chroma Split", "video", "red, green and blue pulled apart - further on the beat", video=True)
def _chroma(ctx, st):
    img = _video(ctx)
    d = (0.01 + ctx.amount * 0.05) * (1.0 + ctx.beat * 2.0)
    ang = ctx.t * 0.7
    du, dv = math.cos(ang) * d, math.sin(ang) * d
    r = sample(img, ctx.u + du, ctx.v + dv)[..., 0]
    g = img[..., 1]
    b = sample(img, ctx.u - du, ctx.v - dv)[..., 2]
    return np.stack([r, g, b], -1)


@look("Melt", "video", "the picture running down in drips", video=True)
def _melt(ctx, st):
    img = _video(ctx)
    drop = (np.sin(ctx.u * 23.0 + ctx.t * 0.9) * 0.5 + 0.5) * (np.sin(ctx.u * 7.0 - ctx.t * 0.4) * 0.5 + 0.5)
    v = ctx.v - drop * (0.05 + ctx.amount * 0.3) * (0.5 + 0.5 * np.sin(ctx.t * 0.6))
    out = sample(img, ctx.u, v)
    prev = st.get("fb")
    if prev is not None and prev.shape == out.shape:
        out = np.maximum(out, sample(prev, ctx.u, ctx.v - 0.012) * 0.86)
    st["fb"] = out
    return out


def _motion(ctx, st):
    """How much each pixel changed since the last frame, 0..1 (kept smooth)."""
    if ctx.video is None or ctx.video_prev is None or ctx.video_prev.shape != ctx.video.shape:
        return np.zeros((ctx.h, ctx.w), np.float32)
    m = np.abs(luma(ctx.video) - luma(ctx.video_prev))
    m = np.clip((m - 0.04) * 6.0, 0, 1)
    sm = st.get("mot")
    sm = m if sm is None or sm.shape != m.shape else np.maximum(m, sm * 0.6)
    st["mot"] = sm
    return sm


@look("Motion Trails", "video", "glowing tracers behind whatever moves", video=True)
def _trails(ctx, st):
    m = _motion(ctx, st)
    tr = st.get("tr")
    tr = np.zeros_like(m) if tr is None or tr.shape != m.shape else tr
    tr = np.maximum(tr * (0.9 + ctx.amount * 0.08), m)
    st["tr"] = tr
    hue = ctx.t * 0.05 + tr * 0.5
    return np.clip(hsv(hue, 0.9, tr) * 1.4 + _video(ctx) * 0.15, 0, 1)


@look("Imprint", "video", "fading afterimages of what moved, in its own colour", video=True)
def _imprint(ctx, st):
    m = _motion(ctx, st)[..., None]
    img = _video(ctx)
    acc = st.get("acc")
    acc = np.zeros_like(img) if acc is None or acc.shape != img.shape else acc
    acc = np.maximum(acc * (0.92 + ctx.amount * 0.07), img * m * 1.5)
    st["acc"] = acc
    return np.clip(acc + img * 0.1, 0, 1)


@look("Follow Spot", "video", "a spotlight that glides after the middle of the motion", video=True)
def _spot(ctx, st):
    m = _motion(ctx, st)
    tot = float(m.sum())
    cx, cy = st.get("c", (0.5, 0.5))
    if tot > 3.0:
        tx, ty = float((m * ctx.u).sum() / tot), float((m * ctx.v).sum() / tot)
        k = 1.0 - math.exp(-ctx.dt * 4.0)
        cx, cy = cx + (tx - cx) * k, cy + (ty - cy) * k
    st["c"] = (cx, cy)
    rad = 0.12 + ctx.amount * 0.2
    d = np.hypot((ctx.u - cx) * ctx.w / ctx.h, ctx.v - cy)
    spot = np.clip((rad - d) / 0.04, 0, 1)
    ring = np.clip(1.0 - abs(d - rad - 0.03) / 0.012, 0, 1) * (0.5 + 0.5 * ctx.beat)
    img = _video(ctx)
    return np.clip(img * (0.08 + spot[..., None]) + ring[..., None] * np.array([1.0, 0.85, 0.4]), 0, 1)


