def gradient(name):
    stops = GRADIENTS.get(name)
    if stops is None:
        return lambda x: hsv(x, np.full_like(x, 0.9), np.ones_like(x))
    n = len(stops)

    def g(x):
        x = np.clip(np.asarray(x, np.float32), 0, 1) * (n - 1)
        i = np.minimum(x.astype(np.int32), n - 2)
        f = (x - i)[..., None]
        return stops[i] * (1 - f) + stops[i + 1] * f
    return g
