@look("Plasma", "shader", "the old demo-scene plasma, sped by the mid")
def _plasma(ctx, st):
    t = ctx.t * (0.6 + ctx.mid)
    x, y = ctx.x * (2 + ctx.amount * 4), ctx.y * (2 + ctx.amount * 4)
    p = np.sin(x + t) + np.sin((y + t) * 0.7) + np.sin((x + y + t) * 0.5) + np.sin(np.hypot(x, y) * 1.5 - t)
    return ctx.grad(p * 0.125 + 0.5 + ctx.beat * 0.2)


@look("Tunnel", "shader", "flying down a tunnel (Shadertoy's classic 1/r), faster on the bass")
def _tunnel(ctx, st):
    st["z"] = st.get("z", 0.0) + ctx.dt * (0.4 + ctx.bass * 1.5) * ctx.speed
    r = np.maximum(ctx.r, 0.05)
    z = 0.5 / r + st["z"]
    a = ctx.a / math.pi + ctx.t * 0.05
    n = 4 + int(ctx.amount * 8)
    chk = ((np.floor(z * 2) + np.floor(a * n)) % 2) * 0.6 + 0.4
    return ctx.grad(np.mod(z * 0.25, 1.0)) * (chk * np.clip(r * 1.6, 0, 1))[..., None]


@look("Warp", "shader", "noise folded into itself (Inigo Quilez's domain warping)")
def _warp(ctx, st):
    t = ctx.t * 0.15
    s = 1.5 + ctx.amount * 3
    x, y = ctx.x * s, ctx.y * s
    qx, qy = fbm(x + t, y, 3), fbm(x + 5.2, y + 1.3 - t, 3)
    v = fbm(x + 4 * qx + 1.7, y + 4 * qy + 9.2, 3, seed=3)
    return ctx.grad(np.clip(v * 1.2 - 0.1 + ctx.bass * 0.2, 0, 1)) * (0.5 + v)[..., None]


@look("Voronoi", "shader", "cells round drifting points, their edges bright on the beat")
def _voronoi(ctx, st):
    n = 6 + int(ctx.amount * 18)
    rng = np.random.default_rng(7)
    ph = rng.random((n, 4)) * 6.283
    t = ctx.t * 0.3
    px = np.sin(t * (0.5 + ph[:, 2] * 0.1) + ph[:, 0]) * (ctx.w / ctx.h)
    py = np.cos(t * (0.4 + ph[:, 3] * 0.1) + ph[:, 1])
    d = np.hypot(ctx.x[..., None] - px, ctx.y[..., None] - py)
    s = np.sort(d, axis=-1)
    k = np.argmin(d, axis=-1)
    edge = np.clip(1.0 - (s[..., 1] - s[..., 0]) * 12, 0, 1)
    return ctx.grad(k / n) * (0.55 + 0.45 * np.cos(s[..., 0] * 6))[..., None] + edge[..., None] * (0.3 + ctx.beat)


@look("Kaleido Tunnel", "shader", "a tunnel seen through a kaleidoscope's mirrors")
def _ktunnel(ctx, st):
    n = 3 + int(ctx.amount * 6)
    a = np.abs(np.mod(ctx.a + ctx.t * 0.2, 2 * math.pi / n) - math.pi / n)
    r = np.maximum(ctx.r, 0.04)
    st["z"] = st.get("z", 0.0) + ctx.dt * (0.3 + ctx.bass) * ctx.speed
    x, y = np.cos(a) / r, np.sin(a) / r
    p = np.sin(x * 2 + st["z"] * 3) * np.cos(y * 3 - st["z"] * 2)
    return ctx.grad(np.mod(p * 0.5 + 0.5 + st["z"] * 0.1, 1.0)) * np.clip(r * 1.5, 0, 1)[..., None]


@look("Starfield", "shader", "stars rushing past - hyperspace on the beat")
def _stars(ctx, st):
    if "s" not in st:
        rng = np.random.default_rng(3)
        st["s"] = np.column_stack([rng.uniform(-1, 1, 300), rng.uniform(-1, 1, 300), rng.uniform(0.05, 1, 300)])
    s = st["s"]
    s[:, 2] -= ctx.dt * (0.15 + ctx.amount * 0.6 + ctx.beat * 1.2) * ctx.speed
    gone = s[:, 2] <= 0.02
    if gone.any():
        k = int(gone.sum())
        rng = np.random.default_rng()
        s[gone] = np.column_stack([rng.uniform(-1, 1, k), rng.uniform(-1, 1, k), np.ones(k)])
    out = np.zeros((ctx.h, ctx.w), np.float32)
    sx = (s[:, 0] / s[:, 2] * 0.3 * ctx.h / ctx.w + 0.5) * (ctx.w - 1)
    sy = (s[:, 1] / s[:, 2] * 0.3 + 0.5) * (ctx.h - 1)
    ok = (sx >= 0) & (sx < ctx.w) & (sy >= 0) & (sy < ctx.h)
    np.add.at(out, (sy[ok].astype(int), sx[ok].astype(int)), (1.1 - s[ok, 2]) * 1.5)
    trail = st.get("tr")
    trail = out if trail is None or trail.shape != out.shape else np.maximum(out, trail * (0.6 + ctx.beat * 0.3))
    st["tr"] = trail
    return np.clip(trail[..., None] * (ctx.grad(np.full_like(trail, 0.8)) * 0.5 + 0.5), 0, 1)


@look("Metaballs", "shader", "soft blobs that merge and part, swelling on the bass")
def _meta(ctx, st):
    n = 5
    f = np.zeros((ctx.h, ctx.w), np.float32)
    for k in range(n):
        px = math.sin(ctx.t * (0.31 + k * 0.07) + k * 2.1) * 0.9 * ctx.w / ctx.h
        py = math.cos(ctx.t * (0.27 + k * 0.05) + k * 1.3) * 0.8
        f += (0.09 + ctx.bass * 0.06 + ctx.amount * 0.05) / ((ctx.x - px) ** 2 + (ctx.y - py) ** 2 + 1e-3)
    v = np.clip(f - 0.8, 0, 3)
    return ctx.grad(np.clip(v * 0.35, 0, 1)) * np.clip(v, 0, 1)[..., None]


@look("Beat Rings", "shader", "a ring thrown out from the middle on every beat")
def _rings(ctx, st):
    rings = st.setdefault("rings", [])
    if ctx.beat_hit:
        rings.append(0.0)
    rings[:] = [r + ctx.dt * (0.6 + ctx.amount) * ctx.speed for r in rings if r < 2.0]
    out = np.zeros((ctx.h, ctx.w), np.float32)
    col = np.zeros((ctx.h, ctx.w), np.float32)
    for k, r in enumerate(rings):
        w = np.clip(1.0 - np.abs(ctx.r - r) / (0.05 + r * 0.05), 0, 1) * (1.0 - r / 2.0)
        out = np.maximum(out, w)
        col = np.where(w > 0.01, r * 0.5, col)
    return ctx.grad(col) * out[..., None] + ctx.grad(np.full_like(out, 0.0)) * 0.05


