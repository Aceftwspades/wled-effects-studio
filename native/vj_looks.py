def look(name, family, desc, video=False):
    def reg(fn):
        LOOKS[name] = Look(name, family, fn, desc, video)
        return fn
    return reg


# --- helpers -------------------------------------------------------------------------------------
def luma(img):
    return img[..., 0] * 0.3 + img[..., 1] * 0.59 + img[..., 2] * 0.11


def sample(img, u, v, wrap=False):
    """img (h, w, c) read at u, v (0..1, arrays), bilinear; clamped at the edges (or wrapped)."""
    h, w = img.shape[:2]
    x = u * (w - 1)
    y = v * (h - 1)
    if wrap:
        x = np.mod(x, w); y = np.mod(y, h)
    else:
        x = np.clip(x, 0, w - 1); y = np.clip(y, 0, h - 1)
    x0 = np.floor(x).astype(np.int32); y0 = np.floor(y).astype(np.int32)
    fx = (x - x0)[..., None]; fy = (y - y0)[..., None]
    x1 = (x0 + 1) % w if wrap else np.minimum(x0 + 1, w - 1)
    y1 = (y0 + 1) % h if wrap else np.minimum(y0 + 1, h - 1)
    x0 %= w; y0 %= h
    a = img[y0, x0] * (1 - fx) + img[y0, x1] * fx
    b = img[y1, x0] * (1 - fx) + img[y1, x1] * fx
    return a * (1 - fy) + b * fy


def hsv(hh, s, v):
    """Arrays of hue (turns), saturation and value to (..., 3) rgb."""
    hh = np.mod(hh, 1.0) * 6.0
    k = lambda n: np.mod(n + hh, 6.0)                                   # noqa: E731
    f = lambda n: v - v * s * np.clip(np.minimum(k(n), 4.0 - k(n)), 0.0, 1.0)  # noqa: E731
    return np.stack([f(5.0), f(3.0), f(1.0)], axis=-1)


def blur(img, n=1):
    for _ in range(n):
        img = (img + np.roll(img, 1, 0) + np.roll(img, -1, 0) + np.roll(img, 1, 1) + np.roll(img, -1, 1)) / 5.0
    return img


def _video(ctx):
    return ctx.video if ctx.video is not None else np.zeros((ctx.h, ctx.w, 3), np.float32)


def noise(x, y, seed=0):
    """Smooth value noise, 0..1."""
    xi, yi = np.floor(x), np.floor(y)
    xf, yf = x - xi, y - yi
    def hsh(a, b):
        n = np.sin(a * 127.1 + b * 311.7 + seed * 74.7) * 43758.5453
        return n - np.floor(n)
    u = xf * xf * (3 - 2 * xf); v = yf * yf * (3 - 2 * yf)
    return (hsh(xi, yi) * (1 - u) + hsh(xi + 1, yi) * u) * (1 - v) + (hsh(xi, yi + 1) * (1 - u) + hsh(xi + 1, yi + 1) * u) * v


def fbm(x, y, oct=4, seed=0):
    s, a = 0.0, 0.5
    for k in range(oct):
        s = s + a * noise(x, y, seed + k)
        x, y, a = x * 2.03 + 1.7, y * 2.03 - 0.4, a * 0.5
    return s


