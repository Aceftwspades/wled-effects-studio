    col = ctx.grad((ctx.u + ctx.t * 0.1) % 1.0)
    col = col / np.maximum(col.max(axis=2, keepdims=True), 0.2)       # the words at the colours' full brightness
    return np.clip(col, 0, 1) * out[..., None]


