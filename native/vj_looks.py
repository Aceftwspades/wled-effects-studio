def _p(v, c):
    return float(v(c)) if callable(v) else float(v)


def _grad_colour(ctx, x):
    """One colour of the deck's colours at x (wrapping, as a hue does), at full brightness: a preset's hue sweep
    becomes a sweep through the deck's gradient (rainbow: the hues, as MilkDrop's own)."""
    c = np.asarray(ctx.grad(np.array([math.fmod(x, 1.0) % 1.0], np.float32)), np.float32).reshape(-1)[:3]
    return c / max(float(c.max()), 0.2)


def milkdrop_frame(ctx, st, pre):
    """One frame of a MilkDrop preset: the last frame warped and faded, the sound drawn over it."""
    h, w = ctx.h, ctx.w
    fb = st.get("fb")
    if fb is None or fb.shape != (h, w, 3):
        fb = np.zeros((h, w, 3), np.float32)
    k = ctx.dt * 30.0                                                   # presets are tuned at 30 frames a second
    zoom = _p(pre.get("zoom", 1.0), ctx) ** k
    rot = _p(pre.get("rot", 0.0), ctx) * ctx.dt * 2 * math.pi * ctx.speed
    warp = _p(pre.get("warp", 0.0), ctx) * (0.5 + ctx.amount)
    x, y = ctx.x / zoom, ctx.y / zoom
    cr, sr = math.cos(rot), math.sin(rot)
    x, y = x * cr - y * sr, x * sr + y * cr
    if warp:
        wt = ctx.t * 0.7
        x = x + np.sin(y * 3.1 + wt) * 0.01 * warp
        y = y + np.cos(x * 2.7 - wt * 1.3) * 0.01 * warp
    x = x + _p(pre.get("dx", 0.0), ctx) * k
    y = y + _p(pre.get("dy", 0.0), ctx) * k
    if pre.get("mirror"):
        x = -np.abs(x)
    u = x * (ctx.h / ctx.w) * 0.5 + 0.5
    v = y * 0.5 + 0.5
    fb = sample(fb, u, v) * (_p(pre.get("decay", 0.95), ctx) ** k)
    fb = blur(fb, 1) if ctx.h > 40 else fb
    hue = _p(pre.get("hue", 0.0), ctx)
    col = _grad_colour(ctx, hue)                                       # the deck's colours, swept as the preset's hue
    wave = pre.get("wave")
    lvl = 0.6 + ctx.level * 0.8
    if wave:
        s = np.interp(np.linspace(0, len(ctx.wave) - 1, 256), np.arange(len(ctx.wave)), ctx.wave)
        n = len(s) if wave != "dots" else 48
        if wave == "circle":
            ang = np.linspace(0, 2 * math.pi, n, endpoint=False)
            rr = 0.35 + s * 0.15 + ctx.bass * 0.1
            px, py = np.cos(ang) * rr * ctx.h / ctx.w, np.sin(ang) * rr
        elif wave == "dots":
            rng = np.random.default_rng(int(ctx.t * 7))
            px, py = rng.uniform(-0.9, 0.9, n), rng.uniform(-0.9, 0.9, n) * (0.4 + ctx.level)
        else:
            px, py = np.linspace(-0.95, 0.95, n), s * 0.4
        ix = ((px * 0.5 + 0.5) * (w - 1)).astype(int).clip(0, w - 1)
        iy = ((py * 0.5 + 0.5) * (h - 1)).astype(int).clip(0, h - 1)
        for oy, ox, f in ((0, 0, 1.0), (1, 0, 0.7), (0, 1, 0.7), (-1, 0, 0.4), (0, -1, 0.4)):   # a line two wide
            jy, jx = np.clip(iy + oy, 0, h - 1), np.clip(ix + ox, 0, w - 1)
            fb[jy, jx] = np.maximum(fb[jy, jx], col * lvl * f)
    if pre.get("shape") and ctx.beat_hit:
        ring = np.clip(1.0 - np.abs(ctx.r - 0.25) / 0.03, 0, 1)
        fb = np.maximum(fb, ring[..., None] * _grad_colour(ctx, hue + 0.5))
    if pre.get("grid"):
        g = ((np.abs(np.mod(ctx.x * 4, 1.0) - 0.5) < 0.04) | (np.abs(np.mod(ctx.y * 4, 1.0) - 0.5) < 0.04))
        fb = np.maximum(fb, g[..., None] * col * ctx.beat * 0.8)
    if ctx.video is not None:                                         # a deck's video seeds the feedback
        fb = np.maximum(fb, ctx.video * 0.08 * (0.5 + ctx.amount))
    st["fb"] = np.clip(fb, 0, 1)
    return st["fb"]


