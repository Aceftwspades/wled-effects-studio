# --- what the panel shows --------------------------------------------------------------------------------------
def _clip(app):
    """The selected control and its clip target, or (None, None)."""
    s = _ui()._sel(app)
    if isinstance(s, dict) and (s.get("target") or {}).get("kind") in vj_clips.KINDS:
        return s, s["target"]
    return None, None


def how(typ, mode):
    """What a pad of type `typ` does with a clip of `mode` (a camera: None), in a sentence."""
    if mode is None:
        return {"hold": "Shows the camera while held; let go, it fades over its release.",
                "toggle": "On: the camera shows; off: it fades over its release."}.get(
            typ, "A press brings the camera up; the next press lets it fade.")
    if typ == "hold":
        return ("Plays while held, to Out at most; let go, it fades over its release." if mode == "oneshot" else
                "Loops while held; let go, it fades over its release.")
    if typ == "toggle":
        return "On: it plays (once to Out, or round); off: it fades over its release."
    return ("Each press plays it from In to Out - pressed while it plays, from In again." if mode == "oneshot" else
            "A press starts it looping; the next press lets it fade.")


def fill(app, s):
    """The CLIP rows shown and set for the selected control (hidden for any other action)."""
    if not dpg.does_item_exist(ROW):
        return
    t = (s or {}).get("target") or {}
    on = isinstance(s, dict) and t.get("kind") in vj_clips.KINDS
    dpg.configure_item(ROW, show=on)
    if not on:
        return
    vj_clips.fill(t)
    cam = t["kind"] == "pad_cam"
    dpg.set_value("pads_clip_head", "CAMERA" if cam else "CLIP")
    for tag in ("pads_clip_filerow", "pads_clip_mode", "pads_clip_parts"):
        dpg.configure_item(tag, show=not cam)
    dpg.configure_item("pads_clip_camrow", show=cam)
    dpg.set_value("pads_clip_deck", DECK_WORDS[t["deck"]])
    for k in ("attack", "decay", "sustain", "release", "level"):
        num.set(f"pads_clip_{k}", float(t[k]))
    _draw_env(t)
    if cam:
        dpg.set_value("pads_clip_how", how(s["type"], None))
        dpg.set_value("pads_clip_len", "")
        _look_for_cams(app)
        return
    items = vj_clips.files(app)
    if t["file"] and t["file"] not in items:
        items = [t["file"]] + items
    dpg.configure_item("pads_clip_file", items=items)
    dpg.set_value("pads_clip_file", t["file"])
    dpg.set_value("pads_clip_deck", DECK_WORDS[t["deck"]])
    dpg.set_value("pads_clip_mode", dict(vj_clips.MODES)[t["mode"]])
    dpg.set_value("pads_clip_how", how(s["type"], t["mode"]))
    for k in ("in", "attack", "decay", "sustain", "release", "level"):
        num.set(f"pads_clip_{k}", float(t[k]))
    _show_out(app, t)
    _draw_env(t)
    app._clip_strip_key = None                       # drawn again next frame (poll)


def _look_for_cams(app, again=False):
    """The camera list filled - asked of ffmpeg on a worker the first time (or again), the pad's own camera in it
    though it is not plugged in now."""
    from native import tasks
    names = getattr(app, "_clip_cams", None)
    if names is None or again:
        app._clip_cams = names = []

        def done(got):
            app._clip_cams = got
            _cam_items(app)
        tasks.run(app, "pads_cam_list", "looking for cameras", vj_clips.cameras, done)
    _cam_items(app)


def _cam_items(app):
    _, t = _clip(app)
    if t is None or t.get("kind") != "pad_cam" or not dpg.does_item_exist("pads_clip_cam"):
        return
    items = list(getattr(app, "_clip_cams", None) or [])
    if t["name"] and t["name"] not in items:
        items = [t["name"]] + items
    dpg.configure_item("pads_clip_cam", items=items)
    if not t["name"] and items:                     # a new camera pad: the first camera found, picked for it
        _set(app, name=items[0])
        return
    dpg.set_value("pads_clip_cam", t["name"])


def _path(app, t):
    from native import vj
    return vj.media(app, t.get("file", ""))


def _strip(app, t):
    """The strip's frames for t's file - made on a thread the first time (None until then)."""
    from native import video
    p = _path(app, t)
    try:
        key = (p, os.path.getmtime(p))
    except OSError:
        return None
    if key not in _THUMBS:
        _THUMBS[key] = None
        while len(_THUMBS) > 24:
            _THUMBS.pop(next(iter(_THUMBS)))

        def work():
            img = video.thumbs(p, 8, TW // 8, TH)
            _THUMBS[key] = img if img is not None else np.zeros((TH, TW, 3), np.uint8)
        threading.Thread(target=work, daemon=True, name="clip thumbs").start()
    return _THUMBS[key]


def _draw_strip(app, t):
    """The strip: the file's frames end to end, the part outside In - Out dimmed, the two handles, and where it is
    while it plays."""
    from native import chrome as c, textures, video
    dpg.delete_item(STRIP, children_only=True)
    w, h = _w(), px(40)
    p = _path(app, t)
    dur = video.duration_of(p, wait=False) if os.path.isfile(p) else None
    img = _strip(app, t) if dur else None
    if img is not None:
        data = np.concatenate([img.astype(np.float32) / 255.0, np.ones((TH, TW, 1), np.float32)], axis=2).ravel()
        if dpg.does_item_exist(STRIP_TEX):
            dpg.set_value(STRIP_TEX, data)
        else:
            dpg.add_raw_texture(TW, TH, data, format=dpg.mvFormat_Float_rgba, tag=STRIP_TEX, parent=textures.registry())
        dpg.draw_image(STRIP_TEX, (0, 0), (w, h), parent=STRIP)
    else:
        dpg.draw_rectangle((0, 0), (w, h), fill=(40, 44, 52, 255), color=(0, 0, 0, 0), parent=STRIP)
        why = "no file picked" if not t.get("file") else ("its length is not known (ffprobe)" if not dur
                                                          else "its frames...")
        dpg.draw_text((px(6), h / 2 - px(7)), why, color=c.DIM, size=px(13), parent=STRIP)
    dpg.set_value("pads_clip_len", "" if not dur else f"{vj_clips.length(app, t) or 0:.2f} s of {dur:.2f} s")
    if not dur:
        return
    a, b = float(t["in"]), float(t["out"]) or dur
    xa, xb = w * min(1.0, a / dur), w * min(1.0, b / dur)
    shade = (0, 0, 0, 170)
    if xa > 0:
        dpg.draw_rectangle((0, 0), (xa, h), fill=shade, color=(0, 0, 0, 0), parent=STRIP)
    if xb < w:
        dpg.draw_rectangle((xb, 0), (w, h), fill=shade, color=(0, 0, 0, 0), parent=STRIP)
    for x in (xa, xb):
        dpg.draw_line((x, 0), (x, h), color=HANDLE_RGBA, thickness=px(3), parent=STRIP)
        dpg.draw_rectangle((x - px(4), 0), (x + px(4), px(8)), fill=HANDLE_RGBA, color=(0, 0, 0, 0), parent=STRIP)
    at = _playhead(app, t)
    if at is not None:
        x = w * min(1.0, (a + at) / dur)
        dpg.draw_line((x, 0), (x, h), color=PLAYHEAD_RGBA, thickness=px(1), parent=STRIP)


def _playhead(app, t):
    """Seconds into the clip the selected pad's playing clip is, or None."""
    s, _ = _clip(app)
    if s is None:
        return None
    from native import clock
    for p in vj_clips._rt(app).values():
        if p["owner"] in (s["id"], ("try", s["id"])) and p["t0"] is not None:
            n = vj_clips.length(app, p["t"]) or 0.0
            return (clock.now() - p["t0"]) % n if n > 0 else None
    return None


def _draw_env(t):
    """The envelope drawn: attack up, decay down to sustain, a held stretch, the release down."""
    from native import chrome as c
    if not dpg.does_item_exist(ENV_DRAW):
        return
    dpg.delete_item(ENV_DRAW, children_only=True)
    w, h = _w(), px(34)
    a, d, s, r = (float(t[k]) for k in ("attack", "decay", "sustain", "release"))
    hold = max(0.2, 0.3 * (a + d + r))
    total = a + d + hold + r
    x = lambda sec: w * sec / total                       # noqa: E731
    y = lambda lv: h - px(2) - (h - px(4)) * lv          # noqa: E731
    pts = [(0, y(0)), (x(a), y(1)), (x(a + d), y(s)), (x(a + d + hold), y(s)), (w, y(0))]
    dpg.draw_rectangle((0, 0), (w, h), fill=(30, 33, 40, 255), color=(0, 0, 0, 0), parent=ENV_DRAW)
    dpg.draw_polyline(pts, color=c.ACCENT, thickness=px(2), parent=ENV_DRAW)


# --- edits --------------------------------------------------------------------------------------------------------
def _set(app, quiet=False, **kw):
    """Fields of the selected pad's clip set: a choice saved at once and the rows set again; a number (a drag field,
    each step of it) saved once it is left alone."""
    s, t = _clip(app)
    if t is None:
        return
    t.update(kw)
    vj_clips.fill(t)
    _draw_env(t)
    if quiet:
        _ui()._save_soon(app)
        return
    _ui()._save(app)
    fill(app, s)


def _set_part(app, which, v):
    """In or Out typed: kept inside the file and at least MIN_PART_S apart (Out at the file's end: 0, to the end)."""
    from native import video
    s, t = _clip(app)
    if t is None:
        return
    dur = video.duration_of(_path(app, t)) or 0.0
    a, b = float(t["in"]), float(t["out"])
    v = max(0.0, float(v))
    if which == "in":
        end = b or dur
        a = min(v, end - MIN_PART_S) if end else v
    else:
        b = 0.0 if (dur and v >= dur - 1e-3) or v <= 0 else max(v, a + MIN_PART_S)
    _set(app, quiet=True, **{"in": round(max(0.0, a), 2), "out": round(b, 2)})
    num.set("pads_clip_in", float(t["in"]))
    _show_out(app, t)
    app._clip_strip_key = None


def _show_out(app, t):
    """Out as a time: the file's end where it is kept as 0 (to the end)."""
    from native import video
    num.set("pads_clip_out", float(t["out"]) or float(video.duration_of(_path(app, t), wait=False) or 0.0))


def _set_file(app, f):
    if f:
        _set(app, file=f, **{"in": 0.0, "out": 0.0})


def _chosen(app, a):
    """A file from the dialog: copied into the project (a worker - a video can be large), then the pad's."""
    from native import tasks, vj
    f = a.get("file_path_name", "")
    if not f or not os.path.isfile(f):
        return
    opened = getattr(app, "_clip_dialog_for", None)
    if opened and opened[2] is not app.project:      # another project opened while the file was picked: not
        app.gp.status("another project was opened while the file was picked - not copied", "warn")   # copied in
        return
    proj, into = app.project, _into(app)
    cid = _dialog_for(app)[0]                        # the pad it was opened for
    tasks.run(app, "pads_clip_copy", f"copying {os.path.basename(f)} into the project",
              lambda: vj.keep_media(into, f), lambda kept: app.project is proj and _file_of(app, cid, kept))


def _file_of(app, cid, f):
    """The pad `cid`'s clip given file f (its part from the start again) - the panel's, when it is the one shown."""
    from native import pads
    c = pads.find(_ui()._st(app), cid) if cid is not None else None
    t = (c or {}).get("target") or {}
    if t.get("kind") != "pad_clip":
        return
    t.update(file=f, **{"in": 0.0, "out": 0.0})
    vj_clips.fill(t)
    _ui()._save(app)
    if _ui()._sel(app) is c:
        fill(app, c)


def _add_many(app, a):
    """Several files from the dialog, each a trigger pad playing it once on deck C - in the bank's free cells, in
    the order picked, labelled by the file's name."""
    from native import tasks, vj
    sel = [f for f in (list((a.get("selections") or {}).values()) or [a.get("file_path_name", "")])
           if f and os.path.isfile(f)]
    if not sel:
        return

    proj, into = app.project, _into(app)
    bank = _dialog_for(app)[1]                       # its bank then (another project's open: not added)
    if bank is None:
        app.gp.status("another project was opened while the files were picked - none added", "warn")
        return
    tasks.run(app, "pads_clips_copy", f"copying {len(sel)} video file(s) into the project",
              lambda: [vj.keep_media(into, f) for f in sel],
              lambda kept: app.project is proj and _made(app, kept, bank))


def _open_dialog(app, tag):
    """A file dialog shown, the pad and the bank it is for kept (another may be picked while it is open)."""
    s, _ = _clip(app)
    app._clip_dialog_for = (s["id"] if s else None, _ui()._st(app)["bank"], app.project)
    dpg.show_item(tag)


def _dialog_for(app):
    """(pad id, bank) the open file dialog is for - none once another project is open (its ids are its own)."""
    got = getattr(app, "_clip_dialog_for", None)
    if not got or got[2] is not app.project:
        return None, None
    return got[0], got[1]


def _into(app):
    """The project open now, for a worker copying files into it (another opened meanwhile not handed them)."""
    import types
    return types.SimpleNamespace(project=app.project)


def add_pads(app, kept, bank=None):
    """One trigger pad a kept file, playing it once on deck C - in the current bank's free cells, then (it full) in
    new banks named Clips, a grid as big as they need (up to 8 x 8). [the banks' indexes used], the pads made."""
    from native import pads
    st = _ui()._st(app)
    colours = [n for n, _ in pads.COLOURS if n != "grey"]
    if bank is None or not 0 <= bank < len(st["banks"]):
        bank = st["bank"]
    b, used, made = st["banks"][bank], [bank], 0
    for k, f in enumerate(kept):
        cell = _ui()._free_cell(b)
        if cell is None:
            if len(st["banks"]) >= pads.MAX_BANKS:
                break
            n = len(kept) - k
            side = max(4, min(pads.GRID_MAX, int(n ** 0.5 + 0.999)))
            b = pads.new_bank("Clips", side, side, "violet")
            st["banks"].append(b)
            used.append(len(st["banks"]) - 1)
            cell = (0, 0)
        label = os.path.splitext(os.path.basename(f))[0][:18]
        b["controls"].append(pads.new_control(st, "trigger", cell[0], cell[1], target=dict(vj_clips.DEFAULT, file=f),
                                              label=label, colour=colours[k % len(colours)]))
        made += 1
    return used, made


def _made(app, kept, bank=None):
    from native import pads
    ui = _ui()
    used, made = add_pads(app, kept, bank)
    if used[-1] != ui._st(app)["bank"]:
        ui.switch_bank(app, used[-1])                    # the new bank shown
    ui._save(app)
    ui._fill_banks(app)
    ui._fill_side(app)
    left = len(kept) - made
    app.gp.status(f"{made} clip pad(s) made" + (f" in {len(used) - 1} new bank(s) named Clips" if len(used) > 1 else "")
                  + (f" - {left} not made: the pads have {pads.MAX_BANKS} banks at most" if left else ""),
                  "warn" if left else "info")


def _try(app):
    """The selected pad's clip played as the pad would (a one shot to Out, a loop round), or stopped."""
    from native import vj
    s, t = _clip(app)
    if t is None:
        return
    owner = ("try", s["id"])
    if vj_clips.held(app, owner):
        vj_clips.stop(app, owner)
        return
    vj_clips.play(app, t, owner)
    if not vj.on(app) and not getattr(app, "_vj_open", False):
        app.gp.status("the clip plays on the VJ: turn it on (On air) to see it", "info")


# --- each frame -----------------------------------------------------------------------------------------------
def keep_try(app, editing):
    """Each frame (pads_ui.poll, the window shown or not): a clip the editor's Play started let go once its pad is
    no longer the one edited - another picked, Edit left, the window closed, the pad gone."""
    s, t = _clip(app) if editing else (None, None)
    vj_clips.stop_tries(app, keep=s["id"] if t is not None else None)


def poll(app):
    """While the CLIP rows show: the strip drawn when it changes (its frames come in, it plays), In and Out dragged."""
    s, t = _clip(app)
    if t is None or not dpg.does_item_exist(STRIP) or not dpg.is_item_shown(ROW):
        app._clip_drag = None
        return
    if t["kind"] == "pad_cam":
        dpg.configure_item("pads_clip_play", label="Stop" if vj_clips.held(app, ("try", s["id"])) else "Play")
        return
    from native import video
    dur = video.duration_of(_path(app, t), wait=False) if t.get("file") else None
    mx, _ = dpg.get_mouse_pos(local=False)
    x0 = dpg.get_item_rect_min(STRIP)[0]
    w = _w()
    drag = getattr(app, "_clip_drag", None)
    down = dpg.is_mouse_button_down(dpg.mvMouseButton_Left)
