def name_of(source, fallback):
    """The look's name: a "// NAME: ..." line in the shader, else the file's."""
    for line in source.splitlines()[:40]:
        s = line.strip()
        if s.startswith("//") and "NAME:" in s:
            n = s.split("NAME:", 1)[1].strip()
            if n:
                return n
    return fallback


_MARK = re.compile(r"^\s*//@\s*(common|image|buffer\s+([A-Da-d]))\s*$", re.I)
_CHAN = re.compile(r"^\s*//@\s*iChannel([0-3])\s*[=:]\s*([A-Za-z]+)\s*$", re.I)


def passes(src):
    """The shader's passes, in the order they run: [(name, code, {channel: what})] - the buffers A..D it has, then
    the image (the whole file when it names none) - and the Common code, put before each. Channels a pass names,
    else those named before the first pass, else the defaults."""
    common, before, parts = [], {}, {}
    cur, lines, chans = None, [], {}

    def close():
        if cur == "common":
            common.extend(lines)
        elif cur is not None:
            parts[cur] = ("\n".join(lines), dict(chans))
    for line in src.splitlines():
        m = _MARK.match(line)
        c = _CHAN.match(line)
        if m:
            close()
            cur = "common" if m.group(1).lower() == "common" else ("image" if m.group(1).lower() == "image" else m.group(2).upper())
            lines, chans = [], {}
            continue
        if c:
            what = c.group(2)
            what = what.upper() if what.upper() in BUFFERS else what.lower()
            if what not in CHANNELS:
                raise ValueError(f"//@ iChannel{c.group(1)} = {c.group(2)}: a channel is one of {', '.join(CHANNELS)}")
            (chans if cur is not None else before)[int(c.group(1))] = what
            continue
        lines.append(line)
    if cur is None:                                               # one pass: the file is the image
        parts["image"] = ("\n".join(lines), {})
    else:
        close()
    if "image" not in parts:
        raise ValueError("it has passes but no  //@ image")
    out = []
    for name in list(BUFFERS) + ["image"]:
        if name in parts:
            code, ch = parts[name]
            full = {k: ch.get(k, before.get(k, DEFAULT_CHANNELS[k])) for k in range(4)}
            out.append((name, ("\n".join(common) + "\n" if common else "") + code, full))
    return out


def channels_of(src):
    """The image pass's channels as the file names them (what a deck's choice falls back to)."""
    try:
        return [passes(src)[-1][2][k] for k in range(4)]
    except Exception:
        return list(DEFAULT_CHANNELS)


class _Jobs:
    """The GL thread's jobs, one a key: a key asked for again before its job is taken has the newer job in its place
    (a deck's frame the card has not got to yet is replaced by the next, never queued behind it)."""

    def __init__(self):
        self.cond = threading.Condition()
        self.jobs = {}               # key -> job, in the order first asked for

    def put(self, key, job):
        with self.cond:
            self.jobs[key] = job
            self.cond.notify()

    def get(self):
        with self.cond:
            while not self.jobs:
                self.cond.wait()
            return self.jobs.pop(next(iter(self.jobs)))


HUNG = 5.0                          # seconds on one job: the graphics card (or a shader) is taken as stuck


class _GL:
    """The thread that owns the OpenGL context: programs built once a source, frames drawn on request."""

    def __init__(self):
        self.q = _Jobs()
        self.ready = threading.Event()
        self.error = ""
        self.results = {}            # key -> (image or None, error)
        self.lock = threading.Condition()    # the results' guard, told whenever one is put
        self.waiting = set()         # run_frag's jobs still waited for (one given up on: its result dropped)
        self.busy_since = None       # when the job being drawn was taken (None: idle)
        self.seq = 0
        self.t = threading.Thread(target=self._run, daemon=True, name="vj-glsl")
        self.t.start()

    def stuck(self):
        """How long the thread has been on its job, when that is longer than HUNG (else 0)."""
        b = self.busy_since
        d = 0.0 if b is None else time.perf_counter() - b
        return d if d > HUNG else 0.0

    def _run(self):
        try:
            import moderngl
            self.ctx = moderngl.create_standalone_context(require=330)
        except ImportError:
            self.error = "shaders need moderngl:  pip install moderngl"
            self.ready.set()
            return
        except Exception as e:
            self.error = f"no OpenGL 3.3 for shaders here: {e}"
            self.ready.set()
            return
        self.ready.set()
        self.progs = {}              # pass source -> (program, vao) or error
        self.fbos = {}               # (w, h) -> framebuffer of the picture
        self.tex = {}                # name -> texture (video, sound, a caller's own shader's inputs)
        self.static = {}             # name -> texture uploaded once (MilkDrop's noise: the same for every preset)
        self.bufs = {}               # (key, buffer) -> [[texture, framebuffer] x 2, which is the last]
        self.pics = {}               # path -> (mtime, texture)
        quad = np.array([-1, -1, 3, -1, -1, 3], np.float32)          # one triangle over the whole frame
        self.vbo = self.ctx.buffer(quad.tobytes())
        rng = np.random.default_rng(1234)
        self.noise = self.ctx.texture((NOISE_N, NOISE_N), 4, rng.integers(0, 256, (NOISE_N, NOISE_N, 4), dtype=np.uint8).tobytes())
        self.noise.repeat_x = self.noise.repeat_y = True
        self.black = self.ctx.texture((1, 1), 4, bytes(4))
        self.cube = self.ctx.texture_cube((CUBE_N, CUBE_N), 3, sky_cube().tobytes())
        self.font = None                                          # made the first time a shader asks for it
        while True:
            job = self.q.get()
            key = job[0]
            self.busy_since = time.perf_counter()
            try:
                img = self._frag(*job[1:]) if _is_frag(key) else self._draw(*job)
                err = ""
            except Exception as e:
                img, err = None, str(e)
            self.busy_since = None
            with self.lock:
                if _is_frag(key) and key not in self.waiting:    # its caller gave up on it
                    continue
                self.results.pop(key, None)
                self.results[key] = (img, err)
                self.lock.notify_all()
            if _is_frag(key):
                continue
            with self.lock:
                while len(self.results) > 32:                     # looks long since changed: their last frames let go
                    gone = next(iter(self.results))
                    self.results.pop(gone)
                    for bk in [b for b in self.bufs if b[0] == gone]:
                        for t, f in self.bufs.pop(bk)[0]:
                            f.release(); t.release()

    def _compiled(self, src, final, frag=False):
        """A fragment shader's program and its triangle, built once a source (past 48, the least lately used let
        go), or the compiler's message raised."""
        p = self.progs.pop(src, None)
        if p is None:
            try:
                prog = self.ctx.program(vertex_shader=VERTEX, fragment_shader=src)
                p = (prog, self.ctx.vertex_array(prog, [(self.vbo, "2f", "vj_pos")]))
            except Exception as e:
                p = _compile_error(str(e), final)
                if frag:
                    p = p.replace("line ", "line ~")              # the lines are the translation's, near the preset's
            while len(self.progs) >= 48:
                old = self.progs.pop(next(iter(self.progs)))
                if not isinstance(old, str):
                    old[1].release()
                    old[0].release()
        self.progs[src] = p                                       # the latest used last
        if isinstance(p, str):
            raise RuntimeError(p)
        return p

    def _program(self, code, final, cubes=()):
        head = HEADER
        for k in cubes:                                          # a cubemap channel: read with a direction
            head = head.replace(f"uniform sampler2D iChannel{k};", f"uniform samplerCube iChannel{k};")
        return self._compiled(head + final + _webgl(code) + FOOTER, final)

    def _texture(self, name, w, h, comps, data):
        t = self.tex.get(name)
        if t is None or t.size != (w, h) or t.components != comps:
            if t is not None:
                t.release()
            t = self.ctx.texture((w, h), comps)
            t.repeat_x = t.repeat_y = False
            self.tex[name] = t
        t.write(data)
        return t

    def _picture(self, path):
        if not path:
            return None
        import os
        try:
            mt = os.path.getmtime(path)
        except OSError:
            return None
        got = self.pics.get(path)
        if got is None or got[0] != mt:
            from PIL import Image
            im = Image.open(path).convert("RGBA").transpose(Image.FLIP_TOP_BOTTOM)
            t = self.ctx.texture(im.size, 4, im.tobytes())
            t.repeat_x = t.repeat_y = True
            if got:
                got[1].release()
            got = self.pics[path] = (mt, t)
        return got[1]

    def _buffer(self, key, name, w, h):
        b = self.bufs.get((key, name))
        if b is None or b[0][0][0].size != (w, h):
            pair = []
            for _ in range(2):
                t = self.ctx.texture((w, h), 4, dtype="f2")
                t.repeat_x = t.repeat_y = False
                f = self.ctx.framebuffer(color_attachments=[t])
                f.clear(0.0, 0.0, 0.0, 0.0)
                pair.append((t, f))
            b = self.bufs[(key, name)] = [pair, 0]
        return b

    def _upload(self, store, tkey, a, write):
        """The texture `tkey` in `store` for the array `a` - made, or remade when its shape changed (the old let go) -
        with `a` written into it when `write`, or when just made."""
        if a.ndim == 4:                                              # a volume (MilkDrop's noisevol)
            size, comps, dt = tuple(a.shape[:3]), a.shape[3], "f1"
        else:
            size, comps = (a.shape[1], a.shape[0]), (1 if a.ndim == 2 else a.shape[2])
            dt = "f1" if a.dtype == np.uint8 else "f4"
        t = store.get(tkey)
        if t is None or tuple(t.size) != size or t.components != comps or t.dtype != dt:
            if t is not None:
                t.release()
            if a.ndim == 4:
                t = self.ctx.texture3d(size, comps, dtype=dt)
                t.repeat_z = True
            else:
                t = self.ctx.texture(size, comps, dtype=dt)
            t.repeat_x = t.repeat_y = True
            store[tkey] = t
            write = True
        if write:
            t.write(np.ascontiguousarray(a, np.uint8 if dt == "f1" else np.float32).tobytes())
        return t

    def _frag(self, src, w, h, uni, textures, static):
        """A whole fragment shader of a caller's own (MilkDrop 2's, milk_md2.py): its uniforms set, its textures -
        {name: (h, w, c) float array, or (n, n, n, 4) uint8 for a 3-D one} - bound, drawn at w x h, the picture back.
        `textures` are written each time, one texture a name whoever's shader it is (the thread draws one at a
        time); `static` ones - the same every time and for every caller - once."""
        prog, vao = self._compiled(src, "", frag=True)
        unit = 0
        for name, arr in list(textures.items()) + list(static.items()):
            if name not in prog:
                continue
            if name in static:
                t = self._upload(self.static, name, arr, False)
            else:
                t = self._upload(self.tex, f"frag:{name}", arr, True)
            t.use(unit)
            prog[name].value = unit
            unit += 1
        for k, val in uni.items():
            if k in prog:
                try:
                    if isinstance(val, list):                   # an array (MilkDrop's turning matrices): its kept length
                        _set_array(prog[k], val)
                    else:
                        prog[k].value = val
                except Exception:
                    pass
        fbo = self.fbos.get(("frag", w, h))
        if fbo is None:
            fbo = self.fbos[("frag", w, h)] = self.ctx.simple_framebuffer((w, h), components=4)
        fbo.use()
        fbo.clear(0.0, 0.0, 0.0, 1.0)
        vao.render()
        data = fbo.read(components=3)
        return np.frombuffer(data, np.uint8).reshape(h, w, 3).astype(np.float32) / 255.0   # row 0 the bottom of GL's

    def _draw(self, key, src, w, h, uni, video, audio, picture, chosen):
        plan = passes(src)
        if video is not None:
            v = np.ascontiguousarray(np.flipud(video))                # GL's rows run upward
            tv = self._texture("video", v.shape[1], v.shape[0], 3, v.tobytes())
        else:
            tv = self.black
        ta = self._texture("audio", AUDIO_W, 2, 1, np.ascontiguousarray(audio).tobytes())
        tp = self._picture(picture) or self.black
        out = None
        for name, code, chans in plan:
            image = name == "image"
            if image and chosen:                                  # the deck's own choice over the file's
                chans = {k: (chosen[k] or chans[k]) for k in range(4)}
            prog, vao = self._program(code, FINAL_IMAGE if image else FINAL_BUFFER,
                                      tuple(k for k in range(4) if chans[k] == "cube"))
            res = []
            for unit in range(4):
                what = chans[unit]
                if what in BUFFERS:
                    b = self._buffer(key, what, w, h)
                    t = b[0][b[1]][0]                              # its last: this frame's if drawn already, else the one before
                else:
                    if what == "font" and self.font is None:
                        a = font_atlas()
                        self.font = self.ctx.texture((a.shape[1], a.shape[0]), 4, np.ascontiguousarray(a).tobytes())
                        self.font.build_mipmaps()
                    if what.startswith("image:"):                 # the deck's picture for this channel
                        t = self._picture(what[6:]) or self.noise
                    else:
                        t = {"video": tv, "sound": ta, "noise": self.noise, "picture": tp, "cube": self.cube,
                             "font": self.font, "image": self.noise}.get(what, self.black)
                t.use(unit)
                res.append((float(t.size[0]), float(t.size[1]), 1.0))
                if f"iChannel{unit}" in prog:
                    prog[f"iChannel{unit}"].value = unit
            for k, val in uni.items():
                if k in prog:
                    prog[k].value = val
            if "iChannelResolution" in prog:
                _set_array(prog["iChannelResolution"], res)
            if "iChannelTime" in prog:
                _set_array(prog["iChannelTime"], [float(uni.get("iTime", 0.0))] * 4)
            if "iSampleRate" in prog:
                prog["iSampleRate"].value = 44100.0
            if image:
                fbo = self.fbos.get((w, h))
                if fbo is None:
                    fbo = self.fbos[(w, h)] = self.ctx.simple_framebuffer((w, h), components=4)
                fbo.use()
                fbo.clear(0.0, 0.0, 0.0, 1.0)
                vao.render()
                data = fbo.read(components=3)
                out = np.flipud(np.frombuffer(data, np.uint8).reshape(h, w, 3)).astype(np.float32) / 255.0
            else:
                b = self._buffer(key, name, w, h)
                nxt = 1 - b[1]
                b[0][nxt][1].use()
                vao.render()
                b[1] = nxt                                          # what it drew is its last now
        return out


CUBE_N = 64


def sky_cube(n=CUBE_N):
    """A cubemap's six faces (+x, -x, +y, -y, +z, -z), n x n RGB bytes each: a sky - deep blue overhead, pale at the
    horizon, a dark ground below - with a little noise, so a reflection has something to show."""
    k = (np.arange(n) + 0.5) / n * 2 - 1
    a, b = np.meshgrid(k, k)
    one = np.ones_like(a)
    faces = [(one, -b, -a), (-one, -b, a), (a, one, b), (a, -one, -b), (a, -b, one), (-a, -b, -one)]
    rng = np.random.default_rng(5)
    out = []
    for x, y, z in faces:
        d = np.stack([x, y, z], -1)
        d /= np.linalg.norm(d, axis=-1, keepdims=True)
        up = d[..., 1:2]
        sky = np.array([0.18, 0.35, 0.75]) * np.clip(up, 0, 1) + np.array([0.85, 0.82, 0.75]) * (1 - np.abs(up)) ** 6
        ground = np.array([0.12, 0.1, 0.08]) * np.clip(-up, 0, 1) ** 0.5
        c = np.clip(sky + ground + rng.normal(0, 0.02, d.shape), 0, 1)
        out.append((c * 255).astype(np.uint8))
    return np.stack(out)


FONT_CELL = 64


def font_atlas(cell=FONT_CELL):
    """A font atlas as Shadertoy's "Font 1" lays its characters out - 16 x 16 cells, code c at column c % 16 and row
    c // 16 from the top - each printable ASCII letter white in r, g and b, and in a a distance field (0.5 at the
    letter's edge, lower inside, higher outside). RGBA bytes, (16 * cell)^2, its first row GL's bottom (as the
    other textures go up)."""
    from PIL import Image, ImageDraw, ImageFilter, ImageFont
    n = 16 * cell
    mask = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(mask)
    font = None
    for name in ("consolab.ttf", "DejaVuSansMono-Bold.ttf", "Menlo.ttc", "LiberationMono-Bold.ttf"):
        try:
            font = ImageFont.truetype(name, int(cell * 0.78))
            break
        except OSError:
            continue
    if font is None:
        font = ImageFont.load_default()
    for c in range(32, 127):
        x, y = (c % 16) * cell, (c // 16) * cell
        l, t, r, b = d.textbbox((0, 0), chr(c), font=font)
        d.text((x + (cell - (r - l)) / 2 - l, y + (cell - (b - t)) / 2 - t), chr(c), fill=255, font=font)
    m = np.asarray(mask, np.float32) / 255.0
    soft = np.asarray(mask.filter(ImageFilter.GaussianBlur(cell / 12)), np.float32) / 255.0
    dist = np.clip(1.0 - soft, 0, 1)                             # 1 - a blur of it: 0.5 about at the edge
    rgba = np.dstack([m, m, m, dist])
    return (np.flipud(rgba) * 255 + 0.5).astype(np.uint8)


# Shadertoy's inputs as channels here (the textures it ships are not here: noise stands in, its font is drawn)
_ST_INPUT = {"texture": "noise", "keyboard": "none", "webcam": "video", "video": "video", "music": "sound",
             "musicstream": "sound", "mic": "sound", "cubemap": "cube", "volume": "none"}
_ST_FONT = "08b42b43ae9d3c0605da11d0eac86618ea888e62cdd9518ee8b9097488b31560"    # its "Font 1" texture's file
_ST_PASS = {"Buffer A": "A", "Buffer B": "B", "Buffer C": "C", "Buffer D": "D"}


def from_shadertoy(data):
    """A shader from shadertoy.com's JSON - the API's {"Shader": {...}}, or its inside - as a studio .glsl:
    (source, name, [what of it is not here]). Its Common, Buffer A..D and Image passes as //@ sections, each pass's
    inputs as its channels (a buffer as its letter, a cubemap as the sky, its font as the font, another texture as
    noise, music or the microphone as the sound, a webcam or video as the deck's video); a keyboard, a 3-D
    texture, a cubemap pass or a sound pass are left out, and said. Its name, author and page are kept at the top -
    a shader on shadertoy.com is its author's (CC BY-NC-SA 3.0 unless it says otherwise)."""
    s = data.get("Shader", data) if isinstance(data, dict) else None
    if not isinstance(s, dict) or not isinstance(s.get("renderpass"), list):
        raise ValueError("not a Shadertoy shader (no renderpass)")
    info = s.get("info") or {}
    rp = s["renderpass"]
    letter = {}
    for p in rp:
        if p.get("type") == "buffer":
            for o in p.get("outputs") or []:
                letter[str(o.get("id"))] = _ST_PASS.get(p.get("name"), "A")
    lost, notes = [], []
    sid = info.get("id", "")
    name = info.get("name") or sid or "shadertoy"
    lines = [f"// NAME: {name}", f"// {name}" + (f" by {info['username']}" if info.get("username") else ""),
             f"// https://www.shadertoy.com/view/{sid}" if sid else "// from shadertoy.com",
             "// imported from its JSON - the author's (CC BY-NC-SA 3.0 unless the code says otherwise)"]
    lines += [f"// {line}" for line in (info.get("description") or "").splitlines()[:6] if line.strip()]
    for p in rp:
        if p.get("type") == "common":
            lines += ["//@ common", p.get("code", "")]
    order = [p for p in rp if p.get("type") == "buffer"] + [p for p in rp if p.get("type") == "image"]
    if not any(p.get("type") == "image" for p in rp):
        raise ValueError("the shader has no Image pass")
    for p in order:
        image = p.get("type") == "image"
        lines.append("//@ image" if image else f"//@ buffer {_ST_PASS.get(p.get('name'), 'A')}")
        chans = {}
        for i in p.get("inputs") or []:
            kind = i.get("ctype") or i.get("type")
            if kind == "buffer":
                what = letter.get(str(i.get("id")), "none")
            elif kind == "texture" and _ST_FONT in str(i.get("src") or i.get("filepath") or ""):
                what = "font"
            elif kind == "texture":                                # a photo or pattern of the site's: one of yours
                what = "image"
                notes.append(f"//   {p.get('name', 'a pass')}'s iChannel{i.get('channel')} was a texture on Shadertoy"
                             " - choose a picture of your own for it beside the deck's channels (noise until then)")
            else:
                what = _ST_INPUT.get(kind, "none")
                if kind in ("keyboard", "volume") or kind not in _ST_INPUT:
                    lost.append(f"{p.get('name', 'a pass')}'s {kind} (iChannel{i.get('channel')})")
            chans[int(i.get("channel", 0))] = what
        lines += [f"//@ iChannel{k} = {chans.get(k, 'none')}" for k in range(4)]
        lines.append(p.get("code", ""))
    for p in rp:
        if p.get("type") in ("cubemap", "sound"):
            lost.append(f"its {p.get('name') or p.get('type')} pass")
    if notes:
        lines[4:4] = ["// textures:"] + notes
    return "\n".join(lines) + "\n", name, lost


_FN_MACRO = re.compile(r"^(\s*#\s*define\s+)([A-Za-z_]\w*)\(", re.M)


def _webgl(code):
    """A Shadertoy pass made to compile as it does in WebGL, where the desktop's GLSL differs - its lines kept, so
    the compiler's line numbers stay the shader's:
    - noise1..noise4 are desktop GLSL's (long dead) built-ins: a shader's own `noise2` clashed with them;
    - a function-like macro's name used alone (`#define f(x) ...` and `float f = ...`) the desktop's preprocessor
      would not take: the macro and its calls renamed, so the name alone is the variable again (only where it is a
      variable - declared, assigned or a swizzle: a macro's name handed bare to another macro, tri(p, Fa), is the
      macro's own and kept)."""
    code = re.sub(r"\bnoise([1-4])\b", r"vj_noise\1", code)
    body = re.sub(r"^\s*#.*$", "", code, flags=re.M)

    def clashes(n):
        n = re.escape(n)
        return re.search(rf"\.\s*{n}\b(?!\s*\()|\b(?:float|int|bool|[iub]?vec[234]|mat[234])\s+{n}\b"
                         rf"|\b{n}\s*[-+*/]?=(?!=)", body) is not None
    names = set(m.group(2) for m in _FN_MACRO.finditer(code) if clashes(m.group(2)))
    if names:
        code = _FN_MACRO.sub(lambda m: f"{m.group(1)}vjm_{m.group(2)}(" if m.group(2) in names else m.group(0), code)
        code = re.sub(r"\b(" + "|".join(sorted(map(re.escape, names), key=len, reverse=True)) + r")(\s*\()",
                      lambda m: f"vjm_{m.group(1)}{m.group(2)}", code)
    return code


def _set_array(uniform, items):
    """An array uniform set to `items`, as many of them as the program keeps: a driver may cut an array down to the
    elements the shader reads (macOS does - a shader reading iChannelTime[0] alone has a float there, and four
    refused it)."""
    n = max(1, int(getattr(uniform, "array_length", len(items)) or 1))
    uniform.value = items[0] if n == 1 else list(items[:n])


def _compile_error(msg, final=""):
    """The compiler's message, its line numbers made the shader's own (the header the studio adds left out)."""
    skip = HEADER_LINES + final.count("\n")
    out = []
    for line in msg.splitlines():
        line = re.sub(r"(\d+)\((\d+)\)", lambda m: f"line {max(1, int(m.group(2)) - skip)}", line)
        line = re.sub(r"0:(\d+)", lambda m: f"line {max(1, int(m.group(1)) - skip)}", line)
        if line.strip() and "GLSL Compiler failed" not in line and "fragment_shader" not in line and "===" not in line:
            out.append(line.strip())
    return "the shader did not compile: " + ("; ".join(out[:3]) or msg.strip()[:200])


_GLOBAL = None


def _gl():
    global _GLOBAL
    if _GLOBAL is None:
        _GLOBAL = _GL()
        _GLOBAL.ready.wait(10.0)
    return _GLOBAL


def available():
    g = _gl()
