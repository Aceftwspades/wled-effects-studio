import time

import numpy as np

HEADER = """#version 330
uniform vec3 iResolution;
uniform float iTime;
uniform float iTimeDelta;
uniform int iFrame;
uniform vec4 iMouse;
uniform vec4 iDate;
uniform sampler2D iChannel0;
uniform sampler2D iChannel1;
uniform sampler2D iChannel2;
uniform sampler2D iChannel3;
uniform vec3 iChannelResolution[4];
uniform float iBeat;
uniform float iBass;
uniform float iMid;
uniform float iTreble;
uniform float iLevel;
uniform float iAmount;
out vec4 vj_fragColor;
"""
FOOTER = """
void main() {
    vec4 c = vec4(0.0, 0.0, 0.0, 1.0);
    mainImage(c, gl_FragCoord.xy);
    vj_fragColor = vj_final(c);
}
"""
FINAL_IMAGE = "vec4 vj_final(vec4 c) { return vec4(clamp(c.rgb, 0.0, 1.0), 1.0); }\n"
FINAL_BUFFER = "vec4 vj_final(vec4 c) { return c; }\n"            # a buffer keeps what it is given, out of 0..1 too
VERTEX = """#version 330
in vec2 vj_pos;
void main() { gl_Position = vec4(vj_pos, 0.0, 1.0); }
"""
HEADER_LINES = HEADER.count("\n")
AUDIO_W = 512
NOISE_N = 256
CHANNELS = ("video", "sound", "noise", "picture", "A", "B", "C", "D", "none")
DEFAULT_CHANNELS = ("video", "sound", "noise", "none")
BUFFERS = ("A", "B", "C", "D")

TEMPLATE = """// A Shadertoy shader for the VJ frame: paste one from shadertoy.com over this (its Image tab), save,
// and it runs on its deck. Its channels: iChannel0 the deck's video, iChannel1 the sound (Shadertoy's
// audio input), iChannel2 a noise texture, iChannel3 nothing - a line like  //@ iChannel3 = picture
// changes one (video, sound, noise, picture, A..D, none). The studio's own: iBeat, iBass, iMid, iTreble,
// iLevel, iAmount (0..1).
// Several passes (Buffer A..D, Common): each after a line  //@ buffer A  (//@ common, //@ image), and in
// a pass  //@ iChannel0 = A  reads buffer A. Keyboard input will not work.
// NAME: {name}

void mainImage(out vec4 fragColor, in vec2 fragCoord)
{
    vec2 uv = (fragCoord - 0.5 * iResolution.xy) / iResolution.y;
    float r = length(uv), a = atan(uv.y, uv.x);
    float rings = sin(12.0 * r - iTime * 3.0 - iBass * 6.0);
    vec3 col = 0.5 + 0.5 * cos(iTime + a * 3.0 + vec3(0.0, 2.0, 4.0));
    fragColor = vec4(col * smoothstep(0.0, 0.2, rings) * (0.6 + 0.4 * iBeat), 1.0);
}
"""


def name_of(source, fallback):
    """The look's name: a "// NAME: ..." line in the shader, else the file's."""
    for line in source.splitlines()[:40]:
        s = line.strip()
        if s.startswith("//") and "NAME:" in s:
            n = s.split("NAME:", 1)[1].strip()
            if n:
                return n
    return fallback


_MARK = re.compile(r"^\s*//@\s*(common|image|buffer\s+([A-Da-d]))\s*$", re.I)
_CHAN = re.compile(r"^\s*//@\s*iChannel([0-3])\s*[=:]\s*([A-Za-z]+)\s*$", re.I)


def passes(src):
    """The shader's passes, in the order they run: [(name, code, {channel: what})] - the buffers A..D it has, then
    the image (the whole file when it names none) - and the Common code, put before each. Channels a pass names,
    else those named before the first pass, else the defaults."""
    common, before, parts = [], {}, {}
    cur, lines, chans = None, [], {}

    def close():
        if cur == "common":
            common.extend(lines)
        elif cur is not None:
            parts[cur] = ("\n".join(lines), dict(chans))
    for line in src.splitlines():
        m = _MARK.match(line)
        c = _CHAN.match(line)
        if m:
            close()
            cur = "common" if m.group(1).lower() == "common" else ("image" if m.group(1).lower() == "image" else m.group(2).upper())
            lines, chans = [], {}
            continue
        if c:
            what = c.group(2)
            what = what.upper() if what.upper() in BUFFERS else what.lower()
            if what not in CHANNELS:
                raise ValueError(f"//@ iChannel{c.group(1)} = {c.group(2)}: a channel is one of {', '.join(CHANNELS)}")
            (chans if cur is not None else before)[int(c.group(1))] = what
            continue
        lines.append(line)
    if cur is None:                                               # one pass: the file is the image
        parts["image"] = ("\n".join(lines), {})
    else:
        close()
    if "image" not in parts:
        raise ValueError("it has passes but no  //@ image")
    out = []
    for name in list(BUFFERS) + ["image"]:
        if name in parts:
            code, ch = parts[name]
            full = {k: ch.get(k, before.get(k, DEFAULT_CHANNELS[k])) for k in range(4)}
            out.append((name, ("\n".join(common) + "\n" if common else "") + code, full))
    return out


def channels_of(src):
    """The image pass's channels as the file names them (what a deck's choice falls back to)."""
    try:
        return [passes(src)[-1][2][k] for k in range(4)]
    except Exception:
        return list(DEFAULT_CHANNELS)


class _GL:
    """The thread that owns the OpenGL context: programs built once a source, frames drawn on request."""

    def __init__(self):
        self.q = queue.Queue(maxsize=8)
        self.ready = threading.Event()
        self.error = ""
        self.results = {}            # key -> (image or None, error)
        self.lock = threading.Lock()
        self.frag_done = threading.Event()   # a caller's own shader drawn (run_frag waits on it)
        self.t = threading.Thread(target=self._run, daemon=True, name="vj-glsl")
        self.t.start()

    def _run(self):
        try:
            import moderngl
            self.ctx = moderngl.create_standalone_context(require=330)
        except ImportError:
            self.error = "shaders need moderngl:  pip install moderngl"
            self.ready.set()
            return
        except Exception as e:
            self.error = f"no OpenGL 3.3 for shaders here: {e}"
            self.ready.set()
            return
        self.ready.set()
        self.progs = {}              # pass source -> (program, vao) or error
        self.fbos = {}               # (w, h) -> framebuffer of the picture
        self.tex = {}                # name -> texture (video, sound, a picture)
        self.bufs = {}               # (key, buffer) -> [[texture, framebuffer] x 2, which is the last]
        self.pics = {}               # path -> (mtime, texture)
        quad = np.array([-1, -1, 3, -1, -1, 3], np.float32)          # one triangle over the whole frame
        self.vbo = self.ctx.buffer(quad.tobytes())
        rng = np.random.default_rng(1234)
        self.noise = self.ctx.texture((NOISE_N, NOISE_N), 4, rng.integers(0, 256, (NOISE_N, NOISE_N, 4), dtype=np.uint8).tobytes())
        self.noise.repeat_x = self.noise.repeat_y = True
        self.black = self.ctx.texture((1, 1), 4, bytes(4))
        while True:
            job = self.q.get()
            if job is None:
                return
            key = job[0]
            try:
                img = self._frag(*job[1:]) if key == FRAG else self._draw(*job)
                err = ""
            except Exception as e:
                img, err = None, str(e)
            with self.lock:
                self.results.pop(key, None)
                self.results[key] = (img, err)
            if key == FRAG:
                self.frag_done.set()
                continue
            with self.lock:
                while len(self.results) > 32:                     # looks long since changed: their last frames let go
                    gone = next(iter(self.results))
                    self.results.pop(gone)
                    for bk in [b for b in self.bufs if b[0] == gone]:
                        for t, f in self.bufs.pop(bk)[0]:
                            f.release(); t.release()

    def _program(self, code, final):
        src = HEADER + final + code + FOOTER
        p = self.progs.get(src)
        if p is None:
            try:
                prog = self.ctx.program(vertex_shader=VERTEX, fragment_shader=src)
                vao = self.ctx.vertex_array(prog, [(self.vbo, "2f", "vj_pos")])
                p = (prog, vao)
            except Exception as e:
                p = _compile_error(str(e), final)
            if len(self.progs) > 48:
                self.progs.clear()
            self.progs[src] = p
        if isinstance(p, str):
            raise RuntimeError(p)
        return p

    def _texture(self, name, w, h, comps, data):
        t = self.tex.get(name)
        if t is None or t.size != (w, h) or t.components != comps:
            t = self.ctx.texture((w, h), comps)
            t.repeat_x = t.repeat_y = False
            self.tex[name] = t
        t.write(data)
        return t

    def _picture(self, path):
        if not path:
            return None
        import os
        try:
            mt = os.path.getmtime(path)
        except OSError:
            return None
        got = self.pics.get(path)
        if got is None or got[0] != mt:
            from PIL import Image
            im = Image.open(path).convert("RGBA").transpose(Image.FLIP_TOP_BOTTOM)
            t = self.ctx.texture(im.size, 4, im.tobytes())
            t.repeat_x = t.repeat_y = True
            if got:
                got[1].release()
            got = self.pics[path] = (mt, t)
        return got[1]

    def _buffer(self, key, name, w, h):
        b = self.bufs.get((key, name))
        if b is None or b[0][0][0].size != (w, h):
            pair = []
            for _ in range(2):
                t = self.ctx.texture((w, h), 4, dtype="f2")
                t.repeat_x = t.repeat_y = False
                f = self.ctx.framebuffer(color_attachments=[t])
                f.clear(0.0, 0.0, 0.0, 0.0)
                pair.append((t, f))
            b = self.bufs[(key, name)] = [pair, 0]
        return b

    def _frag(self, rkey, src, w, h, uni, textures):
        """A whole fragment shader of a caller's own (MilkDrop 2's, milk_md2.py): its uniforms set, its textures -
        {name: (h, w, c) float array, or (n, n, n, 4) uint8 for a 3-D one} - bound, drawn at w x h, the picture back."""
        p = self.progs.get(src)
        if p is None:
            try:
                prog = self.ctx.program(vertex_shader=VERTEX, fragment_shader=src)
                p = (prog, self.ctx.vertex_array(prog, [(self.vbo, "2f", "vj_pos")]))
            except Exception as e:
                p = _compile_error(str(e), "")
                p = p.replace("line ", "line ~")                    # the lines are the translation's, near the preset's
            if len(self.progs) > 48:
                self.progs.clear()
            self.progs[src] = p
        if isinstance(p, str):
            raise RuntimeError(p)
        prog, vao = p
        unit = 0
        for name, arr in textures.items():
            if name not in prog:
                continue
            a = np.ascontiguousarray(arr)
            tkey = f"frag:{rkey}:{name}"
            if a.ndim == 4:                                          # a volume (MilkDrop's noisevol)
                t = self.tex.get(tkey)
                if t is None:
                    t = self.tex[tkey] = self.ctx.texture3d(a.shape[:3], a.shape[3], a.tobytes())
                    t.repeat_x = t.repeat_y = t.repeat_z = True
            else:
                hh, ww = a.shape[:2]
                comps = 1 if a.ndim == 2 else a.shape[2]
                dt = "f1" if a.dtype == np.uint8 else "f4"
                t = self.tex.get(tkey)
                if t is None or t.size != (ww, hh) or t.components != comps or t.dtype != dt:
                    t = self.tex[tkey] = self.ctx.texture((ww, hh), comps, dtype=dt)
                    t.repeat_x = t.repeat_y = True
                t.write(a.astype(np.uint8 if dt == "f1" else np.float32).tobytes())
            t.use(unit)
            prog[name].value = unit
            unit += 1
        for k, val in uni.items():
            if k in prog:
                try:
                    prog[k].value = val
                except Exception:
                    pass
        fbo = self.fbos.get(("frag", w, h))
        if fbo is None:
            fbo = self.fbos[("frag", w, h)] = self.ctx.simple_framebuffer((w, h), components=4)
        fbo.use()
        fbo.clear(0.0, 0.0, 0.0, 1.0)
        vao.render()
        data = fbo.read(components=3)
        return np.frombuffer(data, np.uint8).reshape(h, w, 3).astype(np.float32) / 255.0   # row 0 the bottom of GL's

    def _draw(self, key, src, w, h, uni, video, audio, picture, chosen):
        plan = passes(src)
        if video is not None:
            v = np.ascontiguousarray(np.flipud(video))                # GL's rows run upward
            tv = self._texture("video", v.shape[1], v.shape[0], 3, v.tobytes())
        else:
            tv = self.black
        ta = self._texture("audio", AUDIO_W, 2, 1, np.ascontiguousarray(audio).tobytes())
        tp = self._picture(picture) or self.black
        out = None
        for name, code, chans in plan:
            image = name == "image"
            prog, vao = self._program(code, FINAL_IMAGE if image else FINAL_BUFFER)
            if image and chosen:                                  # the deck's own choice over the file's
                chans = {k: (chosen[k] or chans[k]) for k in range(4)}
            res = []
            for unit in range(4):
                what = chans[unit]
                if what in BUFFERS:
                    b = self._buffer(key, what, w, h)
                    t = b[0][b[1]][0]                              # its last: this frame's if drawn already, else the one before
                else:
                    t = {"video": tv, "sound": ta, "noise": self.noise, "picture": tp}.get(what, self.black)
                t.use(unit)
                res.append((float(t.width), float(t.height), 1.0))
                if f"iChannel{unit}" in prog:
                    prog[f"iChannel{unit}"].value = unit
            for k, val in uni.items():
                if k in prog:
                    prog[k].value = val
            if "iChannelResolution" in prog:
                prog["iChannelResolution"].value = res
            if image:
                fbo = self.fbos.get((w, h))
                if fbo is None:
                    fbo = self.fbos[(w, h)] = self.ctx.simple_framebuffer((w, h), components=4)
                fbo.use()
                fbo.clear(0.0, 0.0, 0.0, 1.0)
                vao.render()
                data = fbo.read(components=3)
                out = np.flipud(np.frombuffer(data, np.uint8).reshape(h, w, 3)).astype(np.float32) / 255.0
            else:
                b = self._buffer(key, name, w, h)
                nxt = 1 - b[1]
                b[0][nxt][1].use()
                vao.render()
                b[1] = nxt                                          # what it drew is its last now
        return out


def _compile_error(msg, final=""):
    """The compiler's message, its line numbers made the shader's own (the header the studio adds left out)."""
    skip = HEADER_LINES + final.count("\n")
    out = []
    for line in msg.splitlines():
        line = re.sub(r"(\d+)\((\d+)\)", lambda m: f"line {max(1, int(m.group(2)) - skip)}", line)
        line = re.sub(r"0:(\d+)", lambda m: f"line {max(1, int(m.group(1)) - skip)}", line)
        if line.strip() and "GLSL Compiler failed" not in line and "fragment_shader" not in line and "===" not in line:
            out.append(line.strip())
    return "the shader did not compile: " + ("; ".join(out[:3]) or msg.strip()[:200])


_GLOBAL = None


def _gl():
    global _GLOBAL
    if _GLOBAL is None:
        _GLOBAL = _GL()
        _GLOBAL.ready.wait(10.0)
    return _GLOBAL


def available():
    g = _gl()
    return (not g.error), g.error


def audio_texture(bands, wave):
    """Shadertoy's audio input: 512 x 2 bytes, the spectrum (from the effects' 16 bands) over the wave."""
    f = np.interp(np.linspace(0, len(bands) - 1, AUDIO_W), np.arange(len(bands)), np.asarray(bands, np.float32))
    w = np.interp(np.linspace(0, len(wave) - 1, AUDIO_W), np.arange(len(wave)), np.asarray(wave, np.float32))
    out = np.empty((2, AUDIO_W), np.uint8)
    out[0] = np.clip(f * 255, 0, 255)
    out[1] = np.clip((w * 0.5 + 0.5) * 255, 0, 255)
    return out


def render(key, src, w, h, uni, video=None, audio=None, wait=False, picture="", channels=None):
    """This frame asked for (deck `key`) and the last one finished given: (image or None, error). `wait` blocks
    for this frame's own (a render's, the tests'). `channels`: the deck's choice for iChannel0..3 ("" the file's)."""
    g = _gl()
    if g.error:
        return None, g.error
    vid = None if video is None else (np.clip(video, 0, 1) * 255).astype(np.uint8)
    aud = audio if audio is not None else np.zeros((2, AUDIO_W), np.uint8)
    if wait:
        with g.lock:
            g.results.pop(key, None)
    try:
        g.q.put_nowait((key, src, int(w), int(h), dict(uni), vid, aud, picture or "",
                        list(channels) if channels else None))
    except queue.Full:
        pass                                                     # the card is behind: the frame before stands
    if wait:
        t0 = time.perf_counter()
        while time.perf_counter() - t0 < 5.0:
            with g.lock:
                if key in g.results:
                    return g.results[key]
            time.sleep(0.002)
        return None, "the shader took more than 5 s"
    with g.lock:
        return g.results.get(key, (None, ""))


FRAG = "__frag__"                   # the queue's key for a caller's own shader (run_frag)


def run_frag(rkey, src, w, h, uni, textures):
    """A whole fragment shader run now, waited for: (picture (h, w, 3) float - its first row GL's bottom - or None,
    error). For MilkDrop 2's warp and composite shaders (milk_md2.py)."""
    g = _gl()
    if g.error:
        return None, g.error
    with g.lock:
        g.results.pop(FRAG, None)
    g.frag_done.clear()
    g.q.put((FRAG, rkey, src, int(w), int(h), dict(uni), dict(textures)))
    if not g.frag_done.wait(5.0):
        return None, "the shader took more than 5 s"
    with g.lock:
        return g.results.pop(FRAG, (None, "the shader gave nothing back"))


def uniforms(ctx, frame):
    """The uniforms of a deck's frame, from its look ctx."""
    lt = time.localtime()
    return {"iResolution": (float(ctx.w), float(ctx.h), 1.0), "iTime": float(ctx.t), "iTimeDelta": float(ctx.dt),
            "iFrame": int(frame), "iMouse": (0.0, 0.0, 0.0, 0.0),
            "iDate": (float(lt.tm_year), float(lt.tm_mon - 1), float(lt.tm_mday),
                      float(lt.tm_hour * 3600 + lt.tm_min * 60 + lt.tm_sec)),
            "iBeat": float(ctx.beat), "iBass": float(ctx.bass), "iMid": float(ctx.mid), "iTreble": float(ctx.treb),
            "iLevel": float(ctx.level), "iAmount": float(ctx.amount)}


def look_draw(src, name):
    """A look's draw for a shader's source: its frame of a frame ago (dark until the first is back)."""
    passes(src)                                                  # a file whose passes cannot be read: said at once

    def draw(ctx, st):
        from native import clock
        st["n"] = st.get("n", 0) + 1
        bands = getattr(ctx, "bands", None)
        aud = audio_texture(bands if bands is not None else np.full(16, ctx.bass, np.float32), ctx.wave)
        key = st.setdefault("key", f"{name}-{id(st)}")
        deck = getattr(ctx, "deck", None) or {}
        # a video or an FSEQ being rendered (the clock held): this frame's own, not the one before
        img, err = render(key, src, ctx.w, ctx.h, uniforms(ctx, st["n"]), ctx.video, aud,
                          wait=bool(getattr(ctx, "wait", False)) or clock.held(),
                          picture=getattr(ctx, "image_path", "") or "", channels=deck.get("channels"))
        if err:
            raise RuntimeError(err)
        if img is None or img.shape[:2] != (ctx.h, ctx.w):
            return st.get("last", np.zeros((ctx.h, ctx.w, 3), np.float32))
        st["last"] = img
        return img
    return draw
