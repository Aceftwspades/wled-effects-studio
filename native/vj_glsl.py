"""Shadertoy shaders as the VJ's looks: a fragment shader written for
shadertoy.com - its mainImage(out vec4 fragColor, in vec2 fragCoord) -
pasted into a .glsl file in the project's looks/ folder and run as it is, on
the graphics card, at the deck's canvas size.

    ok, why = available()                       # whether there is OpenGL here (moderngl), and why not
    img, err = render(key, src, w, h, uniforms, video, audio, picture, channels)   # (h, w, 3) float 0..1

What a shader has, as on Shadertoy: iResolution, iTime, iTimeDelta, iFrame,
iMouse (still), iDate, iChannel0..3 and iChannelResolution. And the
studio's own: iBeat (a pulse on each beat), iBass, iMid, iTreble, iLevel and
iAmount (the deck's knob), all 0..1.

What its channels hold - Shadertoy's inputs - is chosen per channel:

    video     the deck's video (black without one)
    sound     the sound as Shadertoy's audio input: 512 x 2, the spectrum over the wave
    noise     a 256 x 256 RGBA noise texture (as Shadertoy's "RGBA Noise Medium"), repeating
    picture   the deck's picture file
    A..D      a buffer's last frame (one pass of a multi-pass shader)
    none      black

By default iChannel0 is the video, 1 the sound, 2 the noise and 3 none; a
shader says otherwise in its file (`//@ iChannel2 = picture`), and a deck can
choose again (the VJ frame's channels row).

Several passes (Shadertoy's Buffer A..D tabs, and Common) go in one file,
each after a line naming it:

    //@ common            code put before every pass
    //@ buffer A          a pass drawn into buffer A (kept from frame to frame, in float)
    //@ iChannel0 = A     in a pass: its channel 0 reads buffer A (its own: its last frame)
    //@ image             the pass that is the picture

The passes run in order - A, B, C, D, then the image - each reading the
buffers already drawn this frame, and its own last frame.

The shaders run on a thread of their own with an OpenGL context of its own
(moderngl's standalone one): the studio draws its windows with another, and a
context is the thread's that made it current - the two never meet. A frame
is asked for and the one finished before is taken, so a deck's shader is a
frame behind and the studio never waits on the graphics card (while a video
or an FSEQ renders, it waits: each frame its own). A deck asks for one frame
at a time: one asked for again before the card got to it is replaced, so a
slow card drops frames rather than falling behind. Without moderngl, or without
OpenGL 3.3, the .glsl looks say so and draw dark.
"""
