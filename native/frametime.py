"""Where a frame's time goes: milliseconds per named part, smoothed, for the stats popover.

    frametime.add("views", ms)                      # a top-level part of the frame, measured by the main loop
    with frametime.part("VJ deck A", under="sim"):  # a part inside one: timed from here to the end of the block
        ...
    frametime.rows()                                # [(name, ms, depth)], each top-level part then what is under it

The main loop measures its own parts (polls, the sim's step, the views, the interface); the engine, the VJ's
decks, MilkDrop and the thumbnails say what they took inside those. A part not heard from for a few seconds
drops off the list (a deck taken off air, the thumbnails done). Workers (the library's thumbnails) add from
their own thread: their time is beside the frame's, not in it, and their rows say so.
"""
# AI: below section was generated by an AI
import threading
import time
from contextlib import contextmanager

SMOOTH = 0.05                # each new measure's share of the average (the main loop's own figures smooth the same)
STALE_S = 3.0                # a part not measured for this long is dropped from the list
TOP = ("polls", "sim", "views", "interface")      # the main loop's parts, in the frame's order

_avg = {}                    # name -> [smoothed ms, parent or None, when last added (time.monotonic)]
_lock = threading.Lock()


def add(name, ms, under=None):
    """A measure of part `name` (milliseconds), inside part `under` (None: a part of the frame itself)."""
    now = time.monotonic()
    with _lock:
        e = _avg.get(name)
        if e is None or now - e[2] > STALE_S:
            _avg[name] = [float(ms), under, now]         # new, or back after a while: from this measure, not a fade-in
        else:
            e[0] += (float(ms) - e[0]) * SMOOTH
            e[1], e[2] = under, now


@contextmanager
def part(name, under="sim"):
    """The block's time added as part `name` inside `under`."""
    t0 = time.perf_counter()
    try:
        yield
    finally:
        add(name, (time.perf_counter() - t0) * 1000.0, under)


def rows(limit=12):
    """(name, ms, depth): the frame's parts in its order, each followed by what was measured inside it (the
    biggest first), then the rest (a worker's) - all with a measure in the last STALE_S seconds."""
    now = time.monotonic()
    with _lock:
        live = {k: (v[0], v[1]) for k, v in _avg.items() if now - v[2] <= STALE_S}
    out = []
    tops = [k for k in TOP if k in live] + sorted((k for k, (_, p) in live.items() if p is None and k not in TOP),
                                                  key=lambda k: -live[k][0])
    for t in tops:
        out.append((t, live[t][0], 0))
        out += [(k, ms, 1) for k, (ms, p) in sorted(live.items(), key=lambda kv: -kv[1][0]) if p == t]
    seen = {r[0] for r in out}
    out += [(k, ms, 1) for k, (ms, p) in sorted(live.items(), key=lambda kv: -kv[1][0]) if k not in seen]
    return out[:limit]


def clear():
    with _lock:
        _avg.clear()
