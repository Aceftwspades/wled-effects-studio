import datetime
import ipaddress
import json
import os

from native import paths


def available():
    try:
        import cryptography  # noqa: F401
        return True
    except ImportError:
        return False


def _dir():
    d = os.path.join(paths.HOME, "phone")
    os.makedirs(d, exist_ok=True)
    return d


def ensure(addresses=None):
    """The certificate and key files for these addresses (this machine's on the network, and the loopback's), made
    when there are none or the ones there do not name the addresses. None without cryptography."""
    if not available():
        return None
    from native import phone
    want = sorted({a for a in (addresses or [phone.lan_address()]) if a} | {"127.0.0.1"})
    d = _dir()
    cert, key, meta = os.path.join(d, "cert.pem"), os.path.join(d, "key.pem"), os.path.join(d, "cert.json")
    try:
        have = json.load(open(meta, encoding="utf-8")).get("addresses")
    except (OSError, ValueError):
        have = None
    if have == want and os.path.exists(cert) and os.path.exists(key):
        return cert, key
    _make(cert, key, want)
    with open(meta, "w", encoding="utf-8") as f:
        json.dump({"addresses": want}, f)
    return cert, key


def _make(cert_path, key_path, addresses):
    from cryptography import x509
    from cryptography.x509.oid import NameOID
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "WLED Effects Studio")])
    sans = [x509.DNSName("localhost")]
    for a in addresses:
        try:
            sans.append(x509.IPAddress(ipaddress.ip_address(a)))
        except ValueError:
            sans.append(x509.DNSName(a))
    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (x509.CertificateBuilder().subject_name(name).issuer_name(name).public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - datetime.timedelta(days=1))
            .not_valid_after(now + datetime.timedelta(days=3650))
            .add_extension(x509.SubjectAlternativeName(sans), critical=False)
            .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    # the key written for this user alone where the system allows it (it never leaves this machine)
    with open(key_path, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    try:
        os.chmod(key_path, 0o600)
    except OSError:
        pass
    with open(cert_path, "wb") as f:
        f.write(cert.public_bytes(serialization.Encoding.PEM))
