"""The phone remote's certificate: what lets it be served over HTTPS, which a
phone's browser asks of a page before it offers the camera (the phone camera
source, native/phone.py's /camera page). Self-signed - made here, once, and
kept in HOME/phone, so the phone is asked to trust it once (its browser shows
a warning to click through: "Advanced", then go on to the address), and
again only when this machine's address on the network changes.

    pair = ensure()            # (cert.pem, key.pem) paths, or None without the cryptography package

Needs the cryptography package (requirements.txt); without it the remote is
served over plain HTTP and the camera page says why it cannot open.
"""
