import hashlib
import json
import os
import re
import urllib.request

from native import paths, version

INDEX_MAX = 1 << 20              # the index: a megabyte is thousands of entries
BUNDLE_MAX = 2 << 20             # a bundle: the biggest graph here is under 100 KB
PREVIEW_MAX = 6 << 20            # a preview GIF
TIMEOUT = 10
ID = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")


class GalleryError(Exception):
    pass


def base_url():
    """Where the gallery's files are read from (ending in /)."""
    url = os.environ.get("STUDIO_GALLERY_URL") or f"https://raw.githubusercontent.com/{version.GALLERY_REPO}/main/"
    return url if url.endswith("/") else url + "/"


def page_url():
    """The gallery's page for people: its README says how to share."""
    return f"https://github.com/{version.GALLERY_REPO}"


def cache_dir():
    d = os.path.join(paths.HOME, "gallery")
    os.makedirs(d, exist_ok=True)
    return d


class Entry:
    __slots__ = ("id", "name", "author", "description", "tags", "sha256", "requires")

    def __init__(self, d):
        self.id = d["id"]
        self.name = _text(d.get("name"), 60) or self.id
        self.author = _text(d.get("author"), 60)
        self.description = _text(d.get("description"), 400)
        self.tags = [_text(t, 20) for t in (d.get("tags") or [])[:8] if _text(t, 20)]
        self.sha256 = str(d.get("sha256") or "").lower()
        self.requires = [_text(t, 30) for t in (d.get("requires") or [])[:8] if _text(t, 30)]

    def bundle_url(self):
        return f"{base_url()}effects/{self.id}.graph.json"

    def preview_url(self):
        return f"{base_url()}previews/{self.id}.gif"


def _text(v, n):
    """A short line of the index's text: a string, no control characters, at most n long."""
    if not isinstance(v, str):
        return ""
    return re.sub(r"[\x00-\x1f\x7f]", " ", v).strip()[:n]


def _get(url, limit):
    """The bytes at `url`, or GalleryError - also when there are more than `limit` of them."""
    req = urllib.request.Request(url, headers={"User-Agent": "wled-effects-studio"})
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as r:
            data = r.read(limit + 1)
    except Exception as e:
        raise GalleryError(f"the gallery did not answer ({e})") from None
    if len(data) > limit:
        raise GalleryError(f"{url.rsplit('/', 1)[-1]} is larger than the {limit >> 10} KB a gallery file may be")
    return data


def parse_index(data):
    """[Entry] from the index's bytes: the entries that are whole (an id of the right form, said once), the rest
    left out. GalleryError when it is not an index at all."""
    try:
        d = json.loads(data.decode("utf-8"))
    except (ValueError, UnicodeError):
        raise GalleryError("the gallery's index does not read as JSON") from None
    if not isinstance(d, dict) or not isinstance(d.get("entries"), list):
        raise GalleryError("the gallery's index has no entries")
    out, seen = [], set()
    for e in d["entries"][:2000]:
        if not isinstance(e, dict) or not isinstance(e.get("id"), str) or not ID.match(e["id"]) or e["id"] in seen:
            continue
        if not re.fullmatch(r"[0-9a-fA-F]{64}", str(e.get("sha256") or "")):
            continue
        seen.add(e["id"])
        out.append(Entry(e))
    return out


def fetch_index():
    return parse_index(_get(base_url() + "index.json", INDEX_MAX))


def fetch_bundle(entry):
    """The entry's bundle into HOME/gallery/<id>.graph.json, checked: the index's sha256, and a bundle's shape
    (the graph pane's import checks the rest). Its path."""
    data = _get(entry.bundle_url(), BUNDLE_MAX)
    got = hashlib.sha256(data).hexdigest()
    if got != entry.sha256:
        raise GalleryError(f"{entry.name}: the file is not the one the index names (its sha256 differs) - not used")
    try:
        b = json.loads(data.decode("utf-8"))
    except (ValueError, UnicodeError):
        raise GalleryError(f"{entry.name}: the bundle does not read as JSON") from None
    if not isinstance(b, dict) or not isinstance(b.get("graph"), dict):
        raise GalleryError(f"{entry.name}: not a graph bundle")
    path = os.path.join(cache_dir(), entry.id + ".graph.json")
    with open(path, "wb") as f:
        f.write(data)
    return path


def fetch_preview(entry, size=96, max_frames=48):
    """The entry's preview GIF as RGB frames (size x size), from the cache when it was fetched before; None when
    it has none or it does not read."""
    path = os.path.join(cache_dir(), entry.id + ".gif")
    if not os.path.exists(path):
        try:
            data = _get(entry.preview_url(), PREVIEW_MAX)
        except GalleryError:
            return None
        with open(path, "wb") as f:
            f.write(data)
    return read_gif(path, size, max_frames)


def read_gif(path, size=96, max_frames=48):
    """A GIF's frames, square and `size` across (cropped to its middle), at most `max_frames` of them."""
    import numpy as np
    from PIL import Image, ImageSequence
    try:
        im = Image.open(path)
        frames = []
        n = getattr(im, "n_frames", 1)
        step = max(1, n // max_frames)
        for k, fr in enumerate(ImageSequence.Iterator(im)):
            if k % step:
                continue
            rgb = fr.convert("RGB")
            w, h = rgb.size
            s = min(w, h)
            rgb = rgb.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s)).resize((size, size))
            frames.append(np.asarray(rgb, np.uint8))
            if len(frames) >= max_frames:
                break
        return frames or None
    except Exception:
        return None


def make_id(name):
    """An entry's id from a name: lower case, dashes between the words."""
    s = re.sub(r"[^a-z0-9]+", "-", (name or "").lower()).strip("-")[:63]
    return s or "effect"


def prepare_share(bundle_path, gif_path, name, author="", description="", tags=()):
    """What to send to share one's graph: a folder in captures/gallery-share/<id> with the bundle and the preview
    under the gallery's names, and entry.json - the index entry, its sha256 made - ready for a pull request (the
    gallery's README says how). Its path."""
    eid = make_id(name)
    out = os.path.join(paths.CAPTURES, "gallery-share", eid)
    os.makedirs(os.path.join(out, "effects"), exist_ok=True)
    os.makedirs(os.path.join(out, "previews"), exist_ok=True)
    data = open(bundle_path, "rb").read()
    with open(os.path.join(out, "effects", eid + ".graph.json"), "wb") as f:
        f.write(data)
    if gif_path and os.path.exists(gif_path):
        with open(gif_path, "rb") as src, open(os.path.join(out, "previews", eid + ".gif"), "wb") as f:
            f.write(src.read())
    try:
        req = sorted(json.loads(data.decode("utf-8")).get("requires") or [])
    except (ValueError, UnicodeError, AttributeError):
        req = []
    entry = {"id": eid, "name": name, "author": author, "description": description, "tags": list(tags),
             "sha256": hashlib.sha256(data).hexdigest(), "requires": req, "studio": version.__version__}
    with open(os.path.join(out, "entry.json"), "w", encoding="utf-8") as f:
        json.dump(entry, f, indent=1)
    return out
