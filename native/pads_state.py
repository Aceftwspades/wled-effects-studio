"""The pads' run state: what the pad surface and its clip editor keep between frames that is not saved.

    S = pads_state.of(app)      # the app's (made the first time it is asked for)
    S.sel, S.drag, ...          # every field below, always there, with its default
    S.forget("rt", ...)         # fields put back to their defaults

It was 27 loose `app._pads_*` / `app._clip_*` attributes, each read with its own default at each place;
here each has one default and one comment (vj_state.py is the VJ's, made the same way). The pads themselves
are saved in the project's options (pads.state).
"""
# AI: below section was generated by an AI
import dataclasses as _dc
from dataclasses import dataclass


@dataclass(eq=False)
class PadsState:
    # --- playing the pads ---------------------------------------------------------------------------------
    rt: object = None               # what is held, counted, toggled on, flashing and staged (pads._rt makes it)
    hw_rt: object = None            # the pad controller's held notes, lights sent, and output (pads_hw._hw makes it)
    remote: object = None           # control id -> [what the phone holds, when it last said so] (pads.remote_*)
    drag: object = None             # the control being dragged with the mouse: (id, what it started at...)
    knob: object = None             # a knob's drag: (the pointer's y at the press, the knob's value then)
    down_at: object = None          # when the mouse went down on a control (time.monotonic)
    learn: object = None            # a pad controller's learn waiting: what the next note is learnt for
    out: object = None              # the pad controller's MIDI output, open
    out_tried: object = None        # (the output's name, when it was last looked for): looked for every RETRY_S

    # --- the panel ----------------------------------------------------------------------------------------
    edit: bool = False              # the panel is in edit mode (a click selects, a drag moves)
    sel: object = None              # the cell or control selected in edit mode
    axis: str = "x"                 # the XY pad's axis being set up
    whole: object = None            # the project's pads as made whole last (made again when the options change)
    project: object = None          # the project the panel last drew (another one: its selection dropped)
    typed: object = None            # (when, the project) of a name or label typed and not saved yet
    drawn: object = None            # the grid's key as last drawn (a change draws it again)
    swung: object = None            # the swing lines' key as last drawn
    mods_key: object = None         # the modulator list's key as last listed
    labels: object = None           # the action list: (label, target) for every target a pad can drive
    labels_key: object = None       # what the action list was made for (another key: made again)
    label_ix: object = None         # target -> its label, from the action list
    state_err: object = None        # the phone's /pads state failed with this (said once)
    list_for: object = None         # (the control, its axis) whose action list was opened by hand (else folded)

    # --- a clip pad's editor ------------------------------------------------------------------------------
    clip_cams: object = None        # the cameras listed for a camera pad (None: not listed yet)
    clip_dialog_for: object = None  # (control id, bank, project) the clip dialog was opened for
    clip_drag: object = None        # "in" or "out": the strip's handle being dragged
    clip_strip_key: object = None   # the frame strip's key as last drawn (None: drawn again)

    def forget(self, *names):
        """Fields put back to their defaults."""
        for n in names:
            setattr(self, n, _DEFAULTS[n]())


_DEFAULTS = {f.name: (f.default_factory if f.default_factory is not _dc.MISSING else (lambda v=f.default: v))
             for f in _dc.fields(PadsState)}


def of(app):
    """The app's pads run state (any object can hold one: the tests' stand-in apps too)."""
    s = app.__dict__.get("pads_state")
    if s is None:
        s = app.__dict__.setdefault("pads_state", PadsState())
    return s
