"""The VJ's run state: what the VJ keeps between frames that is not saved with the project.

    S = vj_state.of(app)        # the app's (made the first time it is asked for)
    S.pending, S.sweep, ...     # every field below, always there, with its default
    S.take("opened")            # a field's value, the field put back to its default
    S.forget("pending", ...)    # fields put back to their defaults

It was some 70 loose `app._vj_*` attributes, each read with its own default at each place (the browser's
filter was "" in one and "all looks" in another; a beat's time -1e9 in one and None in another): here
each one has one default, one comment, and a reset that cannot miss one. What the project saves stays in
the project's options (vj.options); what a source holds open is let go by vj.close.
"""
# AI: below section was generated by an AI
import dataclasses as _dc
from dataclasses import dataclass, field

UNSET = "unset"                     # a count not taken yet (its first look fires nothing): sec, csec can be None

@dataclass(eq=False)
class VJState:
    # --- the mix: cuts, fades and sweeps in flight --------------------------------------------------------
    pending: object = None          # a Cut waiting for the next beat or bar: (beat it fires on, what it does)
    cpending: object = None         # deck C's press waiting the same way
    fade: object = None             # a blend from the last picture into a VJ step's, under way (t0, dur, from, style)
    sweep: object = None            # the crossfader's sweep: (start, from, to, seconds) on clock.now()
    csweep: object = None           # deck C's level sweep, the same
    goes: int = 0                   # how many times a deck went on air (a staged pad's GO compares it)
    hand_at: object = None          # when the crossfader was last moved by hand (a VJ show step yields to it)
    morphs: dict = field(default_factory=dict)      # deck -> a look morph under way (a preset going into another)
    mod: dict = field(default_factory=dict)         # (deck, knob) -> a modulator's value over the knob
    pals: dict = field(default_factory=dict)        # a palette's name -> (when it was read, its grad(x)): vj.colours
    blackout: bool = False          # the mix held dark (the decks run on under it): the hand's, never saved
    freeze: bool = False            # the mix held as it was when this was set
    frozen: object = None           # ... that picture (None: not held, or the next one is to be)
    dirty: bool = False             # the options changed: the panel redrawn, the project saved soon
    knobs_moved: bool = False       # a knob moved since the last undo snapshot
    save_at: object = None          # when the VJ's options are saved next

    # --- the beat and the bars --------------------------------------------------------------------------
    at: object = None               # when the VJ last counted its beats (None: not yet)
    beats: float = 0.0              # the beats counted
    hits: int = 0                   # sound hits heard since the VJ started
    last_hit: object = None         # app.last_hit_at as last seen: a new one is a hit heard
    downbeat: object = None         # the bar's first beat, as set by hand
    grid_beat_at: object = None     # when the beat grid last fired
    pulse: float = 0.0              # the beat's pulse, decaying between beats
    pulse_beats: object = None      # the beat count the pulse was last taken at
    count: tuple = (None, None)     # (whether the show's count is the clock, the beats) at the last look
    bar_k: object = None            # the auto-mix's bar, as last counted (None: not yet - the first fires nothing)
    cbar_k: object = None           # deck C's, the same
    sec: object = UNSET             # the auto-mix's song section, as last seen (None: none; UNSET: not looked yet)
    csec: object = UNSET            # deck C's, the same
    clipbar: dict = field(default_factory=dict)     # deck -> its clip list's bar, as last counted (absent: not yet)

    # --- the decks' sources -----------------------------------------------------------------------------
    runs: object = None             # the decks' DeckRuns (made by vj._runs)
    clip_runs: object = None        # decks A and B's pad-clip DeckRuns (vj._clip_runs)
    pool: object = None             # key -> (source, ...): the sources open (vj._pool)
    pool_at: dict = field(default_factory=dict)     # key -> [when it was opened, the wait before again]
    opening: dict = field(default_factory=dict)     # key -> the generation its open was started in (_OPEN_LOCK)
    opened: dict = field(default_factory=dict)      # key -> a worker's opened source, to collect (_OPEN_LOCK)
    gen: int = 0                    # vj.close's generation: an open started before it is closed when it lands
    cam_keys: set = field(default_factory=set)      # the pads' cameras kept warm
    release_due: bool = False       # sources no deck uses are let go at the next update
    skip: object = None             # per deck: the time it was not drawn for, given back once (vj._skipped)
    clips: dict = field(default_factory=dict)       # deck -> the pad clip playing on it (vj_clips)
    clip_take: int = 0              # the pad clips' take number: a new press, a new take
    last_pic: object = None         # the last frame the VJ gave the LEDs, a VJ step's blend done (a blend starts there)
    out: object = None              # the mix's last frame, as LEDs

    # --- the panel --------------------------------------------------------------------------------------
    open: bool = False              # the VJ panel is open
    tick: int = 0                   # the VJ's update count (some work is done every Nth)
    desk: object = None             # the desk as it was before a show's VJ step took it over (put back after)
    by_show: bool = False           # the VJ is being driven by the Sequence's show
    preview: object = False         # the decks whose previews are on screen (a set; False: the panel not drawn yet)
    packs: object = None            # the look packs listed
    ch_target: tuple = (0, 0)       # (deck, knob) the channel picker sets
    browse_deck: int = 0            # the deck the look browser puts a look on
    br_filter: str = "all looks"    # the look browser's filter
    file_errs: list = field(default_factory=list)   # look files that would not load, as read last
    files_at: float = 0.0           # when the project's own looks were last read from disk (time.monotonic)
    src_names: dict = field(default_factory=dict)   # deck -> (kind, the names listed for its source)
    src_rest: dict = field(default_factory=dict)    # deck -> a source's settings kept while another is chosen
    py_asked: set = field(default_factory=set)      # projects asked before their Python looks ran

    # --- the look browser's thumbnails -------------------------------------------------------------------
    thumbs: object = None           # look -> its thumbnail's item and state (None: the browser not built)
    th_made: dict = field(default_factory=dict)     # look -> its thumbnail's texture
    th_src: object = None           # the test-pattern video the thumbnails' video looks play
    th_ctx: object = None           # the look context the thumbnails were drawn with
    th_frame: int = 0               # the thumbnail frame count
    th_k: int = 0                   # where the next round of thumbnails starts
    th_ck: int = 0                  # the next costly thumbnail to draw
    th_costly: int = -10 ** 9       # the frame a costly thumbnail was last drawn on
    th_freed: bool = False          # the thumbnails' textures let go

    def take(self, name):
        """A field's value; the field put back to its default."""
        v = getattr(self, name)
        self.forget(name)
        return v

    def forget(self, *names):
        """Fields put back to their defaults."""
        for n in names:
            setattr(self, n, _DEFAULTS[n]())


_DEFAULTS = {f.name: (f.default_factory if f.default_factory is not _dc.MISSING else (lambda v=f.default: v))
             for f in _dc.fields(VJState)}


def of(app):
    """The app's VJ run state (any object can hold one: the tests' stand-in apps too)."""
    s = app.__dict__.get("vj_state")
    if s is None:
        s = app.__dict__.setdefault("vj_state", VJState())   # (setdefault: two threads asking at once get one)
    return s
