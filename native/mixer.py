def build(app):
    import dearpygui.dearpygui as dpg
    from native import chrome, form, num
    from native.typeface import px
    o = options(app)
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(480), height=px(340)):
        chrome.dialog_header(TAG, "Mixer")
        dpg.add_text("Deck A is the effect the studio has; deck B runs beside it, hearing the same sound. The fader takes "
                     "the picture from one to the other through the blend - in the sim and the stream. MIDI (the "
                     "mixer's fader) and the phone move it too.", color=chrome.DIM, wrap=px(450))
        dpg.add_checkbox(label="mix in deck B", tag="mx_on", default_value=bool(o["on"]),
                         callback=lambda s, v: _set(app, "on", bool(v)))
        with form.row("deck B", tip="the second effect"):
            dpg.add_combo(list(app.eng.names), tag="mx_b", width=-1, default_value=o["b"],
                          callback=lambda s, v: _set(app, "b", v))
        with form.row("its speed"):
            num.add("mx_sx", int(o["sx"]), 0, 255, integer=True, callback=lambda s, v: _set(app, "sx", int(v)))
        with form.row("its intensity"):
            num.add("mx_ix", int(o["ix"]), 0, 255, integer=True, callback=lambda s, v: _set(app, "ix", int(v)))
        with form.row("blend", tip="how the two mix between the fader's ends"):
            dpg.add_combo(list(MODES), tag="mx_mode", width=-1, default_value=o["mode"],
                          callback=lambda s, v: _set(app, "mode", v))
        with form.row("A - fader - B"):
            num.add("mx_fader", float(o["fader"]), 0.0, 1.0, digits=2, callback=lambda s, v: set_fader(app, v))
        with dpg.group(horizontal=True):
            dpg.add_button(label="A", tag="mx_to_a", callback=lambda: set_fader(app, 0.0))
            chrome.tip("all deck A")
            dpg.add_button(label="Swap", tag="mx_swap", callback=lambda: swap(app))
            chrome.tip("deck B becomes the studio's effect (deck A), and A goes to deck B - the fader turned round")
            dpg.add_button(label="B", tag="mx_to_b", callback=lambda: set_fader(app, 1.0))
            chrome.tip("all deck B")


def _set(app, key, v):
    options(app)[key] = v
    app.project.save()


def show(app):
    import dearpygui.dearpygui as dpg
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    o = options(app)
    if not o["b"]:
        o["b"] = next((n for n in app.eng.names if n != app.eng.names[app.eng.idx] and n.lower() != "solid"), "")
    dpg.configure_item("mx_b", items=list(app.eng.names))
    dpg.set_value("mx_b", o["b"])
    chrome._centre(TAG, 480, 340)
    dpg.show_item(TAG)


def swap(app):
    """Deck B's effect onto deck A (the studio's) and A's onto B, the fader turned round: the same picture, the
    decks the other way, so B can be changed next."""
    o = options(app)
    if not o["b"] or o["b"] not in app.eng.names:
        return
    a_name = app.eng.names[app.eng.idx]
    a_fx = (int(app.eng.fx.get("sx", 128)), int(app.eng.fx.get("ix", 128)))
    b_name, b_fx = o["b"], (int(o["sx"]), int(o["ix"]))
    from native import midi_ui
    midi_ui.switch_effect(app, b_name)
    app.eng.fx["sx"], app.eng.fx["ix"] = b_fx
    app.eng.push()
    app.rebuild_params()
    o["b"], (o["sx"], o["ix"]) = a_name, a_fx
    app._mixer_sel = None
    import dearpygui.dearpygui as dpg
    for tag, v in (("mx_b", a_name), ("mx_sx", a_fx[0]), ("mx_ix", a_fx[1])):
        if dpg.does_item_exist(tag):
            from native import num
            num.set(tag, v) if tag != "mx_b" else dpg.set_value(tag, v)
    set_fader(app, 1.0 - float(o["fader"]))
    app.project.save()
