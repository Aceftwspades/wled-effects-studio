import numpy as np

TAG = "mixer_win"
MODES = ("crossfade", "add", "screen", "multiply", "lighten", "difference")
DEFAULT = {"on": False, "b": "", "fader": 0.0, "mode": "crossfade", "sx": 128, "ix": 128}


def options(app):
    o = app.project.options.setdefault("mixer", {})
    for k, v in DEFAULT.items():
        o.setdefault(k, v)
    return o


def on(app):
    o = options(app)
    return bool(o["on"]) and bool(o["b"])


def _blend(a, b, mode):
    """The two at the fader's middle, float 0..255."""
    if mode == "add":
        return np.minimum(255.0, a + b)
    if mode == "screen":
        return 255.0 - (255.0 - a) * (255.0 - b) / 255.0
    if mode == "multiply":
        return a * b / 255.0
    if mode == "lighten":
        return np.maximum(a, b)
    if mode == "difference":
        return np.abs(a - b)
    return (a + b) * 0.5


def mix(a, b, fader, mode="crossfade"):
    """Deck A's picture to deck B's through the fader (0: A, 1: B), the mode's blend at the middle."""
    a = np.asarray(a, np.uint8)
    b = np.asarray(b, np.uint8)
    if a.shape != b.shape:
        return a
    f = float(max(0.0, min(1.0, fader)))
    if f <= 0.0:
        return a
    if f >= 1.0:
        return b
    af, bf = a.astype(np.float32), b.astype(np.float32)
    m = _blend(af, bf, mode)
    out = af + (m - af) * (f * 2.0) if f < 0.5 else m + (bf - m) * ((f - 0.5) * 2.0)
    return np.clip(out + 0.5, 0, 255).astype(np.uint8)


def deck_b(app):
    """Deck B's engine, its effect selected (again when the shape or the effect changed), or None."""
    if not on(app):
        return None
    o = options(app)
    try:
        eng = app.second_engine("mixer")
    except Exception:
        return None
    if eng.cols != app.eng.cols or eng.rows != app.eng.rows:
        eng.set_geometry(app.project.geometry)
        app._mixer_sel = None
    if o["b"] not in eng.names:
        return None
    want = (o["b"], eng.cols, eng.rows)
    if getattr(app, "_mixer_sel", None) != want:
        eng.select(eng.names.index(o["b"]))
        app._mixer_sel = want
        app._mixer_fx = None
    fx = (int(o["sx"]), int(o["ix"]))
    if getattr(app, "_mixer_fx", None) != fx:
        eng.fx["sx"], eng.fx["ix"] = fx
        eng.push()
        app._mixer_fx = fx
    return eng


def step(app, ms):
    """Deck B a frame on, hearing what deck A hears."""
    eng = deck_b(app)
    if eng is None:
        return
    try:
        eng.fft[:] = app.eng.fft[:]
        eng.audio(*getattr(app.eng, "last_audio", (0.0, 0)))
        eng.frame(ms)
    except Exception as e:
        options(app)["on"] = False
        app.gp.status(f"the mixer's deck B stopped: {e}", "warn")


def picture(app, a):
    """The frame through the mixer (as it is when the mixer is off or at deck A)."""
    o = options(app)
    if not on(app) or float(o["fader"]) <= 0.0:
        return a
    eng = deck_b(app)
    if eng is None:
        return a
    return mix(a, eng.rgb(), float(o["fader"]), o["mode"])


def set_fader(app, v, save=True):
    """The fader (0: deck A, 1: deck B) - the dialog's, a MIDI control's, the phone's."""
    o = options(app)
    o["fader"] = round(float(max(0.0, min(1.0, v))), 4)
    import dearpygui.dearpygui as dpg
    if dpg.does_item_exist("mx_fader") and abs(float(dpg.get_value("mx_fader")) - o["fader"]) > 1e-4:
        from native import num
        num.set("mx_fader", o["fader"])
    if save:
        app._mixer_save_at = __import__("time").perf_counter() + 0.5      # saved once the fader rests


def poll(app):
    import time
    t = getattr(app, "_mixer_save_at", None)
    if t is not None and time.perf_counter() >= t:
        app._mixer_save_at = None
        app.project.save()


