"""A mixer of two effects (the second feature review's eighth, after
Chromatik's and Resolume's decks and crossfader): deck A is the effect the
studio has - edited, sequenced, MIDI-mapped as ever - and deck B a second
effect running beside it on its own engine, hearing the same sound; a fader
takes the picture from one to the other through a blend mode. In the sim,
and so in the stream, a recording, a video, an FSEQ and a device's GIF.

    o = options(app)            # {"on", "b", "fader" 0..1, "mode", "sx", "ix"}
    step(app, ms)               # each engine frame: deck B a frame on
    out = mix(a, b, fader, mode)   # the two pictures, through the fader

At the fader's ends only one deck shows; between them, the two blended by the
mode at its middle, eased from either end into it:

    crossfade   the two averaged          add        summed (to white)
    screen      lightened                 multiply   darkened through each other
    lighten     the brighter of each      difference  how far apart they are

The device has no second deck: it blends between presets itself (a show's
transitions); the mixer is for the sim and the stream.
"""
