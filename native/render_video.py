TAG = "render_video_win"
VIEWS = (("cube", "the 3-D view"), ("net", "the logical net"), ("both", "both, side by side"))
SIZES = (("1280x720", "1280 x 720 (720p)"), ("1920x1080", "1920 x 1080 (1080p)"), ("3840x2160", "3840 x 2160 (4K)"),
         ("1080x1080", "1080 x 1080 (square)"), ("1080x1920", "1080 x 1920 (portrait)"))
RATES = (24, 30, 60)
QUALITIES = (("high", "high (a larger file)", 16), ("standard", "standard", 20), ("small", "a small file", 26))
LENGTHS = (("show", "the whole show"), ("step", "the selected step"))
CAMERAS = (("still", "as it is", 0.0), ("slow", "turning slowly", 8.0), ("turn", "turning", 24.0))   # degrees a second
DEFAULTS = {"view": "cube", "size": "1920x1080", "fps": 30, "quality": "standard", "length": "show", "camera": "still",
            "audio": True}


def options(app):
    from native import sequence_ui
    o = sequence_ui._steps(app).setdefault("render", {})
    for k, v in DEFAULTS.items():
        o.setdefault(k, v)
    return o


def _words(pairs, key):
    return next((p[1] for p in pairs if p[0] == key), pairs[0][1])


def _key(pairs, words):
    return next((p[0] for p in pairs if p[1] == words), pairs[0][0])


def span(app):
    """(start, end) seconds of the show the video is of."""
    from native import sequence_ui
    starts, total = sequence_ui._starts(app)
    if options(app)["length"] == "step":
        i = getattr(app, "_seq_sel", 0)
        steps = sequence_ui._steps(app)["steps"]
        if 0 <= i < len(steps):
            return starts[i], starts[i] + float(steps[i].get("dur", 10))
    return 0.0, total


def size(app):
    w, h = (int(v) for v in options(app)["size"].split("x"))
    return w, h


def has_audio(app):
    from native import sequence_ui
    return any(tr.get("clips") for tr in sequence_ui._tracks(app))


