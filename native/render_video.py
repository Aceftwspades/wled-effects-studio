"""The Sequence rendered to a video, frame by frame: the show stepped a
frame's time at a time on the studio's clock held for it (native/clock.py),
each frame's picture made at the video's size and sent to ffmpeg as it is
made - however long a frame takes, the video has every one - and the show's
audio (native/showaudio.py) mixed for the same stretch and put in with it.

    render_video.show(app)       # the dialog: the view, the size, the rate, the quality, the length, the camera, the audio
    render_video.start(app)      # with the options the show keeps (S["render"])
    render_video.advance(app)    # each frame, before the show's poll: the clock a frame on
    render_video.capture(app)    # each frame, after the views are drawn: the frame into the video
    render_video.cancel(app)

The 3-D view is drawn square at the video's height, on the background the
whole frame has, the look's spill round it and its curve, vignette and
grain over all of it: a wide video has no bars beside it. Into captures/,
as the GIF and the recordings are.
"""
