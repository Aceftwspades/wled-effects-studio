def build(app):
    from native import chrome, form
    with dpg.window(tag=TAG, show=False, no_title_bar=True, no_collapse=True, width=px(470), height=px(390)):
        chrome.dialog_header(TAG, "Render the show to a video")
        dpg.add_text("The show played once and made into an mp4, every frame drawn at the video's size - however long "
                     "each takes - with the show's audio. Into captures/; needs ffmpeg.", color=chrome.DIM, wrap=px(440))

        def row(label, tag, pairs, key, tip):
            with form.row(label, tip=tip):
                dpg.add_combo([p[1] for p in pairs], tag=tag, width=-1, default_value=_words(pairs, key),
                              callback=lambda s, v: _set(app, tag, v))
        o = options(app)
        row("view", "rv_view", VIEWS, o["view"], "what the video shows")
        row("size", "rv_size", SIZES, o["size"], "the video's frame, in pixels: the 3-D view fills its height, the room "
            "round it the rest")
        row("frames a second", "rv_fps", [(r, str(r)) for r in RATES], o["fps"], "smoother, and slower to render, the more")
        row("quality", "rv_quality", [(q[0], q[1]) for q in QUALITIES], o["quality"], "the picture's quality against the file's size")
        row("length", "rv_length", LENGTHS, o["length"], "all of the show, or the step selected in the list")
        row("camera", "rv_camera", [(c[0], c[1]) for c in CAMERAS], o["camera"], "the 3-D view held as it is now, or "
            "turning round the shape as the show plays")
        dpg.add_checkbox(label="with the show's audio", tag="rv_audio", default_value=bool(o["audio"]),
                         callback=lambda s, v: _set(app, "rv_audio", v))
        chrome.tip("the tracks under the timeline, mixed for the video's stretch of the show")
        dpg.add_text("", tag="rv_words", color=chrome.DIM, wrap=px(440))
        with dpg.group(horizontal=True):
            dpg.add_button(label="Render", tag="rv_go", callback=lambda: start(app))
            from native import weight
            weight.primary("rv_go")
            chrome.tip("plays the show from the length's start, frame by frame, into the video")
            dpg.add_button(label="Cancel the render", tag="rv_cancel", callback=lambda: cancel(app), show=False)
            chrome.tip("stops it: the frames so far are thrown away")
    return TAG


def _set(app, tag, v):
    o = options(app)
    if tag == "rv_view":
        o["view"] = _key(VIEWS, v)
    elif tag == "rv_size":
        o["size"] = _key(SIZES, v)
    elif tag == "rv_fps":
        o["fps"] = int(v)
    elif tag == "rv_quality":
        o["quality"] = _key([(q[0], q[1]) for q in QUALITIES], v)
    elif tag == "rv_length":
        o["length"] = _key(LENGTHS, v)
    elif tag == "rv_camera":
        o["camera"] = _key([(c[0], c[1]) for c in CAMERAS], v)
    elif tag == "rv_audio":
        o["audio"] = bool(v)
    app.project.save()
    refresh(app)


def refresh(app):
    """The dialog's line: what the video will be, or how far the render is."""
    if not dpg.does_item_exist("rv_words"):
        return
    job = getattr(app, "_video_job", None)
    dpg.configure_item("rv_go", show=job is None)
    dpg.configure_item("rv_cancel", show=job is not None)
    if job is not None:
        done = job.frame / max(1, job.frames)
        took = time.perf_counter() - job.t_real
        left = took / done - took if done > 0.02 else None
        dpg.set_value("rv_words", f"rendering: frame {job.frame} of {job.frames} ({done * 100:.0f}%)"
                      + (f", about {left:.0f} s left" if left is not None else ""))
        return
    t0, t1 = span(app)
    o = options(app)
    n = int(math.ceil((t1 - t0) * o["fps"]))
    audio = " with the show's audio" if o["audio"] and has_audio(app) else (" (no audio: the show has no tracks)" if o["audio"] else "")
    dpg.set_value("rv_words", f"{t1 - t0:.1f} s, {n} frames at {o['size'].replace('x', ' x ')}{audio}"
                  + ("" if app.has_ffmpeg() else " - ffmpeg is not on the path: it cannot be made"))
    dpg.configure_item("rv_audio", enabled=has_audio(app))


def show(app):
    from native import chrome
    if not dpg.does_item_exist(TAG):
        build(app)
    o = options(app)
    for tag, pairs, key in (("rv_view", VIEWS, o["view"]), ("rv_size", SIZES, o["size"]),
                            ("rv_fps", [(r, str(r)) for r in RATES], o["fps"]),
                            ("rv_quality", [(q[0], q[1]) for q in QUALITIES], o["quality"]), ("rv_length", LENGTHS, o["length"]),
                            ("rv_camera", [(c[0], c[1]) for c in CAMERAS], o["camera"])):
        dpg.set_value(tag, _words(pairs, key))
    dpg.set_value("rv_audio", bool(o["audio"]))
    refresh(app)
    chrome._centre(TAG, 470, 390)
    dpg.show_item(TAG)


# --- the render ----------------------------------------------------------------------------------
class Job:
    def __init__(self, app, path, t0, t1, w, h, fps, crf, view, deg, audio):
        self.path, self.t0, self.t1, self.w, self.h, self.fps = path, t0, t1, w, h, fps
        self.view, self.deg, self.audio = view, deg, audio
        self.frames = max(1, int(math.ceil((t1 - t0) * fps)))
        self.frame = 0
        self.t_real = time.perf_counter()
        self.yaw0 = app.yaw
        self.video = path[:-4] + ".video.mp4" if audio else path
        ff = shutil.which("ffmpeg")
        cmd = [ff, "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{w}x{h}", "-r", str(fps),
               "-i", "-", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", str(crf), "-preset", "medium", self.video]
        self.proc = procs.popen(cmd, stdin=subprocess.PIPE, stderr=subprocess.PIPE)


def start(app):
    """The render begun: the show from the length's start on the held clock, the speakers silent."""
    from native import sequence_ui
    if getattr(app, "_video_job", None) is not None:
        return False
    if not app.has_ffmpeg():
        app.gp.status("a video needs ffmpeg on the path - not found", "warn"); return False
    if not sequence_ui._has_steps(app):
        app.gp.status("no steps to render"); return False
    o = options(app)
    t0, t1 = span(app)
    w, h = size(app)
    crf = next(q[2] for q in QUALITIES if q[0] == o["quality"])
    deg = next(c[2] for c in CAMERAS if c[0] == o["camera"])
    from native.recorder import GIF_DIR
    os.makedirs(GIF_DIR, exist_ok=True)
    name = "".join(ch if ch.isalnum() else "_" for ch in str(sequence_ui._steps(app).get("name") or "show"))
    path = os.path.join(GIF_DIR, f"{name}_{int(time.time())}.mp4")
    audio = bool(o["audio"]) and has_audio(app)
    try:
        job = Job(app, path, t0, t1, w, h, int(o["fps"]), crf, o["view"], deg, audio)
    except Exception as e:
        app.gp.status(f"the video could not be begun: {e}", "warn"); return False
    sequence_ui.stop(app)
    clock.hold()
    sequence_ui.seek(app, t0)
    p = getattr(app, "_seq_play", None)
    if p is not None and p.get("paused") is not None:
        sequence_ui.play_pause(app)
    if getattr(app, "_seq_play", None) is not None:
        app._seq_play["once"] = True
    app.playing = True
    app._video_job = job
    refresh(app)
    app.gp.status(f"rendering {t1 - t0:.1f} s of the show ({job.frames} frames)...")
    return True


def advance(app):
    """Before the show's poll, each frame of a render: the held clock a frame's time on (the first frame stays at
    the start)."""
    job = getattr(app, "_video_job", None)
    if job is not None and job.frame > 0:
        clock.step(1.0 / job.fps)


MARGIN = 0.86            # the shape's share of the square it is drawn in, as the live view leaves round it


def _scene(app, side, bg):
    """The 3-D view square at `side` on `bg` (its part of the frame's background), the look's finish not yet, and
    where the room shows in it."""
    return app.view_image_room(app.net_image(), side, app.eng, bg=bg)


def frame_picture(app, job):
    """This frame of the video: (h, w, 3) uint8."""
    from native import look
    w, h = job.w, job.h
    bgp = app.view_background(min(w, h), w, h) if app.prefs.get("view_bg") else None
    out = np.array(bgp, np.uint8) if isinstance(bgp, np.ndarray) else np.zeros((h, w, 3), np.uint8)
    box = None
    room = np.ones((h, w), bool)
    if job.view in ("cube", "both"):
        # the shape square, at the live view's margin, in the middle of its part of the frame
        side = int(min(h, w if job.view == "cube" else w // 2 - 8) * MARGIN)
        x0 = (w - side) // 2 if job.view == "cube" else (w // 2 - side) // 2
        y0 = (h - side) // 2
        img, rm = _scene(app, side, out[y0:y0 + side, x0:x0 + side].copy())
        out[y0:y0 + side, x0:x0 + side] = img
        room[y0:y0 + side, x0:x0 + side] = rm
        box = (x0, y0, side)
    if job.view in ("net", "both"):
        net = app.net_image()
        nx0, nw = (0, w) if job.view == "net" else (w // 2 + 8, w - w // 2 - 8)
        k = max(1, min(nw // net.shape[1], h // net.shape[0]))
        big = net.repeat(k, 0).repeat(k, 1)
        if big.shape[0] > h or big.shape[1] > nw:                        # a net wider than the frame: fitted down
            from PIL import Image
            f = min(nw / net.shape[1], h / net.shape[0])
            big = np.asarray(Image.fromarray(net).resize((max(1, int(net.shape[1] * f)), max(1, int(net.shape[0] * f))), Image.NEAREST))
        y, x = (h - big.shape[0]) // 2, nx0 + (nw - big.shape[1]) // 2
        out[y:y + big.shape[0], x:x + big.shape[1]] = big
    if box is not None:
        lk = app.view_look()
        if look.active(lk):
            light = look.mean_light(app.frame_rgb(app.eng)) if lk["spill"] > 0 else None
            out = look.finish(out, lk, job.frame, light, spill_box=box, room=room)
    return out


def capture(app):
    """After the views are drawn, each frame of a render: this frame of the show into the video; at its end the
    audio mixed in and the show stopped."""
    from native import sequence_ui
    job = getattr(app, "_video_job", None)
    if job is None:
        return
    try:
        if job.deg:
            app.yaw = job.yaw0 + math.radians(job.deg) * (job.frame / job.fps)
        job.proc.stdin.write(np.ascontiguousarray(frame_picture(app, job)).tobytes())
    except Exception as e:
        _end(app, f"the video failed: {e}")
        return
    job.frame += 1
    if job.frame % 15 == 0:
        refresh(app)
    if job.frame >= job.frames:
        _finish(app)


def _finish(app):
    job = app._video_job
    try:
        job.proc.stdin.close()
        err = job.proc.stderr.read().decode("utf-8", "replace")
        if job.proc.wait() != 0:
            raise RuntimeError(err.strip()[-160:])
        if job.audio:
            _mux(app, job)
        took = time.perf_counter() - job.t_real
        _end(app, f"{os.path.basename(job.path)}: {job.t1 - job.t0:.1f} s, {job.frames} frames, "
                  f"{os.path.getsize(job.path) / 1e6:.1f} MB, made in {took:.0f} s", ok=True)
    except Exception as e:
        _end(app, f"the video failed: {e}")


def _mux(app, job):
    """The show's audio for the video's stretch, mixed (as the speakers hear it) into a WAV and put in the video."""
    from native import sequence_ui, showaudio
    resolved = showaudio.resolve(sequence_ui._steps(app), app.project.path)
    n = int(round((job.t1 - job.t0) * showaudio.RATE))
    mix = np.zeros((n, 2), np.float32)
    step = showaudio.RATE * 10
    for k in range(0, n, step):
        mix[k:k + step] = showaudio.render(resolved, job.t0 + k / showaudio.RATE, min(step, n - k))
    wav = job.path[:-4] + ".audio.wav"
    with wave.open(wav, "wb") as f:
        f.setnchannels(2); f.setsampwidth(2); f.setframerate(showaudio.RATE)
        f.writeframes((np.clip(mix, -1, 1) * 32767).astype(np.int16).tobytes())
    ff = shutil.which("ffmpeg")
    r = procs.run([ff, "-y", "-loglevel", "error", "-i", job.video, "-i", wav, "-map", "0:v", "-map", "1:a", "-c:v", "copy",
                   "-c:a", "aac", "-b:a", "192k", "-shortest", job.path], capture_output=True, timeout=600)
    for p in (wav, job.video):
        try:
            os.remove(p)
        except OSError:
            pass
    if r.returncode != 0:
        raise RuntimeError("the audio could not be put in: " + (r.stderr or b"").decode("utf-8", "replace").strip()[-160:])


def _end(app, words, ok=False):
    from native import sequence_ui
    job = getattr(app, "_video_job", None)
    app._video_job = None
    if job is not None:
        app.yaw = job.yaw0
        if not ok:
            try:
                job.proc.kill()
            except Exception:
                pass
            for p in {job.video, job.path, job.path[:-4] + ".audio.wav"}:
                try:
                    if os.path.exists(p):
                        os.remove(p)
                except OSError:
                    pass
    clock.release()
    app.last = time.perf_counter()                 # the engine's step from the real clock again, not the held one's
    sequence_ui.stop(app)
    if ok:
        app.gp.status(words)
    else:
        app.gp.status(words, "warn")
    app.rec_msg = words
    refresh(app)


def cancel(app):
    if getattr(app, "_video_job", None) is not None:
        _end(app, "the render was cancelled")


def rendering(app):
    return getattr(app, "_video_job", None) is not None
