def load(path):
    """A .milk file: its settings and its equations, read; the code compiled."""
    import os
    text = open(path, encoding="utf-8", errors="replace").read()
    return parse(text, os.path.splitext(os.path.basename(path))[0])


def parse(text, name="preset"):
    base = {v: d for v, d in BASE.values()}
    eq = {"init": {}, "frame": {}, "pixel": {}}
    for line in text.splitlines():
        if "=" not in line or line.lstrip().startswith(("[", ";", "//")):
            continue
        k, _, val = line.partition("=")
        k = k.strip()
        m = re.match(r"^(per_frame_init|per_frame|per_pixel)_(\d+)$", k, re.I)
        if m:
            which = {"per_frame_init": "init", "per_frame": "frame", "per_pixel": "pixel"}[m.group(1).lower()]
            eq[which][int(m.group(2))] = val
            continue
        if k in BASE:
            try:
                base[BASE[k][0]] = float(val.strip())
            except ValueError:
                pass
    code = {w: "\n".join(eq[w][n] for n in sorted(eq[w])) for w in eq}
    return {"name": name, "base": base, "src": code,
            "init": compile_code(code["init"], "per-frame-init equations"),
            "frame": compile_code(code["frame"], "per-frame equations"),
            "pixel": compile_code(code["pixel"], "per-pixel equations") if code["pixel"].strip() else None}


# --- the drawing -----------------------------------------------------------------------------------
GRID_W, GRID_H = 32, 24          # the warp mesh the per-pixel equations run on (MilkDrop's is 48 x 36)
MOTION = ("zoom", "zoomexp", "rot", "warp", "cx", "cy", "dx", "dy", "sx", "sy")


def _mesh(w, h):
    """The mesh's points in MilkDrop's terms: x, y 0..1 (y up), rad (0 middle, 1 corner), ang."""
    x, y = np.meshgrid(np.linspace(0, 1, GRID_W), np.linspace(1, 0, GRID_H))
    aspect = w / float(h)
    dx, dy = (x - 0.5) * 2 * aspect, (y - 0.5) * 2
    rad = np.hypot(dx, dy) / np.hypot(aspect, 1.0)
    ang = np.arctan2(dy, dx)
    return x, y, rad, ang


def look_draw(preset):
    """A VJ look's draw for a preset: MilkDrop's frame on the deck's canvas."""
    from native import vj_looks

    def draw(ctx, st):
        w, h = ctx.w, ctx.h
        if st.get("fb") is None or st["fb"].shape != (h, w, 3):
            st["fb"] = np.zeros((h, w, 3), np.float32)
            st["v"] = dict(preset["base"])
            st["q"] = {}
            st["frame"] = 0
            st["att"] = [0.0, 0.0, 0.0]
            v = st["v"]
            v.update(time=0.0, fps=30.0, frame=0, bass=1.0, mid=1.0, treb=1.0, bass_att=1.0, mid_att=1.0, treb_att=1.0,
                     progress=0.0, meshx=GRID_W, meshy=GRID_H, aspectx=1.0, aspecty=1.0)
            preset["init"](v)
            st["q"] = {k: v[k] for k in v if re.match(r"q\d+$", k)}
        v = st["v"]
        # the sound as MilkDrop gives it: 1 its usual level, above it louder (the effects' bands, 0..1, made so)
        att = st["att"]
        for k, val in enumerate((ctx.bass, ctx.mid, ctx.treb)):
            att[k] = att[k] * 0.9 + val * 0.1
        for k in preset["base"]:                                   # each frame from the settings again, as MilkDrop does
            v[k] = preset["base"][k]
        v.update(st["q"])
        v.update(time=float(ctx.t), fps=1.0 / max(1e-3, ctx.dt), frame=st["frame"],
                 bass=0.5 + 1.5 * ctx.bass, mid=0.5 + 1.5 * ctx.mid, treb=0.5 + 1.5 * ctx.treb,
                 bass_att=0.5 + 1.5 * att[0], mid_att=0.5 + 1.5 * att[1], treb_att=0.5 + 1.5 * att[2])
        preset["frame"](v)
        st["frame"] += 1
        # the motion over the mesh: the per-frame values everywhere, the per-pixel equations changing them point by point
        x, y, rad, ang = _mesh(w, h)
        pv = {k: v[k] for k in v}
        pv.update(x=x, y=y, rad=rad, ang=ang)
        for k in MOTION:
            pv[k] = np.full_like(x, float(v.get(k, 0.0)))
        if preset["pixel"] is not None:
            preset["pixel"](pv)
        g = {k: np.broadcast_to(np.asarray(pv[k], np.float64), x.shape) for k in MOTION}
        k30 = ctx.dt * 30.0 * ctx.speed                          # presets run at 30 frames a second
        zoom = np.power(np.maximum(g["zoom"], 1e-3), np.power(np.maximum(g["zoomexp"], 1e-3), rad * 2.0 - 1.0))
        zoom = np.power(zoom, k30)
        u = (x - g["cx"]) / zoom
        vv = (y - g["cy"]) / zoom
        u, vv = u / np.where(np.abs(g["sx"]) < 1e-3, 1e-3, g["sx"]), vv / np.where(np.abs(g["sy"]) < 1e-3, 1e-3, g["sy"])
        wt = float(ctx.t) * float(v.get("warpanimspeed", 1.0))
        ws = 1.0 / max(1e-3, float(v.get("warpscale", 1.0)))
        amt = g["warp"] * 0.0035 * k30
        u = u + amt * np.sin(wt * 0.333 + ws * (x * 0.83 - y * 1.21))
        vv = vv + amt * np.cos(wt * 0.375 - ws * (x * 1.07 + y * 0.92))
        u = u + amt * np.cos(wt * 0.753 - ws * (x * 0.73 - y * 0.91))
        vv = vv + amt * np.sin(wt * 0.825 + ws * (x * 0.68 + y * 1.33))
        a = -g["rot"] * k30
        cs, sn = np.cos(a), np.sin(a)
        u, vv = u * cs - vv * sn, u * sn + vv * cs
        u = u + g["cx"] - g["dx"] * k30
        vv = vv + g["cy"] - g["dy"] * k30
        # the mesh's sample places spread over the canvas (bilinear between the mesh's points), then the feedback
        from PIL import Image
        U = np.asarray(Image.fromarray(u.astype(np.float32), "F").resize((w, h), Image.BILINEAR))
        V = np.asarray(Image.fromarray(vv.astype(np.float32), "F").resize((w, h), Image.BILINEAR))
        fb = vj_looks.sample(st["fb"], U, 1.0 - V, wrap=True)
        decay = float(v.get("decay", 0.98))
        fb = fb * (decay ** k30)
        if v.get("darken_center"):
            fb = fb * np.clip(ctx.r / 0.25, 0.6, 1.0)[..., None]
        fb = _wave(ctx, v, fb)
        if ctx.video is not None:                                # a deck's video seeds it, as the built-in presets' does
            fb = np.maximum(fb, ctx.video * 0.06 * (0.5 + ctx.amount))
        st["fb"] = np.clip(fb, 0, 1)
        out = st["fb"]
        gamma = float(v.get("gamma", 1.0))
        if gamma != 1.0:
            out = np.clip(out * gamma, 0, 1)
        if v.get("brighten"):
            out = np.sqrt(out)
        if v.get("darken"):
            out = out * out
        if v.get("solarize"):
            out = out * (1 - out) * 4
        if v.get("invert"):
            out = 1 - out
        st["q"] = {k: v[k] for k in v if re.match(r"q\d+$", k)}
        return out
    return draw


def _wave(ctx, v, fb):
    """The sound drawn as the preset's wave: its mode as a circle, a line, a spiral or dots, its colour and place."""
    h, w = fb.shape[:2]
    a = float(v.get("wave_a", 0.8))
    if a <= 0.001:
        return fb
    col = np.array([v.get("wave_r", 1.0), v.get("wave_g", 1.0), v.get("wave_b", 1.0)], np.float32)
    col = np.clip(np.nan_to_num(col), 0, 1)
    if v.get("wave_brighten", 1) and col.max() > 0:
        col = col / col.max()
    s = np.interp(np.linspace(0, len(ctx.wave) - 1, 256), np.arange(len(ctx.wave)), ctx.wave)
    s = s * float(v.get("wave_scale", 1.0)) * (0.6 + ctx.level)
    mode = int(v.get("wave_mode", 0)) % 8
    cx, cy = float(v.get("wave_x", 0.5)), 1.0 - float(v.get("wave_y", 0.5))
    t = np.linspace(0, 1, len(s))
    if mode in (0, 1):                                            # a circle, the sound its radius
        ang = t * 2 * math.pi
        r = 0.25 + s * 0.12 + (0.05 * math.sin(ctx.t) if mode == 1 else 0.0)
        px, py = cx + np.cos(ang) * r * h / w, cy + np.sin(ang) * r
    elif mode == 2:                                               # dots scattered by the sound
        px, py = cx + s * 0.4 * np.cos(t * 13.0), cy + np.roll(s, 32) * 0.4
    elif mode == 3:                                               # a spiral
        ang = t * 4 * math.pi + ctx.t
        r = t * 0.4 + s * 0.05
        px, py = cx + np.cos(ang) * r * h / w, cy + np.sin(ang) * r
    elif mode in (4, 5):                                          # a line across, the sound its height
        px, py = t, cy + s * 0.25
    else:                                                         # a line, tilted
        ang = float(v.get("wave_mystery", 0.0)) * math.pi
        px = cx + (t - 0.5) * math.cos(ang) - s * 0.2 * math.sin(ang)
        py = cy + (t - 0.5) * math.sin(ang) + s * 0.2 * math.cos(ang)
    ix = np.clip((px * (w - 1)).astype(int), 0, w - 1)
    iy = np.clip((py * (h - 1)).astype(int), 0, h - 1)
    thick = ((0, 0, 1.0), (1, 0, 0.6), (0, 1, 0.6)) if v.get("wave_thick") or w > 64 else ((0, 0, 1.0),)
    for oy, ox, f in thick:
        jy, jx = np.clip(iy + oy, 0, h - 1), np.clip(ix + ox, 0, w - 1)
        if v.get("wave_additive"):
            fb[jy, jx] = np.minimum(1.0, fb[jy, jx] + col * a * f)
        else:
            fb[jy, jx] = np.maximum(fb[jy, jx], col * a * f)
    return fb


