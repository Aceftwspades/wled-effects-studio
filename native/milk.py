# --- the expression language -----------------------------------------------------------------------
_TOKEN = re.compile(r"\s*(?:(\d+\.\d*|\.\d+|\d+)([eE][-+]?\d+)?|([A-Za-z_][A-Za-z0-9_]*)|(==|!=|<=|>=|&&|\|\||[-+*/%]=|[-+*/%^=<>!(),;&|]))")


def _tokens(src):
    out, i = [], 0
    src = re.sub(r"//[^\n]*", "", src)
    while i < len(src):
        m = _TOKEN.match(src, i)
        if not m or m.end() == i:
            if src[i:].strip() == "":
                break
            raise SyntaxError(f"cannot read {src[i:i + 12]!r}")
        if m.group(1) is not None:
            out.append(("num", m.group(1) + (m.group(2) or "")))
        elif m.group(3) is not None:
            out.append(("id", m.group(3).lower()))
        else:
            out.append(("op", m.group(4)))
        i = m.end()
    return out


_BIN = {"||": 1, "|": 1, "&&": 2, "&": 2, "==": 3, "!=": 3, "<": 4, ">": 4, "<=": 4, ">=": 4, "+": 5, "-": 5,
        "*": 6, "/": 6, "%": 6, "^": 7}


class _Parser:
    """ns-eel to Python source: statements become assignments to vars (a dict), expressions numpy-safe calls."""

    def __init__(self, toks):
        self.t, self.k = toks, 0

    def peek(self):
        return self.t[self.k] if self.k < len(self.t) else (None, None)

    def take(self, want=None):
        tok = self.peek()
        if want is not None and tok[1] != want:
            raise SyntaxError(f"expected {want!r}, found {tok[1]!r}")
        self.k += 1
        return tok

    def statements(self):
        out = []
        while self.peek()[0] is not None:
            if self.peek()[1] == ";":
                self.take(); continue
            out.append(self.statement())
            if self.peek()[1] == ";":
                self.take()
            elif self.peek()[0] is not None:
                raise SyntaxError(f"expected ';', found {self.peek()[1]!r}")
        return out

    def statement(self):
        kind, val = self.peek()
        if kind == "id" and self.k + 1 < len(self.t) and self.t[self.k + 1][1] in ("=", "+=", "-=", "*=", "/=", "%="):
            self.take()
            op = self.take()[1]
            rhs = self.expr(0)
            if op == "=":
                return f"v[{val!r}] = {rhs}"
            return f"v[{val!r}] = _g(v, {val!r}) {op[0]} ({rhs})" if op[0] != "/" else \
                f"v[{val!r}] = _div(_g(v, {val!r}), {rhs})"
        return f"_ = {self.expr(0)}"

    def expr(self, prec):
        """Precedence climbing: operators at least `prec` bind here; ^ to the right, the rest to the left."""
        left = self.unary()
        while True:
            kind, op = self.peek()
            if kind != "op" or op not in _BIN or _BIN[op] < prec:
                break
            p = _BIN[op]
            self.take()
            right = self.expr(p if op == "^" else p + 1)
            left = _binop(op, left, right)
        return left

    def unary(self):
        kind, val = self.peek()
        if val == "-":
            self.take(); return f"(-{self.unary()})"
        if val == "+":
            self.take(); return self.unary()
        if val == "!":
            self.take(); return f"_not({self.unary()})"
        return self.primary()

    def primary(self):
        kind, val = self.take()
        if kind == "num":
            return f"{float(val)!r}"
        if val == "(":
            e = self.expr(0)
            self.take(")")
            return f"({e})"
        if kind == "id":
            if self.peek()[1] == "(":
                self.take()
                args = []
                while self.peek()[1] != ")":
                    args.append(self.expr(0))
                    if self.peek()[1] == ",":
                        self.take()
                self.take(")")
                return f"_f_{val}({', '.join(args)})" if val in _FUNCS else f"_unknown({val!r})"
            return f"_g(v, {val!r})"
        raise SyntaxError(f"unexpected {val!r}")


def _binop(op, a, b):
    return {"+": f"({a} + {b})", "-": f"({a} - {b})", "*": f"({a} * {b})", "/": f"_div({a}, {b})",
            "%": f"_mod({a}, {b})", "^": f"_pow({a}, {b})", "==": f"_eq({a}, {b})", "!=": f"_ne({a}, {b})",
            "<": f"_lt({a}, {b})", ">": f"_gt({a}, {b})", "<=": f"_le({a}, {b})", ">=": f"_ge({a}, {b})",
            "&&": f"_and({a}, {b})", "&": f"_and({a}, {b})", "||": f"_or({a}, {b})", "|": f"_or({a}, {b})"}[op]


def _num(x):
    return np.asarray(x, np.float64) if isinstance(x, np.ndarray) else float(x)


def _div(a, b):
    b = np.where(np.abs(b) < 1e-12, np.nan, b) if isinstance(b, np.ndarray) else b
    if isinstance(b, np.ndarray):
        return np.nan_to_num(a / b, nan=0.0)
    return a / b if abs(b) > 1e-12 else 0.0


def _mod(a, b):
    a, b = np.floor(a), np.floor(b)
    if isinstance(b, np.ndarray):
        return np.where(b != 0, np.fmod(a, np.where(b == 0, 1, b)), 0.0)
    return float(np.fmod(a, b)) if b != 0 else 0.0


def _pow(a, b):
    with np.errstate(all="ignore"):
        r = np.power(np.abs(a) if np.any(np.asarray(a) < 0) and not np.all(np.asarray(b) == np.round(b)) else a, b)
    return np.nan_to_num(r, nan=0.0, posinf=0.0, neginf=0.0) if isinstance(r, np.ndarray) else (
        0.0 if not math.isfinite(float(r)) else float(r))


def _bool(x):
    return np.asarray(x) != 0


def _f(x):
    return x.astype(np.float64) if isinstance(x, np.ndarray) else float(x)


_FUNCS = {}


def _fn(name):
    def reg(f):
        _FUNCS[name] = f
        return f
    return reg


for _n, _impl in {
    "sin": np.sin, "cos": np.cos, "tan": np.tan, "asin": lambda x: np.arcsin(np.clip(x, -1, 1)),
    "acos": lambda x: np.arccos(np.clip(x, -1, 1)), "atan": np.arctan, "atan2": np.arctan2,
    "sqrt": lambda x: np.sqrt(np.abs(x)), "sqr": lambda x: np.asarray(x) * x, "abs": np.abs,
    "exp": lambda x: np.exp(np.clip(x, -50, 50)), "log": lambda x: np.log(np.maximum(np.abs(x), 1e-12)),
    "log10": lambda x: np.log10(np.maximum(np.abs(x), 1e-12)), "sign": np.sign, "int": np.trunc, "floor": np.floor,
    "ceil": np.ceil, "min": np.minimum, "max": np.maximum, "pow": _pow,
    "sigmoid": lambda x, c: 1.0 / (1.0 + np.exp(np.clip(-np.asarray(x) * c, -50, 50))),
    "above": lambda a, b: _f(np.asarray(a) > b), "below": lambda a, b: _f(np.asarray(a) < b),
    "equal": lambda a, b: _f(np.asarray(a) == b), "band": lambda a, b: _f(_bool(a) & _bool(b)),
    "bor": lambda a, b: _f(_bool(a) | _bool(b)), "bnot": lambda a: _f(~_bool(a)),
    "if": lambda c, a, b: np.where(_bool(c), a, b) if isinstance(c, np.ndarray) or isinstance(a, np.ndarray) or
    isinstance(b, np.ndarray) else (a if c != 0 else b),
    "rand": lambda x: float(np.random.randint(0, max(1, int(x)))) if not isinstance(x, np.ndarray) else
    np.floor(np.random.random(x.shape) * np.maximum(1, x)),
    "invsqrt": lambda x: 1.0 / np.sqrt(np.maximum(np.abs(x), 1e-12)),
}.items():
    _FUNCS[_n] = _impl

_ENV = {"_div": _div, "_mod": _mod, "_pow": _pow,
        "_eq": lambda a, b: _f(np.asarray(a) == b), "_ne": lambda a, b: _f(np.asarray(a) != b),
        "_lt": lambda a, b: _f(np.asarray(a) < b), "_gt": lambda a, b: _f(np.asarray(a) > b),
        "_le": lambda a, b: _f(np.asarray(a) <= b), "_ge": lambda a, b: _f(np.asarray(a) >= b),
        "_and": lambda a, b: _f(_bool(a) & _bool(b)), "_or": lambda a, b: _f(_bool(a) | _bool(b)),
        "_not": lambda a: _f(~_bool(a)), "_g": lambda v, k: v.get(k, 0.0),
        "_unknown": lambda name: 0.0, "np": np}
_ENV.update({f"_f_{k}": f for k, f in _FUNCS.items()})


def compile_code(src, what="equations"):
    """ns-eel statements as a Python function run(v) on a dict of the variables; SyntaxError said with `what`."""
    try:
        body = _Parser(_tokens(src)).statements()
    except SyntaxError as e:
        raise SyntaxError(f"the preset's {what}: {e}")
    code = "def run(v):\n" + ("".join(f"    {s}\n" for s in body) or "    pass\n")
    ns = dict(_ENV)
    with np.errstate(all="ignore"):
        exec(compile(code, f"<{what}>", "exec"), ns)
    run = ns["run"]

    def safe(v):
        with np.errstate(all="ignore"):
            run(v)
    return safe


