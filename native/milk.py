"""MilkDrop presets (.milk files) as the VJ's looks: a preset's settings and
its equations - the per-frame ones, run each frame, and the per-pixel ones,
run over the whole warp grid at once - read and run on the deck's canvas,
the way MilkDrop draws (Ryan Geiss, 2001): the last frame fed back through
the preset's zoom, rotation, warp, stretch and drift, faded by its decay, the
sound drawn over it as its wave.

    preset = load(path)                    # {"name", "base": {...}, "init": code, "frame": code, "pixel": code}
    draw = look_draw(preset)               # a VJ look's draw(ctx, st)

Approximate by design: the motion, the decay, the wave (its mode, colour,
place, size), the per-frame and per-pixel equations, the q variables, and
the brighten / darken / invert / solarize / gamma flags are run; the custom
shapes and waves, the borders, the motion vectors, the echo, and MilkDrop 2's
warp and composite shaders are left out. Most classic presets read as
themselves, the ones made of shapes or shaders as their motion only.

The equations are MilkDrop's expression language (ns-eel): C-like
statements ended by ';', `=` and `+=`-style assignments, arithmetic and
comparisons, and its functions (sin, cos, pow, sqr, sqrt, abs, sign, min,
max, if, above, below, equal, band, bor, bnot, rand, int, sigmoid ...). They
are parsed into Python - numpy, so a per-pixel equation runs on every point
of the grid in one go.
"""
