"""Work that waits on a device, off the main loop.

Sending a script, the settings, the shape, palettes or the outputs to a
device was done in the button's callback, on the main loop: a device that
did not answer froze the whole studio - the sim, the stream, the UI - for
a timeout of 5 to 10 seconds each, about 35 s for a script to a slow one.
run() does the waiting on a worker and hands the result back to the main
loop, where poll() calls `done` with it - so `done` may touch the UI and the
engine, and `work` must not (it gets what it needs gathered before).

One job a key at a time: the same button pressed again while its job runs
is told so, not queued (a second send of the same thing is no use)."""
# AI: below section was generated by an AI
import queue
import threading
import traceback

_Q = queue.Queue()
_RUNNING = {}                     # key -> what it is doing, while it runs


def busy(key):
    return key in _RUNNING


def run(app, key, what, work, done):
    """`work()` on a worker; on the main loop then `done(result)`, or, when work raised, the error said in the
    footer (and in the frame's log, through `done`'s own messages - it is not called). False when a job of
    this key is running already."""
    if key in _RUNNING:
        app.gp.status(f"{_RUNNING[key]} - still going")
        return False
    _RUNNING[key] = what
    app.gp.status(f"{what}...")

    def go():
        try:
            r = (True, work())
        except Exception as e:                      # a network error, a device answering nonsense: said, not raised
            r = (False, e)
        _Q.put((key, what, done, r))
    threading.Thread(target=go, daemon=True).start()
    return True


def poll(app):
    """Each finished job's `done`, on the main loop."""
    while True:
        try:
            key, what, done, (ok, value) = _Q.get_nowait()
        except queue.Empty:
            return
        _RUNNING.pop(key, None)
        if not ok:
            app.gp.status(f"{what}: failed - {value}", "error")
            continue
        try:
            done(value)
        except Exception:
            traceback.print_exc()                   # one job's display: not the loop's other polls
