"""Errors the studio carries on past, made visible: once per place, in its log.

    try:
        ...
    except Exception:
        oops.swallowed()        # said once for this line, counted after

An `except Exception: pass` hid what went wrong; the review rounds found such failures by reading code.
swallowed() prints the first one at each place (file and line) to the studio's output - the log a report
zips and a test reads - and counts the rest; counts() gives them all (Help > Report a problem puts them in).
It costs a dict lookup after the first, so it is fine in code that runs every frame.
"""
# AI: below section was generated by an AI
import os
import sys
import threading

_SEEN = {}                      # (file, line) -> [count, the first exception's words]
_LOCK = threading.Lock()


def swallowed(note=""):
    """Called in an except block: the exception there said once for this place, and counted."""
    f = sys._getframe(1)
    key = (f.f_code.co_filename, f.f_lineno)
    with _LOCK:
        got = _SEEN.get(key)
        if got is not None:
            got[0] += 1
            return
        e = sys.exc_info()[1]
        words = repr(e).replace("Error:", "Error -")[:200] if e is not None else "(no exception)"
        _SEEN[key] = [1, words]
    where = f"{os.path.basename(key[0])}:{key[1]} ({f.f_code.co_name})"
    try:
        print(f"carried on at {where}: {words}" + (f" - {note}" if note else ""), flush=True)
    except Exception:           # a console that cannot print it (closed, or the wrong encoding): still counted
        pass


def counts():
    """Every place an error was carried on past: 'file:line count first-words', the most frequent first."""
    with _LOCK:
        rows = sorted(_SEEN.items(), key=lambda kv: -kv[1][0])
    return [f"{os.path.basename(k[0])}:{k[1]} x{v[0]} {v[1]}" for k, v in rows]
