"""The phone remote's side in the studio (native/phone.py is the server and
the page): its row in the MIDI, OSC and phone window, and each frame on the main
thread the page's commands applied and the state it shows published.

    phone_ui.build_row(app)       # in the MIDI, OSC and phone window, under OSC
    phone_ui.poll(app)            # each frame, beside midi_ui.poll

The setting is the studio's, not a project's (prefs "phone": on, port and
the key), so the link a phone keeps works whichever project is open. The
page drives what MIDI drives - the sliders and checks of the effect on
screen, the effect (next and previous step through the setlist, as MIDI's
do), the palette - through midi_ui's own paths, and the Sequence's show:
play, stop, a step tapped plays from it. Its brightness is the studio's
master (app.master_bri, 0..255, and a blackout): the picture every view
and the stream read is dimmed by it (Features._seq_dim). Served over HTTPS
(prefs "https", on when the cryptography package is there), its Camera page
sends the phone's camera to the studio - the VIDEO section's "the phone's
camera" and the mapping window's camera list read it (video.PhoneSource).
"""
