import time

import dearpygui.dearpygui as dpg

from native import phone, phone_tls, midi
from native.typeface import px
from native import typeface

PUBLISH_S = 0.25                 # the state the page reads, made again at most this often


def _c():
    from native import chrome
    return chrome


def _st(app):
    st = app.prefs.setdefault("phone", {})
    st.setdefault("on", False)
    st.setdefault("port", phone.DEFAULT_PORT)
    st.setdefault("https", phone_tls.available())     # a phone's browser offers the camera only over HTTPS
    if not st.get("key"):
        st["key"] = phone.new_key()
    return st


def _save(app):
    from native.project import save_prefs
    save_prefs(app.prefs)


def build_row(app):
    """The PHONE row: on, the port, the link to open on the phone, a new key."""
    c = _c()
    app.phone = phone.PhoneRemote()
    app._phone_error = ""
    app._phone_at = 0.0
    with dpg.group(horizontal=True):
        typeface.label(dpg.add_text("PHONE", color=c.ACCENT))
        dpg.add_checkbox(label="serve a remote page on port", tag="phone_on", default_value=False,
                         callback=lambda s, v: set_on(app, v))
        c.tip("a page for a phone or a tablet on this network: the effect, its settings, the palette, a master "
              "brightness and blackout, and the show - for running it away from the desk. The link below has a "
              "key, so a machine without it cannot use the page; it is off until turned on here")
        typeface.mono(dpg.add_input_int(tag="phone_port", width=px(90), default_value=int(_st(app)["port"]), min_value=1,
                                        max_value=65535, min_clamped=True, max_clamped=True, step=0, on_enter=True,
                                        callback=lambda s, v: set_port(app, int(v))))
        c.tip("the TCP port the page is served on; Enter to serve there")
        dpg.add_checkbox(label="HTTPS", tag="phone_https", default_value=bool(_st(app)["https"]),
                         callback=lambda s, v: set_https(app, v))
        c.tip("served over HTTPS, with a certificate the studio makes itself: a phone's browser offers its camera "
              "only so (the remote page's Camera link). The first time, the browser warns that it does not know the "
              "certificate: Advanced, then go on to the address")
        dpg.add_button(label="New key", tag="phone_rekey", callback=lambda: new_key(app))
        c.tip("a new key for the link: a phone with the old link cannot use the page any more")
    with dpg.group(horizontal=True):
        dpg.add_spacer(width=px(58))
        typeface.mono(dpg.add_input_text(tag="phone_url", width=px(380), readonly=True, default_value=""))
        c.tip("open this on the phone (on the same network); select it to copy")
        dpg.add_text("", tag="phone_state", color=c.DIM)


def open_saved(app):
    """The remote as the studio's settings have it - on as the studio starts when it was left on."""
    st = _st(app)
    if dpg.does_item_exist("phone_on"):
        dpg.set_value("phone_on", bool(st["on"]))
        dpg.set_value("phone_https", bool(st["https"]))
    _open(app, quiet=True)


def set_on(app, on):
    _st(app)["on"] = bool(on)
    _save(app)
    _open(app)


def set_https(app, on):
    _st(app)["https"] = bool(on)
    _save(app)
    _open(app)


def set_port(app, port):
    _st(app)["port"] = max(1, min(65535, int(port)))
    _save(app)
    _open(app)


def new_key(app):
    _st(app)["key"] = phone.new_key()
    _save(app)
    _open(app)


def _open(app, quiet=False):
    st = _st(app)
    app.phone.close()
    app._phone_error = ""
    if st["on"]:
        try:
            app.phone.open(int(st["port"]), st["key"], str(st.get("host") or "0.0.0.0"), tls=bool(st["https"]))
            if not quiet:
                app.gp.status(f"phone remote: {app.phone.url()}")
        except ValueError as e:                              # HTTPS asked, and no cryptography package
            app._phone_error = str(e)
            app.gp.status(f"phone remote: {e}", "warn")
        except (OSError, OverflowError) as e:
            app._phone_error = f"port {st['port']} cannot be opened ({getattr(e, 'strerror', None) or e})"
            app.gp.status(f"phone remote: {app._phone_error}", "warn")
    elif not quiet:
        app.gp.status("phone remote: off")
    _words(app)


def _words(app):
    if not dpg.does_item_exist("phone_url"):
        return
    r = getattr(app, "phone", None)
    dpg.set_value("phone_url", r.url() if r is not None and r.is_open else "")
    if app._phone_error:
        txt = app._phone_error
    elif r is not None and r.is_open:
        ago = time.time() - r.last if r.last else None
        txt = ("a phone asked " + (f"{int(ago)} s ago" if ago < 120 else "a while ago")) if ago is not None else "waiting for a phone"
        cam = phone.CAMERA.age()
        if cam is not None and cam < 2:
            txt += " - its camera is sending"
    else:
        txt = "off"
    dpg.set_value("phone_state", txt)


