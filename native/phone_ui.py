def poll(app):
    r = getattr(app, "phone", None)
    if r is None:
        return
    if not getattr(app, "_phone_started", False):
        app._phone_started = True                          # left on: served again as the studio starts
        open_saved(app)
    if not r.is_open:
        return
    for cmd in r.drain():
        try:
            apply(app, cmd)
        except Exception as e:                              # one command the studio could not take: said, not raised
            app.gp.status(f"phone remote: {cmd.get('a')}: {e}", "warn")
    now = time.monotonic()
    if now - app._phone_at >= PUBLISH_S:
        app._phone_at = now
        r.publish(state(app))
        if dpg.does_item_exist("phone_state") and dpg.is_item_visible("phone_state"):
            _words(app)


def apply(app, cmd):
    """One checked command from the page (phone.check) onto the studio."""
    from native import midi_ui, sequence_ui
    a = cmd["a"]
    if a == "fx":
        midi_ui.apply_target(app, {"kind": "fx", "key": cmd["k"]}, cmd["v"], 1.0)
    elif a == "check":
        midi_ui.apply_target(app, {"kind": "check", "key": cmd["k"]}, cmd["v"], 1.0)
    elif a == "effect":
        midi_ui.switch_effect(app, cmd["v"])
    elif a in ("next", "prev"):
        midi_ui.switch_effect(app, midi.step_effect(app.eng.names, midi_ui._st(app)["setlist"], app.eng.names[app.eng.idx],
                                                    1 if a == "next" else -1))
    elif a == "palette":
        names = dict(app.eng.palette_list())
        if cmd["v"] in names and names[cmd["v"]] != app.eng.pal:
            app.on_palette(None, cmd["v"])
            if dpg.does_item_exist("pal_combo"):
                dpg.set_value("pal_combo", cmd["v"])
    elif a in ("vj", "vjfader", "vjlevel", "vjlook"):    # the VJ frame's (vj.py)
        from native import vj, vj_ui
        if a == "vjfader":
            vj.set_fader(app, cmd["v"])
        elif a == "vjlevel":
            vj.knob_set(app, cmd["d"], "level", cmd["v"])
            vj_ui._save(app)                             # saved once it settles: a drag on the phone one undo step
        elif a == "vjlook":
            if cmd["v"] in vj_ui.look_names():
                vj.options(app)["decks"][cmd["d"]]["look"] = cmd["v"]
                app._vj_dirty = True
                vj_ui._save(app)
        elif cmd["k"] == "cut":
            vj.launch(app, 0.0)
        elif cmd["k"] == "fade":
            vj.launch(app, vj.FADE_BEATS * 60.0 / vj._tempo(app))
        elif cmd["k"].startswith("c_"):
            vj.c_launch(app, cmd["k"][2:])
        elif cmd["k"] == "air":
            vj_ui.set_on(app, not vj.on(app))
        else:
            vj.shuffle(app, 0 if cmd["k"] == "shuffle_a" else 1)
    elif a == "fader":                                   # the mixer's, 0 (deck A) to 1 (deck B)
        from native import mixer
        mixer.set_fader(app, cmd["v"])
    elif a == "bri":
        app.master_bri = int(max(0, min(255, round(cmd["v"]))))
    elif a == "blackout":
        app.blackout = bool(cmd["v"])
    elif a == "play":
        if getattr(app, "_seq_play", None) is None:
            sequence_ui.play(app, getattr(app, "_seq_sel", 0))
        elif app._seq_play.get("paused") is not None:
            sequence_ui.play_pause(app)                     # paused: on from where it was
    elif a == "stop":
        sequence_ui.stop(app)
    elif a == "step":
        n = len(sequence_ui._steps(app)["steps"])
        i = int(cmd["v"])
        if 0 <= i < n:
            app._seq_sel = i
            sequence_ui.play(app, i)                        # a step tapped is a cue: the show from there


def state(app):
    """What the page shows: the effect and the list, its sliders and checks by their own names, the palette,
    the master brightness, the show's steps and where it is."""
    from native import midi_ui, sequence_ui
    eng = app.eng
    labels = midi_ui._fx_labels(app)
    m = eng.meta[eng.idx] if eng.meta else {"labels": []}
    sliders = []
    for i, k in enumerate(midi.FX_KEYS):
        lab = (m["labels"][i] if i < len(m["labels"]) else "").strip()
        if lab and lab != "!":
            sliders.append({"k": k, "label": labels[k], "kind": "fx", "max": 31 if k == "c3" else 255,
                            "v": int(eng.fx.get(k, 0))})
    for i, k in enumerate(midi.CHECK_KEYS):
        if 5 + i < len(m["labels"]) and m["labels"][5 + i].strip():
            sliders.append({"k": k, "label": labels[k], "kind": "check", "v": int(bool(eng.fx.get(k)))})
    pals = eng.palette_list()
    pal = next((n for n, i in pals if i == eng.pal), "")
    S = sequence_ui._steps(app)
    play = getattr(app, "_seq_play", None)
    import os
    return {"project": os.path.basename(app.project.path.rstrip("/\\")),
            "effects": list(eng.names), "effect": eng.names[eng.idx] if eng.names else "",
            "sliders": sliders, "palettes": [n for n, _ in pals], "palette": pal,
            "bri": int(getattr(app, "master_bri", 255)), "blackout": bool(getattr(app, "blackout", False)),
            "vj": _vj_state(app),
            "mixer": {"on": __import__("native.mixer", fromlist=["m"]).on(app),
                      "fader": float(__import__("native.mixer", fromlist=["m"]).options(app)["fader"])},
            "steps": [str(s.get("name") or f"step {i + 1}") for i, s in enumerate(S["steps"])],
            "step": play["i"] if play else getattr(app, "_seq_sel", -1),
            "playing": bool(play) and play.get("paused") is None}


def _vj_state(app):
    """The VJ card's: whether the frame is open, on air, the fader, each deck's look and level, the looks to pick."""
    from native import vj, vj_ui
    o = vj.options(app)
    return {"open": bool(getattr(app, "_vj_open", False)), "on": vj.on(app), "fader": float(o["fader"]),
            "decks": [{"look": d["look"], "level": float(d.get("level", 1.0))} for d in o["decks"]],
            "looks": vj_ui.look_names()}
