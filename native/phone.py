import hmac
import json
import secrets
import socket
import threading
import time
from collections import deque
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

DEFAULT_PORT = 8765
MAX_BODY = 4096                      # a command is a few dozen bytes
MAX_QUEUE = 256                      # commands waiting for the main thread at most: a flood is dropped, oldest first
ACTIONS = {"fx", "check", "effect", "palette", "bri", "blackout", "play", "stop", "step", "next", "prev"}


def new_key():
    """A key for the link: 8 characters a phone can show and a person could type."""
    return secrets.token_urlsafe(6)


def lan_address():
    """This machine's address on the local network, as a phone sees it; 127.0.0.1 when there is none. A UDP
    socket "connected" toward a public address picks the interface - no packet is sent."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("192.0.2.1", 9))           # TEST-NET-1: never routed, and connect() sends nothing
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


def check(cmd):
    """A command from the page made safe, or None: {"a": action, "k": slider key, "v": number or name}."""
    if not isinstance(cmd, dict) or cmd.get("a") not in ACTIONS:
        return None
    out = {"a": cmd["a"]}
    if cmd["a"] in ("fx", "check"):
        if cmd.get("k") not in ("sx", "ix", "c1", "c2", "c3", "o1", "o2", "o3"):
            return None
        out["k"] = cmd["k"]
    if cmd["a"] in ("fx", "check", "bri", "step", "blackout"):
        try:
            v = float(cmd.get("v", 0))
        except (TypeError, ValueError):
            return None
        if v != v:
            return None
        out["v"] = v
    if cmd["a"] in ("effect", "palette"):
        v = cmd.get("v")
        if not isinstance(v, str) or not v or len(v) > 200:
            return None
        out["v"] = v
    return out


class PhoneRemote:
    def __init__(self):
        self.key = None
        self.port = None
        self._srv = None
        self._q = deque(maxlen=MAX_QUEUE)
        self._lock = threading.Lock()
        self._state = b"{}"
        self.served = 0                       # requests answered, for the window's line
        self.last = None                      # when a phone last asked (time.time())

    # --- the main thread's side ---------------------------------------------------------------
    def open(self, port=DEFAULT_PORT, key=None, host="0.0.0.0"):
        """Serve on `port` (0: any free one) with `key`. Raises OSError when the port is taken."""
        self.close()
        self.key = key or new_key()
        srv = ThreadingHTTPServer((host, int(port)), _handler(self))
        srv.daemon_threads = True
        self._srv, self.port = srv, srv.server_address[1]
        threading.Thread(target=srv.serve_forever, kwargs={"poll_interval": 0.25}, daemon=True, name="phone").start()
        return self.port

    def close(self):
        srv, self._srv, self.port = self._srv, None, None
        if srv is not None:
            try:
                srv.shutdown()
                srv.server_close()
            except OSError:
                pass

    @property
    def is_open(self):
        return self._srv is not None

    def url(self, address=None):
        return f"http://{address or lan_address()}:{self.port}/?k={self.key}" if self.is_open else ""

    def publish(self, state):
        data = json.dumps(state, separators=(",", ":")).encode("utf-8")
        with self._lock:
            self._state = data

    def drain(self):
        with self._lock:
            out = list(self._q)
            self._q.clear()
        return out

    # --- the server's threads ------------------------------------------------------------------
    def _state_bytes(self):
        with self._lock:
            return self._state

    def _queue(self, cmds):
        with self._lock:
            self._q.extend(cmds)

    def _key_ok(self, given):
        return bool(self.key) and isinstance(given, str) and hmac.compare_digest(given, self.key)


def _handler(remote):
    class Handler(BaseHTTPRequestHandler):
        server_version = "WLEDEffectsStudio"

        def log_message(self, *a):            # quiet: the studio's console is not the server's log
            pass

        def _send(self, code, body, ctype="application/json"):
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("X-Content-Type-Options", "nosniff")
            if ctype.startswith("text/html"):
                self.send_header("Content-Security-Policy", "default-src 'none'; script-src 'unsafe-inline'; "
                                 "style-src 'unsafe-inline'; connect-src 'self'")
            self.end_headers()
            self.wfile.write(body)

        def _key(self):
            q = parse_qs(urlparse(self.path).query)
            return (q.get("k") or [""])[0]

        def do_GET(self):
            path = urlparse(self.path).path
            if not remote._key_ok(self._key()):
                self._send(403, b"this link needs the key the studio shows (Window > MIDI, OSC and phone)", "text/plain; charset=utf-8")
                return
            remote.served += 1
            remote.last = time.time()
            if path == "/":
                self._send(200, PAGE.encode("utf-8"), "text/html; charset=utf-8")
            elif path == "/state":
                self._send(200, remote._state_bytes())
            else:
                self._send(404, b"{}")

        def do_POST(self):
            if urlparse(self.path).path != "/act" or not remote._key_ok(self._key()):
                self._send(403, b"{}")
                return
            try:
                n = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                n = -1
            if not 0 < n <= MAX_BODY:
                self._send(413, b"{}")
                return
            try:
                got = json.loads(self.rfile.read(n).decode("utf-8"))
            except (ValueError, UnicodeError):
                self._send(400, b"{}")
                return
            cmds = [c for c in (check(x) for x in (got if isinstance(got, list) else [got])[:16]) if c]
            remote._queue(cmds)
            remote.served += 1
            self._send(200, json.dumps({"taken": len(cmds)}).encode())
    return Handler


