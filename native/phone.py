def _stdlib_context():
    """ssl's own SSLContext: a package can put another in its place (pip's truststore, injected), one that checks
    the peer's certificate even on a server's side and so drops every phone, which sends none."""
    return next((c for c in ssl.SSLContext.__mro__ if c.__module__ == "ssl" and c.__name__ == "SSLContext"),
                ssl.SSLContext)


class _Server(ThreadingHTTPServer):
    daemon_threads = True
    ssl_ctx = None

    def finish_request(self, request, client_address):
        # TLS is set up here, on the request's own thread: in the accepting thread a phone that stalls in the
        # handshake would stop every other one
        if self.ssl_ctx is None:
            return super().finish_request(request, client_address)
        request.settimeout(HANDSHAKE_S)
        try:
            conn = self.ssl_ctx.wrap_socket(request, server_side=True)
        except (OSError, ssl.SSLError):
            return                                # a browser that does not trust the certificate yet, or no TLS
        try:
            self.RequestHandlerClass(conn, client_address, self)
        finally:
            try:
                conn.close()
            except OSError:
                pass


class PhoneRemote:
    def __init__(self):
        self.key = None
        self.port = None
        self._srv = None
        self._q = deque(maxlen=MAX_QUEUE)
        self._lock = threading.Lock()
        self._state = b"{}"
        self.served = 0                       # requests answered, for the window's line
        self.last = None                      # when a phone last asked (time.time())
        self.tls = False
        self.camera = CAMERA

    # --- the main thread's side ---------------------------------------------------------------
    def open(self, port=DEFAULT_PORT, key=None, host="0.0.0.0", tls=False):
        """Serve on `port` (0: any free one) with `key`, over HTTPS with `tls`. Raises OSError when the port is
        taken, ValueError when HTTPS was asked and cannot be (no cryptography package)."""
        self.close()
        ctx = None
        if tls:
            from native import phone_tls
            pair = phone_tls.ensure([lan_address()])
            if pair is None:
                raise ValueError("HTTPS needs the cryptography package (pip install cryptography)")
            ctx = _stdlib_context()(ssl.PROTOCOL_TLS_SERVER)
            ctx.load_cert_chain(*pair)
        self.key = key or new_key()
        srv = _Server((host, int(port)), _handler(self))
        srv.ssl_ctx = ctx
        self.tls = ctx is not None
        self._srv, self.port = srv, srv.server_address[1]
        threading.Thread(target=srv.serve_forever, kwargs={"poll_interval": 0.25}, daemon=True, name="phone").start()
        return self.port

    def close(self):
        srv, self._srv, self.port = self._srv, None, None
        if srv is not None:
            try:
                srv.shutdown()
                srv.server_close()
            except OSError:
                pass

    @property
    def is_open(self):
        return self._srv is not None

    def url(self, address=None):
        return (f"{'https' if self.tls else 'http'}://{address or lan_address()}:{self.port}/?k={self.key}"
                if self.is_open else "")

    def camera_url(self, address=None):
        return self.url(address).replace("/?k=", "/camera?k=", 1)

    def publish(self, state):
        data = json.dumps(state, separators=(",", ":")).encode("utf-8")
        with self._lock:
            self._state = data

    def drain(self):
        with self._lock:
            out = list(self._q)
            self._q.clear()
        return out

    # --- the server's threads ------------------------------------------------------------------
    def _state_bytes(self):
        with self._lock:
            return self._state

    def _queue(self, cmds):
        with self._lock:
            self._q.extend(cmds)

    def _key_ok(self, given):
        return bool(self.key) and isinstance(given, str) and hmac.compare_digest(given, self.key)


def _handler(remote):
    class Handler(BaseHTTPRequestHandler):
        server_version = "WLEDEffectsStudio"
        timeout = 30                          # an idle or stalled connection is let go

        def log_message(self, *a):            # quiet: the studio's console is not the server's log
            pass

        def _send(self, code, body, ctype="application/json"):
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("X-Content-Type-Options", "nosniff")
            if ctype.startswith("text/html"):
                self.send_header("Content-Security-Policy", "default-src 'none'; script-src 'unsafe-inline'; "
                                 "style-src 'unsafe-inline'; connect-src 'self'; media-src 'self' blob: mediastream:")
            self.end_headers()
            self.wfile.write(body)

        def _key(self):
            q = parse_qs(urlparse(self.path).query)
            return (q.get("k") or [""])[0]

        def do_GET(self):
            path = urlparse(self.path).path
            if not remote._key_ok(self._key()):
                self._send(403, b"this link needs the key the studio shows (Window > MIDI, OSC and phone)", "text/plain; charset=utf-8")
                return
            remote.served += 1
            remote.last = time.time()
            if path == "/":
                self._send(200, PAGE.encode("utf-8"), "text/html; charset=utf-8")
            elif path == "/camera":
                self._send(200, CAMERA_PAGE.encode("utf-8"), "text/html; charset=utf-8")
            elif path == "/pads":
                self._send(200, PADS_PAGE.encode("utf-8"), "text/html; charset=utf-8")
            elif path == "/state":
                self._send(200, remote._state_bytes())
            else:
                self._send(404, b"{}")

        def do_POST(self):
            path = urlparse(self.path).path
            if path not in ("/act", "/cam") or not remote._key_ok(self._key()):
                self._send(403, b"{}")
                return
            try:
                n = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                n = -1
            if not 0 < n <= (MAX_FRAME if path == "/cam" else MAX_BODY):
                self._send(413, b"{}")
                return
            if path == "/cam":
                try:
                    remote.camera.put(self.rfile.read(n))
                except ValueError:
                    self._send(400, b"{}")
                    return
                remote.last = time.time()
                self._send(200, json.dumps({"n": remote.camera.count}).encode())
                return
            try:
                got = json.loads(self.rfile.read(n).decode("utf-8"))
            except (ValueError, UnicodeError):
                self._send(400, b"{}")
                return
            cmds = [c for c in (check(x) for x in (got if isinstance(got, list) else [got])[:16]) if c]
            remote._queue(cmds)
            remote.served += 1
            self._send(200, json.dumps({"taken": len(cmds)}).encode())
    return Handler


