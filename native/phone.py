"""The phone remote: a page on the local network that runs the studio from a
phone or a tablet - the effect, its sliders and checks, the palette, a
master brightness with a blackout, and the Sequence's show (play, stop, a
step) - for a show run away from the desk (the feature review's third,
STUDIO.md: LedFx's and Pixelblaze's web pages, Lightjams on an iPad).

    r = PhoneRemote(); r.open(8765)          # serves on its own thread
    r.url()                                  # http://<this machine>:8765/?k=<key>
    for cmd in r.drain(): ...                # taken on the main thread, once a frame
    r.publish(state)                         # what the page shows, set on the main thread
    r.close()

Off until it is turned on (Window > MIDI, OSC and phone: the PHONE row). The page
and every request carry a key - random, kept with the studio's settings,
made again on asking - so a machine on the network that does not have the
link cannot use it; the key is in the link the window shows. Nothing here
touches the studio: the server's threads only queue what the page asked
and read the last state the main thread published (native/phone_ui.py does
both, on the main thread). The page asks for nothing but a fixed set of
actions - no files, no code, no device.
"""
