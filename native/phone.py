DEFAULT_PORT = 8765
MAX_BODY = 4096                      # a command is a few dozen bytes
MAX_QUEUE = 256                      # commands waiting for the main thread at most: a flood is dropped, oldest first
MAX_FRAME = 512 * 1024               # a camera frame: a 640-wide JPEG is 30-80 KB
MAX_PIXELS = 4096 * 4096             # a frame's size as its header says, checked before it is decoded
FRAME_W = 640                        # frames kept at most this wide: the video and mapping read far less
HANDSHAKE_S = 10                     # a connection that does not finish its TLS handshake in this is dropped
ACTIONS = {"fx", "check", "effect", "palette", "bri", "blackout", "play", "stop", "step", "next", "prev", "fader", "vj", "vjfader",
           "vjlevel", "vjlook", "pad", "padbank"}
PAD_EVENTS = ("down", "move", "up", "hold")      # the pads page's: a finger on, moved, off; "hold" says it is still on
VJ_KEYS = ("cut", "fade", "shuffle_a", "shuffle_b", "air", "c_in", "c_out", "c_flash")   # the VJ card's buttons


def new_key():
    """A key for the link: 8 characters a phone can show and a person could type."""
    return secrets.token_urlsafe(6)


def lan_address():
    """This machine's address on the local network, as a phone sees it; 127.0.0.1 when there is none. A UDP
    socket "connected" toward a public address picks the interface - no packet is sent."""
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("192.0.2.1", 9))           # TEST-NET-1: never routed, and connect() sends nothing
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


def _unit(v):
    """A number from the page as 0..1, or None (missing, not a number, NaN)."""
    try:
        v = float(v)
    except (TypeError, ValueError):
        return None
    return None if v != v else max(0.0, min(1.0, v))


def check(cmd):
    """A command from the page made safe, or None: {"a": action, "k": slider key, "v": number or name}; a pad's
    {"a": "pad", "id": control, "e": event, "f"/"x"/"y"/"p": 0..1 where given}; {"a": "padbank", "v": index}."""
    if not isinstance(cmd, dict) or cmd.get("a") not in ACTIONS:
        return None
    out = {"a": cmd["a"]}
    if cmd["a"] in ("pad", "padbank"):
        try:
            n = int(cmd.get("id" if cmd["a"] == "pad" else "v", -1))
        except (TypeError, ValueError):
            return None
        if not 0 <= n < 1 << 30:
            return None
        if cmd["a"] == "padbank":
            return {"a": "padbank", "v": n}
        if cmd.get("e") not in PAD_EVENTS:
            return None
        out.update(id=n, e=cmd["e"])
        for k in ("f", "x", "y", "p"):
            if k in cmd:
                u = _unit(cmd[k])
                if u is None:
                    return None
                out[k] = u
        return out
    if cmd["a"] in ("fx", "check"):
        if cmd.get("k") not in ("sx", "ix", "c1", "c2", "c3", "o1", "o2", "o3"):
            return None
        out["k"] = cmd["k"]
    if cmd["a"] == "vj":
        if cmd.get("k") not in VJ_KEYS:
            return None
        out["k"] = cmd["k"]
    if cmd["a"] in ("vjlevel", "vjlook"):                     # a deck's: A, B or C
        try:
            d = int(cmd.get("d", -1))
        except (TypeError, ValueError):
            return None
        if d not in (0, 1, 2):
            return None
        out["d"] = d
    if cmd["a"] in ("fx", "check", "bri", "step", "blackout", "fader", "vjfader", "vjlevel"):
        try:
            v = float(cmd.get("v", 0))
        except (TypeError, ValueError):
            return None
        if v != v:
            return None
        out["v"] = v
    if cmd["a"] in ("effect", "palette", "vjlook"):
        v = cmd.get("v")
        if not isinstance(v, str) or not v or len(v) > 200:
            return None
        out["v"] = v
    return out


class CameraHub:
    """The phone camera's newest frame: put() on a server thread, newest() anywhere."""

    def __init__(self):
        self._lock = threading.Lock()
        self._img = None
        self.count = 0
        self.t = 0.0                          # when the last frame came (time.monotonic())

    def put(self, data):
        """A JPEG from the page, decoded and kept; ValueError when it is not one or is too big."""
        from PIL import Image
        try:
            img = Image.open(io.BytesIO(data))
            if img.format != "JPEG":
                raise ValueError("not a JPEG")
            if img.size[0] * img.size[1] > MAX_PIXELS:
                raise ValueError("too big")
            img.draft("RGB", (FRAME_W, FRAME_W))  # a JPEG decoded at a fraction of its size where it can
            img = img.convert("RGB")
        except (OSError, SyntaxError, Image.DecompressionBombError) as e:
            raise ValueError(str(e)) from None
        if img.width > FRAME_W:
            img = img.resize((FRAME_W, max(1, round(img.height * FRAME_W / img.width))), Image.BILINEAR)
        with self._lock:
            self._img = img
            self.count += 1
            self.t = time.monotonic()

    def newest(self):
        with self._lock:
            return self._img, self.count

    def age(self):
        """Seconds since the last frame; None when none came."""
        return time.monotonic() - self.t if self.count else None


