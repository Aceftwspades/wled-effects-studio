def _same(a, b):
    if a is None or b is None or len(a) != len(b) or len(a[4]) != len(b[4]):
        return False
    return all(x is y for x, y in zip(a[:4], b[:4])) and all(
        x is y for p, q in zip(a[4], b[4]) for x, y in zip(p, q))


