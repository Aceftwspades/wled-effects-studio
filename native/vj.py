def _open(app, s, key):
    """A source opened for its key (on a worker: _open_soon) - the file's path and the canvas from the key, so
    it reads nothing of the app's that the main loop changes."""
    from native import video
    kind = s["kind"]
    if kind == "file":
        import os
        path, w, h = key[1], key[5], key[6]
        if not path or not os.path.exists(path):
            raise ValueError(f"no video file at {path}" if path else "no video file chosen")
        args = []
        sp = max(0.1, min(8.0, float(s.get("speed", 1.0))))
        if abs(sp - 1.0) > 1e-3:
            args += ["-itsscale", f"{1.0 / sp:.6f}"]               # the clip's own time scaled: faster or slower
        a, b = float(s.get("in", 0.0)), float(s.get("out", 0.0))
        if a > 0:
            args += ["-ss", f"{a:.3f}"]
        if b > a:
            args += ["-t", f"{(b - a) / sp:.3f}"]                # -t counts the scaled time: Out where it was set
        dec, has_alpha = video.alpha_of(path)                 # a file with transparency: read as RGBA, kept
        whole = bool(key[FILE_KEY_WHOLE])                     # fit or tile: the whole picture, clear bars round it
        cut = a > 0 or b > a                                  # In/Out: run again from In each time (not -stream_loop)
        once = bool(s.get("once"))                            # a pad's one shot: played through once, then it ends
        return video.FfmpegSource(args + dec + ["-i", path], os.path.basename(path), "file", w, h, realtime=True,
                                  loop=not cut and not once, rerun=cut and not once, fps=video.FILE_FPS, alpha=has_alpha or whole, fit=whole)
    w, h = key[4], key[5]
    return video.open_source(kind, path=s.get("url") if kind == "stream" else s.get("path"), name=s.get("name"),
                             width=w, height=h, loop=True)


def _source(app, i, run, deck):
    """The deck's video source - the one open for its key, shared, or None while it opens on a worker (the last
    picture held meanwhile)."""
    s = deck["source"]
    key = source_key(app, s, whole_picture(deck))
    pool = _pool(app)
    if key != run.src_key:
        run.src_key = key
        run.video_prev = None                                 # its last frame held until the next source's first
        run.n = -1
        vj_state.of(app).release_due = True                            # (closed at the frame's end, every deck's key set)
    if key is None:
        run.video = None
        run.open_error = ""
        return None
    now = time.monotonic()
    tried = vj_state.of(app).pool_at       # key -> [when it was opened, the wait before again]
    ent, t = pool.get(key), tried.get(key)
    if ent is not None and t is not None and now - t[0] >= t[1] and _dead(ent[0]) and not s.get("take"):
        # (a pad's clip that ended or would not open is not opened again: its last picture held till it is let go)
        # failed to open (a file copied in since), or a stream or webcam that dropped: tried again, the last
        # picture held meanwhile - after REOPEN_S, twice as long each time it fails again (up to REOPEN_MAX_S;
        # one that showed pictures before it stopped: REOPEN_S again)
        _drop_dead(app, key)
        for r in _all_runs(app):
            if r.src_key == key:
                r.n = -1
    if key not in pool:
        if clock.held():                                      # a render: opened here, so no frame it draws is
            got = _wait_opening(app, key)                     # without its picture (the same each render) - one
            if got is not None:                               # a worker is opening waited for, not opened twice
                pool[key] = got
            else:
                tried[key] = [now, tried.get(key, [0, REOPEN_S])[1]]
                try:
                    pool[key] = [_open(app, s, key), ""]
                except Exception as e:
                    pool[key] = [None, str(e)]
        else:
            _open_soon(app, s, key)
            run.open_error = ""
            return None
    src, err = pool[key]
    run.open_error = err
    return src


REOPEN_S = 3.0                    # a source that failed or ended: opened again after this, then
REOPEN_MAX_S = 30.0               # twice as long each time it fails again, up to this
_OPEN_LOCK = threading.Lock()     # a worker's finished source handed over / the VJ closed: one at a time


def _drop_dead(app, key):
    """A dead source out of the pool, to be opened again - its next wait twice as long (REOPEN_S again for one
    that had shown pictures)."""
    pool, tried = _pool(app), vj_state.of(app).pool_at
    ent = pool.pop(key, None)
    t = tried.get(key)
    if t is not None:
        t[1] = REOPEN_S if getattr(ent and ent[0], "n", 0) else min(REOPEN_MAX_S, t[1] * 2)
    if ent and ent[0] is not None:
        try:
            ent[0].close()
        except Exception:
            oops.swallowed()


def _open_soon(app, s, key):
    """Key's source opened on a worker - ffmpeg asked for the cameras, a file probed, a process started: a tenth
    of a second to seconds, never on the main loop (each frame of it was the studio and the stream stopped). The
    result goes in the pool at the next frame's _collect - closed instead if nothing wants it by then, or if the
    VJ closed meanwhile."""
    opening = vj_state.of(app).opening    # key -> the generation it was started in
    if key in opening:
        return                                                # (one from before a close too: it ends first)
    gen = vj_state.of(app).gen
    opening[key] = gen
    tried = vj_state.of(app).pool_at
    tried[key] = [time.monotonic(), tried.get(key, [0, REOPEN_S])[1]]
    s = json_copy(s)

    def work():
        try:
            got = [_open(app, s, key), ""]
        except Exception as e:
            got = [None, str(e)]
        with _OPEN_LOCK:
            if vj_state.of(app).gen == gen:
                vj_state.of(app).opened[key] = got
                return
            if opening.get(key) == gen:                       # the VJ closed while it opened: not kept, and
                del opening[key]                              # opened again only now it is closed
        if got[0] is not None:
            got[0].close()
    threading.Thread(target=work, daemon=True, name="vj source").start()


OPEN_WAIT_S = 15.0                # a render waits this long at most for a source a worker is opening


def _wait_opening(app, key):
    """A source a worker is opening, waited for (a render): its [source, error], or None when none is opening it."""
    if key not in vj_state.of(app).opening:
        return None
    end = time.monotonic() + OPEN_WAIT_S
    while time.monotonic() < end:
        with _OPEN_LOCK:
            got = vj_state.of(app).opened.pop(key, None)
            if got is not None:
                vj_state.of(app).opening.pop(key, None)
                return got
        if key not in vj_state.of(app).opening:
            return None                                     # (its worker's from before a close: closed it)
        time.sleep(0.005)
    return None


def _collect(app):
    """Each frame: the sources the workers opened, put in the pool - one nothing wants any more (its deck moved
    on, its pad re-pointed) closed, not left running with its webcam on."""
    with _OPEN_LOCK:
        done = vj_state.of(app).take("opened")
    if not done:
        return
    pool, opening, used = _pool(app), vj_state.of(app).opening, _used(app)
    for key, got in done.items():
        opening.pop(key, None)
        if key in used and key not in pool:
            pool[key] = got
            for r in _all_runs(app):
                if r.src_key == key:
                    r.n = -1
        elif got[0] is not None:
            try:
                got[0].close()
            except Exception:
                oops.swallowed()


def _dead(src):
    """Whether a pooled source is no source: it did not open, or its reader stopped (ffmpeg ended or failed)."""
    if src is None:
        return True
    t = getattr(src, "thread", None)
    if t is None:                                             # a web video: its page did not resolve, or its ffmpeg
        inner = getattr(src, "_src", None)                    # stopped
        return getattr(src, "error", None) is not None and (inner is None or _dead(inner))
    return not t.is_alive() and getattr(src, "error", None) is not None


def _used(app):
    """The source keys something wants: a deck's, the pads' cameras, and a deck's own under a pad's clip (rolling
    on under it, there again when it ends)."""
    used = {r.src_key for r in _all_runs(app)} | set(vj_state.of(app).cam_keys)
    for i, d in enumerate(options(app)["decks"]):
        if i == 2 and vj_clips.level(app, i) is not None:     # (A and B draw their own under theirs)
            used.add(source_key(app, d["source"], whole_picture(d)))
    used.discard(None)
    return used


def _release(app):
    """Sources nothing looks at any more, closed."""
    pool, used = _pool(app), _used(app)
    for key in [k for k in pool if k not in used]:
        vj_state.of(app).pool_at.pop(key, None)
        src = pool.pop(key)[0]
        if src is not None:
            try:
                src.close()
            except Exception:
                oops.swallowed()


CAM_CHECK_TICKS = 30              # the pads' cameras looked over this often (frames)


def _warm_cams(app):
    """The cameras the pads bring up kept open while the VJ runs (opened on a worker - a camera takes a second
    or so to start - so a press shows its picture at once); one that failed or dropped tried again, as a deck's
    is; one no pad uses any more closed."""
    if vj_state.of(app).tick % CAM_CHECK_TICKS:
        return
    pool = _pool(app)
    tried, now = vj_state.of(app).pool_at, time.monotonic()
    want = {}
    for name in vj_clips.cam_names(app):
        s = vj_clips.cam_source(name)
        want[source_key(app, s)] = s
    gone = set(vj_state.of(app).cam_keys) - set(want)
    vj_state.of(app).cam_keys = set(want)
    if gone:
        vj_state.of(app).release_due = True
    for key, s in want.items():
        t = tried.get(key)
        if key in pool and _dead(pool[key][0]) and (t is None or now - t[0] >= t[1]):
            _drop_dead(app, key)
        if key not in pool:
            _open_soon(app, s, key)


