_GRID = {}


def _grid(w, h):
    g = _GRID.get((w, h))
    if g is None:
        u, v = np.meshgrid(np.linspace(0, 1, w, dtype=np.float32), np.linspace(0, 1, h, dtype=np.float32))
        x = (u - 0.5) * 2.0 * w / h
        y = (v - 0.5) * 2.0
        g = (u, v, x, y, np.hypot(x, y), np.arctan2(y, x))
        for a in g:                                           # shared by every deck and look: read only (a look's
            a.setflags(write=False)                           # c.x *= 3 grew every deck's grid for good)
        g = _GRID[(w, h)] = g
    return g


def sound(app):
    """(bass, mid, treb, level, wave) of what the effects hear now."""
    eng = app.eng
    try:
        f = np.asarray(eng.fft, np.float32) / 255.0
    except Exception:
        oops.swallowed()
        f = np.zeros(16, np.float32)
    bass, mid, treb = float(f[0:3].mean()), float(f[4:9].mean()), float(f[10:16].mean())
    vol = float(getattr(eng, "last_audio", (0.0, 0))[0])
    level = min(1.0, vol / 255.0) if vol > 1.0 else min(1.0, vol)
    pcm = getattr(eng, "last_pcm", None)
    if pcm is not None and len(pcm) >= 16:
        wave = np.asarray(pcm, np.float32)[:: max(1, len(pcm) // 64)][:64] / 127.0
    else:                                                     # no waveform: one drawn from the bands
        t = clock.now()
        k = np.arange(64, dtype=np.float32) / 64.0
        wave = sum(f[j] * np.sin(2 * np.pi * k * (j + 1) + t * (2 + j)) for j in range(0, 16, 3)) * 0.6
    return bass, mid, treb, level, np.asarray(wave, np.float32)


# --- the map onto the shape ----------------------------------------------------------------------
_MAP = {}


def mapping(geom, rows, cols, mode):
    """(u, v) on the canvas for every pixel of the logical grid, (rows*cols,) each, and the lit mask: the
    Video node's projections (nodedefs.py), made once for a geometry and a mode."""
    key = (id(geom), rows, cols, mode)
    got = _MAP.get(key)
    if got is not None and got[0] is geom:                    # the same geometry (not another given its id since)
        return got[1]
    n = rows * cols
    lit = np.ones(n, bool) if geom is None or geom.lit is None or len(geom.lit) != n else np.asarray(geom.lit, bool)
    cu, cv = np.meshgrid(np.linspace(0, 1, cols), np.linspace(0, 1, rows))
    u, v = cu.ravel().astype(np.float32), cv.ravel().astype(np.float32)
    pos = None if geom is None or geom.pos is None or len(geom.pos) != n else np.nan_to_num(np.asarray(geom.pos, np.float32))
    if pos is not None and mode != "picture":
        s = float(np.abs(pos[lit]).max()) if lit.any() else 1.0
        X, Y, Z = (pos / max(1e-6, s)).T
        cube = geom.kind == "cube"
        up = Z if (cube or np.abs(Z).max() > 1e-6) else Y
        if mode == "front":
            u, v = X * 0.5 + 0.5, 0.5 - up * 0.5
        elif mode == "top":
            u, v = X * 0.5 + 0.5, 0.5 - Y * 0.5
        elif mode == "around":
            u, v = np.arctan2(Y, X) / (2 * np.pi) + 0.5, 0.5 - up * 0.5
        elif mode == "faces":
            ax, ay, az = np.abs(X), np.abs(Y), np.abs(Z)
            if cube:
                fz = (az >= ax) & (az >= ay)
                fy = ~fz & (ay >= ax)
                m_ = np.where(fz, az, np.where(fy, ay, ax))
                pa = np.where(fz | fy, X, Y)
                pb = np.where(fz, Y, Z)
            else:
                m_, pa, pb = np.ones_like(X), X, up
            m_ = np.maximum(m_, 1e-3)
            u, v = pa / m_ * 0.5 + 0.5, 0.5 - pb / m_ * 0.5
        elif mode == "sphere":
            nrm = geom.nrm if geom.nrm is not None and len(geom.nrm) == n else pos / np.maximum(
                np.linalg.norm(pos, axis=1, keepdims=True), 1e-6)
            nx, ny, nz = np.asarray(nrm, np.float32).T
            u, v = np.arctan2(ny, nx) / (2 * np.pi) + 0.5, np.arccos(np.clip(nz, -1, 1)) / np.pi
    m = (np.clip(u, 0, 1).astype(np.float32), np.clip(v, 0, 1).astype(np.float32), lit)
    if len(_MAP) > 32:
        _MAP.clear()
    _MAP[key] = (geom, m)
    return m


def to_shape(app, canvas, mode=None):
    """A canvas ((h, w, 3) float 0..1) as the logical grid's picture, (rows, cols, 3) uint8, unlit pixels dark."""
    eng = app.eng
    rows, cols = eng.rows, eng.cols
    u, v, lit = mapping(app.project.geometry, rows, cols, mode or options(app)["map"])
    px = vj_looks.sample(canvas, u, v)
    px[~lit] = 0
    return (np.clip(px, 0, 1) * 255 + 0.5).astype(np.uint8).reshape(rows, cols, 3)


# --- the beat ------------------------------------------------------------------------------------
PULSES = (("grid", "on the bar grid"), ("heard", "every beat heard"))
ATTACK = 0.14                    # s a beat's pulse eases in over (a beat moves a picture, it does not jump it)
HEARD_FOR = 2.0                  # s since a beat was heard that the music still counts as playing


def _pulse(since):
    """The pulse `since` seconds after its ease began: up over ATTACK, then let go."""
    if since < 0:
        return 0.0
    return 0.5 - 0.5 * math.cos(math.pi * since / ATTACK) if since < ATTACK else math.exp(-(since - ATTACK) * 5.0)


def _beat(app, now, heard):
    """(pulse 0..1, True on the frame a beat lands). On the bar grid (the default): the beats of the count the
    auto-mix keeps - the show's while it plays, else the tempo's held on the beats heard - each pulse's ease
    centred on its beat (the grid knows it is coming), none between, and none while nothing is heard. Every beat
    heard (the old way): a pulse on each beat the detector hears, off-beats and all, eased in after it."""
    if options(app).get("pulse", "grid") == "grid":
        beats, src = beat_count(app)
        last = getattr(app, "last_hit_at", None)
        playing = src == "the show's bars" or (last is not None and now - last < HEARD_FOR)
        prev = vj_state.of(app).pulse_beats
        vj_state.of(app).pulse_beats = beats
        if not playing:
            vj_state.of(app).grid_beat_at = None
            return 0.0, False
        spb = 60.0 / _tempo(app)
        lead = ATTACK * 0.5 / spb                                    # in beats: the ease's first half before the beat
        k = math.floor(beats + lead)
        since = (beats + lead - k) * spb
        vj_state.of(app).grid_beat_at = now - since                           # the modulators' beat (modulate.py) the same
        hit = prev is not None and math.floor(prev) != math.floor(beats) and beats > prev
        return _pulse(since), hit
    vj_state.of(app).grid_beat_at = None
    last = getattr(app, "last_hit_at", None)
    if last is None:
        return 0.0, False
    return _pulse(now - last), heard


def _tempo(app):
    try:
        from native import modulate
        return modulate.tempo(app)
    except Exception:
        oops.swallowed()
        return 120.0


LOCK_WINDOW = 0.2                # a beat heard this near (in beats) to where the tempo puts one moves the count
LOCK_PULL = 0.3                  # ... this much of the way to it (the rest: the tempo's own count holds)


def bar_count(app):
    """(bars gone by, where it came from): on the show's grid while it plays (from its first beat, at its tempo),
    else the tempo's own count (four beats a bar) - kept on the beats heard while they come, a heard beat near
    where the tempo puts one nudging it, one between (an off-beat, a hat the detector took) not counted. A tap
    tempo's first tap is a bar's first beat."""
    beats, src = beat_count(app)
    return beats / _per_bar(app, src), src


def _per_bar(app, src):
    if src == "the show's bars":
        try:
            from native import sequence_ui
            return int(sequence_ui._steps(app).get("bar") or 4)
        except Exception:
            oops.swallowed()
    return 4


def beat_count(app):
    """(beats gone by, where they came from): bar_count's, in beats."""
    try:
        from native import sequence_ui
        pos = sequence_ui.position(app)
        S = sequence_ui._steps(app)
        bpm = float(S.get("bpm") or 0)
        if pos is not None and bpm > 0 and seq_state.of(app).play is not None:
            first = float(S.get("first") or 0.0)
            return max(0.0, (pos - first) * bpm / 60.0), "the show's bars"
    except Exception:
        oops.swallowed()
    last = getattr(app, "last_hit_at", None)
    if last is not None and clock.now() - last < HEARD_FOR:
        return vj_state.of(app).beats, "the tempo, kept on the beats heard"
    return vj_state.of(app).beats, "the tempo"


SHOW_COUNT = "the show's bars"


def _rebase(app):
    """Each frame: when the count changes where it comes from (a show started or stopped - the tempo's count runs
    on for ever, the show's from its first beat), what waits on it is carried across instead of reading the jump
    as bars gone by - the bars counted for the auto-mix, deck C and a deck's clips start again from here (no fade
    fired), a Cut or deck C's press waiting for the next beat or bar waits for the next one of the new count, and
    a Mutate over bars keeps how far it had grown."""
    beats, src = beat_count(app)
    show = src == SHOW_COUNT
    was, last = vj_state.of(app).count
    vj_state.of(app).count = (show, beats)
    if was is None or was == show:
        return
    vj_state.of(app).forget("bar_k", "cbar_k", "clipbar")
    q = options(app).get("quant", "now")
    unit = 1 if q == "beat" else _per_bar(app, src)
    nxt = float((math.floor(beats / unit + 1e-6) + 1) * unit)
    p = vj_state.of(app).pending
    if p is not None:
        vj_state.of(app).pending = (nxt, p[1])
    p = vj_state.of(app).cpending
    if p is not None:
        vj_state.of(app).cpending = (nxt, p[1])
    jump = beats - (last or 0.0)
    morphs = vj_state.of(app).morphs
    for i, (t0, n) in list(morphs.items()):
        morphs[i] = (t0 + jump, n)


def _keep_count(app, now, hit):
    """The tempo's beat count a frame on, a beat heard near one of its beats pulling it onto the music, and a tap
    tempo's first tap made a bar's first beat (sequence_ui.tap sets vj_state.downbeat)."""
    bpm = _tempo(app)
    db = vj_state.of(app).downbeat
    if db is not None:
        vj_state.of(app).downbeat = None
        n = vj_state.of(app).beats
        vj_state.of(app).beats = 4.0 * math.floor(n / 4.0 + 0.5) + max(0.0, now - db) * bpm / 60.0
        return
    if hit:
        at = getattr(app, "last_hit_at", now)
        b = vj_state.of(app).beats - max(0.0, now - at) * bpm / 60.0       # the count when the beat was heard
        e = b - round(b)
        if abs(e) < LOCK_WINDOW:
            vj_state.of(app).beats -= e * LOCK_PULL


