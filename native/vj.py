def _react(deck, snd, beat):
    """(what, how much 0..1): the deck's sound routing at this moment."""
    r = deck.get("react") or {}
    to = r.get("to", "off")
    if to == "off":
        return None, 0.0
    bass, mid, treb, level, _ = snd
    v = {"bass": bass, "mid": mid, "treble": treb, "level": level, "beat": beat}.get(to, 0.0)
    return r.get("what", "amount"), max(0.0, min(1.0, float(v))) * float(r.get("depth", 0.5))


def _zoom(img, k):
    """img zoomed in about its middle by 1 + k."""
    if k <= 1e-3:
        return img
    h, w = img.shape[:2]
    u, v, _, _, _, _ = _grid(w, h)
    s = 1.0 / (1.0 + k)
    return vj_looks.sample(img, (u - 0.5) * s + 0.5, (v - 0.5) * s + 0.5)


def _bars(app, deck, w, h):
    """(x, y, width, height) of a fit or tile deck's file inside the clear bars its frames are padded with, or None."""
    from native import video
    s = deck.get("source") or {}
    if s.get("kind") != "file":
        return None
    path = media(app, clip_path(s))
    return video.fit_box(video.size_of(path), w, h) if path else None


def _picture_deck(app, i, deck):
    """The deck as its picture or video is laid out: a modulator's value over a picture knob while one moves it."""
    m = vj_state.of(app).mod
    if not m:
        return deck
    over = {k: v for (j, k), v in m.items() if j == i and k in vj_layer.DEFAULTS}
    return dict(deck, **over) if over else deck


def _take_video(app, i, run, deck):
    """The deck's video source kept open and its newest frame taken (the deck drawn or not: one off the mix rolls
    on, so its clip is where it should be and has a picture the moment it is cut to)."""
    src = _source(app, i, run, deck)
    run.error = run.open_error
    if src is not None:
        frame, n = src.latest()
        if frame is not None and n != run.n:
            run.n = n
            run.video_prev = run.video
            if deck.get("_clip_take"):
                vj_clips.started(app, i, deck["_clip_take"])   # a pad's clip: its time from its first picture
            f = np.asarray(frame, np.float32) / 255.0
            pd = _picture_deck(app, i, deck)
            if whole_picture(deck) and f.shape[-1] == 4:       # the picture inside its clear bars, at its own shape,
                box = _bars(app, deck, f.shape[1], f.shape[0])  # laid on the canvas as the deck fits or tiles it
                if box is not None:                            # (the file's frame: its own clear parts kept)
                    x, y, bw, bh = box
                    f = f[y:y + bh, x:x + bw]
                else:                                          # its size not known: what is not clear
                    ys, xs = np.nonzero(f[..., 3] > 0.0)
                    if len(ys):
                        f = f[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
                cw, ch = canvas_size(app)
                f, run.video_alpha = vj_layer.prepare(f, cw, ch, pd, drift=0.0)
            elif f.shape[-1] == 4 or not vj_layer.plain(pd):   # transparency, or keyed / moved: as the deck lays it
                h, w = f.shape[:2]
                f, run.video_alpha = vj_layer.prepare(f, w, h, pd, drift=0.0)
            else:
                run.video_alpha = None
            run.video = f
        err = getattr(src, "error", None)
        if err:
            run.error = str(err)


def draw_deck(app, i, dt, snd, beat, hit):
    """Deck i a frame on: its video's newest frame taken, its look drawn on the canvas (or its effect run)."""
    o = options(app)
    deck = vj_clips.deck(app, i, o["decks"][i])               # a pad's clip playing on it: its file and a video look
    run = _runs(app)[i]
    what, rv = _react(deck, snd, beat)
    speed = knob_value(app, i, "speed") * (1.0 + 2.0 * rv if what == "speed" else 1.0)
    amount = min(1.0, knob_value(app, i, "amount") + (rv if what == "amount" else 0.0))
    run.t += dt * speed
    if deck["look"] == EFFECT:
        if run.src_key is not None:                           # an Effect deck has no video: its source let go
            run.src_key = None
            run.video = run.video_prev = None
            vj_state.of(app).release_due = True
        run.led = _effect_frame(app, i, run, deck, speed, amount, dt)
        return
    _take_video(app, i, run, deck)
    lk = vj_looks.LOOKS.get(deck["look"]) or vj_looks.LOOKS["Plasma"]
    w, h = canvas_size(app)
    if run.look != lk.name and getattr(run, "handoff", None) == lk.name and run.size == (w, h):
        run.look = lk.name                                  # a flame handed over: the picture goes on from where it was
        run.look_obj = lk
    run.handoff = None
    clip_moved = deck.get("_clip_take") != getattr(run, "clip_take", None)   # a clip on or off the deck: its
    run.clip_take = deck.get("_clip_take")                                  # envelope fades it, not a crossfade
    if run.look != lk.name or run.size != (w, h) or getattr(run, "look_obj", lk) is not lk:
        # another look, the canvas resized, or the look's file saved again (the same name, a new look: the old
        # version's state - a shader's frame count, its buffers - not handed to it): it starts again
        last = getattr(run, "canvas", None)
        recent = clock.now() - getattr(run, "drawn_at", -1e9) < 0.2           # it was being drawn, not long put away
        if (run.look is not None and run.size == (w, h) and recent and last is not None and last.shape[:2] == (h, w)
                and not clip_moved):
            # another look on a deck that was showing: the last picture blended into the new over a beat
            run.xfade = [last.copy(), 0.0, max(0.25, min(0.6, 60.0 / _tempo(app)))]
        run.look = lk.name
        run.look_obj = lk
        run.size = (w, h)
        run.state = {}
        run.trail = None
    c = Ctx()
    c.w, c.h = w, h
    c.u, c.v, c.x, c.y, c.r, c.a = _grid(w, h)
    c.t, c.dt = run.t, dt * speed
    c.bass, c.mid, c.treb, c.level, c.wave = snd
    c.beat, c.beat_hit = beat, hit
    c.beats = vj_state.of(app).beats
    c.deck = _picture_deck(app, i, deck)                    # (the picture knobs as a modulator moves them)
    c.image_path = media(app, deck.get("image") or "")
    c.font_path = media(app, deck.get("text_font") or "")
    try:
        c.bands = np.asarray(app.eng.fft, np.float32) / 255.0             # the sixteen bands, for a shader's spectrum
    except Exception:
        oops.swallowed()
        c.bands = None
    v = run.video
    if v is not None and v.shape[:2] != (h, w):                         # a frame of another size (a canvas change)
        from PIL import Image
        v = np.asarray(Image.fromarray((v * 255).astype(np.uint8)).resize((w, h)), np.float32) / 255.0
        run.video = v
        run.video_prev = None
    c.video, c.video_prev = run.video, run.video_prev
    va = run.video_alpha
    c.video_alpha = va if va is not None and run.video is not None and va.shape == run.video.shape[:2] else None
    c.channel_images = [media(app, p) if p else "" for p in (deck.get("channel_images") or ["", "", "", ""])][:4]
    c.amount, c.speed = amount, speed
    c.knob = lambda key: knob_value(app, i, key)          # a knob as it draws, a modulator's over it
    c.grad = colours(app, deck.get("colours", "neon"))
    c.flame_to = _flame_of(deck.get("morph_to")) if lk.family == "flame" else None
    try:
        img = np.asarray(lk.draw(c, run.state), np.float32)
        if img.shape[:2] != (h, w):
            raise ValueError(f"it drew {img.shape[1] if img.ndim > 1 else '?'} x {img.shape[0] if img.ndim else '?'}, "
                             f"not the canvas's {w} x {h}")
        if img.ndim == 2:
            img = np.repeat(img[..., None], 3, 2)               # grey: as red, green and blue
        elif img.ndim != 3 or img.shape[2] not in (1, 3, 4):
            raise ValueError(f"it drew {img.shape[2] if img.ndim == 3 else img.ndim} channels, not 3 (or 4)")
        elif img.shape[2] == 1:
            img = np.repeat(img, 3, 2)
        if not np.isfinite(img).all():
            img = np.nan_to_num(img, nan=0.0, posinf=1.0, neginf=0.0)
    except Exception as e:                                          # a look of the user's that fails: said, dark
        run.error = f"{lk.name}: {type(e).__name__}: {e}"
        img = np.zeros((h, w, 3), np.float32)
    if run.state.get("warn") and not run.error:              # what of a look could not run, though it draws
        run.error = f"{lk.name}: {run.state['warn']}"
    alpha = None
    if img.ndim == 3 and img.shape[2] == 4:                   # a look with transparency (a picture, a video's)
        img, alpha = img[..., :3], img[..., 3]
    img = post(app, i, c, img, beat, what, rv)
    if alpha is not None:                                     # moved as the picture was by the deck's zoom, kaleidoscope, mirror
        a3 = post_shape(app, i, c, np.repeat(alpha[..., None], 3, 2), what, rv)
        alpha = a3[..., 0]
    run.alpha = None if alpha is None else np.clip(alpha, 0, 1).astype(np.float32)
    xf = getattr(run, "xfade", None)
    if xf is not None:
        xf[1] += dt                                           # on the deck's own frames: a render's as the live run's
        k = xf[1] / xf[2]
        if k >= 1.0 or xf[0].shape != img.shape:
            run.xfade = None
        else:
            e = 0.5 - 0.5 * math.cos(math.pi * max(0.0, k))
            img = xf[0] * (1.0 - e) + img * e
    run.canvas = np.clip(img, 0, 1).astype(np.float32)
    run.drawn_at = clock.now()


def post_shape(app, i, c, img, what=None, rv=0.0):
    """Only what of post() moves the picture - the zoom by the sound, the kaleidoscope, the mirror - for its alpha."""
    deck = options(app)["decks"][i]
    if what == "zoom":
        img = _zoom(img, rv)
    k = int(round(knob_value(app, i, "kaleido")))
    if k > 0:
        img = vj_looks.kaleido(c, img, k)
    if deck.get("mirror"):
        img = vj_looks.mirror(img)
    return img


def post(app, i, c, img, beat, what=None, rv=0.0):
    """What the deck does to its look's picture: zoom by the sound, kaleidoscope, mirror, hue, blur, trails,
    strobe and brightness by the sound."""
    deck = options(app)["decks"][i]
    run = _runs(app)[i]
    if what == "zoom":
        img = _zoom(img, rv)
    k = int(round(knob_value(app, i, "kaleido")))
    if k > 0:
        img = vj_looks.kaleido(c, img, k)
    if deck.get("mirror"):
        img = vj_looks.mirror(img)
    hue = knob_value(app, i, "hue") + (rv * 0.5 if what == "hue" else 0.0)
    if hue:
        img = vj_looks.hue_turn(img, hue)
    b = int(round(knob_value(app, i, "blur")))
    if b > 0:
        img = vj_looks.blur(img, b)
    tr = knob_value(app, i, "trails")
    if tr > 0:
        keep = 0.6 + 0.38 * tr                                         # how much of the last frame stays
        prev = run.trail
        img = img if prev is None or prev.shape != img.shape else np.maximum(img, prev * keep)
        run.trail = img
    else:
        run.trail = None
    if deck.get("strobe"):
        img = img * (0.15 + 0.85 * beat)
    if what == "brightness":
        img = img * (1.0 - float((deck.get("react") or {}).get("depth", 0.5)) + rv)
    return img


FX_STEP = 23                       # ms an engine frame, as the main engine's (app.STEP)
FX_SET = ("c1", "c2", "c3", "o1", "o2", "o3")   # an Effect deck's own settings: the effect's three sliders and checks


FX_SET_WORDS = {"c1": "Custom 1", "c2": "Custom 2", "c3": "Custom 3", "o1": "check 1", "o2": "check 2", "o3": "check 3"}


def fx_most(k):
    """The most an Effect deck's setting takes: a check 1, Custom 3 31, the others 255."""
    return 1 if k[0] == "o" else (31 if k == "c3" else 255)


def fx_value(app, i, k):
    """Deck i's Effect setting k as 0..1 of its range: the deck's own, else its effect's (0 with no effect)."""
    d = options(app)["decks"][i]
    own = d.get("fx_set") or {}
    if k in own:
        return max(0.0, min(1.0, float(own[k]) / fx_most(k)))
    got = {kk: v for kk, _, v, _ in fx_settings(app.eng, d.get("effect", ""), d)}
    return max(0.0, min(1.0, float(got.get(k, 0)) / fx_most(k)))


def fx_set(app, i, k, f):
    """Deck i's Effect setting k set from f (0..1): a slider to its step, a check on from the half up."""
    if k not in FX_SET:
        return
    d = options(app)["decks"][i]
    v = (1 if f >= 0.5 else 0) if k[0] == "o" else int(round(max(0.0, min(1.0, float(f))) * fx_most(k)))
    d.setdefault("fx_set", {})[k] = v
    vj_state.of(app).dirty = True


def fx_words(app, i, k):
    """An Effect deck setting's name for the action lists: "Custom 1", with its effect's own name for it when deck i
    runs an effect that names it ("Custom 1 (Ripple size)")."""
    w = FX_SET_WORDS[k]
    if i >= DECKS:
        return w
    d = options(app)["decks"][i]
    if d.get("look") != EFFECT:
        return w
    lab = {kk: l for kk, l, _, _ in fx_settings(app.eng, d.get("effect", ""), d)}.get(k)
    return f"{w} ({lab.strip()})" if lab and lab.strip() and lab.strip() != "!" else w


def fx_settings(eng, name, d):
    """An Effect deck's effect's own settings: [(key, its label, the value it has now, the most it takes)] - the
    sliders and checks the effect names (the others it does not use), each the deck's or else the effect's own."""
    try:
        meta = eng.meta[eng.names.index(name)]
    except (ValueError, IndexError, AttributeError):
        return []
    labels = list(meta.get("labels") or []) + [""] * 8
    defs = meta.get("defs") or {}
    own = d.get("fx_set") or {}
    out = []
    for n, k in enumerate(("sx", "ix") + FX_SET):
        if k in FX_SET and labels[n]:
            out.append((k, labels[n], int(own.get(k, defs.get(k, 0))), 1 if k[0] == "o" else (31 if k == "c3" else 255)))
    return out


def _effect_frame(app, i, run, deck, speed, amount, dt):
    """An Effect deck: the studio's effect named, on an engine of the deck's, hearing the same sound."""
    name = deck.get("effect") or ""
    run.look = EFFECT                                         # a look again after: it starts afresh (with its cross-
    try:                                                      # fade), not on the state the effect kept in run.state
        eng = app.second_engine(f"vj{i}")
    except Exception as e:
        run.error = str(e)
        return None
    if (getattr(eng, "geom", None) is not app.project.geometry          # another shape, not only another size:
            or eng.cols != app.eng.cols or eng.rows != app.eng.rows):   # six faces, a ledmap's (a pooled engine's)
        eng.set_geometry(app.project.geometry)
        run.state = {}
    if not name:                                              # a deck just put on Effect: the studio's own effect, to
        names, idx = getattr(app.eng, "names", None) or [], getattr(app.eng, "idx", 0)    # start from
        if 0 <= idx < len(names) and names[idx] in eng.names:
            name = options(app)["decks"][i]["effect"] = names[idx]
            vj_state.of(app).dirty = True                     # (the frame's effect list shows it)
    if name not in eng.names:
        run.error = f"no effect called {name!r}" if name else "no effect chosen"
        run.led = None                                        # dark, not the last effect's last picture
        return None
    if run.state.get("sel") != name:
        eng.select(eng.names.index(name))
        run.state = {"sel": name}
    look = (deck.get("palette") or "", deck.get("fx_colours") or "")
    if run.state.get("look") != look:                         # its palette and colours, each a choice or the effect's own
        was = run.state.get("look")
        run.state["look"] = look
        if was and ((was[0] and not look[0]) or (was[1] and not look[1])):
            eng.select(eng.names.index(name))                 # back to the effect's own: the effect chosen again
        pals = dict(eng.palette_list())
        if look[0] in pals:
            eng.pal = pals[look[0]]
        if look[1]:
            g = vj_looks.gradient(look[1])
            rgb = [(np.clip(np.asarray(g(np.array([q], np.float32))).reshape(-1)[:3], 0, 1) * 255).astype(int)
                   for q in (0.3, 0.65, 0.95)]
            eng.colors(*[(int(c[0]) << 16) | (int(c[1]) << 8) | int(c[2]) for c in rgb])
    # its own sliders and checks as the deck sets them (the rest as the effect chose them when it was picked)
    for k, v in (deck.get("fx_set") or {}).items():
        if k in FX_SET:
            eng.fx[k] = int(v)
    # its Speed from the deck's (1.0 is the slider's middle, 2.0 and more its top) and its Intensity the amount
    eng.fx["sx"] = int(max(0, min(255, round(speed * 128))))
    eng.fx["ix"] = int(max(0, min(255, round(amount * 255))))
    eng.push()
    try:
        eng.fft[:] = app.eng.fft[:]
        eng.audio(*getattr(app.eng, "last_audio", (0.0, 0)))
        # its clock run on in the main engine's steps for the time since it was last drawn (a deck only in a
        # preview is drawn every other frame: two steps then, so it runs at the effect's own pace)
        run.fx_acc = min(getattr(run, "fx_acc", FX_STEP) + dt * 1000.0, 8 * FX_STEP)
        while run.fx_acc >= FX_STEP:
            run.fx_acc -= FX_STEP
            eng.frame(FX_STEP)
    except Exception as e:
        run.error = str(e)
        return None
    run.error = ""
    return eng.rgb().copy()


PAL_N = 31                         # a palette read at this many places along it (WLED's sixteen entries, and between)
PAL_LAST = 240                     # ... the last at its sixteenth entry: grad(1) the palette's last colour, where an
                                   # effect's index 255 is most of the way round to its first again
PAL_EVERY_S = 1.0                  # ... again this often: one edited in the Palettes frame, one that moves by itself


def colour_names(app):
    """What a deck's colours can be: the VJ's own gradients, then the palettes the effects have - the project's
    own (the Palettes frame's) and WLED's."""
    out = list(vj_looks.GRADIENTS)
    try:
        pals = [n for n, _ in app.eng.palette_list()]
    except Exception:                                         # no engine yet, or one without palettes
        return out
    own = [n for n in getattr(app.eng, "custom_names", None) or [] if n in pals]
    return out + [n for n in own if n not in out] + [n for n in pals if n not in out and n not in own]


def colours(app, name):
    """A deck's colours as grad(x) for 0..1: one of the VJ's gradients, or a palette of the engine's by its name
    (read along its length, and again each second). A name that is neither - a palette of another project's -
    is the rainbow, as an unknown gradient always was."""
    if not name or name in vj_looks.GRADIENTS:
        return vj_looks.gradient(name or "neon")
    st, now = vj_state.of(app), clock.now()
    hit = st.pals.get(name)
    if hit is None or not 0.0 <= now - hit[0] < PAL_EVERY_S:
        g = None
        try:
            pid = dict(app.eng.palette_list()).get(name)
            if pid is not None:
                g = vj_looks.from_stops(np.asarray(app.eng.palette_swatch(pid, PAL_N, PAL_LAST), np.float32) / 255.0)
        except Exception:
            oops.swallowed()
        hit = st.pals[name] = (now, g or vj_looks.gradient(name))
    return hit[1]


def deck_led(app, i):
    """Deck i's picture on the shape, (rows, cols, 3) uint8, or None before it has drawn."""
    run = _runs(app)[i]
    if _look_now(app, i) == EFFECT:
        own = run.led
    else:
        own = None if run.canvas is None else to_shape(app, run.canvas)
    e, clip, ca = _clip_over(app, i)
    if clip is None:
        return own
    clip = to_shape(app, clip)
    if ca is not None:                                        # where the clip is clear the deck shows through
        e = e * to_shape(app, np.repeat(ca[..., None], 3, 2)).astype(np.float32) / 255.0
    base = own.astype(np.float32) if own is not None and own.shape == clip.shape else np.zeros(clip.shape, np.float32)
    return np.clip(base * (1.0 - e) + clip.astype(np.float32) * e + 0.5, 0, 255).astype(np.uint8)


def _clip_over(app, i):
    """(how much of it shows, its canvas, its alpha or None) of a pad's clip laid over deck A or B, or
    (0, None, None)."""
    if i >= 2:
        return 0.0, None, None
    lv = vj_clips.level(app, i)
    crun = _clip_runs(app)[i]
    if lv is None or crun.canvas is None:
        return 0.0, None, None
    a = crun.alpha if crun.alpha is not None and crun.alpha.shape == crun.canvas.shape[:2] else None
    return max(0.0, min(1.0, lv)), crun.canvas, a


def _draw_clip(app, i):
    """Deck A or B's pad clip a frame on: its newest picture taken onto its canvas (laid over the deck's own by
    deck_led); none playing, its source let go."""
    crun = _clip_runs(app)[i]
    if vj_clips.level(app, i) is None:
        if crun.src_key is not None or crun.canvas is not None:
            crun.src_key, crun.video, crun.video_prev, crun.canvas = None, None, None, None
            vj_state.of(app).release_due = True
        return
    _take_video(app, i, crun, vj_clips.clip_deck(app, i, options(app)["decks"][i]))
    v = crun.video
    if v is None:
        return
    w, h = canvas_size(app)
    va = crun.video_alpha
    if va is None and v.shape[-1] == 4:
        va = v[..., 3]
    v = v[..., :3]
    if va is not None and va.shape != v.shape[:2]:
        va = None
    if v.shape[:2] != (h, w):
        from PIL import Image
        v = np.asarray(Image.fromarray((np.clip(v, 0, 1) * 255).astype(np.uint8)).resize((w, h)), np.float32) / 255.0
        if va is not None:
            va = np.asarray(Image.fromarray((np.clip(va, 0, 1) * 255).astype(np.uint8)).resize((w, h)),
                            np.float32) / 255.0
    crun.canvas = np.clip(v, 0, 1).astype(np.float32)
    crun.alpha = None if va is None else np.clip(va, 0, 1).astype(np.float32)   # (clear parts: the deck under it)


def _look_now(app, i):
    """Deck i's look as it draws: a pad's clip's while one plays on it (a video look), else its own."""
    return vj_clips.deck(app, i, options(app)["decks"][i])["look"]


def deck_alpha(app, i):
    """Deck i's transparency on the shape, (rows, cols) float 0..1 - 1 where it shows - or None (all of it shows)."""
    run = _runs(app)[i]
    if _look_now(app, i) == EFFECT or run.alpha is None or run.canvas is None or run.alpha.shape != run.canvas.shape[:2]:
        return None
    return to_shape(app, np.repeat(run.alpha[..., None], 3, 2))[..., 0].astype(np.float32) / 255.0


def deck_canvas(app, i):
    """Deck i's picture for its preview: its canvas, or an Effect deck's logical grid."""
    run = _runs(app)[i]
    if _look_now(app, i) == EFFECT:                           # (its logical grid: a clip over it laid on that)
        return deck_led(app, i)
    own = None if run.canvas is None else (run.canvas * 255).astype(np.uint8)
    e, clip, ca = _clip_over(app, i)
    if clip is None:
        return own
    clip = clip * 255.0
    if ca is not None:
        e = e * ca[..., None]
    base = own.astype(np.float32) if own is not None and own.shape == clip.shape else np.zeros(clip.shape, np.float32)
    return np.clip(base * (1.0 - e) + clip * e + 0.5, 0, 255).astype(np.uint8)


def _level(img, lv):
    if lv >= 0.999:
        return img
    return (img.astype(np.float32) * max(0.0, lv)).astype(np.uint8)


def mix(app, a, b, c=None, c_alpha=None):
    """The decks' pictures: A and B through the fader (a wipe, or the blend mode), each at its level, then deck C
    over the mix at its level, through its own blend - where it is clear (c_alpha: a picture's or a video's
    transparency, keyed or its own), not at all."""
    from native import mixer, transition
    o = options(app)
    f = fader_now(app)
    a, b = _level(a, knob_value(app, 0, "level")), _level(b, knob_value(app, 1, "level"))
    if o.get("wipe", "blend") != "blend" and 0.0 < f < 1.0:
        out = transition.blend(a, b, f, o["wipe"])
    else:
        out = mixer.mix(a, b, f, o["mode"])
    lc = knob_value(app, 2, "level") if len(o["decks"]) > 2 else 0.0
    if c is not None and lc > 0.0 and c.shape == out.shape:
        mode = o.get("c_mode", "screen")
        base, top = out.astype(np.float32), c.astype(np.float32)
        ca = None if c_alpha is None or c_alpha.shape != out.shape[:2] else c_alpha[..., None]
        if mode == "over":                                    # what deck C draws covers the mix: where it is clear (its
            if ca is not None:                                # alpha), or else its black, lets the mix through
                k = ca * lc                                   # its colour already black where it is clear
                out = base * (1.0 - k) + top * lc
            else:
                k = (top.max(axis=2, keepdims=True) / 255.0) * lc
                out = base * (1.0 - k) + top * k
        else:
            k = lc if ca is None else ca * lc
            out = base + (mixer._blend(base, top, mode) - base) * k
        out = np.clip(out + 0.5, 0, 255).astype(np.uint8)
    return out


_BUILDS = {}                      # a shader's source: whether it has buffers (passes it keeps from frame to frame)


def _builds_up(deck):
    """Whether a deck's look is a shader with buffers - one that builds its picture up over frames: deck C's,
    drawn every other frame off the mix like A's and B's (undrawn, the GL thread lets its buffers go after
    vj_glsl.FORGET_S, and brought in it started from black)."""
    src = getattr(vj_looks.LOOKS.get(deck.get("look")), "glsl", None)
    if not src:
        return False
    if src not in _BUILDS:
        from native import vj_glsl
        try:
            _BUILDS[src] = any(p[0] in vj_glsl.BUFFERS for p in vj_glsl.passes(src))
        except ValueError:
            _BUILDS[src] = False
        if len(_BUILDS) > 64:
            _BUILDS.pop(next(iter(_BUILDS)))
    return _BUILDS[src]


def cue_deck(app):
    """The deck the fader is furthest from: the one to set up before fading to it."""
    return 1 if float(options(app)["fader"]) < 0.5 else 0


def cue_picture(app):
    """The off-air deck's picture on the shape - for the pop-out while Cue is on - or None."""
    o = options(app)
    if not o.get("cue"):
        return None
    return deck_led(app, cue_deck(app))


def update(app, dt=None):
    """Each frame while the VJ frame is on air (or open): both decks drawn, the auto-mix moved, the mix made."""
    o = options(app)
    now = clock.now()
    if dt is None:
        last = vj_state.of(app).at
        dt = 0.0 if last is None else min(0.1, max(0.0, now - last))
    vj_state.of(app).at = now
    vj_state.of(app).beats = vj_state.of(app).beats + dt * _tempo(app) / 60.0
    snd = sound(app)
    last = getattr(app, "last_hit_at", None)
    heard = last is not None and last != vj_state.of(app).last_hit
    if heard:
        vj_state.of(app).hits = vj_state.of(app).hits + 1
    _keep_count(app, now, heard)
    _rebase(app)
    vj_state.of(app).last_hit = last
    beat, hit = _beat(app, now, heard)
    vj_state.of(app).pulse = beat
    _flames(app)
    f = fader_now(app)
    vj_state.of(app).tick = vj_state.of(app).tick + 1
    vj_clips.tick(app)                                      # the pads' clips: their envelopes, the one-shots ended
    _collect(app)                                           # sources opened on workers, into the pool
    _warm_cams(app)                                         # the cameras pads bring up, open
    cue = cue_deck(app) if o.get("cue") else -1
    for i in range(len(o["decks"])):
        _advance_clips(app, i, hit)
        dn, run_i = vj_clips.deck(app, i, o["decks"][i]), _runs(app)[i]
        if run_i.src_key is not None and (dn["look"] == EFFECT or dn["source"].get("kind", "none") == "none"):
            run_i.src_key = None                            # no video shown (none, an Effect, a clip let go): its
            run_i.video = run_i.video_prev = None           # source closed, not decoding on unseen (a webcam off)
            vj_state.of(app).release_due = True
        if i < 2:
            _draw_clip(app, i)                              # a pad's clip over A or B
        if i < 2:
            live = ((i == 0 and f < 1.0) or (i == 1 and f > 0.0)) and knob_value(app, i, "level") > 0.0
            live = live or i == cue
        else:
            live = knob_value(app, i, "level") > 0.0
        # a deck fully off the mix is drawn every other frame (its time kept whole) for its preview - and always
        # when it is A or B, the next one up: its look already running when it is cut to (a feedback look, built up
        # from black only then, would land the drop on black)
        if live or ((i in _previewed(app) or i < 2 or _builds_up(o["decks"][i])) and (vj_state.of(app).tick + i) % 2 == 0):
            with frametime.part(_deck_words(app, i), "polls"):        # the VJ draws its decks in the frame's polls
                draw_deck(app, i, dt + _skipped(app, i), snd, beat, hit)
        else:
            _skips(app)[i] += dt
            d = vj_clips.deck(app, i, o["decks"][i])
            if run_i.error and run_i.look not in (None, d["look"]):
                run_i.error = ""                              # what the look before it said: not this one's
            if d["look"] != EFFECT and d["source"].get("kind", "none") != "none":
                _take_video(app, i, _runs(app)[i], d)         # its video rolling on off the mix
    if vj_state.of(app).take("release_due"):
        _release(app)                                       # once every deck has its key: none closed under another
    _launch_due(app)
    _auto(app, hit)
    _c_update(app)
    shape = (app.eng.rows, app.eng.cols, 3)
    pics = []
    for i in range(len(o["decks"])):
        p = deck_led(app, i)
        pics.append(p if p is not None and p.shape == shape else np.zeros(shape, np.uint8))
    vj_state.of(app).out = _after(app, mix(app, pics[0], pics[1], pics[2] if len(pics) > 2 else None,
                                           deck_alpha(app, 2) if len(pics) > 2 else None))


# --- after the mix: freeze, the master level, blackout ---------------------------------------------
def _after(app, out):
    """The mix as it leaves the desk: held as it was while frozen, at the master level, dark under a blackout.
    The decks run on under all three: let go, the picture is where the music is, not where it was left."""
    st = vj_state.of(app)
    if st.freeze:
        if st.frozen is None or st.frozen.shape != out.shape:
            st.frozen = out.copy()
        out = st.frozen
    else:
        st.frozen = None
    if st.blackout:
        return np.zeros_like(out)
    return _level(out, float(options(app).get("master", 1.0)))


def set_master(app, f):
    options(app)["master"] = round(max(0.0, min(1.0, float(f))), 4)
    vj_state.of(app).knobs_moved = True


def blackout(app, on=None):
    """The blackout set, or flipped (None); whether it is on now."""
    st = vj_state.of(app)
    st.blackout = (not st.blackout) if on is None else bool(on)
    return st.blackout


def freeze(app, on=None):
    """The freeze set, or flipped (None): the mix held as it is at the next frame. Whether it is on now."""
    st = vj_state.of(app)
    st.freeze = (not st.freeze) if on is None else bool(on)
    if not st.freeze:
        st.frozen = None
    return st.freeze


def _deck_words(app, i):
    """Deck i in the stats popover's list: its letter, and MilkDrop or a shader when its look is one."""
    d = vj_clips.deck(app, i, options(app)["decks"][i])
    lk = None if d["look"] == EFFECT else vj_looks.LOOKS.get(d["look"])
    fam = {"milkdrop": " (MilkDrop)", "shader": " (shader)"}.get(getattr(lk, "family", ""), "")
    return f"VJ deck {'ABC'[i] if i < 3 else i + 1}" + (" (an effect)" if d["look"] == EFFECT else fam)


def _advance_clips(app, i, hit):
    """A deck's list of files stepped on by itself: every beat, or with the auto-mix's bars."""
    s = options(app)["decks"][i]["source"]
    adv = s.get("advance", "off")
    if adv == "off" or s.get("kind") != "file" or len([f for f in (s.get("files") or []) if f]) < 2:
        return
    if adv == "beat" and hit:
        next_clip(app, i)
    elif adv == "bars":
        per = max(1, int(options(app)["auto"].get("bars", 4)))
        k = int(bar_count(app)[0] // per)
        bars = vj_state.of(app).clipbar
        if k != bars.get(i, k):
            next_clip(app, i)
        bars[i] = k


def _previewed(app):
    """The decks whose previews are on screen (vj_ui says): only those are drawn while off the mix."""
    p = vj_state.of(app).preview
    if p is True:
        return range(DECKS)
    return p or ()


def _skips(app):
    sk = vj_state.of(app).skip
    if sk is None or len(sk) < DECKS:
        sk = vj_state.of(app).skip = [0.0] * DECKS
    return sk


def _skipped(app, i):
    """The time a deck was not drawn for, given back to it once (and forgotten)."""
    sk = _skips(app)
    t, sk[i] = sk[i], 0.0
    return min(t, 0.25)


def picture(app, rgb):
    """The frame through the VJ: its mix when it is on air, the effect's otherwise - and, while a show's step
    blends into or out of a VJ step (or between two), the picture before blended into this one."""
    rgb = np.asarray(rgb)
    out = rgb
    if on(app):
        v = vj_state.of(app).out
        if v is not None and v.shape == rgb.shape:
            out = v
    fade = vj_state.of(app).fade
    if fade is not None:
        k = (clock.now() - fade["t0"]) / max(0.05, fade["dur"])
        src = fade["from"]
        if k >= 1.0 or src is None or src.shape != out.shape:
            vj_state.of(app).fade = None
        else:
            from native import transition
            out = transition.blend(src, out, k, fade["style"])
    vj_state.of(app).last_pic = out
    return out


# --- auto-mix and shuffle ------------------------------------------------------------------------
FADE_BEATS = 2.0                 # an auto-mix's sweep, in beats (a drop's is a cut)


def _auto(app, hit):
    """The fader moved by itself: to the other deck every n bars, or at the show's sections (a cut into a drop,
    a slow fade into the quiet parts); a deck dealt a new look as the mix leaves it, when shuffling."""
    o = options(app)
    a = o["auto"]
    sweep = vj_state.of(app).sweep
    now = clock.now()
    if sweep is not None:
        t0, dur, f0, f1 = sweep
        k = 1.0 if dur <= 0 else max(0.0, min(1.0, (now - t0) / dur))   # (a start ahead of now: held there)
        e = 0.5 - 0.5 * math.cos(math.pi * k)
        o["fader"] = f0 + (f1 - f0) * e
        if k >= 1.0:
            vj_state.of(app).sweep = None
            if a.get("shuffle"):
                shuffle(app, 0 if f1 >= 0.5 else 1)         # the deck the mix just left
        return
    mode = a.get("mix", "off")
    if mode == "bars":
        per = max(1, int(a.get("bars", 4)))
        k = int(bar_count(app)[0] // per)
        if vj_state.of(app).bar_k is not None and k != vj_state.of(app).bar_k:
            go(app, FADE_BEATS * 60.0 / _tempo(app))
        vj_state.of(app).bar_k = k
    elif mode == "sections":
        sec = _section_now(app)
        was = sec if vj_state.of(app).sec == vj_state.UNSET else vj_state.of(app).sec
        vj_state.of(app).sec = sec
        if sec is not None and sec != was:
            kind = sec[1]
            if kind == "drop":
                dur = 0.0                                   # into a drop: a cut
            elif kind in ("intro", "outro", "breakdown"):
                dur = 4.0                                   # into the quiet parts: a slow fade
            else:
                dur = FADE_BEATS * 60.0 / _tempo(app)
            go(app, dur)


def _section_now(app):
    """(index, kind) of the show's section the playhead is in, or None (not playing, or no sections)."""
    try:
        from native import sequence_ui, seq_sections
        pos = sequence_ui.position(app)
        if pos is None:
            return None
        for k, s in enumerate(seq_sections._sections(app)):
            if float(s["at"]) <= pos < float(s["at"]) + float(s["len"]):
                return (k, s.get("kind", "verse"))
    except Exception:
        oops.swallowed()
        return None
    return None


def go(app, seconds):
    """The fader swept to the other end over `seconds` (0: a cut) - counted, so a staged pad knows its deck went
    on air though the fader is back by the time it looks (pads.staged)."""
    vj_state.of(app).goes = vj_state.of(app).goes + 1
    o = options(app)
    f0 = float(o["fader"])
    f1 = 0.0 if f0 >= 0.5 else 1.0
    if seconds <= 0:
        o["fader"] = f1
        vj_state.of(app).sweep = None
        if o["auto"].get("shuffle"):
            shuffle(app, 0 if f1 >= 0.5 else 1)
        return
    vj_state.of(app).sweep = (clock.now(), float(seconds), f0, f1)


def shuffle(app, i):
    """Deck i dealt a look it does not have: one that suits its source (a video look only with video), from any
    look's family or - the auto-mix's "shuffle from its own family" - from the family of the one it has."""
    import random
    o = options(app)
    d = o["decks"][i]
    if d["look"] == EFFECT:
        return
    has_video = d["source"].get("kind", "none") != "none"
    shown = {dd["look"] for dd in o["decks"]}                # none a deck has now: a swap always changes the picture
    pool = [n for n, lk in vj_looks.LOOKS.items()
            if n not in shown and lk.family != "layer" and (lk.video == has_video or not lk.video)]
    cur = vj_looks.LOOKS.get(d["look"])
    if o["auto"].get("shuffle_from") == "family" and cur is not None:
        kin = [n for n in pool if vj_looks.LOOKS[n].family == cur.family]
        pool = kin or pool                                  # a family of one: any look rather than none
    if pool:
        d["look"] = random.choice(pool)
        vj_state.of(app).dirty = True


def cut(app):
    go(app, 0.0)


QUANTS = (("now", "now"), ("beat", "on the next beat"), ("bar", "on the next bar"))


def launch(app, seconds):
    """Cut (0) or Fade (seconds) by hand - the frame's buttons, MIDI, the phone: at once, or waiting for the next
    beat or bar of the count the auto-mix keeps (quant). Asked again while one waits: the newer in its place.
    What it waits for, in words, or "" when it went at once."""
    q = options(app).get("quant", "now")
    if q not in ("beat", "bar"):
        vj_state.of(app).pending = None
        go(app, seconds)
        return ""
    beats, src = beat_count(app)
    unit = 1 if q == "beat" else _per_bar(app, src)
    target = (math.floor(beats / unit + 1e-6) + 1) * unit
    vj_state.of(app).pending = (float(target), float(seconds))
    return "the next beat" if q == "beat" else "the next bar"


def _launch_due(app):
    """A Cut or Fade waiting for its beat or bar, gone once the count reaches it."""
    p = vj_state.of(app).pending
    if p is None:
        return
    if beat_count(app)[0] >= p[0] - 1e-6:
        vj_state.of(app).pending = None
        go(app, p[1])


def fader_now(app):
    """The crossfader as it mixes: what a modulator moves it to while one does (modulate.py, never saved), else its
    own."""
    from native import modulate
    m = modulate.over(app, "vj.fader")
    return float(options(app)["fader"]) if m is None else float(m)


def set_fader(app, v, hand=True):
    """The crossfader set (by hand: the dialog's, MIDI's, the phone's - a show's recording takes it)."""
    options(app)["fader"] = float(max(0.0, min(1.0, v)))
    vj_state.of(app).sweep = None
    if hand:
        vj_state.of(app).hand_at = clock.now()


# --- deck C: brought in and taken out over the mix ----------------------------------------------------
C_FADES = ((0.0, "a cut"), (1.0, "over a beat"), (2.0, "over two beats"), (4.0, "over four beats"),
           (16.0, "over sixteen beats"))
C_AUTO = (("off", "by hand"), ("bars", "in and out every few bars"), ("flash", "a flash every few bars"),
          ("sections", "in for the drops and choruses"))
C_LOUD = ("drop", "chorus")      # the sections deck C comes in for, on "sections"
FLASH_HOLD = 0.25                # a flash: deck C at its "in to" level this much of a beat, then out over a beat


def c_level(app):
    return float(options(app)["decks"][2].get("level", 0.0) or 0.0)


def c_is_in(app):
    """Deck C in, or on its way in: where a sweep is headed (a flash counts as out), else whether its level is up."""
    sw = vj_state.of(app).csweep
    if sw is not None:
        return sw[3] > 0.0
    return c_level(app) > 0.0


def c_go(app, up, beats=None, flash=False):
    """Deck C's level swept to its "in to" level (up) or to 0 over `beats` (None: its fade length; 0: a cut),
    eased. A flash: up at once, held a moment, then out over a beat."""
    o = options(app)
    beat = 60.0 / _tempo(app)
    l0 = c_level(app)
    if flash:
        up_to = float(o["c_up"])
        o["decks"][2]["level"] = up_to
        vj_state.of(app).csweep = (clock.now(), beat, up_to, 0.0, FLASH_HOLD * beat)
        vj_state.of(app).knobs_moved = True
        return
    l1 = float(o["c_up"]) if up else 0.0
    dur = (float(o["c_fade"]) if beats is None else float(beats)) * beat
    if dur <= 0.0:
        o["decks"][2]["level"] = l1
        vj_state.of(app).csweep = None
        vj_state.of(app).knobs_moved = True
        _c_left(app, l0, l1)
        return
    vj_state.of(app).csweep = (clock.now(), dur, l0, l1, 0.0)


C_PRESSES = ("in", "out", "toggle", "flash")


def c_launch(app, what):
    """Deck C's In, Out, In/Out (toggle) or Flash by hand - the frame's buttons, MIDI, the phone: at once or on
    the next beat or bar, as Cut and Fade go (quant). What it waits for, in words, or "" when it went at once."""
    if what == "toggle":
        what = "out" if c_is_in(app) else "in"
    q = options(app).get("quant", "now")
    if q not in ("beat", "bar"):
        vj_state.of(app).cpending = None
        c_go(app, what == "in", flash=what == "flash")
        return ""
    beats, src = beat_count(app)
    unit = 1 if q == "beat" else _per_bar(app, src)
    vj_state.of(app).cpending = (float((math.floor(beats / unit + 1e-6) + 1) * unit), what)
    return "the next beat" if q == "beat" else "the next bar"


def c_hand(app):
    """Deck C's level set by hand (the knob, MIDI, the phone): a sweep under way, and a press waiting, let go."""
    vj_state.of(app).csweep = None
    vj_state.of(app).cpending = None


def _c_left(app, l0, l1):
    """Deck C just went out under its auto-mix: dealt a new look while shuffling, so it comes back as another."""
    a = options(app)["auto"]
    if l0 > 0.0 and l1 <= 0.0 and a.get("shuffle") and a.get("c", "off") != "off":
        shuffle(app, 2)


def _c_update(app):
    """Each frame: a press waiting for its beat gone, deck C's sweep moved on, and its own auto-mix."""
    o = options(app)
    p = vj_state.of(app).cpending
    if p is not None and beat_count(app)[0] >= p[0] - 1e-6:
        vj_state.of(app).cpending = None
        c_go(app, p[1] == "in", flash=p[1] == "flash")
    sw = vj_state.of(app).csweep
    if sw is not None:
        t0, dur, l0, l1, hold = sw
        t = clock.now() - t0 - hold
        k = 1.0 if t >= dur else max(0.0, t / dur)
        o["decks"][2]["level"] = round(l0 + (l1 - l0) * (0.5 - 0.5 * math.cos(math.pi * k)), 4)
        vj_state.of(app).knobs_moved = True
        if k >= 1.0:
            vj_state.of(app).csweep = None
            _c_left(app, l0, l1)
    a = o["auto"]
    mode = a.get("c", "off")
    if mode in ("bars", "flash"):
        per = max(1, int(a.get("c_bars", 4)))
        k = int(bar_count(app)[0] // per)
        if vj_state.of(app).cbar_k is not None and k != vj_state.of(app).cbar_k:
            c_go(app, not c_is_in(app), flash=mode == "flash")
        vj_state.of(app).cbar_k = k
    elif mode == "sections":
        sec = _section_now(app)
        was = sec if vj_state.of(app).csec == vj_state.UNSET else vj_state.of(app).csec
        vj_state.of(app).csec = sec
        if sec is not None and sec != was:
            loud = sec[1] in C_LOUD
            if loud != c_is_in(app):
                c_go(app, loud, beats=0.0 if sec[1] == "drop" else None)   # into a drop at once, else its fade


# --- the show: a step that is the VJ's --------------------------------------------------------------
SHUFFLE_FROM = (("any", "from any look"), ("family", "from its own family"))
SNAP_KEYS = ("decks", "fader", "mode", "wipe", "map", "canvas", "c_mode", "c_up", "c_fade")


def snapshot(app):
    """What a step keeps of the VJ: its decks, fader, blend, wipe, map and canvas - and which modulators run, how
    deep (modulate.scene)."""
    from native import modulate
    o = options(app)
    snap = json_copy({k: o[k] for k in SNAP_KEYS})
    if modulate.modulators(app):
        snap["mods"] = modulate.scene(app)
    return snap


def _fade_from_here(app, step):
    """A show's step blending in: what showed until now blended into what shows next, over the step's blend."""
    dur = float(step.get("trans", 0.0) or 0.0) if isinstance(step, dict) else 0.0
    last = vj_state.of(app).last_pic
    if dur <= 0.0 or last is None:
        vj_state.of(app).fade = None
        return
    try:
        from native import sequence_ui
        style = str(sequence_ui._steps(app).get("style") or "fade")
    except Exception:
        oops.swallowed()
        style = "fade"
    vj_state.of(app).fade = {"t0": clock.now(), "dur": dur, "from": np.array(last, copy=True), "style": style}


def apply_step(app, step, playing=True):
    """A step loaded: one of the VJ's puts its decks on air (the desk as it was kept, to come back when the show
    lets it go); one that is not takes the VJ off air again - if a VJ step had put it there. Either way, blended
    over the step's blend from what showed before. Not playing (a step shown in the sim, as Load into the sim
    does), a VJ step's decks become the desk's - nothing is kept to come back to - and a step that is not the
    VJ's leaves the desk alone."""
    v = step.get("vj") if isinstance(step, dict) else None
    if not isinstance(v, dict):                             # a damaged show's (true, a number, a list): not the VJ's
        v = None
    o = options(app)
    by_show = vj_state.of(app).by_show
    if not playing:
        if v:
            if by_show:                                    # a show's desk let go: what is loaded now is the desk
                vj_state.of(app).by_show, vj_state.of(app).desk = False, None
            for k in SNAP_KEYS:
                if k in v:
                    o[k] = json_copy(v[k])
            _FILLED[0] = None                              # the step's settings checked as a project's are
            options(app)
            o["on"] = True
            vj_state.of(app).sweep = vj_state.of(app).pending = None
            vj_state.of(app).csweep = vj_state.of(app).cpending = None
            vj_state.of(app).morphs = {}
            vj_state.of(app).dirty = True
            if v.get("mods"):
                from native import modulate
                modulate.load_scene(app, v["mods"])
        return
    if v:
        if not by_show:
            vj_state.of(app).desk = json_copy({k: o[k] for k in SNAP_KEYS + ("on",)})
            for d in vj_state.of(app).desk.get("decks") or ():        # a Mutate growing: the desk kept with it grown (no
                to = d.get("morph_to") or ""                 # one is left to grow it), not frozen part-way
                if to:
                    if to in vj_looks.LOOKS:
                        d["look"] = to
                    d["morph_to"], d["morph"] = "", 0.0
        vj_state.of(app).morphs = {}
        vj_state.of(app).pending = None                             # a Cut waiting for its beat: not over the step's fader
        _fade_from_here(app, step)
        for k in SNAP_KEYS:
            if k in v:
                o[k] = json_copy(v[k])
        _FILLED[0] = None                             # (a hand-edited step's null fader: put right, not raised)
        options(app)                                  # anything the snapshot left out, defaulted
        o["on"] = True
        app.project.save_view = lambda opts, app=app: _desk_saved(app, opts)   # saved meanwhile: the desk, kept
        vj_state.of(app).csweep = vj_state.of(app).cpending = None       # deck C as the step has it, not a fade from before
