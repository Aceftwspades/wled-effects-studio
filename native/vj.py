class Ctx:
    """What a look reads (vj_looks' docstring lists it)."""


_GRID = {}


def _grid(w, h):
    g = _GRID.get((w, h))
    if g is None:
        u, v = np.meshgrid(np.linspace(0, 1, w, dtype=np.float32), np.linspace(0, 1, h, dtype=np.float32))
        x = (u - 0.5) * 2.0 * w / h
        y = (v - 0.5) * 2.0
        g = _GRID[(w, h)] = (u, v, x, y, np.hypot(x, y), np.arctan2(y, x))
    return g


def sound(app):
    """(bass, mid, treb, level, wave) of what the effects hear now."""
    eng = app.eng
    try:
        f = np.asarray(eng.fft, np.float32) / 255.0
    except Exception:
        f = np.zeros(16, np.float32)
    bass, mid, treb = float(f[0:3].mean()), float(f[4:9].mean()), float(f[10:16].mean())
    vol = float(getattr(eng, "last_audio", (0.0, 0))[0])
    level = min(1.0, vol / 255.0) if vol > 1.0 else min(1.0, vol)
    pcm = getattr(eng, "last_pcm", None)
    if pcm is not None and len(pcm) >= 16:
        wave = np.asarray(pcm, np.float32)[:: max(1, len(pcm) // 64)][:64] / 127.0
    else:                                                     # no waveform: one drawn from the bands
        t = clock.now()
        k = np.arange(64, dtype=np.float32) / 64.0
        wave = sum(f[j] * np.sin(2 * np.pi * k * (j + 1) + t * (2 + j)) for j in range(0, 16, 3)) * 0.6
    return bass, mid, treb, level, np.asarray(wave, np.float32)


# --- the map onto the shape ----------------------------------------------------------------------
_MAP = {}


def mapping(geom, rows, cols, mode):
    """(u, v) on the canvas for every pixel of the logical grid, (rows*cols,) each, and the lit mask: the
    Video node's projections (nodedefs.py), made once for a geometry and a mode."""
    key = (id(geom), rows, cols, mode)
    m = _MAP.get(key)
    if m is not None:
        return m
    n = rows * cols
    lit = np.ones(n, bool) if geom is None or geom.lit is None or len(geom.lit) != n else np.asarray(geom.lit, bool)
    cu, cv = np.meshgrid(np.linspace(0, 1, cols), np.linspace(0, 1, rows))
    u, v = cu.ravel().astype(np.float32), cv.ravel().astype(np.float32)
    pos = None if geom is None or geom.pos is None or len(geom.pos) != n else np.nan_to_num(np.asarray(geom.pos, np.float32))
    if pos is not None and mode != "picture":
        s = float(np.abs(pos[lit]).max()) if lit.any() else 1.0
        X, Y, Z = (pos / max(1e-6, s)).T
        cube = geom.kind == "cube"
        up = Z if (cube or np.abs(Z).max() > 1e-6) else Y
        if mode == "front":
            u, v = X * 0.5 + 0.5, 0.5 - up * 0.5
        elif mode == "top":
            u, v = X * 0.5 + 0.5, 0.5 - Y * 0.5
        elif mode == "around":
            u, v = np.arctan2(Y, X) / (2 * np.pi) + 0.5, 0.5 - up * 0.5
        elif mode == "faces":
            ax, ay, az = np.abs(X), np.abs(Y), np.abs(Z)
            if cube:
                fz = (az >= ax) & (az >= ay)
                fy = ~fz & (ay >= ax)
                m_ = np.where(fz, az, np.where(fy, ay, ax))
                pa = np.where(fz | fy, X, Y)
                pb = np.where(fz, Y, Z)
            else:
                m_, pa, pb = np.ones_like(X), X, up
            m_ = np.maximum(m_, 1e-3)
            u, v = pa / m_ * 0.5 + 0.5, 0.5 - pb / m_ * 0.5
        elif mode == "sphere":
            nrm = geom.nrm if geom.nrm is not None and len(geom.nrm) == n else pos / np.maximum(
                np.linalg.norm(pos, axis=1, keepdims=True), 1e-6)
            nx, ny, nz = np.asarray(nrm, np.float32).T
            u, v = np.arctan2(ny, nx) / (2 * np.pi) + 0.5, np.arccos(np.clip(nz, -1, 1)) / np.pi
    m = (np.clip(u, 0, 1).astype(np.float32), np.clip(v, 0, 1).astype(np.float32), lit)
    if len(_MAP) > 32:
        _MAP.clear()
    _MAP[key] = m
    return m


def to_shape(app, canvas, mode=None):
    """A canvas ((h, w, 3) float 0..1) as the logical grid's picture, (rows, cols, 3) uint8, unlit pixels dark."""
    eng = app.eng
    rows, cols = eng.rows, eng.cols
    u, v, lit = mapping(app.project.geometry, rows, cols, mode or options(app)["map"])
    px = vj_looks.sample(canvas, u, v)
    px[~lit] = 0
    return (np.clip(px, 0, 1) * 255 + 0.5).astype(np.uint8).reshape(rows, cols, 3)


# --- drawing -------------------------------------------------------------------------------------
def _beat(app, now):
    last = getattr(app, "last_hit_at", None)
    if last is None:
        return 0.0, False
    since = now - last
    if since < 0:
        return 0.0, False
    pulse = 0.5 - 0.5 * math.cos(math.pi * since / 0.14) if since < 0.14 else math.exp(-(since - 0.14) * 5.0)
    hit = last != getattr(app, "_vj_last_hit", None)
    return pulse, hit


def _tempo(app):
    try:
        from native import modulate
        return modulate.tempo(app)
    except Exception:
        return 120.0


def draw_deck(app, i, dt, snd, beat, hit):
    """Deck i a frame on: its video's newest frame taken, its look drawn on the canvas (or its effect run)."""
    o = options(app)
    deck = o["decks"][i]
    run = _runs(app)[i]
    run.t += dt * float(deck.get("speed", 1.0))
    if deck["look"] == EFFECT:
        run.led = _effect_frame(app, i, run, deck)
        return
    src = _source(app, i, run, deck)
    run.error = run.open_error
    if src is not None:
        frame, n = src.latest()
        if frame is not None and n != run.n:
            run.n = n
            run.video_prev = run.video
            run.video = np.asarray(frame, np.float32) / 255.0
        err = getattr(src, "error", None)
        if err:
            run.error = str(err)
    lk = vj_looks.LOOKS.get(deck["look"]) or vj_looks.LOOKS["Plasma"]
    if run.look != lk.name:
        run.look = lk.name
        run.state = {}
    c = Ctx()
    c.w, c.h = CANVAS_W, CANVAS_H
    c.u, c.v, c.x, c.y, c.r, c.a = _grid(CANVAS_W, CANVAS_H)
    c.t, c.dt = run.t, dt * float(deck.get("speed", 1.0))
    c.bass, c.mid, c.treb, c.level, c.wave = snd
    c.beat, c.beat_hit = beat, hit
    c.beats = getattr(app, "_vj_beats", 0.0)
    v = run.video
    if v is not None and v.shape[:2] != (CANVAS_H, CANVAS_W):           # a source that keeps its own size
        from PIL import Image
        v = np.asarray(Image.fromarray((v * 255).astype(np.uint8)).resize((CANVAS_W, CANVAS_H)), np.float32) / 255.0
        run.video = v
    c.video, c.video_prev = run.video, run.video_prev
    c.amount, c.speed = float(deck.get("amount", 0.5)), float(deck.get("speed", 1.0))
    c.grad = vj_looks.gradient(deck.get("colours", "neon"))
    try:
        img = lk.draw(c, run.state)
    except Exception as e:                                          # a look of the user's that fails: said, dark
        run.error = f"{lk.name}: {type(e).__name__}: {e}"
        img = np.zeros((CANVAS_H, CANVAS_W, 3), np.float32)
    k = int(deck.get("kaleido", 0) or 0)
    if k > 0:
        img = vj_looks.kaleido(c, img, k)
    if deck.get("mirror"):
        img = vj_looks.mirror(img)
    if deck.get("hue"):
        img = vj_looks.hue_turn(img, float(deck["hue"]))
    if deck.get("strobe"):
        img = img * (0.15 + 0.85 * beat)
    run.canvas = np.clip(img, 0, 1).astype(np.float32)


def _effect_frame(app, i, run, deck):
    """An Effect deck: the studio's effect named, on an engine of the deck's, hearing the same sound."""
    name = deck.get("effect") or ""
    try:
        eng = app.second_engine(f"vj{i}")
    except Exception as e:
        run.error = str(e)
        return None
    if eng.cols != app.eng.cols or eng.rows != app.eng.rows:
        eng.set_geometry(app.project.geometry)
        run.state = {}
    if name not in eng.names:
        run.error = f"no effect called {name!r}" if name else "no effect chosen"
        return None
    if run.state.get("sel") != name:
        eng.select(eng.names.index(name))
        run.state = {"sel": name}
    eng.fx["sx"] = int(round(float(deck.get("speed", 1.0)) * 128)) & 255
    eng.fx["ix"] = int(round(float(deck.get("amount", 0.5)) * 255))
    eng.push()
    try:
        eng.fft[:] = app.eng.fft[:]
        eng.audio(*getattr(app.eng, "last_audio", (0.0, 0)))
        eng.frame(23)
    except Exception as e:
        run.error = str(e)
        return None
    run.error = ""
    return eng.rgb().copy()


def deck_led(app, i):
    """Deck i's picture on the shape, (rows, cols, 3) uint8, or None before it has drawn."""
    o = options(app)
    run = _runs(app)[i]
    if o["decks"][i]["look"] == EFFECT:
        return run.led
    if run.canvas is None:
        return None
    return to_shape(app, run.canvas)


def deck_canvas(app, i):
    """Deck i's picture for its preview: its canvas, or an Effect deck's logical grid."""
    o = options(app)
    run = _runs(app)[i]
    if o["decks"][i]["look"] == EFFECT:
        return run.led
    return None if run.canvas is None else (run.canvas * 255).astype(np.uint8)


def update(app, dt=None):
    """Each frame while the VJ frame is on air (or open): both decks drawn, the auto-mix moved, the mix made."""
    from native import mixer
    o = options(app)
    now = clock.now()
    if dt is None:
        last = getattr(app, "_vj_at", None)
        dt = 0.0 if last is None else min(0.1, max(0.0, now - last))
    app._vj_at = now
    app._vj_beats = getattr(app, "_vj_beats", 0.0) + dt * _tempo(app) / 60.0
    snd = sound(app)
    beat, hit = _beat(app, now)
    app._vj_last_hit = getattr(app, "last_hit_at", None)
    f = float(o["fader"])
    app._vj_tick = getattr(app, "_vj_tick", 0) + 1
    for i in (0, 1):
        live = (i == 0 and f < 1.0) or (i == 1 and f > 0.0)
        # a deck fully off the mix is drawn only for its preview, every other frame (its time kept whole)
        if live:
            draw_deck(app, i, dt + _skipped(app, i), snd, beat, hit)
        elif getattr(app, "_vj_preview", False) and (app._vj_tick + i) % 2 == 0:
            draw_deck(app, i, dt + _skipped(app, i), snd, beat, hit)
        else:
            app.__dict__.setdefault("_vj_skip", [0.0, 0.0])[i] += dt
    _auto(app, hit)
    a, b = deck_led(app, 0), deck_led(app, 1)
    shape = (app.eng.rows, app.eng.cols, 3)
    a = a if a is not None and a.shape == shape else np.zeros(shape, np.uint8)
    b = b if b is not None and b.shape == shape else np.zeros(shape, np.uint8)
    app._vj_out = mixer.mix(a, b, float(o["fader"]), o["mode"])


def _skipped(app, i):
    """The time a deck was not drawn for, given back to it once (and forgotten)."""
    sk = app.__dict__.setdefault("_vj_skip", [0.0, 0.0])
    t, sk[i] = sk[i], 0.0
    return min(t, 0.25)


def picture(app, rgb):
    """The frame through the VJ: its mix when it is on air, the effect's as it is otherwise."""
    if not on(app):
        return rgb
    out = getattr(app, "_vj_out", None)
    if out is None or out.shape != np.asarray(rgb).shape:
        return rgb
    return out


# --- auto-mix and shuffle ------------------------------------------------------------------------
FADE_BEATS = 2.0                 # an auto-mix's sweep, in beats (a drop's is a cut)


def _auto(app, hit):
    """The fader moved by itself: to the other deck every n bars, or at the show's sections (a cut into a drop,
    a slow fade into the quiet parts); a deck dealt a new look as the mix leaves it, when shuffling."""
    o = options(app)
    a = o["auto"]
    sweep = getattr(app, "_vj_sweep", None)
    now = clock.now()
    if sweep is not None:
        t0, dur, f0, f1 = sweep
        k = 1.0 if dur <= 0 else min(1.0, (now - t0) / dur)
        e = 0.5 - 0.5 * math.cos(math.pi * k)
        o["fader"] = f0 + (f1 - f0) * e
        if k >= 1.0:
            app._vj_sweep = None
            if a.get("shuffle"):
                shuffle(app, 0 if f1 >= 0.5 else 1)         # the deck the mix just left
        return
    mode = a.get("mix", "off")
    if mode == "bars":
        beats = getattr(app, "_vj_beats", 0.0)
        per = max(1, int(a.get("bars", 4))) * 4
        k = int(beats // per)
        if k != getattr(app, "_vj_bar_k", k):
            go(app, FADE_BEATS * 60.0 / _tempo(app))
        app._vj_bar_k = k
    elif mode == "sections":
        sec = _section_now(app)
        was = getattr(app, "_vj_sec", sec)
        app._vj_sec = sec
        if sec is not None and sec != was:
            kind = sec[1]
            if kind == "drop":
                dur = 0.0                                   # into a drop: a cut
            elif kind in ("intro", "outro", "breakdown"):
                dur = 4.0                                   # into the quiet parts: a slow fade
            else:
                dur = FADE_BEATS * 60.0 / _tempo(app)
            go(app, dur)


def _section_now(app):
    """(index, kind) of the show's section the playhead is in, or None (not playing, or no sections)."""
    try:
        from native import sequence_ui
        pos = sequence_ui.position(app)
        if pos is None:
            return None
        for k, s in enumerate(sequence_ui._sections(app)):
            if float(s["at"]) <= pos < float(s["at"]) + float(s["len"]):
                return (k, s.get("kind", "verse"))
    except Exception:
        return None
    return None


def go(app, seconds):
    """The fader swept to the other end over `seconds` (0: a cut)."""
    o = options(app)
    f0 = float(o["fader"])
    f1 = 0.0 if f0 >= 0.5 else 1.0
    if seconds <= 0:
        o["fader"] = f1
        app._vj_sweep = None
        if o["auto"].get("shuffle"):
            shuffle(app, 0 if f1 >= 0.5 else 1)
        return
    app._vj_sweep = (clock.now(), float(seconds), f0, f1)


def shuffle(app, i):
    """Deck i dealt a look it does not have, of the same family when its source is video, else any canvas look."""
    import random
    o = options(app)
    d = o["decks"][i]
    if d["look"] == EFFECT:
        return
    has_video = d["source"].get("kind", "none") != "none"
    pool = [n for n, lk in vj_looks.LOOKS.items() if n != d["look"] and (lk.video == has_video or not lk.video)]
    if pool:
        d["look"] = random.choice(pool)
        app._vj_dirty = True


# --- the show: a step that is the VJ's --------------------------------------------------------------
SNAP_KEYS = ("decks", "fader", "mode", "map")


def snapshot(app):
    """What a step keeps of the VJ: its decks, fader, blend and map."""
    o = options(app)
    return json_copy({k: o[k] for k in SNAP_KEYS})


def apply_step(app, step):
    """A step loaded: one of the VJ's puts its decks on air; one that is not takes the VJ off air again - if a
    VJ step had put it there."""
    v = step.get("vj") if isinstance(step, dict) else None
    o = options(app)
    if v:
        for k in SNAP_KEYS:
            if k in v:
                o[k] = json_copy(v[k])
        options(app)                                  # anything the snapshot left out, defaulted
        o["on"] = True
        app._vj_by_show = True
        app._vj_sweep = None
        app._vj_dirty = True
    elif getattr(app, "_vj_by_show", False):
        o["on"] = False
        app._vj_by_show = False
        app._vj_dirty = True


def step_name(app):
    o = options(app)
    a, b = (d["look"] if d["look"] != EFFECT else d.get("effect") or EFFECT for d in o["decks"])
    return f"VJ: {a} / {b}"


