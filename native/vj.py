def mutate_flame(app, i):
    """Deck i's flame bred into a new one, kept with the project and put on the deck: its name."""
    import random
    o = options(app)
    d = o["decks"][i]
    lk = vj_looks.LOOKS.get(d["look"])
    if lk is None or lk.family != "flame":
        return None
    base = vj_looks.FLAMES.get(d["look"]) or o["flames"].get(d["look"])
    if base is None:
        return None
    child = vj_looks.mutate(base, random.randrange(1 << 30))
    stem = d["look"].split(" #")[0]
    k = 2
    while f"{stem} #{k}" in vj_looks.LOOKS:
        k += 1
    name = f"{stem} #{k}"
    o["flames"][name] = child
    vj_looks.register_flame(name, child)
    d["look"] = name
    return name


def forget_flame(app, name):
    """A bred flame let go: no longer kept or listed; a deck on it goes back to the flame it was bred from."""
    o = options(app)
    if name not in o["flames"]:
        return False
    del o["flames"][name]
    vj_looks.LOOKS.pop(name, None)
    stem = name.split(" #")[0]
    for d in o["decks"]:
        if d["look"] == name:
            d["look"] = stem if stem in vj_looks.LOOKS else "Plasma"
    return True


def rename_flame(app, old, new):
    o = options(app)
    new = (new or "").strip()
    if old not in o["flames"] or not new or new in vj_looks.LOOKS:
        return False
    fl = o["flames"].pop(old)
    o["flames"][new] = fl
    vj_looks.LOOKS.pop(old, None)
    vj_looks.register_flame(new, fl)
    for d in o["decks"]:
        if d["look"] == old:
            d["look"] = new
    return True


def project_changed(app):
    """Another project opened: the last one's show desk, sources, decks' state and bred flames let go."""
    app._vj_by_show, app._vj_desk, app._vj_fade, app._vj_sweep = False, None, None, None
    app._vj_mod = {}
    close(app)
    app._vj_runs = None
    for n in [n for n, lk in vj_looks.LOOKS.items() if lk.family == "flame" and n not in vj_looks.FLAMES]:
        vj_looks.LOOKS.pop(n, None)
    options(app)                                            # this project's flames registered


def midi_looks():
    """The looks in an order that does not shift as looks are added: the built-in ones as they ship, Effect, then
    the project's own and the bred flames by name (MIDI picks a look by its place along this)."""
    extra = sorted(n for n in vj_looks.LOOKS if n not in vj_looks.BUILTIN)
    return list(vj_looks.BUILTIN) + [EFFECT] + extra


# --- a deck's controls by name: MIDI's and the modulators' -----------------------------------------
KNOBS = (("amount", 0.0, 1.0), ("speed", 0.0, SPEED_MAX), ("hue", 0.0, 1.0), ("kaleido", 0, 12), ("trails", 0.0, 1.0),
         ("blur", 0, 3))
KNOB_WORDS = {"amount": "amount", "speed": "speed", "hue": "hue", "kaleido": "kaleidoscope", "trails": "trails",
              "blur": "blur"}


def knob_value(app, i, key):
    """A deck's knob as it draws: a modulator's value over it while one moves it (vj_mod, never saved), else the
    knob's own (what the dialog, MIDI and the project have)."""
    m = getattr(app, "_vj_mod", None)
    if m and (i, key) in m:
        return m[(i, key)]
    lo = next(a for k, a, _ in KNOBS if k == key)
    return float(options(app)["decks"][i].get(key, lo) or 0)


def knob_get(app, i, key):
    """A deck's knob as 0..1 of its range."""
    lo, hi = next((a, b) for k, a, b in KNOBS if k == key)
    v = float(options(app)["decks"][i].get(key, lo) or 0)
    return (v - lo) / (hi - lo)


def knob_set(app, i, key, f):
    """A deck's knob from 0..1 of its range (whole numbers for the kaleidoscope and the blur)."""
    lo, hi = next((a, b) for k, a, b in KNOBS if k == key)
    f = max(0.0, min(1.0, float(f)))
    v = lo + (hi - lo) * f
    options(app)["decks"][i][key] = int(round(v)) if isinstance(hi, int) else round(v, 4)
    app._vj_knobs_moved = True
