def _runs(app):
    r = app.__dict__.get("_vj_runs")
    if r is None:
        r = app._vj_runs = [DeckRun(), DeckRun()]
    return r


def _pool(app):
    """{source key: [source, error]}: the video sources open, shared by the decks that look at the same one."""
    return app.__dict__.setdefault("_vj_pool", {})


def clip_path(s):
    """The file a deck plays: its clip in its list, else its one path."""
    files = [f for f in (s.get("files") or []) if f]
    if files:
        return files[int(s.get("clip", 0)) % len(files)]
    return s.get("path") or ""


def source_key(app, s):
    kind = s.get("kind", "none")
    if kind == "none":
        return None
    w, h = canvas_size(app)
    if kind == "file":
        return ("file", clip_path(s), round(float(s.get("speed", 1.0)), 3), float(s.get("in", 0.0)),
                float(s.get("out", 0.0)), w, h)
    return (kind, s.get("path"), s.get("name"), s.get("url"), w, h)


def _open(app, s, key):
    from native import video
    w, h = canvas_size(app)
    kind = s["kind"]
    if kind == "file":
        import os
        path = clip_path(s)
        if not path or not os.path.exists(path):
            raise ValueError(f"no video file at {path}" if path else "no video file chosen")
        args = []
        sp = max(0.1, min(8.0, float(s.get("speed", 1.0))))
        if abs(sp - 1.0) > 1e-3:
            args += ["-itsscale", f"{1.0 / sp:.6f}"]               # the clip's own time scaled: faster or slower
        a, b = float(s.get("in", 0.0)), float(s.get("out", 0.0))
        if a > 0:
            args += ["-ss", f"{a:.3f}"]
        if b > a:
            args += ["-t", f"{(b - a):.3f}"]
        return video.FfmpegSource(args + ["-i", path], os.path.basename(path), "file", w, h, realtime=True, loop=True)
    return video.open_source(kind, path=s.get("url") if kind == "stream" else s.get("path"), name=s.get("name"),
                             width=w, height=h, loop=True)


def _source(app, i, run, deck):
    """The deck's video source - the one open for its key, shared, or opened now - or None."""
    s = deck["source"]
    key = source_key(app, s)
    pool = _pool(app)
    if key != run.src_key:
        run.src_key = key
        run.video = run.video_prev = None
        run.n = -1
        _release(app)
    if key is None:
        run.open_error = ""
        return None
    if key not in pool:
        try:
            src = _open(app, s, key)
            import atexit
            atexit.register(src.close)
            pool[key] = [src, ""]
        except Exception as e:
            pool[key] = [None, str(e)]
    src, err = pool[key]
    run.open_error = err
    return src


def _release(app):
    """Sources no deck looks at any more, closed."""
    pool = _pool(app)
    used = {r.src_key for r in _runs(app)}
    for key in [k for k in pool if k not in used]:
        src = pool.pop(key)[0]
        if src is not None:
            try:
                src.close()
            except Exception:
                pass


def close(app):
    for r in _runs(app):
        r.src_key = None
        r.video = r.video_prev = None
    _release(app)


def pause(app, i, on=None):
    """A deck's video paused (the picture holds) or played on; whether it is paused now."""
    run = _runs(app)[i]
    ent = _pool(app).get(run.src_key)
    if not ent or ent[0] is None:
        return False
    src = ent[0]
    src.pause(not src.paused if on is None else bool(on))
    return src.paused


def next_clip(app, i, step=1):
    """A deck's next video file in its list (or the one before)."""
    s = options(app)["decks"][i]["source"]
    files = [f for f in (s.get("files") or []) if f]
    if len(files) > 1:
        s["clip"] = (int(s.get("clip", 0)) + step) % len(files)
        app._vj_dirty = True


