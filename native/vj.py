def knob_value(app, i, key):
    """A deck's knob as it draws: a modulator's value over it while one moves it (vj_mod, never saved), else the
    knob's own (what the dialog, MIDI and the project have)."""
    m = getattr(app, "_vj_mod", None)
    if m and (i, key) in m:
        return m[(i, key)]
    lo = next(a for k, a, _ in KNOBS if k == key)
    return float(options(app)["decks"][i].get(key, lo) or 0)


def knob_get(app, i, key):
    """A deck's knob as 0..1 of its range."""
    lo, hi = next((a, b) for k, a, b in KNOBS if k == key)
    v = float(options(app)["decks"][i].get(key, lo) or 0)
    return (v - lo) / (hi - lo)


def knob_set(app, i, key, f):
    """A deck's knob from 0..1 of its range (whole numbers for the kaleidoscope and the blur)."""
    lo, hi = next((a, b) for k, a, b in KNOBS if k == key)
    f = max(0.0, min(1.0, float(f)))
    v = lo + (hi - lo) * f
    options(app)["decks"][i][key] = int(round(v)) if isinstance(hi, int) else round(v, 4)
    app._vj_knobs_moved = True
    if i == 2 and key == "level":
        c_hand(app)
    if key == "morph":
        morph_hand(app, i)
