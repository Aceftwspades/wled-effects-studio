def options(app):
    o = app.project.options.setdefault("vj", {})
    o.setdefault("on", False)
    o.setdefault("fader", 0.0)
    o.setdefault("mode", "crossfade")
    o.setdefault("map", "picture")
    decks = o.setdefault("decks", [])
    while len(decks) < 2:
        d = json_copy(DECK)
        d["look"] = "Plasma" if not decks else "Drop: Nebula"
        decks.append(d)
    for d in decks:
        for k, v in DECK.items():
            if k not in d:
                d[k] = json_copy(v)
    o.setdefault("presets", {})          # {name: a deck's look and knobs, saved}
    flames = o.setdefault("flames", {})  # {name: a flame bred by Mutate}
    for name, fl in flames.items():
        if name not in vj_looks.LOOKS:
            vj_looks.register_flame(name, fl)
    a = o.setdefault("auto", {})
    a.setdefault("mix", "off")          # "off", "bars" (every n bars) or "sections" (the show's song sections)
    a.setdefault("bars", 4)
    a.setdefault("shuffle", False)
    return o


def json_copy(v):
    import json
    return json.loads(json.dumps(v))


def on(app):
    return bool(options(app)["on"])


# --- the decks' running parts --------------------------------------------------------------------
class DeckRun:
    """What a deck keeps between frames: its video source, its last two frames, its look's state, its time."""

    def __init__(self):
        self.src = None
        self.src_key = None
        self.video = None
        self.video_prev = None
        self.n = -1
        self.state = {}
        self.look = None
        self.t = 0.0
        self.canvas = None              # (h, w, 3) float 0..1, the look's last picture
        self.led = None                 # (rows, cols, 3) uint8: an Effect deck's picture
        self.error = ""
        self.open_error = ""            # the source's, when it could not be opened (kept until it is changed)
        self.eng = None

    def close(self):
        if self.src is not None:
            try:
                self.src.close()
            except Exception:
                pass
        self.src = None
        self.src_key = None
        self.video = self.video_prev = None


def _runs(app):
    r = app.__dict__.get("_vj_runs")
    if r is None:
        r = app._vj_runs = [DeckRun(), DeckRun()]
    return r


def _source(app, i, run, deck):
    """The deck's video source, opened (again when its choice changed) - or None."""
    s = deck["source"]
    key = (s.get("kind"), s.get("path"), s.get("name"), s.get("url"))
    if key == run.src_key:
        return run.src
    run.close()
    run.src_key = key
    run.open_error = ""
    if s.get("kind", "none") == "none":
        return None
    from native import video
    try:
        run.src = video.open_source(s["kind"], path=s.get("url") if s["kind"] == "stream" else s.get("path"),
                                    name=s.get("name"), width=CANVAS_W, height=CANVAS_H, loop=True)
        import atexit
        atexit.register(run.src.close)
    except Exception as e:
        run.src = None
        run.open_error = str(e)
    return run.src


def close(app):
    for r in _runs(app):
        r.close()


