def extract_stock():
    """Lift ColorFromPalette and the chosen stock effects out of the firmware."""
    colors = open(os.path.join(ROOT, "wled00", "colors.cpp"), encoding="utf-8",
                  errors="surrogateescape").read()
    cfp = extract_span(colors, "uint32_t ColorFromPalette(", "void setRandomColor(",
                       "ColorFromPalette")

    fxsrc = open(os.path.join(ROOT, "wled00", "FX.cpp"), encoding="utf-8",
                 errors="surrogateescape").read()
    parts, reg = discover_stock(fxsrc)

    # The roster is built here rather than in sim_main.cpp: the metadata strings
    # are static to this translation unit, and keeping the list beside the
    # extraction means it cannot fall out of step with what was extracted.
    reglines = "\n".join(f"  cfxBankAdd(&{fn}, {meta});" for fn, meta in reg)
    out = ('// GENERATED by build.py - do not edit.\n'
           '// Stock WLED code, lifted verbatim so comparisons are against the real\n'
           '// thing rather than against a paraphrase of it. Every 2-D effect in\n'
           '// FX.cpp is taken, discovered rather than listed.\n'
           '#include "wled.h"\n'
           '#include "cube_fx_bank.h"\n\n'
           + cfp + "\n" + "\n".join(parts) + "\n"
           "void simRegisterStock() {\n" + reglines + "\n}\n")
    path = os.path.join(GEN, "wled_fx.cpp")
    prev = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if prev != out:
        open(path, "w", encoding="utf-8").write(out)
        print(f"  extracted {len(reg)} stock 2-D effects + ColorFromPalette -> gen/wled_fx.cpp")
    else:
        print(f"  stock effects unchanged ({len(reg)})")
    return path


def find_vcvarsall():
    """Locate MSVC. vswhere is the supported way and survives version bumps."""
    pf = os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")
    vswhere = os.path.join(pf, "Microsoft Visual Studio", "Installer", "vswhere.exe")
    if os.path.exists(vswhere):
        r = _procs().run([vswhere, "-latest", "-products", "*",
                            "-requires", "Microsoft.VisualStudio.Component.VC.Tools.x86.x64",
                            "-property", "installationPath"],
                           capture_output=True, text=True)
        root = (r.stdout or "").strip().splitlines()
        if root:
            p = os.path.join(root[0], "VC", "Auxiliary", "Build", "vcvarsall.bat")
            if os.path.exists(p):
                return p
    for p in glob.glob(os.path.join(pf, "Microsoft Visual Studio", "*", "*",
                                    "VC", "Auxiliary", "Build", "vcvarsall.bat")):
        return p
    return None


def build_native(srcs, force=False):
    """Compile the same sources into a shared library the native front end loads.

    Delegated to native/toolchain.py, which compiles one object per translation
    unit with a cache and links a VERSIONED library - build/cubefx_<n>.dll -
    that the app can load while an older one is still open. The reasons for
    clang-not-MSVC (the VLA in CFX_NET_PREP) and for every flag are recorded
    there. cubefx.dll beside this script is still refreshed when it is not
    locked, so the CLI and older scripts keep working unchanged.
    """
    from native.toolchain import build_engine, lib_ext
    rep = build_engine(srcs, include_dirs(), force=force, log=print)
    if not rep.ok:
        print("  native: FAILED")
        return False
    legacy = os.path.join(HERE, "cubefx" + lib_ext())
    try:
        import shutil
        shutil.copyfile(rep.library, legacy)
    except OSError:
        print("  cubefx.dll is open in another process; build/latest points at the new one")
    return True


def engine_sources(extra=(), log=print):
    """Every translation unit the engine is made of - the extractions run
    first, so the generated files are current - plus any `extra` sources a
    project adds (the effects being edited in the studio). Without a WLED
    checkout the generated files in gen/ are taken as they are and the
    firmware files come from runtime/ (paths.py)."""
    fw = paths.firmware_dir()
    if ROOT:
        noise = extract_noise()
        extract_fx_modes()
        stock = extract_stock()
        write_page_palettes(extract_palette_names())
        from native.stock1d import extract as extract_stock1d
        stock1d = extract_stock1d(log=print)
        pal = extract_palettes()
    else:
        noise, stock, stock1d, pal = (os.path.join(GEN, f) for f in ("wled_noise.cpp", "wled_fx.cpp", "wled_fx1d.cpp", "wled_palettes.cpp"))
        missing = [p for p in (noise, stock, stock1d, pal) if not os.path.exists(p)] + ([] if os.path.isdir(fw) else [fw])
        if missing:
            sys.exit("build: no WLED checkout, and these are missing: " + ", ".join(missing) +
                     " - run  python build.py --runtime  from a checkout, or set WLED_ROOT")
        print("  no WLED checkout: gen/ and runtime/ as shipped")
    fx = sorted(glob.glob(os.path.join(fw, "cube_fx_[0-9][0-9]_*.cpp")))
    fx.append(os.path.join(fw, "cube_fx.cpp"))
    # Not an effect: registers audio-reactive palettes as a usermod. It has no NN
    # prefix so the glob above skips it, and it is named here explicitly.
    fx.append(os.path.join(fw, "cube_fx_palettes.cpp"))
    print(f"  {len(fx)} effect translation units")

    srcs = ([os.path.join(HERE, "sim_main.cpp")] + fx + [noise, stock, stock1d,
            paths.tree_path("wled00/wled_math.cpp"),
            # The real palette tables - seven FastLED palettes and 59 cpt-city
            # gradients - rather than a hand-copied handful. Compiling them is
            # what makes a palette id mean the same thing here as on the device.
            pal,
            paths.tree_path("wled00/src/dependencies/fastled_slim/fastled_slim.cpp")])
    return srcs + [os.path.abspath(e) for e in extra]


def include_dirs():
    """Where the engine's includes are found: the shim, the firmware, gen/,
    and FastLED's slim copy - by name, never by a path relative to the file."""
    return [os.path.join(HERE, "shim"), paths.firmware_dir(), GEN, paths.tree_path("wled00/src/dependencies/fastled_slim")]


def write_runtime(dest=None):
    """The firmware files the engine compiles from, copied out of the
    checkout into runtime/ (studio/runtime, or `dest`): what a packaged
    app builds effects from without a WLED tree beside it."""
    import shutil
    if not ROOT:
        sys.exit("build: --runtime needs a WLED checkout (the repo above studio/, or WLED_ROOT)")
    dest = dest or paths.RUNTIME
    for rel in paths.RUNTIME_FILES:
        src = os.path.join(ROOT, *rel.split("/"))
        dst = os.path.join(dest, *rel.split("/"))
        if os.path.isdir(src):
            if os.path.isdir(dst):
                shutil.rmtree(dst)
            shutil.copytree(src, dst, ignore=shutil.ignore_patterns("*.o", "*.pyc", "__pycache__"))
        else:
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(src, dst)
    n = sum(len(f) for _, _, f in os.walk(dest))
    print(f"  runtime: {n} files into {dest}")
    return dest


def main():
    want = set(sys.argv[1:]) or {"--wasm", "--native"}
    if "--wasm-only" in want:   want = {"--wasm"}
    if "--native-only" in want: want = {"--native"}
    if "--runtime" in want:                                # the firmware files out of the checkout, for a packaged app
        write_runtime(); return

    print("studio build")
    srcs = engine_sources()

    if "--native" in want:
        # The return value is NOT optional. build_native() reports a failure and
        # carries on, so ignoring it printed "build OK" over a link error and
        # left the PREVIOUS cubefx.dll in place - which then gets measured as
        # though it were the new code. The usual cause is the simulator app
        # holding the DLL open, so this is a routine failure, not a rare one.
        if not build_native(srcs, force=("--force" in sys.argv)):
            sys.exit("build FAILED - the dll was not replaced")
    if "--wasm" not in want:
        print("build OK")
        return

    # em++, not emcc. The simulator now holds std::vector palette registries
    # and a usermod list, and emcc links as C: the wasm link failed on
    # operator new, __cxa_throw and class vtables. emcc says so itself in
    # the failure - "try linking with em++ or passing -sDEFAULT_TO_CXX".
    cmd = ["em++", "-std=gnu++17", "-O2"]
    for d in include_dirs():                    # the same includes as the native build: the shim, the firmware, gen/, FastLED's slim copy
        cmd += ["-I", d]
    cmd += ["-DWLED_PS_DONT_REPLACE_2D_FX", "-DCFX_BANK_MAX_FX=256",
            "-DCFX_SIM"] + srcs + [
        "-o", "cubefx.js",
        # HEAPU8/HEAPU32 must be listed explicitly - current Emscripten does not
        # attach the heap views to the module by default, and reading pixels
        # back is the entire point of the exercise.
        "-s", "EXPORTED_RUNTIME_METHODS=ccall,cwrap,UTF8ToString,HEAPU8,HEAPU32",
        "-s", "ALLOW_MEMORY_GROWTH=1",
        "-s", "MODULARIZE=1",
        "-s", "EXPORT_NAME=CubeFX",
        "-s", "ENVIRONMENT=web",
    ]
    line = " ".join(f'"{c}"' if " " in c else c for c in cmd)

    # emsdk_env.bat needs SystemRoot and ComSpec, and some shells hand this
    # script an environment where they are EMPTY - Git Bash among them. The bat
    # then fails resolving %SystemRoot%\system32\..., and because the command is
    # chained with && that failure means emcc never runs at all. What you see is
    # "'emcc' is not recognized", which points at PATH and is the wrong trail
    # entirely: emsdk is installed and correct, and putting it on PATH does not
    # help, because the && still short-circuits on the bat.
    #
    # So the two are guaranteed here rather than assumed. Windows-only values,
    # applied only when missing.
    env = dict(os.environ)
    if not env.get("SystemRoot"):
        env["SystemRoot"] = os.environ.get("windir", r"C:\Windows")
    if not env.get("ComSpec"):
        env["ComSpec"] = os.path.join(env["SystemRoot"], "system32", "cmd.exe")

    # And MSYSTEM has to go. emsdk.py checks it (emsdk.py:99) and, seeing
    # MINGW64, writes the PATH it exports in POSIX form - "/c/Users/...", colon
    # separated. That is right for the bash that set it and wrong for the
    # cmd.exe the bat actually runs in, so emcc ends up on a PATH cmd cannot
    # read and `where emcc` returns nothing.
    #
    # Note this is NOT a PATH problem to be solved by converting PATH: Python
    # already holds a perfectly good Windows PATH, and rewriting it here only
    # corrupts it. What has to change is emsdk's idea of which shell it is
    # talking to.
    for k in ("MSYSTEM", "MSYS", "MSYSTEM_PREFIX"):
        env.pop(k, None)

    # Windows needs the batch file; on POSIX em++ is already on PATH.
    r = subprocess.run(wasm_shell_command(line, EMSDK), shell=True, cwd=HERE,
                       capture_output=True, text=True, env=env)
    if os.name == "nt" and r.returncode != 0 and "is not recognized" in ((r.stdout or "") + (r.stderr or "")):
        probe = subprocess.run(f'"{EMSDK}" && where emcc', shell=True, cwd=HERE,
                               capture_output=True, text=True, env=env)
        print("  emcc not found; emsdk_env.bat said:")
        print("   " + "\n   ".join(((probe.stdout or "") + (probe.stderr or "")).splitlines()[-6:]))
    out = (r.stdout or "") + (r.stderr or "")
    if r.returncode != 0:
        print(out[:4000]); sys.exit(f"build FAILED ({r.returncode})")
    if out.strip():
        print(out[:1500])
    for f in ("cubefx.js", "cubefx.wasm"):
        p = os.path.join(HERE, f)
        print(f"  {f}: {os.path.getsize(p):,} bytes" if os.path.exists(p) else f"  {f}: MISSING")
    print("build OK")


if __name__ == "__main__":
    main()
