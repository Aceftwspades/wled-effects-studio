    out = ("// GENERATED by build.py from wled00/FX.h - do not edit.\n#pragma once\n"
           + "\n".join(lines) + "\n")
    path = os.path.join(GEN, "fx_modes.h")
    prev = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if prev != out:
        open(path, "w", encoding="utf-8").write(out)
