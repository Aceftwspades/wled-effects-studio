fails = []


def check(ok, what):
    print(("ok   " if ok else "FAIL ") + what)
    if not ok:
        fails.append(what)


class Eng:
    def __init__(self, g):
        self.rows, self.cols = g.h, g.w
        self.fft = np.zeros(16, np.uint8)
        self.last_audio = (40.0, 0)
        self.fx = {"sx": 128, "ix": 128, "c1": 0, "c2": 0, "c3": 0}

    def push(self):
        pass


class Proj:
    def __init__(self, g):
        self.options = {"sequence": {"steps": [], "bpm": 120}}
        self.geometry = g
        self.path = tempfile.mkdtemp()

    def save(self):
        pass


class App:
    def __init__(self, g):
        self.eng, self.project = Eng(g), Proj(g)


g = geometry.Geometry("cube", B=16)
app = App(g)
vj.options(app)

t = vj_clips.fill({"kind": "pad_clip", "deck": "x", "file": 5, "mode": "bounce", "attack": -1, "sustain": 3,
                   "in": None, "level": "loud"})
check((t["deck"], t["file"], t["mode"], t["attack"], t["sustain"], t["in"], t["level"]) == (2, "", "oneshot", 0.0, 1.0,
      0.0, 1.0), f"a damaged clip target put right ({t})")

clock.hold()
try:
    clip = dict(vj_clips.DEFAULT, file="x.mp4", **{"in": 1.0, "out": 3.0}, attack=0.5, decay=0.5, sustain=0.5,
                release=0.5)
    vj_clips.play(app, clip, "p1")
    clock.step(1.0)
    vj_clips.tick(app)
    check(vj_clips.level(app, 2) == 0.0, "before its first picture: its time not started")
    vj_clips.started(app, 2, vj_clips._rt(app)[2]["take"])
    lv = []
    for _ in range(6):                                       # 0.25 s steps: up over 0.5, down to 0.5 over 0.5, held
        clock.step(0.25)
        vj_clips.tick(app)
        lv.append(round(vj_clips.level(app, 2), 2))
    check(lv == [0.5, 1.0, 0.75, 0.5, 0.5, 0.5], f"attack, decay to the sustain, held ({lv})")
    clock.step(0.25)                                         # the one shot is 2 s: let go at 1.5 s (its release 0.5)
    vj_clips.tick(app)
    mid = vj_clips.level(app, 2)
    clock.step(0.25)
    vj_clips.tick(app)
    check(mid == 0.25 and not vj_clips.playing(app, "p1") and vj_clips.level(app, 2) is None,
          f"a one shot: let go so its release ends at its Out ({mid} at 1.75 s), then off its deck")

    loop = dict(clip, mode="loop", attack=0.0, decay=0.0, sustain=1.0, release=1.0)
    vj_clips.play(app, loop, "p2")
    vj_clips.started(app, 2, vj_clips._rt(app)[2]["take"])
    for _ in range(20):
        clock.step(0.5)
        vj_clips.tick(app)
    check(vj_clips.level(app, 2) == 1.0, "a loop: round again past its length")
    vj_clips.stop(app, "p2")
    clock.step(0.5)
    vj_clips.tick(app)
    half = vj_clips.level(app, 2)
    vj_clips.play(app, clip, "p3")                            # another on the deck: from the level the last had
    check(half == 0.5 and vj_clips.level(app, 2) == 0.5 and not vj_clips.playing(app, "p2"),
          f"stopped: down its release ({half}); another takes its place from there")
    vj_clips.let_go(app)

    # the deck as it draws
    d = vj.options(app)["decks"][2]
    d["look"] = "Plasma"
    vj_clips.play(app, clip, "p4")
    dd = vj_clips.deck(app, 2, d)
    k1 = vj.source_key(app, dd["source"])
    vj_clips.play(app, clip, "p4")
    k2 = vj.source_key(app, vj_clips.deck(app, 2, d)["source"])
    check(dd["look"] == "Clean" and dd["source"]["path"] == "x.mp4" and dd["source"]["in"] == 1.0 and k1 != k2
          and d["look"] == "Plasma" and d["source"]["kind"] == "none",
          "the deck draws the clip (a video look, its file In to Out, a new take each start) - its own settings kept")
    d["look"] = "Thermal"
    check(vj_clips.deck(app, 2, d)["look"] == "Thermal", "a deck on a video look keeps it for the clip")
    clip_lv = dict(clip, attack=0.0, decay=0.0, sustain=1.0, level=0.6)
    vj_clips.play(app, clip_lv, "p4")
    vj_clips.started(app, 2, vj_clips._rt(app)[2]["take"])
    clock.step(0.1)
    vj_clips.tick(app)
    check(abs(vj.knob_value(app, 2, "level") - 0.6) < 1e-6 and d["level"] == 0.0,
          "deck C's level the clip's while it plays (its own knob left at 0)")
    vj.project_changed(app)
    check(vj_clips.level(app, 2) is None, "another project: every clip let go")

    # what each pad type does
    st = pads.state(app.project)
    trig = pads.new_control(st, "trigger", 0, 0, target=dict(clip))
    pads.press(app, trig)
    pads.release(app, trig)
    take = vj_clips._rt(app)[2]["take"]
    pads.press(app, trig)
    check(vj_clips._rt(app)[2]["take"] != take and vj_clips.playing(app, trig["id"]) and pads.lit(app, trig),
          "a trigger: each press from In again; lit while it plays")
    looper = pads.new_control(st, "trigger", 1, 0, target=dict(clip, mode="loop", release=0.0))
    pads.press(app, looper)
    pads.release(app, looper)
    on1 = vj_clips.playing(app, looper["id"])
    pads.press(app, looper)
    pads.release(app, looper)
    vj_clips.started(app, 2, vj_clips._rt(app)[2]["take"])
    clock.step(0.05)
    vj_clips.tick(app)
    check(on1 and not vj_clips.playing(app, looper["id"]), "a trigger on a loop: a press starts it, the next stops it")
    tog = pads.new_control(st, "toggle", 2, 0, target=dict(clip, release=0.0))
    pads.press(app, tog)
    pads.release(app, tog)
    on2 = pads.lit(app, tog)
    pads.press(app, tog)
    pads.release(app, tog)
    vj_clips.started(app, 2, vj_clips._rt(app)[2]["take"])
    clock.step(0.05)
    vj_clips.tick(app)
    check(on2 and not pads.lit(app, tog), "a toggle: on, then off")
    hold = pads.new_control(st, "hold", 3, 0, target=dict(clip, mode="loop", release=0.0))
    pads.press(app, hold)
    on3 = vj_clips.playing(app, hold["id"])
    pads.release(app, hold)
    vj_clips.started(app, 2, vj_clips._rt(app)[2]["take"])
    clock.step(0.05)
    vj_clips.tick(app)
    check(on3 and not vj_clips.playing(app, hold["id"]), "a hold: while held, let go")
    pads.press(app, hold)
    pads.forget(app, hold)
    check(not vj_clips._rt(app)[2]["gate"], "a pad taken away (or re-pointed): its clip let go")
    vj_clips.let_go(app)
finally:
    clock.release()

