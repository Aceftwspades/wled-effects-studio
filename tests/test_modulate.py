    check(app.eng.fx["c3"] == 31, "Custom 3 kept to 31")
    mo.modulators(app)[0]["on"] = False
    mo.apply(app)
    check(app.eng.fx["sx"] == 200 and mo.place(app, "sx") is None, "off: the slider left at its place")
    app.last_hit_at = clock.now()
    mo.modulators(app)[:] = [{"key": "ix", "kind": "beat", "depth": 50, "decay": 0.3, "on": True}]
    clock.step(mo.ATTACK_S)
    mo.apply(app)
    check(app.eng.fx["ix"] == 150 and app.eng.fx["c3"] == 30, f"the beat pushes; c3's modulator gone, it left at 30")
