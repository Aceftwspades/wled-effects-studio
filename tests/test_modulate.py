    mo.apply(app)
    check(app.eng.fx["sx"] == 170, "round the new place")
    app.eng.fx["c3"] = 30
    mo.modulators(app).append({"key": "c3", "kind": "lfo", "shape": "square", "period": 2, "depth": 60, "on": True})
