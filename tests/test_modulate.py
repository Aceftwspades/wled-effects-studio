check(near(mo.offset(lfo, 0.0, None), -50.0) and near(mo.offset(lfo, 0.5, None), 50.0), "a wave swings depth in all")
beat = {"kind": "beat", "depth": 80, "decay": 0.4}
check(mo.offset(beat, 0, None) == 0.0, "no beat yet: no push")
check(near(mo.offset(beat, 0, 0.0), 0.0) and near(mo.offset(beat, 0, mo.ATTACK_S), 80.0), "the beat's push eased in")
