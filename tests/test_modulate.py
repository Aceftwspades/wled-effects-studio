near = lambda a, b, tol=1e-6: abs(a - b) <= tol                          # noqa: E731

# the waves, 0..1
check(near(mo.wave("sine", 0.0), 0.0) and near(mo.wave("sine", 0.5), 1.0), "sine from its low point")
check(near(mo.wave("triangle", 0.25), 0.5) and near(mo.wave("triangle", 0.5), 1.0), "triangle")
check(near(mo.wave("saw up", 0.3), 0.3) and near(mo.wave("saw down", 0.3), 0.7), "saws")
