"""Before a push: every tests/test_*.py as CI runs it, then again under the conditions only CI's runners have.

    python tests/prepush.py                 # all four conditions, 4 tests at a time
    python tests/prepush.py -c bigclock     # one condition (plain, bigclock, noffmpeg, nogl; repeatable)
    python tests/prepush.py -k vj -j 1      # only tests whose name has "vj", one at a time

The conditions (each one has failed CI when local runs passed):
  plain     the test as it is
  bigclock  time.perf_counter ~4.5e6 s ahead, as on a runner up for weeks: there a time stepped by exactly a
            stage's length (native/clock.py's held clock) rounds short
  noffmpeg  no ffmpeg, ffprobe or yt-dlp (the packaged Windows runner)
  nogl      no OpenGL for shaders (the Windows and ARM Linux runners)

A test that fails with others running beside it is run again alone; passing alone, it is reported as a clash
(two tests sharing a port or a file), not a failure. Exit code 0 only when every run passed.

The GUI checks (smoke_app.py, walk_menus.py, pointer_app.py) are not run here: they take over the screen and
must run one at a time - run them after this passes.
"""
# AI: below section was generated by an AI
import argparse
import concurrent.futures as cf
import glob
import os
import runpy
import shutil
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONDITIONS = ("plain", "bigclock", "noffmpeg", "nogl")
BIG_CLOCK_S = 4567890.123            # where a long-running machine's perf_counter is (~53 days)
NO_TOOLS = ("ffmpeg", "ffprobe", "yt-dlp")
TIMEOUT_S = 900                      # one test file, however slow the machine


def _child(cond, path):
    """Run one test file in this process under a condition (the parent starts us as `prepush.py --run`)."""
    sys.path.insert(0, ROOT)
    if cond == "bigclock":           # every perf_counter far from zero, before anything has read it
        real_pc = time.perf_counter
        time.perf_counter = lambda: real_pc() + BIG_CLOCK_S
    elif cond == "noffmpeg":
        real = shutil.which

        def which(cmd, *a, **k):
            name = os.path.splitext(os.path.basename(str(cmd)))[0].lower()
            return None if name in NO_TOOLS else real(cmd, *a, **k)
        shutil.which = which
    elif cond == "nogl":
        sys.modules["moderngl"] = None   # import fails: vj_glsl.available() is False, as with no GL 3.3
    sys.argv = [path]
    sys.path.insert(0, os.path.dirname(os.path.abspath(path)))
    runpy.run_path(path, run_name="__main__")


def _env(cond):
    env = dict(os.environ, STUDIO_NO_UPDATE_CHECK="1", STUDIO_NO_WELCOME="1", PYTHONIOENCODING="utf-8")
    if cond == "noffmpeg":           # programs the test starts must not find the tools either
        keep = [d for d in env.get("PATH", "").split(os.pathsep)
                if not any(os.path.exists(os.path.join(d, t + e)) for t in NO_TOOLS for e in ("", ".exe"))]
        env["PATH"] = os.pathsep.join(keep)
    return env


def _run(cond, path):
    """One test under one condition: (ok, seconds, output tail)."""
    t0 = time.perf_counter()
    try:
        r = subprocess.run([sys.executable, os.path.abspath(__file__), "--run", cond, path], cwd=ROOT,
                           env=_env(cond), capture_output=True, text=True, encoding="utf-8", errors="replace",
                           timeout=TIMEOUT_S)
        ok, out = r.returncode == 0, (r.stdout or "") + (r.stderr or "")
    except subprocess.TimeoutExpired as e:
        ok, out = False, f"timed out after {TIMEOUT_S} s\n{e.stdout or ''}{e.stderr or ''}"
    return ok, time.perf_counter() - t0, "\n".join(out.strip().splitlines()[-25:])


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-c", "--condition", action="append", choices=CONDITIONS)
    ap.add_argument("-k", help="only test files whose name has this")
    ap.add_argument("-j", type=int, default=4, help="tests at a time (default 4)")
    a = ap.parse_args()
    conds = a.condition or list(CONDITIONS)
    tests = sorted(p for p in glob.glob(os.path.join(ROOT, "tests", "test_*.py")) if not a.k or a.k in p)
    if not tests:
        print("no tests match")
        return 2
    jobs = [(c, os.path.relpath(t, ROOT)) for c in conds for t in tests]
    print(f"{len(tests)} test files x {len(conds)} conditions ({', '.join(conds)}), {a.j} at a time")
    t0 = time.perf_counter()
    failed = []
    with cf.ThreadPoolExecutor(max(1, a.j)) as pool:
        futs = {pool.submit(_run, c, t): (c, t) for c, t in jobs}
        for f in cf.as_completed(futs):
            c, t = futs[f]
            ok, s, tail = f.result()
            print(f"{'ok  ' if ok else 'FAIL'} {c:9} {t} ({s:.0f} s)", flush=True)
            if not ok:
                failed.append((c, t, tail))
    clashes, real = [], []
    for c, t, tail in failed:        # again alone: a clash with a neighbour, or a real failure
        if a.j > 1:
            ok, s, tail2 = _run(c, t)
            if ok:
                clashes.append((c, t))
                continue
            tail = tail2
        real.append((c, t, tail))
    print(f"\n{len(jobs)} runs in {time.perf_counter() - t0:.0f} s")
    for c, t in clashes:
        print(f"CLASH {c} {t}: failed beside other tests, passed alone")
    for c, t, tail in real:
        print(f"\n===== FAIL {c} {t}\n{tail}")
    print("\nall passed" if not real else f"\n{len(real)} failed")
    return 1 if real else 0


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "--run":
        _child(sys.argv[2], sys.argv[3])
    else:
        sys.exit(main())
