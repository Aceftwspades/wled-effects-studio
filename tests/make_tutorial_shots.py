"""The sine-wave tutorial's pictures (docs/tutorial/step*_graph.png, step*_view.png, step5_result.png) and the
camera-mapping dialog's (tree_camera.png), taken from
the studio itself: a studio of this script's own is started with remote control on, the tutorial's graph is built
in it step by step as TUTORIAL.md tells the reader to, and after each step the graph and the LEDs are captured from
its frame buffer and cropped. Run again whenever the look of the graph or the views changes.

    python tests/make_tutorial_shots.py

The studio starts from no settings, as a new install does (projects/studio.json is put back after), in a scratch
project (projects/tutorial_shots, removed after). Only the studio this script started is stopped. One studio test
at a time: it drives the app through the same command file as tests/smoke_app.py. The finished graph's node places
are written to docs/tutorial/sine_wave.graph.json, so the bundle a reader opens looks like the pictures."""
# AI: below section was generated by an AI
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

import numpy as np                                          # noqa: E402
from PIL import Image                                       # noqa: E402
from native import scratch                                  # noqa: E402

OUT = os.path.join(ROOT, "docs", "tutorial")
BUNDLE = os.path.join(OUT, "sine_wave.graph.json")
PROJECT = "tutorial_shots"
CMD = scratch.path("command.json")
SHOT_REQ, SHOT_PNG = scratch.path("capture.request"), scratch.path("capture.png")
RECTS = scratch.path("tutorial_rects.txt")
VIEWPORT = (1600, 900)
PAD = 8                                                     # around what a picture is cropped to

# Where the nodes go once the tutorial adds its own (graph units). The starter's seven start where a new graph puts
# them (native/graph.py starter); Add steps down out of the Wave's way, and Palette and Output move right as the
# line's nodes come in - as a reader would make room.
POS = {8: (460, 40), 5: (460, 330), 9: (660, 40), 10: (860, 40), 11: (1060, 40)}
STEP3_OUT = {6: (1060, 180), 7: (1260, 180)}
STEP4_OUT = {6: (1260, 180), 7: (1460, 180)}


def send(cmds, wait=1.0):
    """A batch of commands, once the app has taken the last; then `wait` seconds for it to act."""
    end = time.time() + 60
    while os.path.exists(CMD) and time.time() < end:
        time.sleep(0.1)
    if os.path.exists(CMD):
        raise RuntimeError("the studio stopped taking commands")
    scratch.write_whole(CMD, json.dumps(cmds))
    time.sleep(wait)


def py(expr, wait=0.6):
    send([{"py": expr}], wait)


def capture():
    """The studio's window, from its frame buffer (native/remote.py service_capture)."""
    if os.path.exists(SHOT_PNG):
        os.remove(SHOT_PNG)
    open(SHOT_REQ, "w").close()
    end = time.time() + 20
    while not os.path.exists(SHOT_PNG) and time.time() < end:
        time.sleep(0.1)
    time.sleep(0.3)
    return Image.open(SHOT_PNG).convert("RGB")


def node_rects():
    """Each node's (min, max) on the screen."""
    if os.path.exists(RECTS):
        os.remove(RECTS)
    py("open(" + repr(RECTS) + ", 'w').write(repr("
       "[(dpg.get_item_rect_min(f'gnode_{n}'), dpg.get_item_rect_size(f'gnode_{n}')) for n in app.gp.graph.nodes]))", 1.0)
    return [(a, (a[0] + s[0], a[1] + s[1])) for a, s in eval(open(RECTS).read())]   # rect_max falls short by the padding


def crop(img, box, name):
    x0, y0, x1, y1 = box
    box = (max(0, x0 - PAD), max(0, y0 - PAD), min(img.width, x1 + PAD), min(img.height, y1 + PAD))
    img.crop(tuple(int(v) for v in box)).save(os.path.join(OUT, name), optimize=True)


def matrix_box(img, pane):
    """The LEDs in the logical view's pane: every pixel unlike the pane's background (sampled just inside its left
    edge, beside the matrix), the unlit LEDs' black included - inside the pane's frame and below its title."""
    a = np.asarray(img).astype(int)
    (px0, py0), (px1, py1) = pane
    x0, y0, x1, y1 = int(px0) + 12, int(py0) + 40, int(px1) - 12, int(py1) - 12
    sub = a[y0:y1, x0:x1]
    bg = sub[sub.shape[0] // 2, 2]
    ys, xs = np.nonzero(np.abs(sub - bg).max(axis=2) > 10)
    return xs.min() + x0, ys.min() + y0, xs.max() + 1 + x0, ys.max() + 1 + y0


def build(wait=6.0):
    send([{"graph_build": True}], wait)


def shoot(step):
    send([{"layout": "graph"}, {"py": "room.set_tucked(app, True)"}], 1.0)
    send([{"action": "frame_all"}, {"py": "app.gp.set_selection([]) or app.gp.end_key_selection()"}], 1.5)
    img, r = capture(), node_rects()
    crop(img, (min(a[0] for a, _ in r), min(a[1] for a, _ in r), max(b[0] for _, b in r), max(b[1] for _, b in r)),
         f"step{step}_graph.png")
    send([{"layout": "both"}], 2.0)                          # the panels: the logical view beside the 3-D one
    if os.path.exists(RECTS):
        os.remove(RECTS)
    py("open(" + repr(RECTS) + ", 'w').write(repr((dpg.get_item_pos('net_win'), "
       "[a + b for a, b in zip(dpg.get_item_pos('net_win'), dpg.get_item_rect_size('net_win'))])))", 1.0)
    pane = eval(open(RECTS).read())
    img = capture()
    crop(img, matrix_box(img, pane), f"step{step}_view.png")
    print(f"step {step}: captured")


def link(a, out, b, inp):
    return f"app.gp.graph.link({a}, {out!r}, {b}, {inp!r})"


def add(nid, type_):
    """A node added at its place; the ids follow on from the starter's seven (8 to 11)."""
    x, y = POS[nid]
    return f"app.gp.graph.add({type_!r}, ({x}, {y}))"


def move(places):
    """Nodes put at their places, {id: (x, y)}."""
    sets = ", ".join(f"app.gp.graph.nodes[{n}].__setitem__('pos', [{x}, {y}])" for n, (x, y) in places.items())
    return [{"py": f"app.gp._sync_pos() or [{sets}] and app.gp.rebuild()"}]


def run():
    send([{"viewport": list(VIEWPORT)}, {"project": PROJECT}], 4.0)
    send([{"geometry": {"kind": "matrix", "params": {"w": 32, "h": 16}}}, {"layout": "graph"}], 2.0)
    send([{"graph_new": "Sine Wave"}], 2.0)
    build(); shoot(1)
    # step 2: the Wave, along u, travelling with the slider-scaled clock, two cycles; its value into the palette
    send(move({5: POS[5]}), 0.3)
    py("[" + ", ".join([add(8, "Wave"), link(4, "u", 8, "x"), link(3, "result", 8, "phase"),
                        link(8, "value", 6, "index")]) + "] and app.gp.rebuild()")
    send([{"graph_input": [8, "cycles", 2.0]}], 0.3)
    build(); shoot(2)
    # step 3: the distance from the curve dims a left-to-right rainbow
    send(move(STEP3_OUT), 0.3)
    py("[" + ", ".join([add(9, "Subtract"), add(10, "Abs"), link(4, "v", 9, "a"), link(8, "value", 9, "b"),
                        link(9, "result", 10, "x"), link(4, "u", 6, "index"), link(10, "result", 6, "brightness")])
       + "] and app.gp.rebuild()")
    build(); shoot(3)
    # step 4: a soft switch turns the distance into a line
    send(move(STEP4_OUT), 0.3)
    py("[" + ", ".join([add(11, "Smoothstep"), link(10, "result", 11, "x"), link(11, "result", 6, "brightness")])
       + "] and app.gp.rebuild()")
    send([{"graph_param": [11, "e0", 0.12]}, {"graph_param": [11, "e1", 0.02]}], 0.3)
    build(); shoot(4)
    # step 5: W, the logical view and the 3-D one, full frame
    send([{"action": "view_both"}], 2.5)
    capture().save(os.path.join(OUT, "step5_result.png"), optimize=True)
    print("step 5: captured")
    # the camera-mapping dialog of the second tutorial (tree_camera.png), with a string of 500 on a 150 cm tree
    send([{"action": "view_both"}, {"py": "camera_map_ui.show(app) or num.set('map_n', 500) or num.set('map_height', 150.0) "
                                           "or camera_map_ui._plan_words(app)"}], 2.0)
    if os.path.exists(RECTS):
        os.remove(RECTS)
    py("open(" + repr(RECTS) + ", 'w').write(repr((dpg.get_item_pos(camera_map_ui.TAG), "
       "dpg.get_item_rect_size(camera_map_ui.TAG))))", 1.0)
    (x, y), (w, h) = eval(open(RECTS).read())
    img = capture()
    img.crop((int(x), int(y), int(x + w), int(y + h))).save(os.path.join(OUT, "tree_camera.png"), optimize=True)
    send([{"py": "dpg.hide_item(camera_map_ui.TAG)"}], 0.5)
    print("the camera dialog: captured")
    # the places into the bundle, the rest of it as it is
    if os.path.exists(RECTS):
        os.remove(RECTS)
    py("open(" + repr(RECTS) + ", 'w').write(repr({k: list(n['pos']) for k, n in app.gp.graph.nodes.items()}))", 1.0)
    places = eval(open(RECTS).read())
    b = json.load(open(BUNDLE, encoding="utf-8"))
    for n in b["graph"]["nodes"]:
        n["pos"] = [round(v) for v in places[n["id"]]]
    with open(BUNDLE, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(b, indent=1) + "\n")


def main():
    if not scratch.DIR:
        print("no private scratch folder to drive the studio through (native/scratch.py)")
        return 1
    studio_file = os.path.join(ROOT, "projects", "studio.json")
    saved = open(studio_file, encoding="utf-8").read() if os.path.exists(studio_file) else None
    if saved is not None:
        os.remove(studio_file)                              # from no settings: no frames docked where the graph goes
    proj = os.path.join(ROOT, "projects", PROJECT)
    for f in (CMD, SHOT_REQ):
        if os.path.exists(f):
            os.remove(f)
    log = open(scratch.path("tutorial_shots.log"), "w")
    env = dict(os.environ, STUDIO_NO_UPDATE_CHECK="1", STUDIO_NO_WELCOME="1", STUDIO_REMOTE_CONTROL="1")
    proc = subprocess.Popen([sys.executable, "-u", "-m", "native.app"], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, env=env)
    try:
        time.sleep(9)
        run()
        return 0
    finally:
        proc.kill()                                         # this script's studio, by its own PID - never by name
        time.sleep(1)
        log.close()
        if saved is not None:
            open(studio_file, "w", encoding="utf-8").write(saved)
        elif os.path.exists(studio_file):
            os.remove(studio_file)
        shutil.rmtree(proj, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())
